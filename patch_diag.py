"""
ОДИТ-65 · СЧУПЕН МОЗЪК ИЗГЛЕЖДА КАТО ТИХ ПАЗАР

Последните две потвърдени находки на армията, обединени защото са едно:
диагностиката СЪЩЕСТВУВА, но ботът не я взима.

🔴 1 · `сканирай` строи речник `диаг` с ключове `грешки`, `бележки`, `време_мс`
   и го връща САМО ако `върни_диагностика=True`. Ботът вика без флага:
       _setups = CB.сканирай(_bfr, сега=now_utc, състояние=_bstate, ...)
   Значи гръмне ли модул (свипове, ликвидност, зони…), грешката се записва в
   `диаг["грешки"]` и НЕЗАБАВНО се изхвърля. Мозъкът връща по-малко сетъпи,
   ботът пише «0 повода (тихо)», и собственикът вижда тих пазар вместо
   счупен двигател. Точно класът дефект, който днес ме ухапа три пъти.

🔴 2 · Групата ОБЕМИ мълчи на 1мин и 5м по устройство. Кодът ГО ЗНАЕ и го
   казва в `бел`: «обемът е празен — групата ОБЕМИ ще мълчи». Но `бел` също
   влиза в `диаг` и също се изхвърля. Три точки, които тези рамки не могат да
   вземат, а прагът е един и същ за всички.

ПОПРАВКА: ботът вика с `върни_диагностика=True`, слага грешките в дневника, а
при СЧУПЕН модул вдига видима бележка — не мълчание.
"""
import io, sys, ast, hashlib

ops = []


def rep(old, new, why, n=1):
    global s
    c = s.count(old)
    if c != n:
        print(f"  x СПИРАМ «{why}»: {c} съвпадения, чакам {n}\n    {old[:150]!r}")
        sys.exit(1)
    s = s.replace(old, new)
    ops.append(why)


p = "live_bot.py"
s = io.open(p, encoding="utf-8", newline="").read()

rep('''            _setups = CB.сканирай(_bfr, сега=now_utc, състояние=_bstate,
                                  работни=МОЗЪК_РАМКИ, праг=МОЗЪК_ПРАГ)''',
    '''            # 🔴 ОДИТ-65 · ДОТУК ТУК НЕ СЕ ИСКАШЕ ДИАГНОСТИКА и `сканирай`
            # изхвърляше речника с ГРЕШКИТЕ. Гръмне ли модул (свипове,
            # ликвидност, зони…), мозъкът просто връща по-малко сетъпи, ботът
            # пише «0 повода (тихо)» и счупеният двигател изглежда като тих
            # пазар. Сега грешките влизат в дневника, а счупен модул вдига
            # видима бележка.
            _setups, _диаг = CB.сканирай(_bfr, сега=now_utc, състояние=_bstate,
                                         работни=МОЗЪК_РАМКИ, праг=МОЗЪК_ПРАГ,
                                         върни_диагностика=True)
            try:
                _гр = (_диаг or {}).get("грешки") or {}
                if _гр:
                    notes.append("🔴 МОЗЪКЪТ ГЪРМИ на " + ", ".join(sorted(_гр)[:4])
                                 + (f" (+{len(_гр)-4})" if len(_гр) > 4 else "")
                                 + " — тишината му НЕ е тих пазар")
                    for _к, _в in list(_гр.items())[:3]:
                        notes.append(f"   {_к}: {_в}")
                # ОДИТ-65 №2: групата ОБЕМИ мълчи по устройство на бързите рамки
                # — кодът го знаеше и го казваше само на себе си.
                for _б in (_диаг or {}).get("бележки") or []:
                    if "ОБЕМИ ще мълчи" in str(_б) or "прескочена" in str(_б):
                        notes.append(f"🟡 мозък: {_б}")
            except Exception as _e:
                notes.append(f"диагностиката на мозъка се спъна: {type(_e).__name__}")''',
    "диагностиката влиза в дневника")

io.open(p, "wb").write(s.encode("utf-8"))
ast.parse(io.open(p, encoding="utf-8").read())
print("ПРИЛОЖЕНИ:")
for o in ops:
    print(f"  + {o}")
