import io, sys, ast, json, hashlib

# ── 1 · числата ──────────────────────────────────────────────────────────
p = "backtest_stats.json"
st = json.load(io.open(p, encoding="utf-8"))
ново = json.load(io.open("F25_ma.json", encoding="utf-8"))
стар = st.get("ma_bounce", {})

mb = {"_метод": ("F25 (18.08) · условието е буквално от `_regime`: low<=sma и close>sma "
                 "(лонг), high>=sma и close<sma (шорт), върху дневни барове от самата "
                 "1-минутна лента. Вход на затварянето, ДОСТАВЕНАТА геометрия "
                 "(ТП 7.5/12/20 · стоп 20 · стълба 1/3 · стоп на входа след ТП1), "
                 "реален спред от лентата. Блоков бутстрап по ден, 4000 повторения."),
      "_и_четирите_са_шум": True,
      "_старо": {"защо": ("числата до 18.08. Твърдяха +2.41 до +4.64$ на сделка; "
                          "преизмерено дава −0.35 до −1.29$ и нулата е в интервала на "
                          "четирите. Нямаха нито интервал, нито записан метод."),
                 "стойности": {d: dict(v) for d, v in стар.items() if isinstance(v, dict)}}}
for ключ, а in ново.items():
    посока, ma = ключ.split("_", 1)
    mb.setdefault(посока, {})[ma] = {"n": а["n"], "win": а["win"], "net": а["net"],
                                     "lo": а["lo"], "hi": а["hi"], "дни": а["дни"],
                                     "шум": а["шум"]}
st["ma_bounce"] = mb
json.dump(st, io.open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("1 · ma_bounce преизмерен · старите числа са под `_старо`")

# ── 2 · картата ползва числата ───────────────────────────────────────────
p2 = "live_bot.py"
s = io.open(p2, encoding="utf-8", newline="").read()

СТАРО = '''def _ma_alert_msg(direction, ma_name, price, mb, macro):
    """ОДИТ-28/29 · знак за ниво, НЕ сделка. Нивата паднаха — картата даваше
    вход, по който сама казваше да не влизаш."""
    ико = "🟢" if direction == "long" else "🔴"
    накъде = "нагоре" if direction == "long" else "надолу"
    return "\\n".join([
        f"📌 НИВО · цената се обърна {накъде} от {ma_name.upper()} · {_sofia()}",
        f"{ико} злато <code>{_fmt(price)}</code>",
        "👁 само знак · не влизам, сметката е на минус"])'''

НОВО = '''def _ma_alert_msg(direction, ma_name, price, mb, macro):
    """ОДИТ-28/29 · знак за ниво, НЕ сделка. Нивата паднаха — картата даваше
    вход, по който сама казваше да не влизаш.

    🔴 F25 (18.08) · ДОТУК ТУК `mb` и `macro` СЕ ПОЛУЧАВАХА И СЕ ИЗХВЪРЛЯХА
    (потвърдено с AST), а редът «сметката е на минус» беше закован текст. В
    същото време `backtest_stats.json` твърдеше за същото събитие +4.64$ на
    сделка — тоест картата и файлът си противоречаха, и никой не питаше кой е
    прав. Преизмерено под доставената геометрия върху 1-минутната лента с
    реалния спред: long/ma50 −0.348$ [−1.591 .. +0.863] — ШУМ, и така и на
    четирите. «Не влизам» остава, но вече ЗАЩОТО Е МЕРЕНО, и числото се вижда.
    """
    ико = "🟢" if direction == "long" else "🔴"
    накъде = "нагоре" if direction == "long" else "надолу"
    мб = mb if isinstance(mb, dict) else {}
    нето, брой = мб.get("net"), мб.get("n")
    if нето is None or not брой:
        оценка = "👁 само знак · няма измерване за такъв отскок — не влизам"
    else:
        зн = "+" if нето > 0 else "−"
        пипс = abs(float(нето)) / PIP
        шум = bool(мб.get("шум")) or (мб.get("lo") is not None and мб.get("hi") is not None
                                      and мб["lo"] <= 0 <= мб["hi"])
        # ФАКТ, не лекция: числото и думата до него не бива да си противоречат.
        оценка = (f"👁 само знак · мерено {зн}{пипс:.0f} пипса "
                  f"({зн}{abs(float(нето)):.2f}$) от {брой} случая"
                  + (" · нулата е в интервала" if шум else "")
                  + " — не влизам")
    return "\\n".join([
        f"📌 НИВО · цената се обърна {накъде} от {ma_name.upper()} · {_sofia()}",
        f"{ико} злато <code>{_fmt(price)}</code>",
        оценка])'''

assert s.count(СТАРО) == 1, f"{s.count(СТАРО)} съвпадения за картата"
