def _мозък_свод(път=pathlib.Path("live/brain_result.jsonl"), силни=("⚡ МНОГО СИЛЕН", "💎 РЯДЪК")):
    """Тефтерът на САМИЯ мозък. Кофите на бота са за ДРУГА логика и не бива
    да ѝ обличат дрехите си — затова мереното НЕ идва оттам."""
    try:
        rs = [json.loads(l) for l in io.open(път, encoding="utf-8") if l.strip()]
    except Exception:
        return None
    r = [x for x in rs if x.get("резултат") is not None]
    if not r:
        return None
    s = [x for x in r if x.get("степен") in силни]
    дни = sorted({str(x["отворен"])[:10] for x in r})
    f = lambda xs: (len(xs), sum(1 for x in xs if x["резултат"] > 0), sum(x["резултат"] for x in xs))
    return {"общо": f(r), "силни": f(s), "от_дата": дни[0], "дни": len(дни)}

