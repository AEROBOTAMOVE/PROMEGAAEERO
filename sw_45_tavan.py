"""№45: таванът по група реже ли изобщо?"""
import sys, collections, importlib.util
sys.stdout.reconfigure(encoding='utf-8')
sp=importlib.util.spec_from_file_location("bсл","brain/b_сливане.py")
m=importlib.util.module_from_spec(sp); sp.loader.exec_module(m)
макс=collections.Counter()
бр=collections.Counter()
for име,(т,гр,_) in m.ТАБЛИЦА.items():
    макс[гр]+=т; бр[гр]+=1
режат=[]
for гр in sorted(m.ТАВАН_ГРУПА):
    т=m.ТАВАН_ГРУПА[гр]; мх=макс[гр]
    р = мх>т
    режат.append(р)
    print(f"  група {гр}: условия {бр[гр]:>2}  МАКС точки {мх:>2}  таван {т:>2}  → {'РЕЖЕ' if р else 'НЕ МОЖЕ ДА РЕЖЕ'}")
print("тавани, които могат да режат:", sum(режат), "от", len(режат))
# ВЪЗПРОИЗВЕЖДАНЕ: пусни всички условия на З (диапазон) → колко точки минават
print()
print("=== едно наблюдение, преброено четири пъти (група З) ===")
З=[k for k,(t,g,_) in m.ТАБЛИЦА.items() if g=="З"]
сбор=sum(m.ТАБЛИЦА[k][0] for k in З)
print("  всички 4 условия на З:", З)
print("  сбор =", сбор, "· таван З =", m.ТАВАН_ГРУПА['З'], "→ отрязано:", max(0,сбор-m.ТАВАН_ГРУПА['З']))
print("  степен при", сбор, "точки САМО от диапазона:", m.f_степен(сбор))
print("  прагът за пращане е", m.ПРАГ_ПРАЩАНЕ)
