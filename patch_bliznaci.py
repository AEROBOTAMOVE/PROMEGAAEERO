"""
ОДИТ-45г · ТРИТЕ БЛИЗНАКА НА ЕДНА ПОПРАВКА

Оправих «{n}/7 мащаба» в пулса и щях да мина нататък. Собствената ми поука от
04.08 казва: ТЪРСИ БЛИЗНАКА НА ВСЯКА ПОПРАВКА. Потърсих — и лъжата живееше на
още ТРИ места:
    _спряна_msg   (ред 364) · «⏸ ВИЖДАМ покупка · но не я давам»
    _standing_msg (ред 375) · «⏸ СТОИ · покупка злато»
    _status_msg   (ред 1330) · ръчната карта «какво виждаш»

И ЕДИН ТЕСТ Я ПАЗЕШЕ:
    ck("П23 картата показва колко мащаба са съгласни", "7/7" in _м23)
Тоест дори да бях счупил трите, тестът щеше да е ЗЕЛЕН — той изискваше именно
невярното число. Тестът не се трие; ОБРЪЩА СЕ и пази обратното.

Числото беше невярно, защото рамките са копия: мерено на 1965 живи ръна, в
84.6% седемте са БУКВАЛНО еднакви и различни отчета никога не е имало над 2.
"""
import io, sys, ast, hashlib

ops = []


def rep(p, old, new, why, n=1):
    s = io.open(p, encoding="utf-8", newline="").read()
    c = s.count(old)
    if c != n:
        print(f"  x СПИРАМ «{why}»: {c} съвпадения, чакам {n}\n    {old[:130]!r}")
        sys.exit(1)
    io.open(p, "wb").write(s.replace(old, new).encode("utf-8"))
    ops.append(why)


LB, ST = "live_bot.py", "selftest.py"

# ── близнак 1 · спряната карта ────────────────────────────────────────────
rep(LB, '''    съгл = sum(1 for b in board if b[1] == direction and b[3] != "weak") if board else 0
    return "\\n".join([
        f"⏸ ВИЖДАМ {посока.upper()} · но не я давам · {_sofia(now_utc)}",
        f"{ико} {съгл}/7 мащаба натам · <code>{_fmt(price_user, 2)}</code>",''',
    '''    # ОДИТ-45г: «/7» беше невярно — рамките са копия (84.6% буквално еднакви
    # на 1965 живи ръна). Броим РАЗЛИЧНИТЕ отчети; един отчет не се брои.
    _за, _общо = _съгласни(board, direction)
    return "\\n".join([
        f"⏸ ВИЖДАМ {посока.upper()} · но не я давам · {_sofia(now_utc)}",
        f"{ико}{f' {_за} от {_общо} отчета натам ·' if _общо > 1 else ''} "
        f"<code>{_fmt(price_user, 2)}</code>",''',
    "близнак 1 · спряната карта")

# ── близнак 2 · стоящата карта ────────────────────────────────────────────
rep(LB, '''    съгл = sum(1 for b in board if b[1] == direction and b[3] != "weak")
    lv = _levels(round(price_user, 2), direction)
    L = [f"⏸ СТОИ · {посока} злато · {_sofia(now_utc)}",
         f"{ико} {съгл}/7 мащаба натам · вече {age_h:.0f}ч",''',
    '''    _за, _общо = _съгласни(board, direction)   # ОДИТ-45г: виж близнак 1
    lv = _levels(round(price_user, 2), direction)
    L = [f"⏸ СТОИ · {посока} злато · {_sofia(now_utc)}",
         f"{ико}{f' {_за} от {_общо} отчета натам ·' if _общо > 1 else ''} "
         f"вече {age_h:.0f}ч",''',
    "близнак 2 · стоящата карта")

# ── близнак 3 · ръчната карта «какво виждаш» ──────────────────────────────
rep(LB, '''        _съгл = sum(1 for b in (board or []) if b[1] == new_dir and b[3] != "weak")
        L.append(f"{'🟢' if new_dir == 'long' else '🔴'} очертава се "
                 f"{'нагоре' if new_dir == 'long' else 'надолу'} · {_съгл}/7 мащаба")''',
    '''        _за, _общо = _съгласни(board or [], new_dir)   # ОДИТ-45г: виж близнак 1
        L.append(f"{'🟢' if new_dir == 'long' else '🔴'} очертава се "
                 f"{'нагоре' if new_dir == 'long' else 'надолу'}"
                 + (f" · {_за} от {_общо} отчета" if _общо > 1 else ""))''',
    "близнак 3 · ръчната карта")

# ── тестът се ОБРЪЩА ──────────────────────────────────────────────────────
rep(ST, '''ck("П23 картата показва колко мащаба са съгласни",       # ОДИТ-29: «клас СИЛЕН» падна —
   "7/7" in _м23)                                         # дума от машинното отделение''',
    '''# 🔴 ОДИТ-45г · ОБЪРНАТ. Този тест ИЗИСКВАШЕ невярното число «7/7».
# Мерено на 1965 живи ръна: в 84.6% седемте рамки са БУКВАЛНО еднакви и
# различни отчета никога не е имало повече от ДВА — «7 от 7 съгласни» броеше
# седем копия на едно измерване. Тестът не се трие; пази обратното.
ck("П23 картата НЕ твърди «7/7» — рамките са копия, не седем мнения",
   "7/7" not in _м23 and "/7 мащаба" not in _м23)
ck("П23 при ЕДИН отчет картата не се хвали с брой",
   "отчета" not in _м23 or "от 1 отчета" not in _м23)''',
    "тестът е обърнат")

print("ПРИЛОЖЕНИ:")
for o in ops:
    print(f"  + {o}")
for f in (LB, ST):
    ast.parse(io.open(f, encoding="utf-8").read())
    b = io.open(f, encoding="utf-8").read()
    print(f"{f}: {len(b.splitlines())} реда · sha {hashlib.sha256(b.encode()).hexdigest()[:12]}")
