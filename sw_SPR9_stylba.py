"""Колко ПАРИ струва един ФАНТОМЕН ТП1 по стълбата 1/3 (грешката, която НАИСТИНА
се появява), и колко излиза на сделка при производственото тегло."""
import sys; sys.argv=["x"]; import live_bot as lb
lv=lb._levels(4400.0,"long"); e=4400.0
print("нива:",lv)
# сценарий A (както бота): ТП1 обявен (фалшиво) -> стоп на входа -> «излиза на нула»
a,_=lb._ladder_pnl("sl",{"tp1":True},dict(lv,sl=e),e,1,(e-e))
# сценарий B (честно): ТП1 никога не е ударен -> стопът е на мястото си
b,_=lb._ladder_pnl("sl",{},lv,e,1,(lv["sl"]-e))
print("A фантом:%.2f$  B честно:%.2f$  разлика=%.2f$ на фантом"%(a,b,a-b))
n, ф = 4293, 41
print("фантоми: %d от %d = %.2f%%"%(ф,n,100*ф/n))
print("грешка, ако спотът е ЕДИНСТВЕН съдник: %.3f $/сделка"%((a-b)*ф/n))
print("производство (спот решава 20%% от целите):     %.3f $/сделка"%(0.20*(a-b)*ф/n))
