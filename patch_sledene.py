    if вид == "цел1" and т.get("цел2") is not None:
        L.append(f"🎯 остава {_fmt(т['цел2'], 2)}")
    else:
        L.append("👁 наблюдението приключи")
    L.append("🧪 без пари — само за да знаеш дали работи")
    return "\\n".join(L)


