"""adv · СИНТЕТИЧЕН САМОТЕСТ на `сделка()` от F24_srebro.py — сметката вярна ли е изобщо.
F24 няма нито един такъв тест. Тук резултатът се смята НА РЪКА и се сверява."""
import warnings, io
warnings.filterwarnings("ignore")
import numpy as np

ТП = (0.20, 0.32, 0.54); СТОП = 0.54; ДНИ_МАКС = 21
ВХ = 20.00


def направи(барове):
    """барове = списък (high, low); ден 0 е входният (не се гледа)"""
    H = np.array([ВХ] + [b[0] for b in барове], float)
    L = np.array([ВХ] + [b[1] for b in барове], float)
    C = np.array([ВХ] + [(b[0] + b[1]) / 2 for b in барове], float)
    return H, L, C


def сделка(H, L, C, N, i, лонг):
    """ДОСЛОВНО копие на F24_srebro.py `сделка()`"""
    зн = 1.0 if лонг else -1.0
    вх = C[i]
    tp = [вх + зн * t for t in ТП]; sl = вх - зн * СТОП
    пари = 0.0; взети = 0; бе = False
    for j in range(i + 1, min(i + 1 + ДНИ_МАКС, N)):
        hi, lo = H[j], L[j]
        тек = вх if бе else sl
        уд_ст = (lo <= тек) if лонг else (hi >= тек)
        нови = [k for k, t in enumerate(tp) if k >= взети
                and ((hi >= t) if лонг else (lo <= t))]
        if уд_ст and not нови:
            пари += (тек - вх) * зн * (3 - взети) / 3.0
            return пари, взети, ("be" if бе else "sl")
        if уд_ст and нови:
            пари += (тек - вх) * зн * (3 - взети) / 3.0
            return пари, взети, ("be" if бе else "sl")
        for k in нови:
            пари += (tp[k] - вх) * зн / 3.0
            взети = k + 1
            if k == 0: бе = True
            if k == 2:
                return пари, взети, "tp3"
    посл = C[min(i + ДНИ_МАКС, N - 1)]
    пари += (посл - вх) * зн * (3 - взети) / 3.0
    return пари, взети, "time"


