# -*- coding: utf-8 -*-
"""
F24 · ПОПРАВКА НА СОБСТВЕНАТА МИ КРЪПКА

Тестът в обратната посока падна и е прав. Записах `_епохи_съгласни` във файла,
пресметнато с ФИКСИРАН разход 0.03$. Значи флагът НЕ ЗАВИСИ от `СРЕБРО_СПРЕД`ᵢ
— свали ли собственикът спреда до 0.00, клетките пак остават мъртви. Тоест
«пътят назад» е декоративен, а спирачката — закована.

Точно класът дефект, който ловя цял ден: спирачка, проверена само че СПИРА.

ПОПРАВКА: файлът пази СУРОВИТЕ средни по епохи (`_епохи`), а съгласието се
смята ПРИ ЖИВИЯ СПРЕД, в `_сребро_разход`. Тогава 0.00 наистина оживява
клетките, а 0.03 наистина ги убива — и двете по едно и също правило.
"""
import io, sys, ast, hashlib

p = "live_bot.py"
s = io.open(p, encoding="utf-8", newline="").read()

СТАРО = '''            for к in ("net", "lo", "hi"):
                v = сур.get(к)
                if v is not None:
                    а[к] = round(float(v) - СРЕБРО_СПРЕД, 4)
            пипнати += 1'''

НОВО = '''            for к in ("net", "lo", "hi"):
                v = сур.get(к)
                if v is not None:
                    а[к] = round(float(v) - СРЕБРО_СПРЕД, 4)
            # 🔴 F24б · СЪГЛАСИЕТО НА ЕПОХИТЕ СЕ СМЯТА ТУК, НЕ ВЪВ ФАЙЛА.
            # Първата ми версия го записа в JSON-а с фиксиран разход 0.03$ →
            # свалеше ли собственикът `СРЕБРО_СПРЕД` до 0.00, клетките пак
            # оставаха мъртви и «пътят назад» беше декорация. Мереното: сурово
            # day1/long дава +0.0986$ (2000-2012) и +0.0019$ (2013-2026) — двете
            # ПОЛОЖИТЕЛНИ; след 0.03$ разход стават +0.0686 и −0.0281, тоест
            # РАЗЛИЧНИ. Един и същ ред данни сменя присъдата според разхода,
            # затова разходът трябва да е вътре в сметката, не преди нея.
            еп = а.get("_епохи")
            if isinstance(еп, dict):
                _з = [float(v) - СРЕБРО_СПРЕД for v in еп.values() if v is not None]
                # само при ДВЕ измерими епохи има какво да се сравнява
                а["_епохи_съгласни"] = (len(_з) < 2
                                        or all(x > 0 for x in _з)
                                        or all(x < 0 for x in _з))
            пипнати += 1'''

assert s.count(СТАРО) == 1, f"{s.count(СТАРО)} съвпадения"
s = s.replace(СТАРО, НОВО)
io.open(p, "wb").write(s.encode("utf-8"))
ast.parse(io.open(p, encoding="utf-8").read())
b = io.open(p, encoding="utf-8").read()
print(f"поправено · {p}: {len(b.splitlines())} реда · sha {hashlib.sha256(b.encode()).hexdigest()[:12]}")
