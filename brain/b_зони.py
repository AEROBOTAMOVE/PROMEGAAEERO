def проверка_Н1(df: pd.DataFrame, рамка="1час") -> dict:
    """
    Твърдението Н1: в Pine р. 697-698 max/min са празни — зоната винаги е целият
    базов бар. Проверява се машинно върху реални барове.
    """
    d = _подготви(df)
    tf, _ = _прерамкирай(d, рамка)
    o = tf["open"].to_numpy(); h = tf["high"].to_numpy()
    l = tf["low"].to_numpy(); c = tf["close"].to_numpy()
    a = np.maximum(h, o); b = np.minimum(l, c)
    a2 = np.maximum(h, c); b2 = np.minimum(l, o)
    return dict(барове=len(h),
                бичи_top_различен=int((a != h).sum()), бичи_bottom_различен=int((b != l).sum()),
                мечи_top_различен=int((a2 != h).sum()), мечи_bottom_различен=int((b2 != l).sum()))


def тест_без_надничане(df: pd.DataFrame, точки=(0.55, 0.7, 0.85), надграждане=True) -> dict:
    """
    Реже DataFrame-а на `точки` от дължината му и изисква зоните, родени преди
    отреза, да са БУКВАЛНО същите като при пълния файл (цена, бар, оценка).
    Ако функция надничаше напред, отрязаното бъдеще щеше да промени миналото.
    """
    d = _подготви(df)
    пълен = f_зони(d, само_както_графиката=not надграждане, върни_всички=True)["всички_зони"]
    # Сравняват се САМО замразените на раждането полета. Живата оценка се мени с
    # всеки бар по замисъл (както Pine) и не може да е част от този тест.
    ключ = lambda z: (z["родена"], z["рамка"], z["посока"], round(z["горе"], 4),
                      round(z["долу"], 4), z["оценка_раждане_сурова"],
                      z.get("точки_раждане"))
    П = {ключ(z) for z in пълен}
    отчет = {}
    for f in точки:
        m = int(len(d) * f)
        част = f_зони(d.iloc[:m], само_както_графиката=not надграждане, върни_всички=True)["всички_зони"]
        # сравняваме само зони, родени с достатъчен запас преди отреза
        граница = m - 300
        Ч = {ключ(z) for z in част if z["родена"] < граница}
        Пг = {k for k in П if k[0] < граница}
        отчет[f] = dict(в_отреза=len(Ч), в_пълния=len(Пг),
                        съвпадат=len(Ч & Пг), само_в_отреза=len(Ч - Пг), само_в_пълния=len(Пг - Ч))
    return отчет
