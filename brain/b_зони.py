# 5 · ОТКРИВАНЕ НА ЗОНИТЕ (Pine р. 681-699) — ПРЕНОС, дума по дума
# ═══════════════════════════════════════════════════════════════════════════

def _открий(d, рамка, тегло, времена, P, U, надграждане: bool):
    """
    За всеки ЗАТВОРЕН бар j на рамката: j = импулс, j-1 = база, j-6..j-2 = обраното.
    Връща списък от сурови зони. Ражда се на активиращия базов бар.
    """
    tf, край = _прерамкирай(d, рамка)
    m = len(tf)
    назад = min(P["свип_lookback"] + 1, P["свип_lookback_таван"])   # = 6
    if m < назад + 2:
        return []
    o = tf["open"].to_numpy(float); h = tf["high"].to_numpy(float)
    l = tf["low"].to_numpy(float);  c = tf["close"].to_numpy(float)
    v = tf["volume"].to_numpy(float)
    a = _atr(h, l, c, P["atr_период"])
    акт = np.searchsorted(времена, край.to_numpy(), side="left")
    n_база = len(времена)

    # минимум/максимум на баровете 2..назад ПРЕДИ импулса (Pine f_hist_min_low(arr,2,6))
    мин_l = np.full(m, np.nan); макс_h = np.full(m, np.nan)
    for j in range(назад, m):
        мин_l[j] = l[j - назад:j - 1].min()
        макс_h[j] = h[j - назад:j - 1].max()

    # среден обем по МИНАЛИ барове (само надграждане; причинен: shift(1))
    ср_обем = pd.Series(v).rolling(U["обем_период"], min_periods=10).median().shift(1).to_numpy()

    зони = []
    for j in range(назад, m):
        if np.isnan(a[j]) or np.isnan(c[j - 1]):
            continue
        i0 = int(акт[j])
        if i0 >= n_база:
            continue                                  # барът още не е известен на базовата рамка
        съотн = abs(c[j] - o[j]) / a[j]
        if съотн < P["импулс_atr"]:
            continue
        бичи_имп = c[j] > o[j]; меча_база = c[j - 1] < o[j - 1]
        меча_имп = c[j] < o[j]; бича_база = c[j - 1] > o[j - 1]
        обран_долу = (not P["само_след_свип"]) or (l[j - 1] < мин_l[j])
        обран_горе = (not P["само_след_свип"]) or (h[j - 1] > макс_h[j])
        бичи = бичи_имп and меча_база and обран_долу
        мечи = меча_имп and бича_база and обран_горе
        if not (бичи or мечи):
            continue
        # Pine р. 697-698: max/min са празни — виж Н1. Зоната = целият базов бар.
        горе = max(h[j - 1], o[j - 1] if бичи else c[j - 1])
        долу = min(l[j - 1], c[j - 1] if бичи else o[j - 1])
        if горе <= долу:
            continue
        # НОВО: дълбочина на свипа под/над предходния екстремум, в ATR
        дълб = (мин_l[j] - l[j - 1]) / a[j] if бичи else (h[j - 1] - макс_h[j]) / a[j]
        оi = float(v[j] / ср_обем[j]) if (надграждане and ср_обем[j] and ср_обем[j] > 0
                                          and not np.isnan(ср_обем[j])) else np.nan
        оb = float(v[j - 1] / ср_обем[j]) if (надграждане and ср_обем[j] and ср_обем[j] > 0
                                              and not np.isnan(ср_обем[j])) else np.nan
        зони.append(dict(
            посока="КУПУВА" if бичи else "ПРОДАВА", бичи=бичи, рамка=рамка, тегло=тегло,
            горе=float(горе), долу=float(долу), импулс_atr=float(съотн),
            свип_дълбочина_atr=float(дълб), обем_импулс_отн=оi, обем_база_отн=оb,
            родена=i0, tf_бар=j,
        ))
    return зони


# ═══════════════════════════════════════════════════════════════════════════
# 6 · ЖИВОТЪТ НА ЗОНАТА (Pine р. 745-757) — векторно, но без бъдеще
# ═══════════════════════════════════════════════════════════════════════════

def _живот(z, K, P, U, надграждане: bool):
    """
    Смята за зоната: тестове по време, изяждане, бар на смъртта и причина.
    Всичко е СЛЕД раждането — нищо от това не влиза в оценката ѝ.
    """
    h = K["h"]; l = K["l"]; c = K["c"]; n = K["n"]
    i0 = z["родена"] + 1                       # зоната живее от следващия бар нататък
    i1 = min(n, i0 + U["хоризонт_барове"])
    if i0 >= n:
        z.update(тестове=0, изядена=False, мъртва=None, причина="жива", първи_допир=None,
                 входове=np.zeros(0, dtype=np.int64), изядена_от=None)
        return z
    hh = h[i0:i1]; ll = l[i0:i1]; cc = c[i0:i1]
    вътре = (ll <= z["горе"]) & (hh >= z["долу"])
    предх = np.concatenate(([False], вътре[:-1]))
    влизане = вътре & ~предх
    тестове = np.cumsum(влизане)
    височина = max(z["горе"] - z["долу"], 1e-9)
    прон = np.clip((z["горе"] - ll) / височина if z["бичи"] else (hh - z["долу"]) / височина, 0, 1.5)
    невалидна = (cc < z["долу"]) if z["бичи"] else (cc > z["горе"])
    изчерпана = тестове >= P["изтрий_след_тестове"]
    мъртва_м = невалидна | изчерпана
    if надграждане and U["убий_при_средата"]:
        среда = (z["горе"] + z["долу"]) / 2.0
        мъртва_м = мъртва_м | ((ll <= среда) & (hh >= среда))
    k = int(np.argmax(мъртва_м)) if мъртва_м.any() else -1
    z["мъртва"] = (i0 + k) if k >= 0 else None
    z["причина"] = ("пробита" if невалидна[k] else "изчерпана") if k >= 0 else "жива"
    докъде = k + 1 if k >= 0 else len(вътре)
    z["тестове"] = int(тестове[докъде - 1]) if докъде > 0 else 0
    z["изядена"] = bool((вътре[:докъде] & (прон[:докъде] >= P["проникване_изядена"])).any())
    д = np.nonzero(вътре[:докъде])[0]
    z["първи_допир"] = int(i0 + д[0]) if len(д) else None
    # абсолютни барове на ВЛИЗАНИЯТА и на изяждането — нужни, за да може оценката
    # да се преизчисли за КОЙ ДА Е бар, точно както Pine я смята на всеки бар
    z["входове"] = (i0 + np.nonzero(влизане[:докъде])[0]).astype(np.int64)
    м = вътре[:докъде] & (прон[:докъде] >= P["проникване_изядена"])
    z["изядена_от"] = int(i0 + int(np.argmax(м))) if м.any() else None
    return z


# ═══════════════════════════════════════════════════════════════════════════
# 7 · ИЗХОДЪТ (НОВО · още не е мерено) — задържала ли е зоната
# ═══════════════════════════════════════════════════════════════════════════

def _изход(z, K, U):
    """
    След ПЪРВИЯ допир: стигнала ли е цената +ЦЕЛ$ в посоката на зоната ПРЕДИ
    зоната да бъде пробита. ЦЕЛ = 7.5$ = ТП1 на живия бот (live_bot.py р. 35).
    Връща 'ЗАДЪРЖА' / 'ПРОПАДА' / 'НЕРЕШЕН'. Само броене, БЕЗ разходи и без пари.
    """
    if z["първи_допир"] is None:
        return "БЕЗ ДОПИР"
    h = K["h"]; l = K["l"]; c = K["c"]; n = K["n"]
    i0 = z["първи_допир"]
    i1 = min(n, i0 + U["хоризонт_барове"])
    if i1 - i0 < 2:
        return "НЕРЕШЕН"
    вход = z["горе"] if z["бичи"] else z["долу"]
    цел = вход + U["цел_долари"] if z["бичи"] else вход - U["цел_долари"]
    ц_ок = (h[i0:i1] >= цел) if z["бичи"] else (l[i0:i1] <= цел)
    сп = (c[i0:i1] < z["долу"]) if z["бичи"] else (c[i0:i1] > z["горе"])
    kц = int(np.argmax(ц_ок)) if ц_ок.any() else 10 ** 9
    kс = int(np.argmax(сп)) if сп.any() else 10 ** 9
    if kц == kс == 10 ** 9:
        return "НЕРЕШЕН"
    return "ЗАДЪРЖА" if kц <= kс else "ПРОПАДА"


