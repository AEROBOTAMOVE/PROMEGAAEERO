def f_карта_зони(рез: dict, макс: int = 4) -> str:
    ред = []
    ред.append(f"🧱 ЗОНИ · {рез['време']:%d.%m %H:%M} UTC · цена {рез['цена']:.2f}$")
    к = рез["контекст"]
    ред.append(f"   половина: {'ДОЛНА / по-евтина' if к['дискаунт'] else 'ГОРНА / по-скъпа'}"
               f" · структура: {'НАГОРЕ' if к['структура']==1 else 'НАДОЛУ' if к['структура']==-1 else 'няма'}"
               f" · свип: {'долу ⚡' if к['свеж_свип_долу'] else ''}{'горе ⚡' if к['свеж_свип_горе'] else ''}"
               f"{'няма пресен' if not (к['свеж_свип_долу'] or к['свеж_свип_горе']) else ''}")
    ред.append(f"   живи зони: {рез['брой_живи']} (родени за целия период: {рез['брой_родени']},"
               f" изгонени от тавана {рез['таван']}: {рез['изгонени_от_тавана']})")
    for име, z in (("В ЗОНА ЗА ПОКУПКА", рез["активна_купува"]),
                   ("В ЗОНА ЗА ПРОДАЖБА", рез["активна_продава"])):
        if z is not None:
            ред.append(f"   ➤ {име}: {z['долу']:.2f}–{z['горе']:.2f} · {z['степен']}")
    ред.append("")
    for z in рез["зони"][:макс]:
        стрелка = "🟢" if z["бичи"] else "🔴"
        разст = "ВЪТРЕ" if z["в_нея"] else f"{z['разстояние']:.2f}$ ({z['разстояние_atr']:.1f} ATR)"
        ред.append(f"{стрелка} {z['посока']} · {z['рамка']} · {z['долу']:.2f}–{z['горе']:.2f}"
                   f"  [{разст}]")
        if "от_условия" in z:
            ред.append(f"   {z['степен']} · {z['точки']}/{z['от_условия']} условия"
                       f"   (на графиката: {z['име_pine']} · {z['оценка_pine']}/7)")
        else:
            ред.append(f"   {z['степен']} · графика: {z['име_pine']} · {z['оценка_pine']}/7")
        ред.append(f"   съвпада: {', '.join(z['съвпадения']) or '—'}")
        if z.get("липсва"):
            ред.append(f"   липсва: {', '.join(z['липсва'])}")
        ред.append(f"   {z['състояние']} · импулс {z['импулс_atr']:.2f} ATR"
                   f" · свип {z['свип_дълбочина_atr']:.2f} ATR"
                   + (f" · обем x{z['обем_импулс_отн']:.2f}" if z.get("обем_импулс_отн") == z.get("обем_импулс_отн") else "")
                   + f" · възраст {z['възраст_барове']} бара")
        if z.get("история_n"):
            ред.append(f"   история на този вид: {z['история_задържа']*100:.0f}% задържане"
                       f" от {z['история_n']} случая (само МИНАЛИ, решени преди раждането ѝ)")
        ред.append(f"   статус: {z['статус']}")
        ред.append("")
    return "\n".join(ред)


