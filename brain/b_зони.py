# 2 · МАЛКИ ИНСТРУМЕНТИ
# ═══════════════════════════════════════════════════════════════════════════

def _atr(h, l, c, n=14):
    """ATR по Wilder. Причинен: на бар i влизат само барове <= i."""
    pc = np.concatenate(([np.nan], c[:-1]))
    tr = np.maximum(h - l, np.maximum(np.abs(h - pc), np.abs(l - pc)))
    tr[0] = h[0] - l[0]
    a = np.array(pd.Series(tr).ewm(alpha=1.0 / n, adjust=False).mean().to_numpy(), dtype=float)
    a[: n - 1] = np.nan          # без загрявката — Pine също няма стойност там
    return a


def _пивот(x, L, R, макс=True):
    """
    ta.pivothigh(x, L, R) / ta.pivotlow. Връща булев масив: True на бара НА пивота.
    Строго по-висок/по-нисък от съседите от двете страни.
    ПОТВЪРЖДАВА СЕ на бар p+R — извикващият е длъжен да го спазва.
    """
    n = len(x)
    res = np.zeros(n, dtype=bool)
    if n < L + R + 1:
        return res
    win = sliding_window_view(x, L + R + 1)
    ц = win[:, L]
    ляво = win[:, :L].max(axis=1) if макс else win[:, :L].min(axis=1)
    дясно = win[:, L + 1:].max(axis=1) if макс else win[:, L + 1:].min(axis=1)
    res[L:n - R] = (ц > ляво) & (ц > дясно) if макс else (ц < ляво) & (ц < дясно)
    return res


def _ролящ_екстремум(x, n, макс=True):
    s = pd.Series(x).rolling(n, min_periods=1)
    return (s.max() if макс else s.min()).to_numpy()


def _подготви(df: pd.DataFrame) -> pd.DataFrame:
    """Приема df с open/high/low/close (+volume) и DatetimeIndex или колона timestamp_utc."""
    d = df.copy()
    if not isinstance(d.index, pd.DatetimeIndex):
        for к in ("timestamp_utc", "timestamp", "time", "date"):
            if к in d.columns:
                d.index = pd.DatetimeIndex(pd.to_datetime(d[к]))
                break
        else:
            raise ValueError("няма DatetimeIndex и няма колона за време")
    for к in ("open", "high", "low", "close"):
        if к not in d.columns:
            raise ValueError(f"липсва колона {к}")
    if "volume" not in d.columns:
        d["volume"] = np.nan
    return d[["open", "high", "low", "close", "volume"]]


_ПРАВИЛО = {"1мин": "1min", "5мин": "5min", "15мин": "15min", "30мин": "30min",
            "1час": "1h", "4часа": "4h", "1ден": "1D"}
_МИНУТИ = {"1мин": 1, "5мин": 5, "15мин": 15, "30мин": 30, "1час": 60,
           "4часа": 240, "1ден": 1440}


def _прерамкирай(d: pd.DataFrame, рамка: str):
    """
    Връща (tf_df, край) където `край` е моментът, в който TF-барът е ЗАТВОРИЛ.
    label='left', closed='left' → индексът е времето на ОТВАРЯНЕ, край = отваряне + дължина.
    """
    правило = _ПРАВИЛО[рамка]
    доп = {} if рамка == "1ден" else dict(origin="epoch")
    g = d.resample(правило, label="left", closed="left", **доп)
    tf = pd.DataFrame({
        "open": g["open"].first(), "high": g["high"].max(),
        "low": g["low"].min(), "close": g["close"].last(),
        "volume": g["volume"].sum(min_count=1),
    }).dropna(subset=["close"])
    край = tf.index + pd.Timedelta(minutes=_МИНУТИ[рамка])
    return tf, край


