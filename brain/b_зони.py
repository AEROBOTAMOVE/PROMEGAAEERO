# 4 · FVG (нужно за условието `hasFvg`, Pine р. 560-616 + 622-630)
# ═══════════════════════════════════════════════════════════════════════════

def _fvg_списък(d: pd.DataFrame, рамки, времена) -> dict:
    """
    Открива FVG на всяка рамка и намира кога се запълва — без надничане:
    ражда се при затваряне на TF бара, умира на първия базов бар, който го запълни.
    """
    st, en, tp, bt, bl = [], [], [], [], []
    h = d["high"].to_numpy(float); l = d["low"].to_numpy(float); n = len(h)
    for рамка in рамки:
        tf, край = _прерамкирай(d, рамка)
        if len(tf) < 3:
            continue
        th = tf["high"].to_numpy(float); tl = tf["low"].to_numpy(float)
        акт = np.searchsorted(времена, край.to_numpy(), side="left")
        бичи = tl[2:] > th[:-2]
        мечи = th[2:] < tl[:-2]
        for j in np.nonzero(бичи)[0]:
            i0 = int(акт[j + 2])
            if i0 < n:
                st.append(i0); tp.append(float(tl[j + 2])); bt.append(float(th[j])); bl.append(True)
        for j in np.nonzero(мечи)[0]:
            i0 = int(акт[j + 2])
            if i0 < n:
                st.append(i0); tp.append(float(tl[j])); bt.append(float(th[j + 2])); bl.append(False)
    st = np.array(st, dtype=np.int64); tp = np.array(tp); bt = np.array(bt)
    bl = np.array(bl, dtype=bool)
    en = np.full(len(st), n, dtype=np.int64)
    for k in range(len(st)):
        i0 = st[k]
        ако = (l[i0:] <= bt[k]) if bl[k] else (h[i0:] >= tp[k])   # Pine р. 586
        w = np.argmax(ако)
        if ако.size and ако[w]:
            en[k] = i0 + w
    return dict(старт=st, край=en, горе=tp, долу=bt, бичи=bl)


def _има_fvg(F, i, горе, долу, бичи) -> bool:
    """f_fvg_overlap (Pine р. 622-630) — активен FVG в същата посока, който се застъпва."""
    if len(F["старт"]) == 0:
        return False
    m = (F["старт"] <= i) & (F["край"] > i) & (F["бичи"] == бичи)
    if not m.any():
        return False
    return bool((np.minimum(горе, F["горе"][m]) >= np.maximum(долу, F["долу"][m])).any())


