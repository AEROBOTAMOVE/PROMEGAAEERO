def f_зони(df: pd.DataFrame,
           само_както_графиката: bool = False,
           as_of: int | None = None,
           рамки=None,
           върни_всички: bool = False,
           **params) -> dict:
    """
    БЛОК 4 · зони (order blocks) със силата им.

    Параметри
    ---------
    df                   : pandas DataFrame с open/high/low/close (+volume по желание),
                           DatetimeIndex (UTC) или колона timestamp_utc.
    само_както_графиката : True → ЧИСТ ПРЕНОС. 3 рамки, таван 12 зони ОБЩО (FIFO),
                           оценка 2..7 с рязането, никакви нови условия.
                           False → надграждане (по подразбиране).
    as_of                : индекс на бара, „сега". None = последният бар.
    рамки                : кортеж рамки за надграждането. None = ПАРАМ_НАДГРАЖДАНЕ.
    върни_всички         : True → в резултата влиза и списък с ВСИЧКИ родени зони
                           (за изследване; на живо не трябва).

    Връща dict. Всяка зона носи `статус`: "ПРЕНОС" или "НОВО · още не е мерено".
    """
    P = dict(ПАРАМ_ГРАФИКА); U = dict(ПАРАМ_НАДГРАЖДАНЕ)
    for к, v in params.items():
        (P if к in P else U)[к] = v
    надграждане = not само_както_графиката

    d = _подготви(df)
    n = len(d)
    as_of = (n - 1) if as_of is None else int(as_of)
    K = _контекст(d, P)
    времена = K["времена"]

    # ── кои рамки ──
    if само_както_графиката:
        # v9.3 при 15-минутна графика: autoTf → tf1=15, tf2=60, tf3=240 (Pine р. 193-215)
        използвани = (("15мин", 1), ("1час", 2), ("4часа", 3))
    else:
        сп = list(рамки or U["рамки"])
        # тегло по ДЪЛЖИНА на рамката, а не по ред: <=30мин → 1 · <=4часа → 2 · над → 3.
        # Така 15мин/1час/4часа получават 1/2/2 — почти същото като Pine 1/2/3.
        използвани = tuple((r, 1 if _МИНУТИ[r] <= 30 else (2 if _МИНУТИ[r] <= 240 else 3))
                           for r in сп)

    F = _fvg_списък(d, [r for r, _ in използвани] + (["1ден"] if надграждане else []), времена)

    # ── откриване ──
    зони = []
    for рамка, тегло in използвани:
        зони += _открий(d, рамка, тегло, времена, P, U, надграждане)
    зони.sort(key=lambda z: (z["родена"], z["рамка"]))

    # ── живот ──
    for z in зони:
        _живот(z, K, P, U, надграждане)
        z["изход"] = _изход(z, K, U) if надграждане else None

    # ── таванът (Pine р. 662: 12 ОБЩО, FIFO). Точна симулация на push/shift. ──
    таван = P["зони_на_рамка"] * 3 if само_както_графиката else U["макс_живи"]
    активни = []
    for z in зони:
        z["изгонена"] = None
        i = z["родена"]
        активни = [a for a in активни
                   if (a["мъртва"] is None or a["мъртва"] > i) and a["изгонена"] is None]
        активни.append(z)
        while len(активни) > таван:
            стар = активни.pop(0)
            стар["изгонена"] = i
    изгонени = sum(1 for z in зони if z["изгонена"] is not None)

    # ── оценка на бара на РАЖДАНЕТО (замразена) ──
    _оцени(зони, K, F, P, U, надграждане)

    # ── причинна история (НОВО): само зони, решени ПРЕДИ раждането на текущата ──
    if надграждане:
        _история(зони, U)
        for z in зони:
            _финална_точка(z, U)
            z["точки_раждане"] = z["точки"]           # замразено, за статистиката
            z["степен_раждане"] = z["степен"]
            # ЧЕСТНОСТ: самото НАМИРАНЕ на зоната е пренос, ако рамката е една от
            # трите на графиката. Степента 0..12 обаче е НОВА при всички случаи.
            z["на_графиката"] = z["рамка"] in ("15мин", "1час", "4часа")

    # ── какво е ЖИВО на as_of ──
    живи = [z for z in зони
            if z["родена"] <= as_of
            and (z["мъртва"] is None or z["мъртва"] > as_of)
            and (z["изгонена"] is None or z["изгонена"] > as_of)]

    цена = float(K["c"][as_of]); atr = float(K["atr"][as_of])
    for z in живи:
        _преоцени(z, K, F, P, U, as_of, надграждане)   # както Pine — на ТЕКУЩИЯ бар
        z["разстояние"] = 0.0 if z["долу"] <= цена <= z["горе"] else (
            цена - z["горе"] if цена > z["горе"] else z["долу"] - цена)
        z["разстояние_atr"] = z["разстояние"] / atr if atr and not np.isnan(atr) else np.nan
        z["в_нея"] = z["разстояние"] == 0.0
        z["възраст_барове"] = as_of - z["родена"]
        z["състояние"] = f_състояние(z["тестове"], z["изядена"])
    if надграждане and not np.isnan(atr):
        живи = [z for z in живи if z["разстояние_atr"] <= U["забрава_atr"]]
    живи.sort(key=lambda z: (z["разстояние"], -z["точки"]))

    def _най(бичи):
        c_ = [z for z in живи if z["бичи"] == бичи]
        return c_[0] if c_ else None

    def _активна(бичи):
        c_ = [z for z in живи if z["бичи"] == бичи and z["в_нея"]]
        return max(c_, key=lambda z: z["точки"]) if c_ else None

    рез = dict(
        режим="ПРЕНОС · както на графиката" if само_както_графиката else "НАДГРАЖДАНЕ",
        бар=as_of, време=pd.Timestamp(времена[as_of]), цена=цена, atr=atr,
        рамки=[r for r, _ in използвани],
        зони=живи, брой_живи=len(живи), брой_родени=len(зони), изгонени_от_тавана=изгонени,
        таван=таван,
        в_зона_купува=_активна(True) is not None, активна_купува=_активна(True),
        в_зона_продава=_активна(False) is not None, активна_продава=_активна(False),
        най_близка_купува=_най(True), най_близка_продава=_най(False),
        контекст=dict(
            дискаунт=bool(K["дискаунт"][as_of]), премиум=bool(K["премиум"][as_of]),
            среда_на_диапазона=float(K["среда"][as_of]),
            структура=int(K["посока"][as_of]),
            свеж_свип_долу=bool(K["свеж_свип_долу"][as_of]),
            свеж_свип_горе=bool(K["свеж_свип_горе"][as_of]),
        ),
        статистика=_статистика(зони) if надграждане else None,
    )
    if върни_всички:
        рез["всички_зони"] = зони
    return рез


def _оцени(зони, K, F, P, U, надграждане):
    """Оценката се замразява на бара на раждането. Pine р. 783-792 + 4 нови условия."""
    ключови = K["ключови"]
    for z in зони:
        i = z["родена"]
        atr = K["atr"][i]
        tol = atr * P["ключово_atr"] if not np.isnan(atr) else 0.0
        кл = ключови[:, i]
        брой_ключови = int(np.sum((кл >= z["долу"] - tol) & (кл <= z["горе"] + tol) & ~np.isnan(кл)))
        има_fvg = _има_fvg(F, i, z["горе"], z["долу"], z["бичи"])
        вярна_половина = bool(K["дискаунт"][i]) if z["бичи"] else bool(K["премиум"][i])
        посока_ок = (K["посока"][i] == (1 if z["бичи"] else -1))
        свип_ок = bool(K["свеж_свип_долу"][i]) if z["бичи"] else bool(K["свеж_свип_горе"][i])

        у = {
            "рамка": z["тегло"] >= 2,
            "импулс": z["импулс_atr"] >= P["импулс_atr"] + P["импулс_бонус"],
            "свежа": True,                       # на раждане зоната е винаги 0 теста
            "fvg": има_fvg,
            "ключово": брой_ключови > 0,
            "половина": вярна_половина,
            "структура": bool(посока_ок),
            "свип": свип_ок,
        }
        # ── ПРЕНОС: точната Pine оценка ──
        сурова = 2 + sum(1 for k in у if у[k])
        z["ключови_нива"] = брой_ключови
        z["има_fvg"] = има_fvg
        z["оценка_pine_сурова"] = int(сурова)         # 2..10 — какво БИ било без рязането
        z["оценка_pine"] = int(min(сурова, 7))        # Pine р. 792
        z["име_pine"] = f_име_pine(z["оценка_pine"])
        z["условия"] = у
        # ЗАМРАЗЕНО НА РАЖДАНЕТО — не се пипа никога повече. Само тези полета са
        # годни за статистика и за теста срещу надничане; всичко останало се
        # преизчислява на текущия бар (както Pine), затова СЕ МЕНИ по замисъл.
        z["оценка_раждане_сурова"] = int(сурова)
        z["оценка_раждане"] = int(min(сурова, 7))
        if not надграждане:
            z["статус"] = "ПРЕНОС"
            z["точки"] = z["оценка_pine"]
            z["степен"] = f_степен(z["оценка_pine"])
            z["съвпадения"] = [име for к, име in УСЛОВИЯ[:8] if у.get(к)]
            continue
        # ── НАДГРАЖДАНЕ: 4 нови условия ──
        у["обем"] = bool(z["обем_импулс_отн"] == z["обем_импулс_отн"]
                         and z["обем_импулс_отн"] >= U["обем_праг"])
        у["свип_дълбок"] = bool(z["свип_дълбочина_atr"] >= U["свип_дълбок_atr"])
        у["рамки_2"] = False                      # попълва се по-долу (нужен е целият списък)
        у["история"] = False                      # попълва се от _история()
        z["статус"] = "НОВО · още не е мерено"

    if not надграждане:
        return
    # ── НОВО · съгласие между рамките: жива зона в същата посока, друга рамка, застъпване ──
    родени = np.array([z["родена"] for z in зони])
    мъртви = np.array([z["мъртва"] if z["мъртва"] is not None else 10 ** 12 for z in зони])
    горе = np.array([z["горе"] for z in зони]); долу = np.array([z["долу"] for z in зони])
    бичи = np.array([z["бичи"] for z in зони])
    рам = np.array([z["рамка"] for z in зони])
    for k, z in enumerate(зони):
        i = z["родена"]
        m = (родени <= i) & (мъртви > i) & (бичи == z["бичи"]) & (рам != z["рамка"])
        if m.any():
            z["условия"]["рамки_2"] = bool(
                (np.minimum(z["горе"], горе[m]) >= np.maximum(z["долу"], долу[m])).any())


def _преоцени(z, K, F, P, U, i, надграждане):
    """
    ПРЕОЦЕНКА НА БАР `i` — точно както Pine я прави на ВСЯКА свещ (р. 745-792).
    Замразената оценка от раждането става безполезна веднага щом зоната бъде
    тествана: `tests == 0` е ВИНАГИ вярно на раждането и затова като условие
    е мъртво, ако се смята само там. Тук се преизчислява всичко, което зависи
    от бара: свежест, изядена, FVG, ключови нива, половина, структура, свип.
    Свойствата на самото раждане (рамка, импулс, обем, дълбочина на свипа) не се
    пипат — те са факти за бара, който я е родил.
    """
    тестове = int(np.searchsorted(z["входове"], i, side="right"))
    изядена = z["изядена_от"] is not None and z["изядена_от"] <= i
    atr = K["atr"][i]
    tol = atr * P["ключово_atr"] if not np.isnan(atr) else 0.0
    кл = K["ключови"][:, i]
    брой_ключови = int(np.sum((кл >= z["долу"] - tol) & (кл <= z["горе"] + tol) & ~np.isnan(кл)))
    у = dict(z["условия"])
    у["свежа"] = тестове == 0
    у["fvg"] = _има_fvg(F, i, z["горе"], z["долу"], z["бичи"])
    у["ключово"] = брой_ключови > 0
    у["половина"] = bool(K["дискаунт"][i]) if z["бичи"] else bool(K["премиум"][i])
    у["структура"] = bool(K["посока"][i] == (1 if z["бичи"] else -1))
    у["свип"] = bool(K["свеж_свип_долу"][i]) if z["бичи"] else bool(K["свеж_свип_горе"][i])
    if надграждане and U.get("половина_обърната"):
        # ИЗМЕРЕНО в тази сесия: условието на графиката работи В ОБРАТНАТА посока.
        # По подразбиране НЕ е обърнато — виж бележката при ПАРАМ_НАДГРАЖДАНЕ.
        у["половина"] = not у["половина"]
    z["условия_сега"] = у
    z["тестове"] = тестове
    z["изядена"] = изядена
    z["ключови_нива"] = брой_ключови
    z["има_fvg"] = у["fvg"]
    сурова = 2 + sum(1 for к, _ in УСЛОВИЯ[:8] if у.get(к))
    z["оценка_pine_сурова"] = int(сурова)
    z["оценка_pine"] = int(min(сурова, 7))
    z["име_pine"] = f_име_pine(z["оценка_pine"])
    if надграждане:
        z["точки"] = sum(1 for к, _ in УСЛОВИЯ if у.get(к))
        z["от_условия"] = БРОЙ_УСЛОВИЯ
        z["степен"] = f_степен(z["точки"])
        z["съвпадения"] = [име for к, име in УСЛОВИЯ if у.get(к)]
        z["липсва"] = [име for к, име in УСЛОВИЯ if not у.get(к)]
    else:
        z["точки"] = z["оценка_pine"]
        z["степен"] = f_степен_pine(z["оценка_pine_сурова"])
        z["съвпадения"] = [име for к, име in УСЛОВИЯ[:8] if у.get(к)]
    return z


def _история(зони, U):
    """
    НОВО · причинна историческа задържаемост.
    За зона, родена на бар i, се броят САМО зони, чиято съдба е била известна ПРЕДИ i:
    родени по-рано И решени (първи допир + изход) преди i. Разширяващ се прозорец.
    Кофата е (посока, точки_база 0..11) — точки_база не включва самата история,
    за да няма кръг.
    """
    for z in зони:
        у = z["условия"]
        z["точки_база"] = sum(1 for к, _ in УСЛОВИЯ if к != "история" and у.get(к))
    ред = sorted(range(len(зони)), key=lambda k: зони[k]["родена"])
    # кога изходът на дадена зона става известен
    реш = []
    for k in ред:
        z = зони[k]
        if z["изход"] in ("ЗАДЪРЖА", "ПРОПАДА") and z["първи_допир"] is not None:
            край = z["мъртва"] if z["мъртва"] is not None else z["първи_допир"]
            реш.append((max(край, z["първи_допир"]), k))
    реш.sort()
    брой = {}; удари = {}
    п = 0
    for k in ред:
        z = зони[k]
        i = z["родена"]
        while п < len(реш) and реш[п][0] < i:
            zz = зони[реш[п][1]]
            кл = (zz["бичи"], zz["точки_база"])
            брой[кл] = брой.get(кл, 0) + 1
            удари[кл] = удари.get(кл, 0) + (1 if zz["изход"] == "ЗАДЪРЖА" else 0)
            п += 1
        кл = (z["бичи"], z["точки_база"])
        n_ = брой.get(кл, 0); u_ = удари.get(кл, 0)
        дял = (u_ / n_) if n_ else np.nan
        z["история_n"] = n_
        z["история_задържа"] = дял
        z["условия"]["история"] = bool(n_ >= U["история_мин_n"] and дял >= U["история_праг"])


def _финална_точка(z, U):
    у = z["условия"]
    z["точки"] = sum(1 for к, _ in УСЛОВИЯ if у.get(к))
    z["от_условия"] = БРОЙ_УСЛОВИЯ
    z["степен"] = f_степен(z["точки"])
    z["съвпадения"] = [име for к, име in УСЛОВИЯ if у.get(к)]
    z["липсва"] = [име for к, име in УСЛОВИЯ if not у.get(к)]


def f_по_допири(зони, df: pd.DataFrame, **params) -> dict:
    """
    ПРЯКА ПРОВЕРКА НА ЕДНО ТВЪРДЕНИЕ ОТ ГРАФИКАТА (Pine р. 786: `tests == 0` дава +1).
    Условието „свежа" е мъртво, ако се мери на раждането — там ВСЯКА зона е свежа.
    Затова се мери по друга единица: не зоната, а ВЛИЗАНЕТО в нея.
    За всяко влизане (1-во, 2-ро, 3-то) се пита същото: стигна ли цената +ЦЕЛ$
    в посоката на зоната, преди зоната да бъде пробита.
    """
    U = dict(ПАРАМ_НАДГРАЖДАНЕ); U.update(params)
    d = _подготви(df)
    h = d["high"].to_numpy(float); l = d["low"].to_numpy(float)
    c = d["close"].to_numpy(float); n = len(c)
    от = {}
    for z in зони:
        for k, e in enumerate(list(z.get("входове", []))[:3]):
            e = int(e); i1 = min(n, e + U["хоризонт_барове"])
            if i1 - e < 2:
                continue
            вход = z["горе"] if z["бичи"] else z["долу"]
            цел = вход + U["цел_долари"] if z["бичи"] else вход - U["цел_долари"]
            ц = (h[e:i1] >= цел) if z["бичи"] else (l[e:i1] <= цел)
            сп = (c[e:i1] < z["долу"]) if z["бичи"] else (c[e:i1] > z["горе"])
            kц = int(np.argmax(ц)) if ц.any() else 10 ** 9
            kс = int(np.argmax(сп)) if сп.any() else 10 ** 9
            if kц == kс == 10 ** 9:
                continue
            b = от.setdefault(k + 1, [0, 0])
            b[0] += 1; b[1] += 1 if kц <= kс else 0
    return от


def _статистика(зони):
    """Пълноизвадкова таблица — за ЧЕТЕНЕ, не за решение (в извадката е и бъдещето)."""
    от = {}
    for z in зони:
        if z.get("изход") not in ("ЗАДЪРЖА", "ПРОПАДА"):
            continue
        # САМО замразените стойности от раждането — иначе живите зони биха влезли
        # с оценка от друг бар и таблицата щеше да смесва две различни неща.
        for ключ in (("точки", z.get("точки_раждане", z.get("точки"))),
                     ("оценка_pine", z.get("оценка_раждане", z.get("оценка_pine"))),
                     ("степен", z.get("степен_раждане", z.get("степен")))):
            d = от.setdefault(ключ[0], {})
            b = d.setdefault(ключ[1], [0, 0])
            b[0] += 1; b[1] += 1 if z["изход"] == "ЗАДЪРЖА" else 0
    по_условие = {}
    for к, име in УСЛОВИЯ:
        да = [z for z in зони if z.get("изход") in ("ЗАДЪРЖА", "ПРОПАДА") and z["условия"].get(к)]
        не = [z for z in зони if z.get("изход") in ("ЗАДЪРЖА", "ПРОПАДА") and not z["условия"].get(к)]
        f = lambda s: (len(s), sum(1 for x in s if x["изход"] == "ЗАДЪРЖА") / len(s) if s else np.nan)
        по_условие[име] = dict(с=f(да), без=f(не))
    брой_изходи = {}
    for z in зони:
        брой_изходи[z.get("изход")] = брой_изходи.get(z.get("изход"), 0) + 1
    return dict(по_ключ=от, по_условие=по_условие, изходи=брой_изходи,
                бележка="СУРОВО БРОЕНЕ на изходи, без разходи и без пари. "
                        "НОВО · още не е мерено като стратегия.")


