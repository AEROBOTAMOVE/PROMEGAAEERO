# 3 · КОНТЕКСТЪТ ПО БАРОВЕ (structureDirection, свипове, ключови нива, диапазон)
#     Един-единствен цикъл по баровете, за да е ясно кое кога става известно.
# ═══════════════════════════════════════════════════════════════════════════

def _контекст(d: pd.DataFrame, P: dict) -> dict:
    o = d["open"].to_numpy(float); h = d["high"].to_numpy(float)
    l = d["low"].to_numpy(float);  c = d["close"].to_numpy(float)
    n = len(c)
    atr = _atr(h, l, c, P["atr_период"])

    # ── диапазон / премиум-дискаунт (Pine р. 328-332) ──
    rh = _ролящ_екстремум(h, P["диапазон_барове"], True)
    rl = _ролящ_екстремум(l, P["диапазон_барове"], False)
    среда = (rh + rl) / 2.0
    дискаунт = c < среда
    премиум = c > среда

    # ── пивоти ──
    sp = P["структура_пивот"]; lp = P["ликв_пивот"]
    пв_стр = _пивот(h, sp, sp, True)
    пд_стр = _пивот(l, sp, sp, False)
    пв_ликв = _пивот(h, lp, lp, True)
    пд_ликв = _пивот(l, lp, lp, False)

    посока = np.zeros(n, dtype=np.int8)          # structureDirection
    свеж_свип_горе = np.zeros(n, dtype=bool)
    свеж_свип_долу = np.zeros(n, dtype=bool)
    свип_бар_горе = np.full(n, -1, dtype=np.int64)
    свип_бар_долу = np.full(n, -1, dtype=np.int64)

    посл_връх = np.nan; посл_дъно = np.nan
    стр_посока = 0
    пред_ликв_връх = np.nan; пред_ликв_дъно = np.nan
    ниво_цена = []; ниво_връх = []; ниво_ползвано = []
    посл_свип_г = -1; посл_свип_д = -1
    допуск_пр = P["ликв_допуск_процент"] / 100.0
    макс_нива = P["ликв_макс_страна"] * 2
    свеж = P["свеж_свип_барове"]

    for i in range(n):
        # 1) пивоти, които СЕГА стават известни (потвърждават се R бара по-късно)
        p = i - sp
        if p >= 0:
            if пв_стр[p]:
                посл_връх = h[p]
            if пд_стр[p]:
                посл_дъно = l[p]
        q = i - lp
        if q >= 0:
            if пв_ликв[q]:
                v = h[q]
                if not np.isnan(пред_ликв_връх) and abs(v - пред_ликв_връх) <= c[i] * допуск_пр:
                    ниво_цена.append((v + пред_ликв_връх) / 2.0)
                    ниво_връх.append(True); ниво_ползвано.append(False)
                пред_ликв_връх = v
            if пд_ликв[q]:
                v = l[q]
                if not np.isnan(пред_ликв_дъно) and abs(v - пред_ликв_дъно) <= c[i] * допуск_пр:
                    ниво_цена.append((v + пред_ликв_дъно) / 2.0)
                    ниво_връх.append(False); ниво_ползвано.append(False)
                пред_ликв_дъно = v
            while len(ниво_цена) > макс_нива:      # Pine р. 463: таван 10 ОБЩО
                ниво_цена.pop(0); ниво_връх.pop(0); ниво_ползвано.pop(0)

        # 2) структура (Pine р. 364-397): пробив на последния суинг при затваряне
        if not np.isnan(посл_връх) and c[i] > посл_връх:
            стр_посока = 1
            посл_връх = np.nan                    # р. 387: нивото се ползва веднъж
        if not np.isnan(посл_дъно) and c[i] < посл_дъно:
            стр_посока = -1
            посл_дъно = np.nan
        посока[i] = стр_посока

        # 3) свип на ликвидност (Pine р. 486-504)
        for k in range(len(ниво_цена) - 1, -1, -1):
            if ниво_ползвано[k]:
                continue
            lv = ниво_цена[k]
            if ниво_връх[k]:
                if h[i] > lv and c[i] < lv:
                    ниво_ползвано[k] = True; посл_свип_г = i
            else:
                if l[i] < lv and c[i] > lv:
                    ниво_ползвано[k] = True; посл_свип_д = i
        свип_бар_горе[i] = посл_свип_г
        свип_бар_долу[i] = посл_свип_д
        свеж_свип_горе[i] = посл_свип_г >= 0 and i - посл_свип_г <= свеж
        свеж_свип_долу[i] = посл_свип_д >= 0 and i - посл_свип_д <= свеж

    # ── ключови нива (Pine р. 273-286) ──
    idx = d.index
    ден = pd.Series(idx.floor("D"), index=idx)
    dh = d["high"].groupby(ден.values).max(); dl = d["low"].groupby(ден.values).min()
    pdh = ден.map(dh.shift(1)).to_numpy(float)
    pdl = ден.map(dl.shift(1)).to_numpy(float)
    сед = pd.Series((idx - pd.to_timedelta(idx.dayofweek, unit="D")).floor("D"), index=idx)
    wh = d["high"].groupby(сед.values).max(); wl = d["low"].groupby(сед.values).min()
    pwh = сед.map(wh.shift(1)).to_numpy(float)
    pwl = сед.map(wl.shift(1)).to_numpy(float)

    # азиатски диапазон 03:00-11:00 София (Pine р. 277-285) — текущ, не предишен
    try:
        мест = idx.tz_localize("UTC").tz_convert("Europe/Sofia") if idx.tz is None \
            else idx.tz_convert("Europe/Sofia")
        в_азия = (мест.hour >= 3) & (мест.hour < 11)
        азия_ден = pd.Series(мест.floor("D").tz_localize(None), index=idx)
    except Exception:
        в_азия = np.zeros(n, dtype=bool)
        азия_ден = pd.Series(idx.floor("D"), index=idx)
    hs = pd.Series(np.where(в_азия, h, np.nan), index=idx)
    ls = pd.Series(np.where(в_азия, l, np.nan), index=idx)
    ah = hs.groupby(азия_ден.values).cummax().ffill().to_numpy(float)
    al = ls.groupby(азия_ден.values).cummin().ffill().to_numpy(float)

    return dict(o=o, h=h, l=l, c=c, atr=atr, n=n, времена=idx.to_numpy(),
                среда=среда, дискаунт=дискаунт, премиум=премиум,
                посока=посока, свеж_свип_горе=свеж_свип_горе, свеж_свип_долу=свеж_свип_долу,
                свип_бар_горе=свип_бар_горе, свип_бар_долу=свип_бар_долу,
                ключови=np.vstack([pdh, pdl, pwh, pwl, ah, al]))


