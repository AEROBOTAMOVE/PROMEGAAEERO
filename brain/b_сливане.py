# 6 · ГЛАВНАТА ВРАТА
# ═══════════════════════════════════════════════════════════════════════════

def f_сливане(d: pd.DataFrame, R: dict, *, праг_карта: int = ПРАГ_ПРАЩАНЕ,
              решавай_спора: bool = True) -> list[dict]:
    """
    d : прозорецът барове ДО и ВКЛЮЧИТЕЛНО текущия ЗАТВОРЕН бар (без бъдеще).
    R : речник с вече пресметнатите резултати на 7-те блока:
        {"свип":…, "ликвидност":…, "гапове":…, "зони":…, "структура":…,
         "обем":{"отн_сега":float,"последен_скок":dict}, "диапазон":…}
    Връща списък карти (обикновено 0 или 1; рядко 2 при сблъсък на посоки).
    """
    a = _atr(d)
    поводи = _поводи(len(d) - 1, d, R)
    if not поводи:
        return []

    карти = []
    for лонг in (True, False):
        if not any(p["лонг"] == лонг for p in поводи):
            continue
        точки, съвпаднали, всички, сурови = _брои(лонг, поводи, d, R, a)
        степен, ранг = f_степен(точки)
        if точки < праг_карта:
            continue    # ✨ ИСКРА не се праща — влиза само в дневника
        з = _залог(лонг, поводи, d, R, a)
        карти.append(dict(
            бар=len(d) - 1,
            време=d.index[-1] if isinstance(d.index, pd.DatetimeIndex) else None,
            посока=_посока_текст(лонг),
            лонг=лонг,
            точки=точки, макс=МАКС_ТОЧКИ, степен=степен, ранг=ранг,
            съвпаднали=съвпаднали,
            всички_условия=всички,
            сурови=сурови,      # непревърнати мерки — за прескалиране без нов обход
            поводи=[p["вид"] for p in поводи if p["лонг"] == лонг],
            повод_текст=[p["текст"] for p in поводи if p["лонг"] == лонг],
            залог=з,
            atr=round(a, 2) if np.isfinite(a) else None,
            цена=round(float(d["close"].to_numpy(float)[-1]), 2),
            статус="НОВО · още не е мерено",
        ))

    # ── СПОРЪТ · ако и двете посоки палят на един бар ───────────────────────
    # Две противоположни карти в един и същи миг са шум, не информация.
    # По-силната печели; при равенство не се праща НИЩО — равният спор е
    # честен отговор „не знам", а не повод да се хвърли ези-тура.
    if len(карти) == 2 and решавай_спора:
        a, b = карти
        if a["точки"] == b["точки"]:
            for к in карти:
                к["спор"] = "равен — не се праща"
            return []
        победител = a if a["точки"] > b["точки"] else b
        губещ = b if победител is a else a
        победител["спор"] = (f"насрещна {губещ['посока']} карта със "
                             f"{губещ['точки']} т. — отхвърлена")
        return [победител]
    return карти
