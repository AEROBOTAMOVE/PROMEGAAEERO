def _брои(лонг: bool, поводи: list, d: pd.DataFrame, R: dict, a: float) -> tuple:
    """
    Връща (точки, съвпаднали, всички_условия, сурови_мерки) за ЕДНА посока.
    Всяко условие е ДА/НЕ. Никъде няма преценка — само сравнение с праг.
    „Стъпалата" (B1b, V1b, D2b, J1b, Z2b) са ОТДЕЛНИ условия върху същата
    мярка с по-строг праг — така една силна мярка носи 2 точки вместо 1,
    без да се въвежда плаваща оценка, която не се проверява с броене.
    """
    у: dict[str, bool] = {к: False for к in ТАБЛИЦА}
    посл = len(d) - 1
    цена = float(d["close"].to_numpy(float)[посл])

    мои = [p for p in поводи if p["лонг"] == лонг]

    # ── А · поводите ───────────────────────────────────────────────────────
    свип_обект = None
    for p in мои:
        if p["вид"] == "свип":
            у["A1_повод_свип"] = True; свип_обект = p["обект"]
        elif p["вид"] == "структура":
            у["A2_повод_структура"] = True
        elif p["вид"] == "зона":
            у["A3_повод_зона"] = True
        elif p["вид"] == "гап":
            у["A4_повод_гап"] = True
    if not мои:
        return 0, {}, у, {}

    # ── Б · силата на свипа (само ако има свип) ────────────────────────────
    if свип_обект is not None:
        дълб = float(свип_обект.get("дълбочина_atr") or 0)
        у["B1_пробождане"] = дълб >= 0.30
        у["B1b_дълбоко"] = дълб >= 0.60
        у["B2_върнат"] = float(свип_обект.get("връщане_дял") or 0) >= 0.28
        у["B3_защитавано"] = (int(свип_обект.get("пипания_преди") or 0) >= 1
                              or int(свип_обект.get("сила_ниво") or 0) >= 3)

    # ── В · ликвидност ─────────────────────────────────────────────────────
    L = R["ликвидност"] or {}
    нива = L.get("нива", []) or []
    # V1: обраното (или най-близкото в гърба ни) ниво е от 3+ допира
    гръб = "дъно" if лонг else "връх"
    свои = [x for x in нива if x.get("вид") == гръб]
    if свои:
        най = min(свои, key=lambda x: abs(x.get("разстояние_atr") or 99))
        доп = int(най.get("допири") or 0)
        у["V1_троен_допир"] = доп >= 3
        у["V1b_четворен"] = доп >= 4
    # V2: цел пред нас на ≤3 ATR
    цел_вид = "връх" if лонг else "дъно"
    цели = [x for x in нива if x.get("вид") == цел_вид and not x.get("обран")]
    напред = [x for x in цели if (x["цена"] > цена if лонг else x["цена"] < цена)]
    у["V2_цел_наблизо"] = any((x.get("разстояние_atr") or 99) <= 3.0 for x in напред)

    # ── Г · гапове ─────────────────────────────────────────────────────────
    G = R["гапове"] or {}
    искан = "бичи" if лонг else "мечи"
    вътре = [x for x in (G.get("гапове") or [])
             if not x.get("запълнен") and x.get("вид") == искан
             and x.get("долу") is not None and цена is not None
             and x["долу"] <= цена <= x["горе"]]
    if вътре:
        у["G1_в_гап"] = True
        у["G2_висока_рамка"] = any(float(x.get("тежест") or 0) >= 2.0 for x in вътре)
        у["G3_едър_гап"] = any(float(x.get("размер_atr") or 0) >= 1.5 for x in вътре)

    # ── Д · зони ───────────────────────────────────────────────────────────
    Z = R["зони"] or {}
    искана = "КУПУВА" if лонг else "ПРОДАВА"
    в_зона = [x for x in (Z.get("зони") or [])
              if x.get("посока") == искана and x.get("причина") == "жива"
              and x.get("долу") is not None and цена is not None
              and x["долу"] <= цена <= x["горе"]]
    if в_зона:
        у["D1_в_зона"] = True
        у["D2_силна"] = any(int(x.get("оценка_pine") or 0) >= 6 for x in в_зона)
        у["D2b_най_силна"] = any(int(x.get("оценка_pine") or 0) >= 7 for x in в_зона)
        у["D3_непипана"] = any(int(x.get("тестове") or 0) == 0 for x in в_зона)

    # ── Е · структура ──────────────────────────────────────────────────────
    S = (R["структура"] or {}).get("структура", {}) or {}
    знак = 1 if лонг else -1
    у["E1_съгласна"] = int(S.get("посока") or 0) == знак
    у["E2_пробив_пресен"] = bool(S.get("пресен_бик_пробив") if лонг
                                 else S.get("пресен_мечи_пробив"))
    ске = S.get("скелет") or ""
    у["E3_скелет"] = (ске == "HH/HL") if лонг else (ске == "LH/LL")
    у["E4_серия"] = int((S.get("серия_нагоре") if лонг
                         else S.get("серия_надолу")) or 0) >= 2

    # ── Ж · обеми ──────────────────────────────────────────────────────────
    V = R["обем"] or {}
    отн = V.get("отн_сега")
    има_обем = отн is not None and np.isfinite(отн)
    у["J1_обем_над"] = има_обем and отн >= 1.5
    у["J1b_обем_голям"] = има_обем and отн >= 2.5
    посл_скок = V.get("последен_скок")
    if посл_скок and посл_скок.get("бар") is not None:
        пресен = (посл - int(посл_скок["бар"])) <= 3
        съгл = посл_скок.get("посока") == ("НАГОРЕ" if лонг else "НАДОЛУ")
        у["J2_скок"] = bool(пресен and съгл)

    # ── З · диапазон ───────────────────────────────────────────────────────
    D = R["диапазон"] or {}
    искана_страна = "ДИСКАУНТ" if лонг else "ПРЕМИУМ"
    у["Z1_дискаунт_премиум"] = (D.get("посока") == искана_страна)
    съгл = D.get("съгласие") or {}
    водеща_съгласна = (съгл.get("водеща") == искана_страна)
    у["Z2_хоризонти"] = водеща_съгласна and int(съгл.get("мнозинство") or 0) >= 5
    у["Z2b_единодушно"] = водеща_съгласна and bool(съгл.get("единодушно"))
    об = D.get("обем") or {}
    у["Z3_извън_стойността"] = bool(об.get("изместена_надолу") if лонг
                                    else об.get("изместена_нагоре"))

    # ── СУРОВИТЕ МЕРКИ ─────────────────────────────────────────────────────
    # Пазят се НЕПРЕВЪРНАТИ в точки, за да може таблицата да се прескалира
    # после, без да се пуска наново целият скъп обход. Първата версия пазеше
    # само ДА/НЕ и всяка промяна в праговете искаше нови 25 минути.
    сур = dict(
        свип_дълбочина_atr=float(свип_обект.get("дълбочина_atr") or 0) if свип_обект else None,
        свип_връщане=float(свип_обект.get("връщане_дял") or 0) if свип_обект else None,
        свип_пипания=int(свип_обект.get("пипания_преди") or 0) if свип_обект else None,
        свип_сила_ниво=int(свип_обект.get("сила_ниво") or 0) if свип_обект else None,
        свип_обем=float(свип_обект.get("обем_кратно") or 0) if свип_обект else None,
        # ВАЖНО: допирите на НАЙ-БЛИЗКОТО ниво, не максимумът по всички.
        # Първата версия пазеше максимума по ~40 живи нива — той е почти винаги
        # ≥3, тоест условието палеше винаги и не носеше информация.
        ликв_допири=(int(min(свои, key=lambda x: abs(x.get("разстояние_atr") or 99))
                         .get("допири") or 0) if свои else 0),
        ликв_цел_atr=min([float(x.get("разстояние_atr") or 99)
                          for x in (напред if цена is not None else [])], default=None),
        гап_брой=len(вътре),
        гап_размер_atr=max([float(x.get("размер_atr") or 0) for x in вътре], default=0.0),
        гап_тежест=max([float(x.get("тежест") or 0) for x in вътре], default=0.0),
        зона_брой=len(в_зона),
        зона_оценка=max([int(x.get("оценка_pine") or 0) for x in в_зона], default=0),
        зона_тестове=min([int(x.get("тестове") or 0) for x in в_зона], default=None),
        стр_посока=int(S.get("посока") or 0),
        стр_серия=int((S.get("серия_нагоре") if лонг else S.get("серия_надолу")) or 0),
        стр_скелет=S.get("скелет"),
        обем_отн=float(отн) if (отн is not None and np.isfinite(отн)) else None,
        диап_посока=D.get("посока"),
        диап_мнозинство=int(съгл.get("мнозинство") or 0),
        диап_водеща=съгл.get("водеща"),
        диап_единодушно=bool(съгл.get("единодушно")),
        брой_поводи=len(мои),
    )

    # ── СБОР С ТАВАН ПО ГРУПА ──────────────────────────────────────────────
    по_група: dict[str, int] = {}
    for к, вярно in у.items():
        if not вярно:
            continue
        тегло, гр, _ = ТАБЛИЦА[к]
        по_група[гр] = по_група.get(гр, 0) + тегло
    точки = sum(min(с, ТАВАН_ГРУПА[гр]) for гр, с in по_група.items())

    съвпаднали = {к: ТАБЛИЦА[к][2] for к, в in у.items() if в}
    return int(точки), съвпаднали, у, сур


