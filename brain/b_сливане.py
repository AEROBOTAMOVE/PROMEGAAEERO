def _atr(df: pd.DataFrame, n: int = 14) -> float:
    h = df["high"].to_numpy(float); l = df["low"].to_numpy(float)
    c = df["close"].to_numpy(float)
    if len(c) < n + 2:
        return float("nan")
    пр = np.maximum(h[1:] - l[1:], np.maximum(np.abs(h[1:] - c[:-1]),
                                              np.abs(l[1:] - c[:-1])))
    a = пр[:n].mean()
    for x in пр[n:]:
        a = (a * (n - 1) + x) / n
    return float(a)


