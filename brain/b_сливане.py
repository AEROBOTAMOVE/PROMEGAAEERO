def _поводи(i: int, d: pd.DataFrame, R: dict) -> list[dict]:
    """
    Кои събития се случиха ИМЕННО на бар i. Всеки повод носи посока.
    БЕЗ НАДНИЧАНЕ: всяко събитие се взима по неговия собствен `бар`, който
    блоковете вече поставят на бара на ПОТВЪРЖДЕНИЕТО, не на пивота.
    """
    п = []
    n = len(d)
    посл = n - 1
    c = d["close"].to_numpy(float)
    h = d["high"].to_numpy(float)
    l = d["low"].to_numpy(float)

    # ── А1 · свип на този бар ──────────────────────────────────────────────
    for с in (R["свип"] or {}).get("свипове", []):
        if с.get("бар") == посл:
            п.append(dict(вид="свип", лонг=(с.get("посока") == "ДОЛУ"), обект=с,
                          текст=с.get("текст", "")))

    # ── А2 · структурно събитие на този бар ────────────────────────────────
    for е in (R["структура"] or {}).get("събития", []):
        if е.get("бар") != посл:
            continue
        в = е.get("вид", "")
        if в in ("BOS", "CHOCH", "CHoCH", "РЕТЕСТ_ЗАДЪРЖА"):
            п.append(dict(вид="структура", лонг=(е.get("посока", 0) > 0),
                          обект=е, текст=е.get("текст", в)))

    # ── А3 · влизане в зона на този бар ────────────────────────────────────
    # „Влизане" = този бар е пипнал зоната, а предишният е бил ИЗВЪН нея.
    for з in (R["зони"] or {}).get("зони", []):
        if з.get("причина") != "жива":
            continue
        г, до = з.get("горе"), з.get("долу")
        if г is None or до is None or посл < 1:
            continue
        сега_вътре = (l[посл] <= г) and (h[посл] >= до)
        преди_вътре = (l[посл - 1] <= г) and (h[посл - 1] >= до)
        if сега_вътре and not преди_вътре:
            п.append(dict(вид="зона", лонг=(з.get("посока") == "КУПУВА"),
                          обект=з,
                          текст=f"вход в {з.get('име_pine','')} зона {з.get('рамка','')}"))

    # ── А4 · влизане в незапълнен гап на този бар ──────────────────────────
    # ИЗМЕРЕНО в пробния обход: без филтър гапът пали 11 от 24 пъти — защото
    # живите гапове са 70 и цената постоянно влиза в някой. Затова поводът
    # иска ЗНАЧИМ гап: от рамка ≥1 час (тежест ≥2) и с размер ≥0.5 ATR.
    # Малките 15-минутни гапове остават в БРОЕНЕТО (Г1/Г2), но не раждат карта.
    най_гап: dict = {}          # посока → най-едрият влязъл гап (един повод на посока)
    for г in (R["гапове"] or {}).get("гапове", []):
        if г.get("запълнен") or float(г.get("тежест") or 0) < 2.0:
            continue
        if float(г.get("размер_atr") or 0) < 0.5:
            continue
        гор, дол = г.get("горе"), г.get("долу")
        if гор is None or дол is None or посл < 1:
            continue
        сега_вътре = (l[посл] <= гор) and (h[посл] >= дол)
        преди_вътре = (l[посл - 1] <= гор) and (h[посл - 1] >= дол)
        if not (сега_вътре and not преди_вътре):
            continue
        лонг = (г.get("вид") == "бичи")
        стар = най_гап.get(лонг)
        if стар is None or float(г.get("размер_atr") or 0) > float(стар.get("размер_atr") or 0):
            най_гап[лонг] = г
    for лонг, г in най_гап.items():
        п.append(dict(вид="гап", лонг=лонг, обект=г,
                      текст=f"вход в {г.get('вид','')} гап {г.get('рамка','')} "
                            f"({г.get('размер_atr')} ATR)"))
    return п


