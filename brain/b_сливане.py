# 5 · СЛОЙ 2 · ЗАЛОГЪТ (вход / стоп / цел)
# ═══════════════════════════════════════════════════════════════════════════

# ОДИТ-41 · граници на стопа в ATR. Мерено на 102 истински сетъпа: без долна
# граница 36% от стоповете са под 0.5× ATR — шум, който изгаря сметката.
# Разширяването до 1.0× ATR не губи нито един сетъп (ср. R:R остава 4.0).
МИН_СТОП_ATR = float(_os.environ.get("МИН_СТОП_ATR", "1.0"))
МАКС_СТОП_ATR = float(_os.environ.get("МАКС_СТОП_ATR", "3.0"))


def _залог(лонг: bool, поводи: list, d: pd.DataFrame, R: dict, a: float) -> dict:
    """
    Вход = затварянето на бара-повод (така се вижда на живо, без гадаене).
    Стоп = отвъд екстремума на повода + буфер 0.25 ATR.
    Цел  = първата ликвидна цел пред нас; ако няма — 2R.
    """
    посл = len(d) - 1
    c = float(d["close"].to_numpy(float)[посл])
    h = float(d["high"].to_numpy(float)[посл])
    l = float(d["low"].to_numpy(float)[посл])
    буфер = 0.25 * a if np.isfinite(a) else 1.0

    мои = [p for p in поводи if p["лонг"] == лонг]
    свипове = [p for p in мои if p["вид"] == "свип"]
    ако_свип = свипове[0]["обект"] if свипове else None

    if ако_свип is not None:
        екстр = float(ако_свип.get("екстремум"))
        стоп = екстр - буфер if лонг else екстр + буфер
    else:
        стоп = l - буфер if лонг else h + буфер

    риск = abs(c - стоп)
    # 🔴 ОДИТ-41 · СТОПЪТ БЕШЕ ТВЪРДЕ ТЕСЕН И ВСИЧКО ГОРЕШЕ.
    # Собственикът, 18-ия час: «много малки стопове и всичко гори».
    # МЕРЕНО върху 102 истински сетъпа (2000 бара, 15м):
    #     медиана 0.69× ATR · 36% под 0.5× ATR · 16% под 3$
    # Стоп от 3$ на злато при ATR 8$ не е стоп, а шум — цената го минава
    # в рамките на един бар, без сетъпът да се е провалил.
    # Старата защита се палеше чак под 0.05× ATR (0.4$!) — практически никога.
    #
    # МЕРЕНО КОЛКО СТРУВА ПОПРАВКАТА (същите 102 сетъпа):
    #     мин 0.0× → ср. стоп  8.38$ · ср. R:R 7.6 · 2 сетъпа под 1:1
    #     мин 1.0× → ср. стоп 11.47$ · ср. R:R 4.0 · 2 сетъпа под 1:1
    # Тоест разширяването НЕ губи нито един сетъп — само маха шума.
    # Таванът пази обратното: стоп над 3× ATR значи, че сетъпът е разлят
    # и «прецизен вход» е самозаблуда.
    if np.isfinite(a) and a > 0:
        риск = min(max(риск, МИН_СТОП_ATR * a), МАКС_СТОП_ATR * a)
        стоп = c - риск if лонг else c + риск
    elif риск <= 0:
        риск = 1.0
        стоп = c - риск if лонг else c + риск

    # ── ЦЕЛТА = ПЪРВАТА ПРЕЧКА ПРЕД НАС, не най-далечната мечта ────────────
    # Търговецът се цели в следващото препятствие. Три вида препятствия:
    #   1) непобрана ликвидност (връх при лонг / дъно при късо)
    #   2) насрещна зона (ПРОДАВА при лонг) — близкият ѝ ръб
    #   3) насрещен незапълнен гап (мечи при лонг) — близкият му ръб
    # Взима се НАЙ-БЛИЗКАТА. Така съотношението спира да е измислено:
    # първата версия връщаше 12.44R, защото гледаше само ликвидност на 50$.
    # ЗНАЧИМА пречка, не всяка. Първата версия вземаше НАЙ-БЛИЗКИЯ ръб на кой
    # да е от ~70-те живи гапа — той е почти винаги на 4–5$ и трите примерни
    # карти излязоха със съотношение под 1:1, включително една 💎. Дребният гап
    # на 5$ не е цел, а шум. Затова: пречката трябва да е поне 0.5 ATR напред,
    # а гаповете и зоните — да са значими (същия филтър като за повод).
    праг = 0.5 * a if np.isfinite(a) else 0.5
    напред_ли = lambda p: (p > c + праг) if лонг else (p < c - праг)
    кандидати = []

    L = R["ликвидност"] or {}
    цел_вид = "връх" if лонг else "дъно"
    for x in (L.get("нива") or []):
        if x.get("вид") == цел_вид and not x.get("обран") and напред_ли(x["цена"]):
            кандидати.append((float(x["цена"]), "ликвидност"))

    Z = R["зони"] or {}
    насрещна = "ПРОДАВА" if лонг else "КУПУВА"
    for z in (Z.get("зони") or []):
        if z.get("посока") != насрещна or z.get("причина") != "жива":
            continue
        if int(z.get("оценка_pine") or 0) < 5:      # слабите зони не спират цената
            continue
        ръб = z.get("долу") if лонг else z.get("горе")
        if ръб is not None and напред_ли(ръб):
            кандидати.append((float(ръб), "насрещна зона"))

    G = R["гапове"] or {}
    насрещен = "мечи" if лонг else "бичи"
    for g in (G.get("гапове") or []):
        if g.get("запълнен") or g.get("вид") != насрещен:
            continue
        if float(g.get("тежест") or 0) < 2.0 or float(g.get("размер_atr") or 0) < 0.5:
            continue
        ръб = g.get("долу") if лонг else g.get("горе")
        if ръб is not None and напред_ли(ръб):
            кандидати.append((float(ръб), "насрещен гап"))

    кандидати.sort(key=lambda t: abs(t[0] - c))
    if кандидати:
        цел, основа_цел = кандидати[0]
    else:
        цел = c + 2 * риск if лонг else c - 2 * риск
        основа_цел = "2R (няма значима пречка напред)"
    # ВТОРА ЦЕЛ · следващата пречка отвъд първата, иначе 2× първата награда.
    # Ботът и без това работи със стълба 1/3, така че две цели са естествени.
    ако_втора = [к for к in кандидати[1:] if abs(к[0] - c) > abs(цел - c) * 1.2]
    if ако_втора:
        цел2, основа_цел2 = ако_втора[0]
    else:
        цел2 = c + 2 * abs(цел - c) * (1 if лонг else -1)
        основа_цел2 = "2× първата цел (няма втора пречка)"

    награда = abs(цел - c)
    награда2 = abs(цел2 - c)
    return dict(вход=round(c, 2), стоп=round(стоп, 2), цел=round(цел, 2),
                риск=round(риск, 2), награда=round(награда, 2),
                съотношение=round(награда / риск, 2) if риск > 0 else None,
                основа_цел=основа_цел,
                цел2=round(цел2, 2), награда2=round(награда2, 2),
                съотношение2=round(награда2 / риск, 2) if риск > 0 else None,
                основа_цел2=основа_цел2)


