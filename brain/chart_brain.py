_ИМЕНА = {"open": "open", "high": "high", "low": "low", "close": "close",
          "volume": "volume", "vol": "volume", "adj close": "close",
          "o": "open", "h": "high", "l": "low", "c": "close", "v": "volume"}


def _подготви(df, име_рамка: str = "") -> tuple[pd.DataFrame | None, list[str]]:
    """
    Прави от какъвто и да е DataFrame такъв, какъвто блоковете могат да ядат.
    Връща (df или None, списък бележки). НИКОГА не хвърля.

    ЗАЩО СЪЩЕСТВУВА (проверено в тази сесия, не предположено):
      · NaN в close на последния бар → `b_ликвидност` вдига
        ValueError: arange: cannot compute length
      · същият вход → `b_диапазон` вдига
        ValueError: cannot convert float NaN to integer
    Двата блока умират, а живият фийд дава NaN при дупка в котировките.
    """
    бел: list[str] = []
    if df is None:
        return None, [f"{име_рамка}: няма данни"]
    try:
        d = df.copy()
    except Exception:
        return None, [f"{име_рамка}: не се копира"]

    # ── имената на колоните (Open/OPEN/open → open) ────────────────────────
    прекр = {}
    for к in list(d.columns):
        н = _ИМЕНА.get(str(к).strip().lower())
        if н and н not in прекр.values():
            прекр[к] = н
    d = d.rename(columns=прекр)
    липсват = [к for к in ("open", "high", "low", "close") if к not in d.columns]
    if липсват:
        return None, [f"{име_рамка}: липсват колони {липсват}"]
    d = d[[к for к in ("open", "high", "low", "close", "volume") if к in d.columns]]

    # ── числа, не текст ────────────────────────────────────────────────────
    for к in d.columns:
        d[к] = pd.to_numeric(d[к], errors="coerce")

    # ── индексът: време, подреден, без дубликати ───────────────────────────
    if not isinstance(d.index, pd.DatetimeIndex):
        try:
            d.index = pd.DatetimeIndex(d.index)
        except Exception:
            бел.append(f"{име_рамка}: индексът не е време — рамковите проверки мълчат")
    if isinstance(d.index, pd.DatetimeIndex):
        if not d.index.is_monotonic_increasing:
            d = d.sort_index()
            бел.append(f"{име_рамка}: барове в разбъркан ред — подредени")
        дубл = d.index.duplicated(keep="last")
        if дубл.any():
            d = d[~дубл]
            бел.append(f"{име_рамка}: {int(дубл.sum())} дублирани времена — махнати")

    # ── редовете с дупки в цената НЕ минават нататък ───────────────────────
    преди = len(d)
    d = d.dropna(subset=["open", "high", "low", "close"])
    if len(d) < преди:
        бел.append(f"{име_рамка}: {преди - len(d)} бара с празна цена — изхвърлени")

    # ── безсмислени барове (high < low, нулева/отрицателна цена) ───────────
    лош = (d["high"] < d["low"]) | (d["close"] <= 0) | (~np.isfinite(d["close"]))
    if лош.any():
        d = d[~лош]
        бел.append(f"{име_рамка}: {int(лош.sum())} невъзможни бара — изхвърлени")

    if "volume" in d.columns:
        v = pd.to_numeric(d["volume"], errors="coerce")
        if not np.isfinite(v.to_numpy(float)).any() or float(np.nansum(v.to_numpy(float))) <= 0:
            d = d.drop(columns=["volume"])
            бел.append(f"{име_рамка}: обемът е празен — групата ОБЕМИ ще мълчи")
        else:
            d["volume"] = v.fillna(0.0)

    if len(d) < МИН_БАРОВЕ:
        бел.append(f"{име_рамка}: само {len(d)} бара (искат се {МИН_БАРОВЕ}) — прескочена")
        return None, бел
    return d, бел


def _отрежи_незатворен(d: pd.DataFrame, име_рамка: str, сега) -> tuple[pd.DataFrame, bool]:
    """
    Т2 · маха последния бар, ако още се формира.

    ЗАЩО: блоковете смятат последния подаден бар за ЗАТВОРЕН. Условието на свипа
    е `high > ниво И close < ниво` — докато свещта расте, `high > ниво` веднъж
    вярно ОСТАВА вярно, а `close < ниво` се обръща. Сигнал, който изчезва.
    Ботът ресемплва 5м→15м, тоест последният бар е полуготов почти винаги.
    """
    if not isinstance(d.index, pd.DatetimeIndex) or len(d) < 2 or сега is None:
        return d, False
    мин = МИНУТИ.get(име_рамка)
    if мин is None:
        раз = pd.Series(d.index[-50:]).diff().dropna()
        if раз.empty:
            return d, False
        мин = max(1, int(round(раз.median().total_seconds() / 60)))
    try:
        t_сега = pd.Timestamp(сега)
        посл = d.index[-1]
        зона = getattr(посл, "tz", None)
        # часовите пояси трябва да СЪВПАДНАТ, иначе сравнението гърми мълчаливо
        if зона is not None:
            t_сега = (t_сега.tz_localize("UTC") if t_сега.tz is None
                      else t_сега).tz_convert(зона)
        elif t_сега.tz is not None:
            t_сега = t_сега.tz_convert("UTC").tz_localize(None)
        if t_сега < посл + pd.Timedelta(minutes=мин):
            return d.iloc[:-1], True
    except Exception:
        return d, False
    return d, False


