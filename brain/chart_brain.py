def самопроверка(df15: pd.DataFrame | None = None) -> dict:
    """
    Бърза проверка, че мозъкът е жив и не наднича. Връща речник с резултати.
    Без реални данни прави каквото може с подадения df; ако няма — синтетични.
    """
    рез = {}
    if df15 is None:
        n = 700
        rng = np.random.default_rng(7)
        c = 2000 + np.cumsum(rng.normal(0, 1.2, n))
        df15 = pd.DataFrame({"open": c, "high": c + 1.5, "low": c - 1.5, "close": c,
                             "volume": rng.uniform(1, 3, n)},
                            index=pd.date_range("2024-01-01", periods=n, freq="15min"))
    # 1 · не гърми на мръсен вход
    мръсен = df15.copy()
    мръсен.iloc[-1, мръсен.columns.get_loc("close")] = np.nan
    try:
        сканирай({"15м": мръсен})
        рез["мръсен_вход"] = "ОК"
    except Exception as e:
        рез["мръсен_вход"] = f"СРИВ {type(e).__name__}: {e}"
    # 2 · празно / късо
    for име, вход in (("празен", pd.DataFrame()), ("нищо", None),
                      ("къс", df15.iloc[:10])):
        try:
            сканирай({"15м": вход})
            рез[име] = "ОК"
        except Exception as e:
            рез[име] = f"СРИВ {type(e).__name__}: {e}"
    # 3 · надничане — резултатът при T не бива да зависи от баровете след T
    if len(df15) >= МИН_БАРОВЕ + 60:
        реж = len(df15) - 30
        a = сканирай({"15м": df15.iloc[:реж]})
        b_ = сканирай({"15м": df15.iloc[:реж]})   # детерминизъм
        рез["детерминизъм"] = "ОК" if _отпечатък(a) == _отпечатък(b_) else "РАЗЛИЧЕН"
    return рез


def _отпечатък(сетъпи: list) -> list:
    """Сравнимият скелет на резултата — за тестовете за надничане."""
    return sorted([(с["рамка"], str(с.get("време")), с["посока"], с["точки"],
                    с["степен"], с["ниво"], с["вход"], с["стоп"], с["цел"])
                   for с in сетъпи])
