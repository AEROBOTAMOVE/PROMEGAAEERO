def _прочети(d: pd.DataFrame, име_рамка: str = "15м") -> tuple[dict, dict, dict]:
    """
    Пуска седемте блока върху ЕДИН прозорец. Връща (R, времена_мс, грешки).
    Блок, който гръмне, НЕ поваля останалите — влиза като None и се отбелязва.
    """
    # `b_ликвидност` проверява нивата срещу рамки 1ч и 4ч. На 15-минутен прозорец
    # това е истинска проверка — ИЗМЕРЕНО в тази сесия: точката я взимат 8% от
    # нивата (+0.08 средни точки). Но пуснат върху 1-ЧАСОВ прозорец, «провери
    # срещу 1ч» е тъждествено преоразмеряване: точката я взимат 100% (+1.00) —
    # всяко ниво потвърждава само себе си. Затова на рамки ≥1 час се изключва.
    мин = МИНУТИ.get(име_рамка, 15)
    _mtf = ("1h", "4h") if мин < 60 else None
    R: dict = {}
    вр: dict = {}
    гр: dict = {}

    def пусни(име, fn):
        t = time.perf_counter()
        try:
            r = fn()
        except Exception as e:
            гр[име] = f"{type(e).__name__}: {str(e)[:120]}"
            r = None
        вр[име] = round((time.perf_counter() - t) * 1000)
        return r

    R["свип"] = пусни("свип", lambda: B1.f_свипове(d))
    R["ликвидност"] = пусни("ликвидност", lambda: B2.f_ликвидност(d, mtf=_mtf))
    R["гапове"] = пусни("гапове", lambda: B3.f_гапове(d, lookback=min(1000, len(d) - 5)))
    R["зони"] = пусни("зони", lambda: B4.f_зони(d))
    R["структура"] = пусни("структура", lambda: B5.f_структура(d))
    R["диапазон"] = пусни("диапазон", lambda: B7.f_диапазон(d))

    def обем():
        if "volume" not in d.columns:
            return {"отн_сега": float("nan"), "последен_скок": None}
        ск = B6.f_обемен_скок(d)
        отн = B6.f_относителен_обем(d)
        о = отн.get("отн")
        return {"отн_сега": float(о[-1]) if о is not None and len(о) else float("nan"),
                "последен_скок": ск.get("последен")}
    R["обем"] = пусни("обем", обем) or {"отн_сега": float("nan"), "последен_скок": None}
    return R, вр, гр


def _ниво_на_повода(вид: str, обект: dict) -> float | None:
    """НИВОТО, което собственикът гледа на екрана — според вида на повода."""
    if обект is None:
        return None
    if вид == "свип":
        return _чис(обект.get("ниво"))
    if вид == "структура":
        return _чис(обект.get("ниво"))
    for двойка in (("горе", "долу"),):
        г, д = обект.get(двойка[0]), обект.get(двойка[1])
        if г is not None and д is not None:
            return round((float(г) + float(д)) / 2, 3)
    return _чис(обект.get("среда"))


def _чис(x):
    try:
        v = float(x)
        return round(v, 3) if np.isfinite(v) else None
    except Exception:
        return None


def _барове_между(t1, t2, минути_на_бар: int):
    """Колко бара делят два момента. None, ако времената не се сравняват."""
    try:
        a, b = pd.Timestamp(t1), pd.Timestamp(t2)
        if (a.tz is None) != (b.tz is None):     # едното с пояс, другото без
            a = a.tz_localize(None) if a.tz is not None else a
            b = b.tz_localize(None) if b.tz is not None else b
        return int((b - a).total_seconds() // (60 * max(1, минути_на_бар)))
    except Exception:
        return None


def _липсващи_групи(всички: dict) -> list[str]:
    имена = KT.ГРУПИ_ИМЕ
    има = set()
    for к, в in (всички or {}).items():
        if в:
            има.add(ТАБЛИЦА[к][1])
    липс = []
    for гр in ("А", "Б", "В", "Г", "Д", "Е", "Ж", "З"):
        if гр == "Б" and not (всички or {}).get("A1_повод_свип"):
            continue          # неприложима, не липсваща
        if гр not in има:
            липс.append(имена[гр])
    return липс


