# 3 · ГЛАВНАТА ВРАТА
# ═══════════════════════════════════════════════════════════════════════════

def сканирай(рамки: dict,
             *,
             сега=None,
             работни: tuple = РАБОТНИ,
             контекст: tuple = КОНТЕКСТ,
             праг: int = ПРАГ_ПРАЩАНЕ,
             състояние: dict | None = None,
             режи_незатворен: bool = True,
             прозорец: int = ПРОЗОРЕЦ,
             върни_диагностика: bool = False):
    """
    ЕДИНСТВЕНАТА функция, която живият бот вика.

    рамки  : {"1м": df, "5м": df, "15м": df, "1час": df, "4час": df, ...}
             Колоните може да са Open/High/Low/Close (yfinance) или малки букви.
             Липсваща рамка = None. Нищо не е задължително освен поне една
             работна рамка с ≥300 бара.
    сега   : текущият час (UTC). Служи САМО за отрязване на незатворения бар.
             None → не се реже (за бектест/обход върху затворени барове).
    състояние : речник, който се ПРОМЕНЯ на място — пази застудяването между
             пусканията. Ботът го чете/пише в json. None → без застудяване.

    ВРЪЩА : list[dict] — сетъпи, подредени по точки надолу. Всеки носи:
             степен · ранг · точки · посока · ниво · вход · стоп · цел · цел2
             · съотношение · повод · съвпаднали · липсва · съгласие_рамки
             · праща (bool) · статус="НОВО · още не е мерено"
    """
    диаг = {"бележки": [], "грешки": {}, "време_мс": {}, "рамки": {}}
    if състояние is not None and not isinstance(състояние, dict):
        състояние = None          # подаден боклук → работим без застудяване

    # ── 1 · подготовка на всички подадени рамки ────────────────────────────
    готови: dict[str, pd.DataFrame] = {}
    for име, сурова in (рамки or {}).items():
        d, бел = _подготви(сурова, име)
        диаг["бележки"].extend(бел)
        if d is None:
            continue
        if режи_незатворен:
            d, рязан = _отрежи_незатворен(d, име, сега)
            if рязан:
                диаг["бележки"].append(f"{име}: последният бар още се формира — отрязан")
        if len(d) > прозорец:
            d = d.iloc[-прозорец:]
        if len(d) >= МИН_БАРОВЕ:
            готови[име] = d
        else:
            диаг["бележки"].append(f"{име}: {len(d)} бара след чистене — прескочена")

    # ── 2 · съгласието на рамките (Т4 · СВЕДЕНИЕ, не точки) ────────────────
    съгласие: dict[str, int] = {}
    for име in контекст:
        d = готови.get(име)
        if d is None:
            continue
        t = time.perf_counter()
        try:
            с = B5.f_структура(d).get("структура") or {}
            съгласие[име] = int(с.get("посока") or 0)
        except Exception as e:
            диаг["грешки"][f"{име}·структура"] = f"{type(e).__name__}: {str(e)[:90]}"
        диаг["време_мс"][f"{име}·структура"] = round((time.perf_counter() - t) * 1000)

    # ── 3 · пълният прочит на работните рамки ──────────────────────────────
    сетъпи: list[dict] = []
    for име in работни:
        d = готови.get(име)
        if d is None:
            диаг["рамки"][име] = "няма"
            continue
        R, вр, гр = _прочети(d, име)
        диаг["време_мс"].update({f"{име}·{k}": v for k, v in вр.items()})
        диаг["грешки"].update({f"{име}·{k}": v for k, v in гр.items()})
        диаг["рамки"][име] = f"{len(d)} бара · {d.index[0]} → {d.index[-1]}"

        # блок, който е гръмнал, влиза като None — сливането го чете като празен
        try:
            карти = SL.f_сливане(d, R, праг_карта=0)
        except Exception as e:
            диаг["грешки"][f"{име}·сливане"] = f"{type(e).__name__}: {str(e)[:120]}"
            continue

        for к in карти:
            повод_вид = (к.get("поводи") or ["—"])[0]
            обект = None
            for p in SL._поводи(len(d) - 1, d, R):
                if p["лонг"] == к["лонг"]:
                    обект = p["обект"]
                    повод_вид = p["вид"]
                    break
            з = к["залог"]
            съгл_с_мен = sum(1 for _, зн in съгласие.items()
                             if зн == (1 if к["лонг"] else -1))
            с = {
                "рамка": име,
                "време": к.get("време"),
                "бар": к.get("бар"),
                "посока": к["посока"],
                "лонг": к["лонг"],
                "степен": к["степен"],
                "ранг": к["ранг"],
                "точки": к["точки"],
                "повод": повод_вид,
                "повод_текст": к["повод_текст"],
                "ниво": _ниво_на_повода(повод_вид, обект),
                "цена": к["цена"],
                "atr": к["atr"],
                "вход": з["вход"], "стоп": з["стоп"],
                "цел": з["цел"], "цел2": з.get("цел2"),
                "риск": з["риск"], "награда": з["награда"],
                "съотношение": з["съотношение"], "съотношение2": з.get("съотношение2"),
                "основа_цел": з["основа_цел"], "основа_цел2": з.get("основа_цел2"),
                "съвпаднали": к["съвпаднали"],
                "всички_условия": к["всички_условия"],
                "липсва": _липсващи_групи(к["всички_условия"]),
                "сурови": к.get("сурови", {}),
                "съгласие_рамки": {"съгласни": съгл_с_мен, "от": len(съгласие),
                                   "по_рамка": dict(съгласие)},
                "спор": к.get("спор"),
                "праща": bool(к["точки"] >= праг),
                "статус": "НОВО · още не е мерено",
                "_карта_вход": к,       # суровият вход за b_карта.сглоби
            }
            сетъпи.append(с)

    # ── 4 · застудяване ────────────────────────────────────────────────────
    # ПО ВРЕМЕ, НЕ ПО ИНДЕКС НА БАР. Първата ми версия пазеше `бар`, а `бар` е
    # `len(d)-1` — при постоянен прозорец той е ЕДНО И СЪЩО число на всяко
    # пускане (1199). Тоест «изминали бара» излизаше 0 винаги и застудяването
    # заглушаваше всяка следваща карта завинаги. Хванато, като си отпечатах
    # индекса на живо повикване, не по четене на кода.
    for с in сетъпи:
        ключ = f"{с['рамка']}|{с['посока']}"
        стар = (състояние or {}).get(ключ)
        мин_бар = МИНУТИ.get(с["рамка"], 15)
        if с["праща"] and стар and стар.get("време"):
            изминали = _барове_между(стар["време"], с.get("време"), мин_бар)
            # по-висока степен винаги минава — иначе 💎 се губи зад ✅
            ако_по_силна = с["ранг"] > int(стар.get("ранг", -1))
            if изминали is not None and 0 <= изминали < ПАУЗА_БАРОВЕ and not ако_по_силна:
                с["праща"] = False
                с["застудяване"] = (f"мълчи · още {ПАУЗА_БАРОВЕ - изминали} "
                                    f"бара до отпушване")
        if с["праща"] and състояние is not None:
            състояние[ключ] = {"ранг": с["ранг"], "точки": с["точки"],
                               "време": str(с.get("време"))}

    сетъпи.sort(key=lambda x: (-x["точки"], x["рамка"]))
    if върни_диагностика:
        диаг["общо_мс"] = sum(диаг["време_мс"].values())
        return сетъпи, диаг
    return сетъпи


