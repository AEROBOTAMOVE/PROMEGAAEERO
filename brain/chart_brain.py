def _модул(име: str):
    """Внася b_*.py по път — без да замърсява пространството на бота."""
    if име in _кеш_модули:
        return _кеш_модули[име]
    път = БАЗА / f"{име}.py"
    if not път.exists():
        raise ImportError(f"липсва {път}")
    сп = importlib.util.spec_from_file_location(f"_мозък_{име}", път)
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    _кеш_модули[име] = м
    return м


