def карта(с: dict, мерено: dict | None = None,
          предупреждения: list | None = None,
          изместване: float = 0.0, час_сега: str | None = None) -> str:
    """Сетъп → текстът, който отива в пощата. `мерено` идва от бота (виж по-долу)."""
    доп = list(предупреждения or [])
    сг = с.get("съгласие_рамки") or {}
    if сг.get("от"):
        # ОДИТ-27: тук стоеше «(СВЕДЕНИЕ — не влиза в точките)» — обяснение, не факт
        доп.append(f"голямата картина: {сг['съгласни']}/{сг['от']} натам")
    return KT.сглоби(с["_карта_вход"], таблица=ТАБЛИЦА, тавани=ТАВАН_ГРУПА,
                     изместване=изместване, час_сега=час_сега,
                     граници=ПРАГОВЕ, степени=СТЕПЕНИ,
                     мерено=мерено, предупреждения=доп or None)


def мерено_от_стата(stats: dict, кофа: str, лонг: bool) -> dict | None:
    """
    Чете РЕАЛНАТА кофа на бота от backtest_stats.json.
    `кофа` е това, което връща `live_bot._cell_name(streak_n)`:
    day1 / fresh / stale / mixed. Връща None, ако кофата мълчи (n<100).
    НЕ смесва нищо с точките — само пълни отделния ред в картата.
    """
    try:
        сег = ((stats or {}).get("fresh") or {}).get("long" if лонг else "short", {})
        s = сег.get(кофа)
        if not s or int(s.get("n") or 0) < 100:
            return None
        м = {"кофа": кофа, "посока": "long" if лонг else "short",
             "win": s.get("win"), "net": s.get("net"), "n": int(s["n"])}
        if s.get("lo") is not None and s.get("hi") is not None:
            м["ci"] = (float(s["lo"]), float(s["hi"]))
        if not лонг:
            м["бележка"] = "⚠ SHORT класовете са изцяло губещи в мереното (виж _meta)"
        return м
    except Exception:
        return None


