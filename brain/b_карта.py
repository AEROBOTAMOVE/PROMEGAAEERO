"""
КАРТАТА ЗА ТЕЛЕГРАМ.

СТРОЕЖ (в този ред, нарочно):
  1. СТЕПЕНТА — първото нещо на екрана, преди всичко друго
  2. КАКВО СЪВПАДНА — изброено по блокове, с ✓ и ✗, за да се вижда какво ЛИПСВА
  3. ЗАЛОГЪТ — вход / стоп / цел / съотношение
  4. МЕРЕНОТО — отделен ред, само ако е подадено; числата са на СТАРОТО правило
  5. 🔴 НОВО · още не е мерено — задължителен долен ред за новата логика

ЗАЩО МЕРЕНОТО Е ОТДЕЛЕН РЕД:
Кофите fresh/day1/stale/mixed в backtest_stats.json имат зад себе си 20 години
и десетки хиляди сделки. Точките и степента отгоре нямат НИЩО. Ако двете влязат
в едно число, неизмереното си облича дрехите на измереното. Затова са два реда,
никога един.
"""

from __future__ import annotations

# кратки имена на групите за реда „какво съвпадна"
ГРУПИ_ИМЕ = {
    "А": "повод", "Б": "свип", "В": "ликвидност", "Г": "гапове",
    "Д": "зони", "Е": "структура", "Ж": "обеми", "З": "диапазон",
}

ЛЕНТА = {0: "▱▱▱▱▱▱▱", 1: "▰▱▱▱▱▱▱", 2: "▰▰▱▱▱▱▱", 3: "▰▰▰▱▱▱▱",
         4: "▰▰▰▰▱▱▱", 5: "▰▰▰▰▰▱▱", 6: "▰▰▰▰▰▰▱", 7: "▰▰▰▰▰▰▰"}


# човешките имена на групите — «Б: свип» не значи нищо на телефон
ЧОВЕШКИ = {
    "А": "повод", "Б": "обрани стопове", "В": "цел наблизо",
    "Г": "незапълнен пропуск", "Д": "силна зона", "Е": "структурата натам",
    "Ж": "голям обем", "З": "евтина/скъпа половина",
}


def _защо(карта, таблица) -> str:
    """ОДИТ-29 · ЗАЩО, събрано в един ред.

    Дотук тук се печатаха до 25 реда: заглавие на всяка група с точките ѝ,
    после всяко условие поотделно с «· », накрая ред «✗ липсва: …».
    Коста чете това на телефон между сделки. Групите, които са СЪВПАДНАЛИ,
    се изброяват с човешките си имена и толкова; какво липсва не му върши
    работа — вече му е казано колко силна е картата със степента отгоре."""
    по_група = {}
    for ключ, (тегло, гр, _текст) in таблица.items():
        if карта["всички_условия"].get(ключ):
            по_група[гр] = по_група.get(гр, 0) + тегло
    # най-тежките групи първи, без «повод» (той е в заглавния ред)
    редени = sorted((г for г in по_група if г != "А"),
                    key=lambda г: -по_група[г])
    return " + ".join(ЧОВЕШКИ.get(г, г) for г in редени[:4])


def сглоби(карта: dict, *, таблица: dict, тавани: dict, граници: tuple, степени: tuple,
           мерено: dict | None = None, предупреждения: list | None = None) -> str:
    """ОДИТ-29 · седем реда: какво видях, къде се влиза, колко печеля, защо.

    карта  : изходът на f_сливане
    мерено : кофата от backtest_stats.json; числата ѝ НЕ отиват на картата —
             старото правило и новата логика са две различни неща и слети в
             едно съобщение си обличат дрехите взаимно.
    """
    з = карта["залог"]
    глагол = "КУПИ" if карта["лонг"] else "ПРОДАЙ"
    ико = "🟢" if карта["лонг"] else "🔴"
    рамка = карта.get("рамка") or "15м"
    вр = карта.get("време")
    if hasattr(вр, "strftime"):
        try:
            from zoneinfo import ZoneInfo
            _в = вр if вр.tzinfo else вр.replace(tzinfo=ZoneInfo("UTC"))
            час = _в.astimezone(ZoneInfo("Europe/Sofia")).strftime("%H:%M")
        except Exception:
            час = вр.strftime("%H:%M")
    else:
        час = str(вр)[-8:-3] or str(вр)

    Л = [f"{карта['степен']} · {ико} {глагол} ЗЛАТО {рамка} · {час}",
         f"🎯 вход {з['вход']:.2f}",
         f"🛑 стоп {з['стоп']:.2f}"]
    цели = f"1️⃣ {з['цел']:.2f}"
    if з.get("цел2") is not None:
        цели += f" · 2️⃣ {з['цел2']:.2f}"
    Л.append(цели)
    съот = з.get("съотношение2") or з.get("съотношение")
    if съот:
        Л.append(f"💰 печелиш {съот:.1f}× риска" if съот >= 1
                 else f"⚠️ печелиш само {съот:.1f}× риска")
    защо = _защо(карта, таблица)
    if защо:
        Л.append(f"📌 {защо}")
    for п in (предупреждения or []):
        Л.append(f"⚠️ {п}")
    Л.append("🧪 ново · още без бектест")
    return "\n".join(Л)
