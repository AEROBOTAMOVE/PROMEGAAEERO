# -*- coding: utf-8 -*-
"""
КАРТАТА ЗА ТЕЛЕГРАМ.

СТРОЕЖ (в този ред, нарочно):
  1. СТЕПЕНТА — първото нещо на екрана, преди всичко друго
  2. КАКВО СЪВПАДНА — изброено по блокове, с ✓ и ✗, за да се вижда какво ЛИПСВА
  3. ЗАЛОГЪТ — вход / стоп / цел / съотношение
  4. МЕРЕНОТО — отделен ред, само ако е подадено; числата са на СТАРОТО правило
  5. 🔴 НОВО · още не е мерено — задължителен долен ред за новата логика

ЗАЩО МЕРЕНОТО Е ОТДЕЛЕН РЕД:
Кофите fresh/day1/stale/mixed в backtest_stats.json имат зад себе си 20 години
и десетки хиляди сделки. Точките и степента отгоре нямат НИЩО. Ако двете влязат
в едно число, неизмереното си облича дрехите на измереното. Затова са два реда,
никога един.
"""

from __future__ import annotations

# кратки имена на групите за реда „какво съвпадна"
ГРУПИ_ИМЕ = {
    "А": "повод", "Б": "свип", "В": "ликвидност", "Г": "гапове",
    "Д": "зони", "Е": "структура", "Ж": "обеми", "З": "диапазон",
}

ЛЕНТА = {0: "▱▱▱▱▱▱▱", 1: "▰▱▱▱▱▱▱", 2: "▰▰▱▱▱▱▱", 3: "▰▰▰▱▱▱▱",
         4: "▰▰▰▰▱▱▱", 5: "▰▰▰▰▰▱▱", 6: "▰▰▰▰▰▰▱", 7: "▰▰▰▰▰▰▰"}


# човешките имена на групите — «Б: свип» не значи нищо на телефон
ЧОВЕШКИ = {
    # 🔴 ОДИТ-63 · «цел наблизо» се пишеше и когато цел НЯМА: редът «защо»
    # назовава ГРУПАТА, не условието, което е сработило. Група «В» съдържа и
    # условия без нищо общо с цел. Честното име е самата дименсия.
    "А": "повод", "Б": "обрани стопове", "В": "ликвидност",
    "Г": "незапълнен пропуск", "Д": "силна зона", "Е": "структурата натам",
    "Ж": "голям обем", "З": "евтина/скъпа половина",
}


def _защо(карта, таблица) -> str:
    """ОДИТ-29 · ЗАЩО, събрано в един ред.

    Дотук тук се печатаха до 25 реда: заглавие на всяка група с точките ѝ,
    после всяко условие поотделно с «· », накрая ред «✗ липсва: …».
    Коста чете това на телефон между сделки. Групите, които са СЪВПАДНАЛИ,
    се изброяват с човешките си имена и толкова; какво липсва не му върши
    работа — вече му е казано колко силна е картата със степента отгоре."""
    по_група = {}
    for ключ, (тегло, гр, _текст) in таблица.items():
        if карта["всички_условия"].get(ключ):
            по_група[гр] = по_група.get(гр, 0) + тегло
    # най-тежките групи първи, без «повод» (той е в заглавния ред)
    редени = sorted((г for г in по_група if г != "А"),
                    key=lambda г: -по_група[г])
    return " + ".join(ЧОВЕШКИ.get(г, г) for г in редени[:4])


def сглоби(карта: dict, *, таблица: dict, тавани: dict, граници: tuple, степени: tuple,
           мерено: dict | None = None, предупреждения: list | None = None,
           изместване: float = 0.0, час_сега: str | None = None,
           метал: str = "злато", лот: str | None = None,
           ранг_вход: int = 3) -> str:
    """ОДИТ-31 · шест реда: какво виждам · защо · къде е нивото · колко струва.

    изместване : барът на Yahoo е ФЮЧЪРС и е ~10 мин стар; живата цена, която
                 собственикът гледа на графиката, е с ~60$ по-ниска. Всяко ниво
                 се сваля с тази разлика, за да съвпадне с неговия екран.
                 0.0 = стария вид (цени по бара).
    час_сега   : часът, В КОЙТО КАРТАТА ТРЪГВА. Дотук се печаташе часът на
                 БАРА — карта, пристигнала в 17:16, пишеше 17:00.
    мерено     : кофата от backtest_stats.json. НЕ отива на картата: старото
                 правило и новата логика са две различни неща и слети в едно
                 съобщение си обличат дрехите взаимно.
    """
    з = карта["залог"]
    ж = lambda x: (float(x) - изместване) if x is not None else None
    посока = "нагоре" if карта["лонг"] else "надолу"
    рамка = карта.get("рамка") or "15м"
    час = час_сега or "—"

    # ОДИТ-37: «злато» беше ЗАКОВАНО — среброто щеше да получава карти,
    # които го наричат злато. Металът идва отвън.
    # ОДИТ-39 · ОТ «✅ ГОТОВ» НАГОРЕ КАРТАТА Е ВХОД, НЕ НАБЛЮДЕНИЕ.
    # Собственикът: «искам сигнали, съвети, всичко от А до Я». Мозъкът виждаше
    # сетъпи с вход, стоп и цели, но ги наричаше «наблюдение» и не даваше лот —
    # значи не бяха сигнали. Слабите остават наблюдение, силните стават входове.
    # 🔴 ОДИТ-43 · МОЗЪКЪТ НИКОГА НЕ КАЗВА «КУПИ».
    # Вчера го направих да казва, защото поиска «истински входове». Но той
    # НЯМА бектест — той е СЪВЕТ КЪДЕ ДА ГЛЕДАШ, не заповед. Собственикът,
    # 20-ия час: «последните съобщения са все сякаш са вход истински…
    # трябва да измислиш нещо за съобщението, което е съвет за гледане
    # накъде и какво и как — сигналите са други».
    # 🟢/🔴 КУПИ/ПРОДАЙ остават САМО за мереното правило.
    _вход = int(карта.get("ранг", 0)) >= ранг_вход
    _стп = карта["степен"].split(" ", 1)[-1]
    if _вход:
        Л = [f"👁 <b>ГЛЕДАЙ {посока.upper()}</b> · {метал} {рамка} · {_стп} · {час}"]
    else:
        Л = [f"🧠 {_стп} · {метал} {посока} · {рамка} · {час}"]
    защо = _защо(карта, таблица)
    if защо:
        Л.append(f"📌 {защо}")
    # СЪВЕТ говори за НИВА, не за вход и стоп — това са думи на сигнал.
    Л.append(f"📈 нивото е {ж(з['вход']):.2f} · под {ж(з['стоп']):.2f} отпада"
             if (_вход and карта["лонг"]) else
             f"📉 нивото е {ж(з['вход']):.2f} · над {ж(з['стоп']):.2f} отпада"
             if _вход else
             f"👀 ниво {ж(з['вход']):.2f} · 🛑 {ж(з['стоп']):.2f}")
    # ОДИТ-39: при ВХОД целите носят номера (както в сигналната карта), а 🎯
    # остава само за самия вход — инак два реда започват с един и същ знак.
    цели = (f"🎯 ако тръгне: {ж(з['цел']):.2f}" if _вход else f"🎯 {ж(з['цел']):.2f}")
    if з.get("цел2") is not None:
        цели += f" · {ж(з['цел2']):.2f}"
    Л.append(цели)
    # ОДИТ-35 · дотук се вземаше съотношението до ВТОРАТА цел, а картата
    # не го казваше — «11.1× риска» стоеше до първа цел, която е 5.6×.
    _с2 = з.get("съотношение2")
    _с1 = з.get("съотношение")
    # при ВХОД съотношението влиза В РЕДА ЗА ЛОТА — иначе два реда с 💰
    _съотн = ""
    if _с1:
        # при ВХОД редът за лота става дълъг — там съотношението е късо
        _съотн = (f"{_с1:.1f}× и {_с2:.1f}× риска" if (_вход and _с2) else
                  f"{_с1:.1f}× риска" if _вход else
                  f"{_с1:.1f}× риска до първа цел"
                  + (f" · {_с2:.1f}× до втора" if _с2 else ""))
        if not _вход:
            Л.append((f"💰 {_съотн}") if _с1 >= 1 else (f"⚠️ само {_съотн}"))
    elif _с2:
        _съотн = f"{_с2:.1f}× риска до втора цел"
        if not _вход:
            Л.append(f"💰 {_съотн}")
    for п in (предупреждения or []):
        # ⚠️ САМО когато нещо е ПРОТИВ. «голямата картина: 2/2 натам» е добра
        # новина и стоеше с предупредителен знак — обратното на смисъла.
        Л.append(("⚠️ " if "0/" in п or "1/2" in п or "стар" in п else "📌 ") + п)
    if _вход and лот:
        Л.append(лот + (f" · {_съотн}" if _съотн else ""))
    # 🔴🔴 02.09 · КАРТАТА СИ ПРОТИВОРЕЧЕШЕ. `МОЗЪК_РАНГ_ВХОД` е 1, тоест
    # ВСЯКА мозъчна карта е ВХОД — а последният ѝ ред казваше «НЕ е сигнал»
    # ТОЧНО В КЛОНА `_вход`. Преброено на живия дневник: 23 карти «НЕ е
    # сигнал» + 13 «наблюдение», 0 с размер.
    # Три части на кода, писани в различни дни, не се съгласуваха:
    #   live_bot:954   МОЗЪК_РАНГ_ВХОД=1 — «ранг 1 = целият мозък»
    #   live_bot:7361  «съветната карта не дава размер — тя не е вход»
    #   тук           «НЕ е сигнал» ПРИ вход
    # Сега редът казва КАКВО Е, не се извинява. ФАКТ, не извинение —
    # правилото на този проект.
    # ЧЕСТНО НА САМАТА КАРТА: приносът на мозъка над СЛУЧАЕН вход в същия ден
    # е +0.1% [−2.8%, +3.0%] на 1914 сетъпа / 18 дни — НЕДОКАЗАН. Затова
    # картата казва «мерено: недоказан ръб», а не обещава.
    if _вход:
        Л.append("⚡ ВХОД по мозъка · мереното още не доказва ръб")
    else:
        Л.append("🧪 наблюдение, не е вход")
    return "\n".join(Л)
