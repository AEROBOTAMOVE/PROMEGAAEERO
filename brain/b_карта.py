# -*- coding: utf-8 -*-
"""
КАРТАТА ЗА ТЕЛЕГРАМ.

СТРОЕЖ (в този ред, нарочно):
  1. СТЕПЕНТА — първото нещо на екрана, преди всичко друго
  2. КАКВО СЪВПАДНА — изброено по блокове, с ✓ и ✗, за да се вижда какво ЛИПСВА
  3. ЗАЛОГЪТ — вход / стоп / цел / съотношение
  4. МЕРЕНОТО — отделен ред, само ако е подадено; числата са на СТАРОТО правило
  5. 🔴 НОВО · още не е мерено — задължителен долен ред за новата логика

ЗАЩО МЕРЕНОТО Е ОТДЕЛЕН РЕД:
Кофите fresh/day1/stale/mixed в backtest_stats.json имат зад себе си 20 години
и десетки хиляди сделки. Точките и степента отгоре нямат НИЩО. Ако двете влязат
в едно число, неизмереното си облича дрехите на измереното. Затова са два реда,
никога един.
"""

from __future__ import annotations

# кратки имена на групите за реда „какво съвпадна"
ГРУПИ_ИМЕ = {
    "А": "повод", "Б": "свип", "В": "ликвидност", "Г": "гапове",
    "Д": "зони", "Е": "структура", "Ж": "обеми", "З": "диапазон",
}

ЛЕНТА = {0: "▱▱▱▱▱▱▱", 1: "▰▱▱▱▱▱▱", 2: "▰▰▱▱▱▱▱", 3: "▰▰▰▱▱▱▱",
         4: "▰▰▰▰▱▱▱", 5: "▰▰▰▰▰▱▱", 6: "▰▰▰▰▰▰▱", 7: "▰▰▰▰▰▰▰"}


def _ред_условия(карта, таблица, тавани) -> list[str]:
    """
    Съвпадналото се изписва изцяло; липсващото се свива в ЕДИН ред.
    Първата ми версия печаташе и осемте групи, включително „+0 — няма" пет пъти —
    картата ставаше стена от нули и окото губеше това, което Е съвпаднало.
    """
    по_група: dict[str, list] = {}
    for ключ, (тегло, гр, текст) in таблица.items():
        по_група.setdefault(гр, []).append((ключ, текст))

    редове, липсват = [], []
    for гр in ("А", "Б", "В", "Г", "Д", "Е", "Ж", "З"):
        # групата „свип" важи само ако поводът е свип — иначе не е липса, а неприложимост
        ако_неприложима = (гр == "Б" and not карта["всички_условия"].get("A1_повод_свип"))
        if ако_неприложима:
            continue
        точки_гр, има = 0, []
        for ключ, текст in по_група.get(гр, []):
            if карта["всички_условия"].get(ключ):
                има.append(текст); точки_гр += таблица[ключ][0]
        if има:
            редове.append(f"✓ {ГРУПИ_ИМЕ[гр].upper()} +{min(точки_гр, тавани[гр])}")
            for т in има:
                редове.append(f"    · {т}")
        else:
            липсват.append(ГРУПИ_ИМЕ[гр])
    if липсват:
        редове.append("")
        редове.append("✗ липсва: " + " · ".join(липсват))
    return редове


def _ред_точки(карта, граници, степени) -> str:
    """
    НЕ пишем «8/22». Таванът 22 е теоретичен — за да се стигне до него трябва
    всичките осем блока да са пълни едновременно, което на 2 450 бара не се
    случи нито веднъж. «8/22» кара силна карта да изглежда слаба.
    Вместо това: точките + колко остават до следващата степен.
    """
    т = карта["точки"]
    r = карта["ранг"]
    лента = ЛЕНТА.get(r, "")
    if r >= len(степени) - 1:
        опашка = "върхът на скалата"
    else:
        нужни = граници[r + 1] - т
        опашка = f"до {степени[r+1]}: още {нужни}"
    return f"{лента}  {т} точки  ·  {опашка}"


def сглоби(карта: dict, *, таблица: dict, тавани: dict, граници: tuple, степени: tuple,
           мерено: dict | None = None, предупреждения: list | None = None) -> str:
    """
    карта  : изходът на f_сливане
    мерено : {"кофа": "day1", "посока": "long", "win": 79.9, "net": 2.99,
              "n": 4019, "ci": (1.655, 4.196)}  — от backtest_stats.json.
             None → редът казва честно, че старото правило мълчи.
    """
    з = карта["залог"]
    стрелка = "🟢 ЛОНГ" if карта["лонг"] else "🔴 КЪСО"
    вр = карта.get("време")
    # ОДИТ-27: всяка друга карта в чата е по София. Тази беше по UTC — два часовника
    # в един разговор объркват повече, отколкото помагат.
    if hasattr(вр, "strftime"):
        try:
            from zoneinfo import ZoneInfo
            _в = вр if вр.tzinfo else вр.replace(tzinfo=ZoneInfo("UTC"))
            час = _в.astimezone(ZoneInfo("Europe/Sofia")).strftime("%d.%m %H:%M") + " София"
        except Exception:
            час = вр.strftime("%d.%m %H:%M UTC")
    else:
        час = str(вр)

    рамка = карта.get("рамка") or "15мин"
    Л = []
    # ── 1 · ЕДИН ЗАГЛАВЕН РЕД: степен, посока, рамка, час ───────────────────
    Л.append(f"{карта['степен']}  ·  {стрелка}  ЗЛАТО {рамка}  ·  {час}")
    Л.append(_ред_точки(карта, граници, степени))
    Л.append(f"цена {карта['цена']}   ATR {карта['atr']}")
    Л.append("")

    # ── 2 · КАКВО СЪВПАДА ──────────────────────────────────────────────────
    Л.append("━━ СЪВПАДА ━━")
    Л.append("повод: " + " + ".join(карта["повод_текст"]))
    Л.extend(_ред_условия(карта, таблица, тавани))
    Л.append("")

    # ── 3 · ЗАЛОГЪТ ────────────────────────────────────────────────────────
    Л.append("━━ ЗАЛОГ ━━")
    Л.append(f"вход  {з['вход']:.2f}")
    Л.append(f"стоп  {з['стоп']:.2f}   (−{з['риск']:.2f}$)")
    Л.append(f"цел 1 {з['цел']:.2f}   (+{з['награда']:.2f}$)  ← {з['основа_цел']}")
    if з.get("цел2") is not None:
        Л.append(f"цел 2 {з['цел2']:.2f}   (+{з['награда2']:.2f}$)  ← {з['основа_цел2']}")
    съот = з["съотношение"]
    съот2 = з.get("съотношение2")
    оценка = "" if съот is None else ("  ⚠ първата цел е под 1:1" if съот < 1.0 else "")
    ред = f"съотношение  1 : {съот}"
    if съот2 is not None:
        ред += f"  ·  до цел 2  1 : {съот2}"
    Л.append(ред + оценка)
    Л.append("")

    # ── 4 · МЕРЕНОТО — ЕДИН ред, не шест ───────────────────────────────────
    # Дотук тук стоеше цяла секция със заглавие, доверителен интервал и бележка.
    # Собственикът я поиска махната: числото остава, лекцията пада.
    if мерено:
        ci = мерено.get("ci")
        нула = " ⚠ пресича нулата" if (ci and ci[0] < 0 < ci[1]) else ""
        Л.append(f"мерено {мерено['кофа']} {мерено['посока']}: {мерено['win']}% · "
                 f"{мерено['net']:+.2f}$ (n={мерено['n']})" + нула)

    # ── 5 · ДОЛНИЯТ РЕД — четири реда лекция станаха четири думи ───────────
    if предупреждения:
        for п in предупреждения:
            Л.append(f"⚠ {п}")
    Л.append("🔴 ново · още без бектест")
    return "\n".join(Л)
