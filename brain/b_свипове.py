def f_карта_свипове(рез: dict, макс_събития: int = 3) -> str:
    """Текстова карта на български. Нищо не се маха — старото и новото стоят едно до друго."""
    р = ["⚡ ОБРАНИ СТОПОВЕ"]
    ев = рез["свипове"][-макс_събития:]
    if not ев:
        р.append("Няма обрани стопове в този отрязък.")
    for e in reversed(ев):
        р.append(f"{e['степен']} · {e['текст']}")
        р.append(f"   ниво {e['ниво']} · стигна {e['екстремум']} · затвори {e['затваряне']}")
        части = []
        if e["дълбочина_atr"] is not None:
            части.append(f"навлезе {e['дълбочина_atr']} ATR")
        части.append(f"върна се {int(e['връщане_дял']*100)}% в свещта")
        if e["обем_кратно"] is not None:
            части.append(f"обем ×{e['обем_кратно']}")
        части.append(f"ниво от {e['сила_ниво']} върха" if e["посока"] == "ГОРЕ"
                     else f"ниво от {e['сила_ниво']} дъна")
        части.append(f"пипано {e['пипания_преди']} пъти преди")
        р.append("   " + " · ".join(части))
