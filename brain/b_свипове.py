# 4 · НАДГРАЖДАНЕ · МИНУТИ ДО ВРЪЩАНЕТО (от 1-минутни барове)
# ═══════════════════════════════════════════════════════════════════════════

def f_свип_минути(събития: list, df_1мин: pd.DataFrame, дължина_бар_мин: int = 15) -> list:
    """
    НОВО · още не е мерено.
    За всеки свип: колко МИНУТИ след като е направил екстремума, цената се е върнала
    обратно през нивото. Ползва САМО 1-минутните барове ВЪТРЕ в свип-свещта, която
    вече е затворена → няма надничане (свещта е минало в момента на сигнала).
    Изисква df_1мин с DatetimeIndex.
    """
    if not isinstance(df_1мин.index, pd.DatetimeIndex):
        raise ValueError("df_1мин трябва да е с DatetimeIndex")
    o, h, l, c, v, t = _подготви(df_1мин)
    изход = []
    for съб in събития:
        т0 = съб.get("време")
        if т0 is None:
            изход.append(dict(съб, минути_връщане=None, минути_до_върха=None))
            continue
        т1 = pd.Timestamp(т0) + pd.Timedelta(minutes=дължина_бар_мин)
        маска = (t >= pd.Timestamp(т0)) & (t < т1)
        idx = np.flatnonzero(маска)
        if len(idx) == 0:
            изход.append(dict(съб, минути_връщане=None, минути_до_върха=None))
            continue
        горе = съб["посока"] == "ГОРЕ"
        ниво = съб["ниво"]
        под = idx
        екс = int(под[np.argmax(h[под])]) if горе else int(под[np.argmin(l[под])])
        след = под[под >= екс]
        връщане = None
        for j in след:
            ок = (c[j] < ниво) if горе else (c[j] > ниво)
            if ок:
                връщане = int(j - екс)
                break
        изход.append(dict(съб,
                          минути_до_върха=int(екс - под[0]),
                          минути_връщане=връщане,
                          статус_минути="НОВО · още не е мерено"))
    return изход


