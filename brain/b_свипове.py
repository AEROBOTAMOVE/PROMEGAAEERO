def f_свипове(df: pd.DataFrame, само_както_графиката: bool = False,
              и_преносът: bool = True, **params) -> dict:
    """
    Намира равните върхове/дъна (ликвидност) и МОМЕНТА, в който цената ги обира.

    ПРЕНОС (както на графиката, v9.3 р. 441-504):
        · пивот 5/5 → два последователни пивота на разстояние <= close*0.06%
          раждат ниво по СРЕДАТА им;
        · свип нагоре = high > ниво И close < ниво в същата ЗАТВОРЕНА свещ;
        · свип надолу = low < ниво И close > ниво;
        · нивото се маркира „използвано" и не гърми втори път;
        · таван 10 нива общо, FIFO.

    НАДГРАЖДАНЕ (НОВО · още не е мерено), включено по подразбиране:
        · клъстер от 3+ пивота = ЕДНО ниво със сила 3+ (лекува Д1 и Д2);
        · до 200 живи нива вместо 10 (лекува Д3);
        · измерена СИЛА на всеки свип (лекува Д4): дълбочина в ATR, дял на връщането,
          обем спрямо средния, брой пипания преди това, възраст на нивото,
          за колко бара се е върнал;
        · свипът може да се затвори до `прозорец_барове` по-късно, а ако не се върне —
          събитието се записва като ПРОБИВ, не като свип;
        · 7-степенна скала по броене на съвпадения.

    НИЩО СЪЩЕСТВУВАЩО НЕ СЕ МАХА: при `и_преносът=True` (по подразбиране) резултатът
    носи и ключ `пренос` — ПЪЛНИЯТ чист резултат както на графиката, сметнат отделно.
    Измерено: клъстерът мести цената на нивото, затова само 64.9% от чистите свипове
    съвпадат буквално (бар+посока+ниво) с надградените. Затова двата вървят ЗАЕДНО,
    а не единият вместо другия.
    """
    п = dict(ПАРАМ_ГРАФИКА)
    п.update({} if само_както_графиката else ПАРАМ_НАДГРАЖДАНЕ)
    if само_както_графиката:
        п.update(dict(клъстер=False, клъстер_памет=1, макс_активни=None, живот_барове=None,
                      забрава_atr=None, прозорец_барове=0, махай_при_пробив=False,
                      atr_период=14, обем_период=50, близост_atr=1.0, допуск_atr=None))
    п.update(params)

    o, h, l, c, v, t = _подготви(df)
    n = len(c)
    рез_празно = dict(пренос=None, нива=[], свипове=[], под_наблюдение=[], последен_нагоре=None,
                      последен_надолу=None, пресен_нагоре=False, пресен_надолу=False,
                      пресен_нагоре_общо=False, пресен_надолу_общо=False,
                      мета=dict(барове=n, параметри=п, режим="ПРЕНОС" if само_както_графиката else "ПРЕНОС+НАДГРАЖДАНЕ"))
    if n < 2 * п["пивот"] + 2:
        return рез_празно

    atr = _atr_wilder(h, l, c, п["atr_период"])
    обем_ср = _среден_обем(v, п["обем_период"]) if v is not None else None
    пв = _пивоти(h, п["пивот"], п["пивот"], True)    # пивот-връх
    пд = _пивоти(l, п["пивот"], п["пивот"], False)   # пивот-дъно

    R = п["пивот"]
    допуск_дял = п["допуск_процент"] / 100.0
    таван = None if п["макс_активни"] is None else int(п["макс_активни"])
    таван_pine = п["макс_нива_страна"] * 2          # v9.3 р. 463: 10 ОБЩО за двете страни

    нива: list[dict] = []          # активни (живи) нива
    свипове: list[dict] = []
    памет_върхове: list[tuple] = []   # (индекс, цена) последни пивот-върхове
    памет_дъна: list[tuple] = []
    посл_нагоре = посл_надолу = None
    сериен = 0

    for i in range(n):
        цена_c, цена_h, цена_l = c[i], h[i], l[i]
        a = atr[i] if not np.isnan(atr[i]) else np.nan

        # ── 1 · ПОТВЪРДЕНИ ПИВОТИ (p = i - R; потвърждават се ЕДВА СЕГА) ──
        # РЕД: в Pine блокът за раждане на нива (р. 472-479) стои ПРЕДИ цикъла за свип
        # (р. 481-504) → ниво, родено на бар i, МОЖЕ да бъде обрано още на бар i.
        p = i - R
        if p >= R:
            # ПРЕНОС: Pine ползва close * 0.06/100 в момента на потвърждението (р. 445).
            # НАДГРАЖДАНЕ: ако е зададен `допуск_atr`, допускът е в ATR → еднаква строгост
            # на всяка рамка (виж ДОПУСК_ATR_ПО_РАМКА).
            if п["допуск_atr"] and not np.isnan(a):
                толеранс = a * п["допуск_atr"]
            else:
                толеранс = цена_c * допуск_дял
            if пв[p]:
                _обработи_пивот(p, h[p], True, памет_върхове, нива, толеранс, п, i, t)
            if пд[p]:
                _обработи_пивот(p, l[p], False, памет_дъна, нива, толеранс, п, i, t)

        # ── 2 · ЧИСТЕНЕ + ТАВАН (Pine реже вътре в f_add_liquidity, р. 463-470) ──
        if п["живот_барове"] or п["забрава_atr"]:
            живи = []
            for нв in нива:
                стар = п["живот_барове"] and (i - нв["бар_създаване"] > п["живот_барове"])
                далеч = (п["забрава_atr"] and not np.isnan(a)
                         and abs(нв["цена"] - цена_c) > п["забрава_atr"] * a)
                if not (стар or далеч):
                    живи.append(нв)
            нива = живи
        лимит = таван_pine if само_както_графиката else таван
        if лимит is not None:
            while len(нива) > лимит:
                нива.pop(0)

        # ── 3 · СВИП ПРОВЕРКА (преди пипанията — „пипания_преди" значи ПРЕДИ свипа) ──
        # Pine обхожда от най-новото към най-старото (р. 484); държим същия ред.
        за_махане = []
        for идx in range(len(нива) - 1, -1, -1):
            нв = нива[идx]
            ниво = нв["цена"]
            горе = нв["горе"]

            пробожда = (цена_h > ниво) if горе else (цена_l < ниво)
            връща = (цена_c < ниво) if горе else (цена_c > ниво)

            чакащ = нв["пробит_бар"] is not None
            if чакащ:
                нв["пробит_връх"] = max(нв["пробит_връх"], цена_h) if горе else min(нв["пробит_връх"], цена_l)

            if (пробожда or чакащ) and връща:
                # ═══ СВИП ═══
                старт = нв["пробит_бар"] if чакащ else i
                екстремум = нв["пробит_връх"] if чакащ else (цена_h if горе else цена_l)
                if not чакащ:
                    екстремум = цена_h if горе else цена_l
                сериен += 1
                съб = _събитие(сериен, i, старт, нв, ниво, горе, екстремум,
                               o, h, l, c, v, обем_ср, a, t, п, само_както_графиката)
                свипове.append(съб)
                if горе:
                    посл_нагоре = съб
                else:
                    посл_надолу = съб
                за_махане.append(идx)
                continue

            if пробожда and not връща and п["прозорец_барове"] > 0:
                if not чакащ:
                    нв["пробит_бар"] = i
                    нв["пробит_връх"] = цена_h if горе else цена_l

            if чакащ and (i - нв["пробит_бар"]) >= п["прозорец_барове"] and не_върнато(връща):
                # НОВО: минал е през нивото и не се е върнал → това е ПРОБИВ, ликвидността е поета.
                if п["махай_при_пробив"]:
                    за_махане.append(идx)

        for идx in за_махане:
            нива.pop(идx)

        # ── 4 · ПИПАНИЯ (нивото е било защитавано) ──
        for нв in нива:
            if цена_l <= нв["цена"] <= цена_h:
                нв["пипания"] += 1

    # ── 5 · СВЕЖЕСТ (v9.3 р. 515-516) ──
    посл_бар = n - 1
    пресен_г = посл_нагоре is not None and (посл_бар - посл_нагоре["бар"]) <= п["свеж_барове"]
    пресен_д = посл_надолу is not None and (посл_бар - посл_надолу["бар"]) <= п["свеж_барове"]

    # ── 6 · НИВА ПОД НАБЛЮДЕНИЕ (НОВО — какво предстои, преди свипа) ──
    наблюдение = []
    a_края = atr[посл_бар]
    for нв in нива:
        ако_далеч = np.isnan(a_края) or abs(нв["цена"] - c[посл_бар]) > п["близост_atr"] * a_края
        if ако_далеч:
            continue
        точки = int(нв["сила"] >= ПРАГОВЕ["сила_ниво"]) + int(нв["пипания"] >= ПРАГОВЕ["пипания_преди"]) \
            + int(посл_бар - нв["бар_създаване"] >= ПРАГОВЕ["възраст_ниво"])
        наблюдение.append(dict(
            цена=round(нв["цена"], 3), горе=нв["горе"], сила=нв["сила"], пипания=нв["пипания"],
            възраст=посл_бар - нв["бар_създаване"],
            разстояние=round(abs(нв["цена"] - c[посл_бар]), 3),
            разстояние_atr=round(abs(нв["цена"] - c[посл_бар]) / a_края, 2) if not np.isnan(a_края) else None,
            степен=f_степен(точки),
            текст=("ЛИКВИДНОСТ НАД РАВНИ ВЪРХОВЕ" if нв["горе"] else "ЛИКВИДНОСТ ПОД РАВНИ ДЪНА"),
            статус="НОВО · още не е мерено",
        ))
    наблюдение.sort(key=lambda x: x["разстояние"])

    # ── 7 · СТАРОТО ДО НОВОТО (нищо съществуващо не се маха) ──
    пренос = None
    if и_преносът and not само_както_графиката:
        пренос = f_свипове(df, само_както_графиката=True, и_преносът=False)

    return dict(
        пренос=пренос,   # пълният чист резултат „както на графиката", или None
        нива=[dict(цена=round(x["цена"], 3), горе=x["горе"], сила=x["сила"], пипания=x["пипания"],
                   бар_създаване=x["бар_създаване"]) for x in нива],
        свипове=свипове,
        под_наблюдение=наблюдение,
        последен_нагоре=посл_нагоре,
        последен_надолу=посл_надолу,
        пресен_нагоре=bool(пресен_г),
        пресен_надолу=bool(пресен_д),
        # ИЗМЕРЕНО: надградената логика МОЖЕ да пропусне свип, който графиката показва
        # (когато нивото е било махнато като „пробито"). Затова има и ОБЩ флаг —
        # той никога не е по-беден от графиката. Ботът да ползва него, за да не губи сигнал.
        пресен_нагоре_общо=bool(пресен_г or (пренос and пренос["пресен_нагоре"])),
        пресен_надолу_общо=bool(пресен_д or (пренос and пренос["пресен_надолу"])),
        мета=dict(
            барове=n,
            режим="ПРЕНОС" if само_както_графиката else "ПРЕНОС+НАДГРАЖДАНЕ",
            параметри=п,
            брой_свипове=len(свипове),
            обем_наличен=v is not None,
            статус_мерене=("ПРЕНОС · както на графиката" if само_както_графиката
                           else "ПРЕНОС + НОВО · надграждането още не е мерено"),
        ),
    )


def не_върнато(връща: bool) -> bool:
    """Дребен помощник за четимост: изтекъл прозорец и цената НЕ се е върнала."""
    return not връща


def _обработи_пивот(p, цена, връх, памет, нива, толеранс, п, i, t):
    """
    ПРЕНОС (Pine р. 472-479): сравнява се САМО с последния пивот; при съвпадение
      се ражда ниво по средата и силата е твърдо 2.
    НАДГРАЖДАНЕ: гледат се последните `клъстер_памет` пивота; всички в толеранса
      влизат в ЕДИН клъстер → ниво = средното им, сила = броят им (може 3, 4, 5...).
      Членовете се изваждат от паметта, за да не родят второ припокриващо се ниво (Д2).
    """
    if п["клъстер"]:
        близки = [(pi, pc) for (pi, pc) in памет if abs(pc - цена) <= толеранс]
        if близки:
            група = близки + [(p, цена)]
            ниво = float(np.mean([g[1] for g in група]))
            сила = len(група)
            for g in близки:
                памет.remove(g)
            нива.append(_ново_ниво(ниво, връх, сила, i, t, [g[0] for g in група]))
        памет.append((p, цена))
        while len(памет) > п["клъстер_памет"]:
            памет.pop(0)
    else:
        # 1:1 с графиката
        if памет:
            pi, pc = памет[-1]
            if abs(pc - цена) <= толеранс:
                нива.append(_ново_ниво((цена + pc) / 2.0, връх, 2, i, t, [pi, p]))
        памет.append((p, цена))
        while len(памет) > 1:
            памет.pop(0)


def _ново_ниво(цена, горе, сила, бар, t, пивоти):
    return dict(цена=float(цена), горе=bool(горе), сила=int(сила), бар_създаване=int(бар),
                време_създаване=(t[бар] if t is not None else None), пипания=0,
                пробит_бар=None, пробит_връх=None, пивоти=пивоти)


def _събитие(сериен, i, старт, нв, ниво, горе, екстремум, o, h, l, c, v, обем_ср, a, t, п, чист):
    """Изчислява ИЗМЕРИМИТЕ характеристики на свипа и му дава степен."""
    диапазон = max(h[i] - l[i], 1e-9)
    дълбочина = (екстремум - ниво) if горе else (ниво - екстремум)
    дълбочина = max(дълбочина, 0.0)
    дълбочина_atr = (дълбочина / a) if (a and not np.isnan(a) and a > 0) else None
    # колко решително се е върнал в тялото: разстояние на затварянето от нивото,
    # мерено спрямо диапазона на самата свещ
    връщане = (ниво - c[i]) if горе else (c[i] - ниво)
    връщане_дял = max(0.0, min(1.0, връщане / диапазон))
    обем_кратно = None
    if v is not None and обем_ср is not None and not np.isnan(обем_ср[i]) and обем_ср[i] > 0:
        обем_кратно = float(v[i] / обем_ср[i])
    барове_връщане = int(i - старт)
    възраст = int(i - нв["бар_създаване"])

    # 8-мо условие: пробождането е и екстремум за последните N бара (causal — гледа назад)
    N = ПРАГОВЕ["екстремум_барове"]
    от = max(0, i - N)
    нов_екстремум = (екстремум >= float(np.max(h[от:i + 1]))) if горе else \
                    (екстремум <= float(np.min(l[от:i + 1])))

    # ── 8-те ИЗМЕРИМИ съвпадения (НОВО · още не са мерени за печалба) ──
    у = []
    def доб(име, условие):
        у.append((име, bool(условие)))
    доб("пробождане", дълбочина_atr is not None and дълбочина_atr >= ПРАГОВЕ["дълбочина_atr"])
    доб("връщане", връщане_дял >= ПРАГОВЕ["връщане_дял"])
    доб("обем", обем_кратно is not None and обем_кратно >= ПРАГОВЕ["обем_кратно"])
    доб("тройно_ниво", нв["сила"] >= ПРАГОВЕ["сила_ниво"])
    доб("защитавано", нв["пипания"] >= ПРАГОВЕ["пипания_преди"])
    доб("в_същата_свещ", барове_връщане == 0)
    доб("узряло_ниво", възраст >= ПРАГОВЕ["възраст_ниво"])
    доб("връх_за_%d_бара" % N, нов_екстремум)
    точки = sum(1 for _, б in у if б)

    return dict(
        номер=сериен,
        бар=int(i),
        бар_пробождане=int(старт),
        време=(t[i] if t is not None else None),
        посока=("ГОРЕ" if горе else "ДОЛУ"),
        подсказка=("ШОРТ" if горе else "ЛОНГ"),   # свип над върховете → продавачите поемат
        текст=("ОБРАНИ СА СТОПОВЕТЕ НАД ВЪРХОВЕТЕ" if горе else "ОБРАНИ СА СТОПОВЕТЕ ПОД ДЪНАТА"),
        ниво=round(float(ниво), 3),
        екстремум=round(float(екстремум), 3),
        затваряне=round(float(c[i]), 3),
        # ── НОВО · измерена сила ──
        дълбочина=round(float(дълбочина), 3),
        дълбочина_atr=(round(дълбочина_atr, 3) if дълбочина_atr is not None else None),
        връщане_дял=round(float(връщане_дял), 3),
        обем_кратно=(round(обем_кратно, 2) if обем_кратно is not None else None),
        барове_връщане=барове_връщане,
        пипания_преди=int(нв["пипания"]),
        сила_ниво=int(нв["сила"]),
        възраст_ниво=възраст,
        atr=(round(float(a), 3) if a and not np.isnan(a) else None),
        точки=точки,
        съвпадения=[име for име, б in у if б],
        степен=f_степен(точки),
        както_на_графиката=bool(барове_връщане == 0 and нв["сила"] == 2),
        статус=("ПРЕНОС · както на графиката" if чист else "ПРЕНОС + НОВО · силата още не е мерена"),
    )


