БРОЙ_УСЛОВИЯ = 8


def f_степен(точки: int) -> str:
    """
    Броене на съвпадения → една от 7-те степени. Няма усещане, само броене.
    0-1 → ИСКРА · 2 → НАБЛЮДЕНИЕ · 3 → ОФОРМЯ СЕ · 4 → ГОТОВ · 5 → СИЛЕН ·
    6 → МНОГО СИЛЕН · 7 или 8 → РЯДЪК

    ЗАЩО 8 УСЛОВИЯ, А НЕ 7:
    С точно 7 условия последната степен изисква ВСИЧКИТЕ 7 наведнъж. Измерено върху
    22 522 реални свипа: максимумът беше 6 и 💎 РЯДЪК излизаше 0 пъти — върхът на
    скалата беше МЪРТЪВ, точно като мъртвия клон `strength >= 3` в Pine (р. 455).
    С 8 условия 💎 означава „7 от 8" — рядко, но постижимо.
    """
    т = int(max(0, min(БРОЙ_УСЛОВИЯ, точки)))
    if т <= 1:
        return СТЕПЕНИ[0]
    if т >= 7:
        return СТЕПЕНИ[6]
    return СТЕПЕНИ[т - 1]


