def тест_без_надничане(df: pd.DataFrame, точки: int = 12, **params) -> dict:
    """
    Пуска f_свипове върху НАРАСТВАЩИ префикси на данните.
    Ако функцията надничаше напред, събитие издадено на бар i щеше да се промени
    (или да изчезне/да се появи), когато добавим следващите барове.
    Изисква: всяко събитие с бар <= край_на_префикса да е БУКВАЛНО същото.
    """
    n = len(df)
    ключове = ("бар", "посока", "ниво", "екстремум", "затваряне", "дълбочина",
               "връщане_дял", "обем_кратно", "точки", "степен", "сила_ниво",
               "пипания_преди", "барове_връщане")
    пълно = f_свипове(df, **params)["свипове"]
    карта = {e["номер"]: {k: e[k] for k in ключове} for e in пълно}
    провали = []
    проверени = 0
    for стъпка in range(1, точки + 1):
        край = int(n * стъпка / (точки + 1))
        ч = f_свипове(df.iloc[:край], **params)["свипове"]
        for e in ч:
            проверени += 1
            еталон = карта.get(e["номер"])
            if еталон is None:
                провали.append((край, e["бар"], "събитие само в префикса"))
                continue
            for k in ключове:
                ако = еталон[k]
                сега = e[k]
                if ако != сега and not (isinstance(ако, float) and isinstance(сега, float)
                                        and abs(ако - сега) < 1e-9):
                    провали.append((край, e["бар"], f"{k}: префикс={сега} пълно={ако}"))
    return dict(проверени_събития=проверени, провали=провали, чисто=(len(провали) == 0))


