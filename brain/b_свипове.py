РАМКИ_МИН = {"15мин": 15, "30мин": 30, "1час": 60, "2часа": 120, "4часа": 240, "1ден": 1440}


def _прередактирай(df: pd.DataFrame, минути: int) -> pd.DataFrame:
    """Сглобява по-голяма рамка от по-малката. Само затворени барове."""
    правило = f"{минути}min"
    к = {c.lower(): c for c in df.columns}
    r = df.resample(правило, label="left", closed="left")
    нов = pd.DataFrame({
        "open": r[к["open"]].first(),
        "high": r[к["high"]].max(),
        "low": r[к["low"]].min(),
        "close": r[к["close"]].last(),
    })
    if "volume" in к:
        нов["volume"] = r[к["volume"]].sum()
    return нов.dropna(subset=["close"])


def f_свипове_многорамково(df: pd.DataFrame, рамки=("15мин", "30мин", "1час", "4часа"),
                            съвпад_минути: int = 240,
                            допуск_atr: float | None = ДОПУСК_ATR_ПО_РАМКА, **params) -> dict:
    """
    НОВО · още не е мерено.
    Човекът не може да гледа 4-7 рамки едновременно; ботът може. Пуска се същият
    детектор на всяка рамка и се БРОЯТ съвпаденията: колко рамки са дали свип в една
    и съща посока в рамките на `съвпад_минути` НАЗАД от последното събитие.
    Изисква DatetimeIndex.
    """
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("нужен е DatetimeIndex")
    по_рамка = {}
    for име in рамки:
        м = РАМКИ_МИН[име]
        d = df if м == _стъпка_минути(df) else _прередактирай(df, м)
        по_рамка[име] = f_свипове(d, допуск_atr=допуск_atr, **params)

    съб = []
    for име, r in по_рамка.items():
        for e in r["свипове"]:
            if e["време"] is not None:
                съб.append((pd.Timestamp(e["време"]), име, e))
    съб.sort(key=lambda x: x[0])

    съвпадения = []
    for ts, име, e in съб:
        прозорец = [(t2, f2, e2) for (t2, f2, e2) in съб
                    if 0 <= (ts - t2).total_seconds() <= съвпад_минути * 60
                    and e2["посока"] == e["посока"]]
        рамки_вътре = sorted({f2 for _, f2, _ in прозорец})
        if len(рамки_вътре) >= 2:
            съвпадения.append(dict(време=ts, водеща_рамка=име, посока=e["посока"],
                                   рамки=рамки_вътре, брой=len(рамки_вътре),
                                   точки_водещ=e["точки"],
                                   степен=f_степен(min(7, e["точки"] + len(рамки_вътре) - 1)),
                                   статус="НОВО · още не е мерено"))
    return dict(по_рамка=по_рамка, съвпадения=съвпадения,
                мета=dict(рамки=list(рамки), съвпад_минути=съвпад_минути,
                          статус_мерене="НОВО · още не е мерено"))


def _стъпка_минути(df: pd.DataFrame) -> int:
    if len(df) < 3:
        return 0
    d = pd.Series(df.index[1:6]).diff().dropna()
    if len(d) == 0:
        return 0
    return int(d.median().total_seconds() // 60)


