print("\n═══ П25 (човешки език) ═══")
import re as _re
ЖАРГОН = [(r"\bкофа\b","x"),(r"\bстрийк\b","x"),(r"\bбазис\b","x"),(r"\bсегмент\b|\bклетка\b","x"),
          (r"\bУЛТРА\b","x"),(r"\bпремиум\b","x"),(r"\bflip\b|\bранг\b","x"),
          (r"\bday1\b|\bmixed\b|\bstale\b|\bfresh\b","x"),(r"n=\d","x"),
          (r"95%\s*[:(]|доверителн","x"),(r"vol_rank|adv_ok|should_sig|_meta","x"),(r"\bTP\d\b","x")]
РЕЧНИК25 = set("🟢🔴⏸👁👀🎯🛑💰💵📏📈📉✅🏆⚠📌📅☀🌤🌙🥇🥈🤖🔥✨🔨⚡💎🧠😴🧪♻🌡💪👍🪶🍃")
ЕМО = _re.compile("[\U0001F300-\U0001FAFF]|[☀-➿]|[⏩-⏺]|ℹ")
