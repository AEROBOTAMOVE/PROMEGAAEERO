_ДЕЙСТВИЕ25 = ("влез", "премести", "дръж", "чакам", "не влизам", "нищо", "затвор", "следя",
               "прибран", "почивай", "остава", "остават", "спи", "не отварям", "не се прави",
               "само знак", "не съм влизал", "пиша щом", "купи", "продай", "вход")
print("\n" + "=" * 70)
print("РЕПЛИКА НА П25")
print("=" * 70)
лош = 0
for име, т in ГОТОВИ.items():
    ч = re.sub(r"<[^>]+>", "", т)
    р = [x for x in ч.split("\n") if x.strip()]
    беди = []
    if len(р) > 15:
        беди.append(f"{len(р)} реда > 15")
    п = р[0]
    if not _ЕМО25.match(п.strip()):
        беди.append("първият ред без емоджи")
    if not re.search(r"\d{1,2}:\d{2}", п):
        беди.append("първият ред без час")
    if len(п) > 70:
        беди.append(f"първи ред {len(п)} > 70")
    ж = [m.group(0) for изр in _ЖАРГОН25 for m in [re.search(изр, ч)] if m]
    if ж:
        беди.append(f"жаргон {ж}")
    чужди = sorted({z for z in _ЕМО25.findall(ч) if z not in _РЕЧНИК25 and z not in _ПУНКТ25})
    if чужди:
        беди.append(f"емоджи извън речника {чужди}")
    дв = [m.group(0) for m in re.finditer("(?:[\U0001F300-\U0001FAFF☀-➿⏩-⏺]️?\\s?){2,}", ч)
          if not any(c in m.group(0) for c in _ЦИФРИ25)]
    if дв:
        беди.append(f"две емоджита едно до друго {дв[:2]}")
    if not any(d in ч.lower() for d in _ДЕЙСТВИЕ25):
        беди.append("не казва какво да правя")
    лош += len(беди)
    print(f"  {име:38s} {'✓' if not беди else беди}")
print("ОБЩО находки П25:", лош)

