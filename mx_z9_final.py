ЦЕЛ_ЗН = {"tp1": "1️⃣", "tp2": "2️⃣", "tp3": "3️⃣"}


def _части(kind, hit, lv, e, зн, дол, hit_px=None):
    преди, n_hit = [], 0
    for k2 in ("tp1", "tp2"):
        if hit.get(k2) and k2 != kind:
            _ц = (hit_px or {}).get(k2)
            преди.append((ЦЕЛ_ЗН[k2],
                          round(((float(_ц) if _ц is not None else lv[k2]) - e) * зн / 3.0, 2)))
            n_hit += 1
    трета = дол / 3.0
    ост = 3 - n_hit
    if kind in ("tp1", "tp2"):
        return преди, round(трета, 2), 1, round(трета * (ост - 1), 2)
    return преди, round(трета * ост, 2), ост, 0.0


def _изтекли(tr, when):
    """ТОЧНО изразът на `track_trade` (live_bot.py «age = (…).days»), за да не
    може картата да каже «ден 31», когато правилото гърми на 30."""
    try:
        d = (pd.Timestamp(when).tz_localize(None)
             - pd.Timestamp(tr["opened"]).tz_localize(None)).days
        return d if 0 <= d <= 400 else None
    except Exception:
        return None


def _дни_дума(d):
    return "по-малко от ден" if d == 0 else ("един ден" if d == 1 else f"{d} дни")


