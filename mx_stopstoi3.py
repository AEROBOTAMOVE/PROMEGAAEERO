def _възраст_нето(age_h):
    for праг, нето in ВЪЗРАСТ_ВХОД:
        if age_h < праг:
            return нето
    return ВЪЗРАСТ_ВХОД[-1][1]


def _кратки(мъртви):
    """🔴 health['мъртви'] има ДВА правописа: голи ключове (live_bot.py:288) и
    етикети с латиница (live_bot.py:2850 → «долар (DXY)»). Без това изваждането
    на мъртвото краче не хваща втория случай И латиницата изтича на картата."""
    return {str(m).split(" ")[0] for m in (мъртви or [])}


def _живот(tr, now_utc):
    """СЪЩАТА мярка, с която track_trade:2395 решава дали да затвори по време
    (`.days`). 🔴 При сделка под денонощие `.days` дава 0 → «стоя отворена 0 дни».
    Под ден картата минава на ЧАСОВЕ, за да не пише нула за нещо, което е било."""
    try:
        import pandas as pd
        д = (pd.Timestamp(now_utc) - pd.Timestamp(tr["opened"]))
        return (f"{д.days} дни" if д.days >= 2 else
                ("1 ден" if д.days == 1 else f"{д.total_seconds()/3600:.0f} часа"))
    except Exception:
        return None


