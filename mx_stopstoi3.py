def нов_стои(direction, age_h, price_user, macro, health, now_utc):
    посока = "покупка" if direction == "long" else "продажба"
    lv = lb._levels(round(price_user, 2), direction)
    мъртви = _кратки((health or {}).get("мъртви"))
    реш = [k for k in ("долар", "лихви") if k in (macro or {}) and k not in мъртви]
    за = sum(1 for k in реш if (macro[k] if direction == "long" else not macro[k]))
    L = [f"⏸ САМО ЗА СВЕДЕНИЕ · нагласата за {посока} още стои · {lb._sofia(now_utc)}",
         "👉 ТИ НЕ ПРАВИШ НИЩО — това не е карта за вход и аз не съм отворил нищо",
         "↳ нагласа = посоката, накъдето пазарът е наклонен · става сделка само с моя карта"]
    if реш:
        имена = " и ".join(ИМЕ_МАКРО[k] for k in реш)
        гл = "сочи" if len(реш) == 1 else "сочат"
        if за == len(реш):
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} още {гл} натам · нищо не се е развалило")
        elif за == 0:
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} вече {гл} в другата посока · нагласата отслабва")
        else:
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} се дърпат в различни посоки · няма съгласие")
    _мъртви_реш = [k for k in ("долар", "лихви") if k in мъртви]
    if not реш:
        # 🔴 и двете крачета мълчат: картата НЕ съди по посока, защото няма по какво
        L.append("⚠️ НЕ ВИЖДАМ МАКРОТО — нито за долара, нито за лихвите имам число "
                 "в момента · затова изобщо не съдя по тях")
    elif _мъртви_реш:
        _сп = " и ".join(ИМЕ_МАКРО_В[k] for k in _мъртви_реш)
        L.append(f"⚠️ ЛИПСВА — за {_сп} нямам число в момента · източникът мълчи и "
                 f"затова изобщо не го броя")
    ясна = age_h is not None and age_h < СТОЯЩ_МАКС_Ч
    if ясна:
        нето = _възраст_нето(age_h)
        L.append(f"📅 ВЪЗРАСТ — нагласата е отпреди {age_h:.0f} часа · "
                 f"пресният вход по нея вече мина")
        L.append(f"📊 ЗАЩО НЕ ДАВАМ ВХОД — ръбът живее в първите {РЪБ_Ч:.0f} часа на нагласата")
        # 🔴 думата се СМЕНЯ по знака на числото — иначе «+0.05$ · тоест губи»
        _д = ("тоест губи пари" if нето < -0.005 else
              f"тоест нула · за нула не се рискуват {SL_PIPS:,.0f} пипса")
        L.append(f"↳ вход на тази възраст е мерен на {lb._пари(нето)} на сделка · {_д}")
    else:
        L.append("📅 ВЪЗРАСТ — нагласата стои отдавна · точната ѝ възраст не мога да "
                 "гарантирам, затова не давам число")
        L.append(f"📊 ЗАЩО НЕ ДАВАМ ВХОД — ръбът на такава нагласа живее в първите "
                 f"{РЪБ_Ч:.0f} часа, а тази отдавна ги мина")
    L.append("📌 АКО ТРЪГНЕ БЕЗ МЕН — пропускаме я и не я гоня · "
             "ако тръгне надолу — добре, че не сме вътре")
    L.append(f"🎯 САМО ЗА ОРИЕНТИР — целите щяха да са 1️⃣ <code>{lb._fmt(lv['tp1'], 2)}</code> · "
             f"2️⃣ <code>{lb._fmt(lv['tp2'], 2)}</code> · 3️⃣ <code>{lb._fmt(lv['tp3'], 2)}</code>")
    L.append(f"🛑 а стопът — <code>{lb._fmt(lv['sl'], 2)}</code> · "
             f"{lb._разст(price_user, lv['sl'])} под сегашната цена "
             f"<code>{lb._fmt(price_user, 2)}</code>")
    L.append(f"👁 СЛЕДВА — пиша ти веднага при нов и пресен сигнал · иначе пак най-рано "
             f"след {СТОЯЩ_Ч:.0f} часа")
    return "\n".join(L)


