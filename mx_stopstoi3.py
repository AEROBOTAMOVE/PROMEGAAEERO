def нов_стоп(kind, tr, price_hit, when, via, gap, guard_n=0, next_line="", now_utc=None, dec=2):
    _сим = tr.get("sym", "XAUUSD")
    ст = PIP if _сим == "XAUUSD" else 0.001
    метал = "злато" if _сим == "XAUUSD" else "сребро"
    цена_дума = "0.10$ на унция" if _сим == "XAUUSD" else "0.001$ на унция"
    посока = "покупка" if tr["direction"] == "long" else "продажба"
    e = tr["entry"]; lv = tr["levels"]; hit = tr.get("hit", {})
    знак = 1 if tr["direction"] == "long" else -1
    дол = (price_hit - e) * знак
    if abs(дол) < 0.005:
        дол = 0.0
    стълба, взети = lb._ladder_pnl(kind, hit, lv, e, знак, дол, tr.get("hit_px"))
    час = lb._sofia(when) if via in ("бар", "спот") else lb._sofia()
    _повече = abs(дол) / ст - SL_PIPS
    без_риск = (взети > 0)
    L = []
    if без_риск:
        нула = стълба >= 0
        L.append(f"✅ ЗАТВОРЕНА НА НУЛА · {метал} {посока} · {час}" if нула
                 else f"🛑 ЗАТВОРЕНА · {метал} {посока} · {час}")
        L.append("👉 ТИ НЕ ПРАВИШ НИЩО — остатъкът излезе сам, сделката е затворена")
        L.append(f"💵 СДЕЛКАТА ДОНЕСЕ {lb._пари(стълба, _сим)} на унция общо · "
                 f"прибраното по ЦЕЛ 1 си остава твое")
        L.append(f"↳ пипс = най-малкото мръдване на цената · при златото 1 пипс = {цена_дума}")
        L.append(f"🎯 КАК СТАНА — влязохме на <code>{lb._fmt(e, dec)}</code>, а на ЦЕЛ 1 "
                 f"преместих стопа точно там, на входа")
        L.append("↳ оттам нататък най-лошото възможно беше НУЛА, а не загуба · "
                 "затова днес не губиш нищо")
        L.append(f"📌 цената се върна на <code>{lb._fmt(price_hit, dec)}</code> и остатъкът "
                 f"излезе там · по него сметката е нула")
    else:
        L.append(f"🛑 СТОПЪТ СЕ ИЗПЪЛНИ · {метал} {посока} · {час}")
        L.append("👉 ТИ НЕ ПРАВИШ НИЩО — брокерът вече те извади, сделката е затворена")
        L.append(f"💵 ЗАГУБАТА — {lb._пари(стълба, _сим)} на унция · това ѝ е всичко")
        L.append(f"↳ пипс = най-малкото мръдване на цената · при златото 1 пипс = {цена_дума}")
        L.append(f"🎯 КАК СТАНА — влязохме на <code>{lb._fmt(e, dec)}</code> · стопът стоеше "
                 f"на <code>{lb._fmt(lv['sl'], dec)}</code> · излязохме на "
                 f"<code>{lb._fmt(price_hit, dec)}</code>")
        if _повече > 0.5:
            L.append("⚠️ ЦЕНАТА ПРЕСКОЧИ СТОПА, вместо да мине през него — "
                     "на това ниво просто не е имало търговия")
            L.append(f"↳ брокерът вади по първата истинска цена · затова загубата е "
                     f"{_повече:,.0f} пипса над планираните {SL_PIPS:,.0f}")
        else:
            L.append(f"↳ толкова беше планът от самото начало — {SL_PIPS:,.0f} пипса, "
                     f"точно колкото писах в картата за вход")
    д = _живот(tr, now_utc)
    if д:
        L.append(f"📅 сделката стоя отворена {д} · по правило я държа "
                 f"най-много {ДНИ_МАКС} дни")
    if not без_риск:
        L.append("📌 АКО ЦЕНАТА СЕ ВЪРНЕ ОБРАТНО — това вече не те засяга · "
                 "обратно вътре се влиза само с нова карта от мен")
    if not без_риск and guard_n >= 2:
        L.append(f"🛑 СПИРАМ {'ПОКУПКИТЕ' if tr['direction'] == 'long' else 'ПРОДАЖБИТЕ'} ДО УТРЕ"
                 f" — това е {РЕД_ДУМА.get(guard_n, str(guard_n) + '-ят')} стоп днес натам")
    elif not без_риск and guard_n == 1:
        L.append("📌 това е първият стоп днес в тази посока · при втори спирам картите до утре")
    # ♻️ влиза САМО когато казва нещо, което 🛑-редът горе НЕ е казал вече
