"""
ОДИТ-45б · КАРТАТА СЕ СТЯГА ДО СЕДЕМ РЕДА

Рендерирах пулса с ЖИВИТЕ числа от последния рън и излязоха ДЕВЕТ реда, а
правилото на собственика е ≤7. Два от тях са излишни ИМЕННО защото обяснението
вече го казва:

  🟢 очертава се нагоре            ← дъската сочи нагоре…
  ⏸ двете се бият · мълчи         ← …а тук казваме, че няма да го ползваме.
                                     Двете заедно объркват. При разбъркано
                                     макро посоката на дъската е без значение.
  👁 не влизам · не е пресен       ← трети път същото

Правилото му: един ред = едно нещо. Значи при разбъркано макро отпадат и двата.
"""
import io, sys, ast, hashlib

ops = []


def rep(p, old, new, why, n=1):
    s = io.open(p, encoding="utf-8", newline="").read()
    c = s.count(old)
    if c != n:
        print(f"  x СПИРАМ «{why}»: {c} съвпадения, чакам {n}\n    {old[:130]!r}")
        sys.exit(1)
    io.open(p, "wb").write(s.replace(old, new).encode("utf-8"))
    ops.append(why)


LB = "live_bot.py"

# ── 1 · при разбъркано макро посоката на дъската не се обявява ────────────
rep(LB, '''    if new_dir:
        _за, _общо = _съгласни(board, new_dir)
        L.append(f"{'🟢' if new_dir == 'long' else '🔴'} очертава се "
                 f"{'нагоре' if new_dir == 'long' else 'надолу'}"
                 + (f" · {_за} от {_общо} отчета" if _общо > 1 else ""))
    else:
        L.append("📌 посоката е разбъркана")''',
    '''    _обясн = _защо_мълчи(macro_raw, streaks, new_dir)
    _разбъркано = any(r.startswith("⏸") for r in _обясн)
    # ОДИТ-45б: при разбъркано макро НЕ обявяваме посока на дъската — два реда
    # по-долу пише, че няма да я ползваме. Един ред = едно нещо.
    if new_dir and not _разбъркано:
        _за, _общо = _съгласни(board, new_dir)
        L.append(f"{'🟢' if new_dir == 'long' else '🔴'} очертава се "
                 f"{'нагоре' if new_dir == 'long' else 'надолу'}"
                 + (f" · {_за} от {_общо} отчета" if _общо > 1 else ""))
    elif not new_dir and not _разбъркано:
        L.append("📌 посоката е разбъркана")''',
    "1 · без двойно обявяване на посоката")

rep(LB, '''    L += _защо_мълчи(macro_raw, streaks, new_dir)''',
    '''    L += _обясн''',
    "1 · обяснението влиза веднъж")

# ── 2 · опашката мълчи, ако обяснението вече е казало същото ──────────────
rep(LB, '''        L.append("👁 не влизам · не е пресен")''',
    '''        # ОДИТ-45б: ако обяснението горе вече е казало ЗАЩО не влизаме,
        # този ред е трети път същото.
        if not _разбъркано:
            L.append("👁 не влизам · не е пресен")''',
    "2 · без трето повтаряне")

print("ПРИЛОЖЕНИ:")
for o in ops:
    print(f"  + {o}")
ast.parse(io.open(LB, encoding="utf-8").read())
