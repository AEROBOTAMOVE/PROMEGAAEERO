    if свод:
        n, пл, сб = свод["общо"]
        L.append(f"📊 КОЛКО СТРУВА ДОСЕГА — {_бр(n)} такива наблюдения от "
                 f"{свод['от_дата'][8:10]}.{свод['от_дата'][5:7]} насам: {пл} на плюс, "
                 f"сборът е {lb._пари(сб)}")
