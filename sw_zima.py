# -*- coding: utf-8 -*-
import sys,re; sys.argv=["x"]
import live_bot as lb, pandas as pd
def карта(a,b,име):
    tm=lb._търговски_минути(a,b); wall=(pd.Timestamp(b)-pd.Timestamp(a)).total_seconds()/60
    wk=lb._market_closed(b); пали=tm>=lb.СПАЛ_МИН and not wk
    print(f"\n{име}\n  {a} -> {b} | стенно {wall/60:.1f}ч | търговски {tm:.0f}мин | пали={пали}")
    if пали: print(re.sub(r"<[^>]+>","",lb._спал_msg(tm,a,b)))
# РЕАЛНИЯТ график: пет последен рън ~20:55 UTC, нед първи рън 22:01 UTC (наблюдавано 2x)
карта("2026-08-07T20:55","2026-08-09T22:01","ЛЯТО (наблюдавано в живия дневник)")
карта("2026-01-09T20:55","2026-01-11T22:01","ЗИМА · нед 22:01 UTC (пазарът още спи)")
карта("2026-01-09T20:55","2026-01-11T23:01","ЗИМА · нед 23:01 UTC (пазарът тъкмо отвори)")
карта("2026-01-09T20:55","2026-01-12T00:01","ЗИМА · пон 00:01 UTC")
карта("2026-01-09T20:55","2026-01-12T05:01","ЗИМА · пон 05:01 UTC")
