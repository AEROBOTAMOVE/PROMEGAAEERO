# -*- coding: utf-8 -*-
"""Специална ли е група З, или всички стъпала в ТАБЛИЦА работят така?"""
import sys, json, collections, warnings
warnings.filterwarnings("ignore"); sys.path.insert(0, ".")
import brain.b_сливане as SL

r = json.load(open("sw_full.json", encoding="utf-8"))
N = len(r)
print("кандидати:", N)

# всички «стъпала» (по-строг праг върху СЪЩАТА мярка), по коментара в _брои
ДВОЙКИ = [("B1_пробождане", "B1b_дълбоко"), ("V1_троен_допир", "V1b_четворен"),
          ("D2_силна", "D2b_най_силна"), ("J1_обем_над", "J1b_обем_голям"),
          ("G1_в_гап", "G3_едър_гап"), ("Z1_дискаунт_премиум", "Z2_хоризонти"),
          ("Z2_хоризонти", "Z2b_единодушно")]
print("\n[A] всяко стъпало: колко пъти по-строгото гори И носи ВТОРА точка за същата мярка")
for осн, ст in ДВОЙКИ:
    и = sum(1 for x in r if x["всички"][осн] and x["всички"][ст])
    само = sum(1 for x in r if x["всички"][осн] and not x["всички"][ст])
    без = sum(1 for x in r if x["всички"][ст] and not x["всички"][осн])
    печ = (и / (и + само)) if (и + само) else 0
    print(f"    {осн:22s} → {ст:20s}  двете: {и:4d}  само основното: {само:4d}"
          f"  стъпало без основа: {без:3d}   P(стъпало|основа)={печ:5.1%}")

def точки(у, махни=()):
    по = {}
    for к, в in у.items():
        if not в or к in махни: continue
        т, гр, _ = SL.ТАБЛИЦА[к]
        по[гр] = по.get(гр, 0) + т
    return sum(min(с, SL.ТАВАН_ГРУПА[г]) for г, с in по.items())

print("\n[B] контрафакт: махаме ЕДНО стъпало наведнъж (праг 14 = живият МОЗЪК_ПРАГ)")
карти14 = [x for x in r if x["точки"] >= 14]
карти9 = [x for x in r if x["точки"] >= 9]
for ст in ("B1b_дълбоко", "V1b_четворен", "D2b_най_силна", "J1b_обем_голям",
           "G3_едър_гап", "E4_серия", "Z2_хоризонти", "Z2b_единодушно"):
    п14 = sum(1 for x in карти14 if точки(x["всички"], (ст,)) < 14)
    п9 = sum(1 for x in карти9 if точки(x["всички"], (ст,)) < 9)
    print(f"    без {ст:20s}: падат {п14:2d}/{len(карти14)} при праг14 · {п9:3d}/{len(карти9)} при праг9")

print("\n[C] контрафакт: махаме ВСИЧКИ стъпала (B1b,V1b,D2b,J1b,G3,E4,Z2,Z2b)")
ВС = ("B1b_дълбоко", "V1b_четворен", "D2b_най_силна", "J1b_обем_голям",
      "G3_едър_гап", "E4_серия", "Z2_хоризонти", "Z2b_единодушно")
п14 = sum(1 for x in карти14 if точки(x["всички"], ВС) < 14)
п9 = sum(1 for x in карти9 if точки(x["всички"], ВС) < 9)
print(f"    падат {п14}/{len(карти14)} при праг14 · {п9}/{len(карти9)} при праг9")
print(f"    само от З (Z2,Z2b): {sum(1 for x in карти14 if точки(x['всички'],('Z2_хоризонти','Z2b_единодушно'))<14)}/{len(карти14)} при праг14")

print("\n[D] дял на група З в точките на ИЗПРАТЕНИТЕ карти")
for праг, к in ((9, карти9), (14, карти14)):
    if not к: continue
    сЗ = sum(sum([x["Z1"], x["Z2"], x["Z2b"], x["Z3"]]) for x in к) / len(к)
    ст = sum(x["точки"] for x in к) / len(к)
    print(f"    праг {праг}: средно {сЗ:.2f} т. от З при {ст:.2f} общо = {сЗ/ст:.1%} от картата")

print("\n[E] Z1 «подарена точка»? — по колко от двете посоки гори на един бар")
по_бар = collections.defaultdict(list)
for x in r: по_бар[x["t"]].append(x)
дв = [v for v in по_бар.values() if len(v) == 2]
print(f"    барове с кандидат в ДВЕТЕ посоки: {len(дв)}")
print(f"    от тях Z1 гори точно за едната: {sum(1 for v in дв if sum(y['Z1'] for y in v)==1)}")
print(f"    Z1 гори за 0 посоки: {sum(1 for v in дв if sum(y['Z1'] for y in v)==0)}"
      f" · за 2: {sum(1 for v in дв if sum(y['Z1'] for y in v)==2)}")
print(f"    Z1 гори при {sum(1 for x in r if x['Z1'])}/{N} = {sum(1 for x in r if x['Z1'])/N:.1%} от всички кандидати")
