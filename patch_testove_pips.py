# -*- coding: utf-8 -*-
"""
ОБНОВЯВАНЕ НА ЧЕТИРИ ТЕСТА СЛЕД v12.5 (пипсовете)

Четирите паднаха, защото пазеха СТАРИЯ формат на паричния ред:
    беше:  💵 4,358.00 → 4,338.00 · -20.00$/унция
    сега:  💵 4,358.00 → 4,338.00 · −200 пипса (−20.00$)

Две разлики: «/унция» отпадна (излишно — картата вече казва метала в заглавието),
а минусът стана типографски «−», за да не стоят два различни минуса на един ред.

ТЕЗИ ТЕСТОВЕ НЕ СЕ РАЗХЛАБВАТ. Всеки пази СЪЩОТО нещо, но в новия запис, И
получава допълнителна проверка за пипсовете — иначе поправката може да бъде
отменена мълчаливо утре.
"""
import io, ast

p = "selftest.py"
s = io.open(p, encoding="utf-8", newline="").read()
n = 0


def rep(old, new):
    global s, n
    assert s.count(old) == 1, f"{s.count(old)} съвпадения: {old[:70]!r}"
    s = s.replace(old, new)
    n += 1


# ── П7 · сянка-стоп ──────────────────────────────────────────────────────
rep('ck("П7 чист сянка-стоп показва −20.00", "-20.00$" in _sh2)',
    '''# 🔴 ОБНОВЕН v12.5: «-20.00$/унция» → «−200 пипса (−20.00$)». Пази СЪЩОТО
# число, но в записа, на който собственикът говори, + самите пипсове.
ck("П7 чист сянка-стоп показва −20.00", "−20.00$" in _sh2)
ck("П7 и го дава В ПИПСОВЕ", "−200 пипса" in _sh2)''')

# ── П8 · стопът при ДА ───────────────────────────────────────────────────
# (вече очаква «пипса» — минава; допълва се долната граница)
rep('ck("П8 стопът носи И долари, не само пипсове", "$)" in _cy)',
    'ck("П8 стопът носи И долари, не само пипсове", "$)" in _cy)\n'
    'ck("П8 сребърната карта брои по СРЕБЪРНИЯ пипс (0.001$), не по златния",\n'
    '   "540 пипса" in lb._разст(58.970, 58.430, "XAGUSD", 3)\n'
    '   and "5 пипса" in lb._разст(58.970, 58.430, "XAUUSD", 3))')

# ── П11 · общата сметка ──────────────────────────────────────────────────
rep('''ck("П11 картата разграничава крака от общата сметка",     # ОДИТ-29
   "/унция" in _be2 and "донесе" in _be2)''',
    '''# 🔴 ОБНОВЕН v12.5: «/унция» отпадна от паричния ред — картата вече казва
# метала в заглавието, а редът носи пипсове + долари. Пази се СЪЩОТО:
# че общата сметка се различава от голия крак.
ck("П11 картата разграничава крака от общата сметка",     # ОДИТ-29
   "донесе" in _be2 and "пипса" in _be2 and _be2.count("$") >= 2)''')

rep('''ck("П11 истинският стоп показва −20.00",                  # ОДИТ-29: «цяла позиция» падна —
   _hard.count("-20.00$") >= 1)                           # беше същото число, казано два пъти''',
    '''ck("П11 истинският стоп показва −20.00",                  # ОДИТ-29: «цяла позиция» падна —
   _hard.count("−20.00$") >= 1)                           # беше същото число, казано два пъти
ck("П11 и го дава в пипсове (200 пипса = 20.00$ при PIP 0.10)",
   "−200 пипса" in _hard)
# 🔴 ЕДИН ЗНАК на реда: Python дава ASCII «-», пипсовете ползват «−».
ck("П11 паричният ред НЕ смесва два различни минуса",
   not any(("-" in л and "−" in л) for л in _hard.split("\\n")))''')

io.open(p, "wb").write(s.encode("utf-8"))
ast.parse(io.open(p, encoding="utf-8").read())
