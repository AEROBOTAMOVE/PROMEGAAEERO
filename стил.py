# ⏸ ⏳ ⏰ живеят в блока 23E9-23FA — първата версия не ги включваше и вдигна
# осем фалшиви «първият ред няма емоджи». Проверчик, който крещи по невинни,
# скоро спира да се чете.
ЕМОДЖИ = re.compile(
    "[\U0001F300-\U0001FAFF☀-➿⬀-⯿⏩-⏺️⃣]+")

МАКС_РЕДОВЕ = 7
МАКС_ЗНАЦИ = 400


def чист(t):
    return re.sub(r"<[^>]+>", "", html.unescape(str(t)))


def провери(име, текст, макс_редове=МАКС_РЕДОВЕ):
    """Връща списък с находки. Празен списък = картата говори човешки."""
    т = чист(текст)
    редове = [r for r in т.split("\n")]
    н = []

    # 1 · дължина
    ползваеми = [r for r in редове if r.strip() and not set(r.strip()) <= {"─"}]
    if len(ползваеми) > макс_редове:
        н.append(("дълга", f"{len(ползваеми)} реда със съдържание (таван {макс_редове})"))
    if len(т) > МАКС_ЗНАЦИ:
        н.append(("дълга", f"{len(т)} знака (таван {МАКС_ЗНАЦИ})"))

    # 2 · първият ред трябва да казва всичко
    п = редове[0] if редове else ""
    if not ЕМОДЖИ.search(п):
        н.append(("заглавие", "първият ред няма емоджи-знак"))
    if len(п) > 78:
        н.append(("заглавие", f"първият ред е {len(п)} знака — не се чете наведнъж"))

    # 3 · жаргон
    for изр, превод in ЖАРГОН:
        m = re.search(изр, т)
        if m:
            н.append(("жаргон", f"«{m.group(0)}» → трябва: {превод}"))

    # 4 · върнал се шум
    for з in ЗАБРАНЕНИ_ИЗРАЗИ:
        if з in т:
            н.append(("върнат шум", f"«{з}»"))

    # 5 · емоджита извън речника + двойки
    for блок in ЕМОДЖИ.findall(т):
        знаци = [z for z in re.findall(r"(?:[\U0001F300-\U0001FAFF☀-➿⬀-⯿]️?⃣?)", блок)]
        for z in знаци:
            if z not in РЕЧНИК and z.rstrip("️") not in РЕЧНИК:
                н.append(("емоджи", f"«{z}» не е в речника"))
        if len(знаци) >= 2 and not re.match(r"^[1-3]️?⃣", блок):
            н.append(("емоджи", f"два знака един до друг: «{блок}»"))

    # 6 · дълги изречения
    for r in редове:
        ч = чист(r)
        if ч.count(",") >= 3 and len(ч) > 90:
            н.append(("изречение", f"влак от запетайки: «{ч[:60]}…»"))

    # 7 · двоен разделител
    for i in range(len(редове) - 1):
        if set(редове[i].strip()) <= {"─"} and редове[i].strip() and \
           set(редове[i + 1].strip()) <= {"─"} and редове[i + 1].strip():
            н.append(("подредба", "два разделителя един под друг"))

    return н


def мини(текст, макс=3):
    """За одит-картата при «всичко наред» — трябва да е МЕГА къса."""
    т = чист(текст)
    р = [x for x in т.split("\n") if x.strip() and not set(x.strip()) <= {"─"}]
    return [] if len(р) <= макс else [("мега-къса", f"{len(р)} реда, а трябва ≤{макс}")]


