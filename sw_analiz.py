# -*- coding: utf-8 -*-
"""Какво прави група З по ДЕЙСТВИТЕЛНИЯ път — и какво би се променило,
   ако трите стъпала се слеят в едно условие (поправката, която одиторът иска)."""
import sys, os, json, collections, warnings
warnings.filterwarnings("ignore"); sys.path.insert(0, ".")
import brain.b_сливане as SL

r = json.load(open("sw_full.json", encoding="utf-8"))
print("посока-кандидати с повод:", len(r))

def точки_от(у, слей_З=False):
    по_гр = {}
    for к, в in у.items():
        if not в: continue
        т, гр, _ = SL.ТАБЛИЦА[к]
        if слей_З and к in ("Z2_хоризонти", "Z2b_единодушно"):
            continue                     # слети в Z1 → една точка за цялата мярка
        по_гр[гр] = по_гр.get(гр, 0) + т
    if слей_З:
        # ако Z1 е изгаснало, но Z2 гори (невъзможно), пак дай 1
        pass
    return sum(min(с, SL.ТАВАН_ГРУПА[г]) for г, с in по_гр.items())

# проверка, че пресмятам същото като бота
лош = [x for x in r if точки_от(x["всички"]) != x["точки"]]
print("контрола: моето броене != бота в", len(лош), "случая")

карти = [x for x in r if x["точки"] >= SL.ПРАГ_ПРАЩАНЕ]
print(f"карти над ПРАГ_ПРАЩАНЕ={SL.ПРАГ_ПРАЩАНЕ}: {len(карти)}")

# ── 1 · колко точки носи З при ДЕЙСТВИТЕЛНИТЕ кандидати
зр = collections.Counter(sum([x["Z1"], x["Z2"], x["Z2b"], x["Z3"]]) for x in r)
print("\n[1] точки от група З при кандидатите:")
for k in sorted(зр): print(f"    {k}: {зр[k]:5d}  {зр[k]/len(r):6.1%}")
print("    Z1 сам (0 от стъпалата):", sum(1 for x in r if x["Z1"] and not x["Z2"]))
print("    Z1+Z2 без Z2b          :", sum(1 for x in r if x["Z1"] and x["Z2"] and not x["Z2b"]))
print("    и трите заедно         :", sum(1 for x in r if x["Z1"] and x["Z2"] and x["Z2b"]),
      f"= {sum(1 for x in r if x['Z2b'])/len(r):.1%} от кандидатите")

# ── 2 · КОНТРАФАКТ: трите стъпала = едно условие
пром_степен = 0; падат_под_прага = 0; губят_гледай = 0; делти = collections.Counter()
for x in r:
    нов = точки_от(x["всички"], слей_З=True)
    d = x["точки"] - нов
    делти[d] += 1
    с1, р1 = SL.f_степен(x["точки"]); с2, р2 = SL.f_степен(нов)
    if с1 != с2: пром_степен += 1
    if x["точки"] >= SL.ПРАГ_ПРАЩАНЕ and нов < SL.ПРАГ_ПРАЩАНЕ: падат_под_прага += 1
    if р1 >= 3 and р2 < 3: губят_гледай += 1
print("\n[2] ако Z1/Z2/Z2b станат ЕДНО условие (както иска находката):")
print("    загубени точки:", dict(sorted(делти.items())))
print(f"    сменена СТЕПЕН      : {пром_степен}/{len(r)} = {пром_степен/len(r):.1%}")
print(f"    падат под праг 9    : {падат_под_прага}/{len(карти)} от изпратените = "
      f"{(падат_под_прага/len(карти) if карти else 0):.1%}")
print(f"    губят «👁 ГЛЕДАЙ»   : {губят_гледай}")

# ── 3 · разлика между 5/7 и 7/7 в точки (твърдението «5 точки срещу 4»)
пр = [x for x in r if x["Z1"]]
print(f"\n[3] средни точки при Z1: 7/7={sum(x['точки'] for x in пр if x['Z2b'])/max(1,sum(1 for x in пр if x['Z2b'])):.2f}"
      f" · 5-6/7={sum(x['точки'] for x in пр if x['Z2'] and not x['Z2b'])/max(1,sum(1 for x in пр if x['Z2'] and not x['Z2b'])):.2f}"
      f" · 4/7={sum(x['точки'] for x in пр if not x['Z2'])/max(1,sum(1 for x in пр if not x['Z2'])):.2f}")

# ── 4 · ЖИВИЯТ праг е МОЗЪК_ПРАГ=14, не 9 (live_bot.py:74)
for праг in (9, 11, 14):
    ст = [x for x in r if x["точки"] >= праг]
    пад = sum(1 for x in ст if точки_от(x["всички"], слей_З=True) < праг)
    print(f"\n[4] праг {праг}: карти {len(ст)} · падат при сливане на Z1/Z2/Z2b: {пад}"
          f" ({(пад/len(ст) if ст else 0):.1%})")
    if ст:
        з3 = sum(1 for x in ст if x["Z1"] and x["Z2"] and x["Z2b"])
        print(f"          от тях с ПЪЛНО стъпало (Z1+Z2+Z2b): {з3} = {з3/len(ст):.1%}")
        print(f"          средни точки от З: {sum(sum([x['Z1'],x['Z2'],x['Z2b'],x['Z3']]) for x in ст)/len(ст):.2f} от 4")
