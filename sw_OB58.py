# -*- coding: utf-8 -*-
"""ОБОРВАНЕ на находка «таванът по група е декорация» — по РЕАЛНИЯ път."""
import sys, json, collections, warnings
sys.stdout.reconfigure(encoding="utf-8")
warnings.filterwarnings("ignore"); sys.path.insert(0, ".")
import brain.b_сливане as SL

r = json.load(open("sw_full.json", encoding="utf-8"))
N = len(r)
print("посока-кандидати с ПОВОД (реален път, 2026-05-29→07-07):", N)

макс = collections.Counter(); бр = collections.Counter()
for к,(т,г,_) in SL.ТАБЛИЦА.items():
    макс[г]+=т; бр[г]+=1

def погр(у):
    d={}
    for к,в in у.items():
        if не_(в): continue
        т,г,_ = SL.ТАБЛИЦА[к]; d[г]=d.get(г,0)+т
    return d
def не_(v): return not v

def точки(d): return sum(min(с, SL.ТАВАН_ГРУПА[г]) for г,с in d.items())

# КОНТРОЛА
лош = 0
сурови = []
for x in r:
    d = погр(x["всички"]); сурови.append(d)
    if точки(d) != x["точки"]: лош += 1
print("контрола · моето броене != точките на бота:", лош, "случая")

print("\n[1] РЕАЛНО ДОСТИГНАТИ сборове по група (преди тавана)")
print(f"{'гр':>3} {'усл':>4} {'макс':>5} {'таван':>6} {'реален макс':>12} {'достига макс':>13} {'таванът реже (реално)':>22}")
for г in sorted(SL.ТАВАН_ГРУПА):
    сер = [d.get(г,0) for d in сурови]
    рм = max(сер); дм = sum(1 for s in сер if s==макс[г])
    реже = sum(1 for s in сер if s > SL.ТАВАН_ГРУПА[г])
    print(f"{г:>3} {бр[г]:>4} {макс[г]:>5} {SL.ТАВАН_ГРУПА[г]:>6} {рм:>12} {дм:>13} {реже:>22}")

# [2] карти над живия праг
for праг,име in ((9,"ПРАГ_ПРАЩАНЕ"),(14,"МОЗЪК_ПРАГ (живият)")):
    к = [x for x in r if x["точки"]>=праг]
    print(f"\n[2] карти ≥{праг} ({име}): {len(к)}")

# [3] може ли ЕДНА група сама да вдигне карта над праг?
print("\n[3] максимален принос на ЕДНА група (след таван) vs праговете")
for г in sorted(SL.ТАВАН_ГРУПА):
    print(f"    {г}: max след таван = {min(макс[г],SL.ТАВАН_ГРУПА[г])}  → сама ли стига 9? "
          f"{min(макс[г],SL.ТАВАН_ГРУПА[г])>=9}  · 14? {min(макс[г],SL.ТАВАН_ГРУПА[г])>=14}")

# [4] дял на най-голямата група в точките на ИЗПРАТЕНИТЕ карти
for праг in (9,14):
    к = [(x,d) for x,d in zip(r,сурови) if x["точки"]>=праг]
    if not к: continue
    дялове=[]
    for x,d in к:
        макс_гр = max(min(с,SL.ТАВАН_ГРУПА[г]) for г,с in d.items())
        дялове.append(макс_гр/x["точки"])
    print(f"\n[4] праг {праг}: n={len(к)} · среден дял на НАЙ-ГОЛЯМАТА група = {sum(дялове)/len(дялове):.1%}"
          f" · макс дял = {max(дялове):.1%} · брой групи средно = {sum(len(d) for _,d in к)/len(к):.2f}")

# [5] КОНТРАФАКТ: какво би променил «истински» таван = макс-1 за всяка от 7-те
print("\n[5] контрафакт: стягам тавана на всяка «декоративна» група с 1 (макс-1)")
for г in sorted(SL.ТАВАН_ГРУПА):
    if макс[г] > SL.ТАВАН_ГРУПА[г]: continue
    нов = dict(SL.ТАВАН_ГРУПА); нов[г] = SL.ТАВАН_ГРУПА[г]-1
    def т2(d): return sum(min(с, нов[г2]) for г2,с in d.items())
    п9 = sum(1 for x,d in zip(r,сурови) if x["точки"]>=9 and т2(d)<9)
    п14= sum(1 for x,d in zip(r,сурови) if x["точки"]>=14 and т2(d)<14)
    смяна = sum(1 for x,d in zip(r,сурови) if SL.f_степен(x["точки"])[1]!=SL.f_степен(т2(d))[1])
    засег = sum(1 for d in сурови if d.get(г,0) > нов[г])
    print(f"    {г}: засегнати кандидати {засег:5d}/{N} · сменена степен {смяна:5d} · падат под 9: {п9:4d} · под 14: {п14:3d}")

# [6] реже ли А наистина
сА=[d.get("А",0) for d in сурови]
print("\n[6] група А (единственият «жив» таван): разпределение на сбора")
c=collections.Counter(сА)
for k in sorted(c): print(f"    {k}: {c[k]:6d}  {c[k]/N:6.1%}   {'← РЕЖЕ (>5)' if k>5 else ''}")
print("    реално отрязани точки от А общо:", sum(max(0,s-5) for s in сА))
