# ── НОВО ПАРЧЕ · само вече реализираните трети (без плаващата част) ────────
def _прибрано(hit, lv, entry, sign, hit_px=None):
    """`_ladder_pnl` с НУЛЕВ остатък → сборът на затворените трети.
    Единственият източник си остава _ladder_pnl; тук няма нова аритметика."""
    return _лад("прибрано", hit or {}, lv, float(entry), sign, 0.0, hit_px)[0]


def _ако_край(kind, hit, lv, entry, sign, цена, hit_px=None):
    """Колко ще е сделката, ако свърши на `цена` — пак през _ladder_pnl."""
    return _лад(kind, hit or {}, lv, float(entry), sign,
                (float(цена) - float(entry)) * sign, hit_px)[0]


def _ориг_стоп(tr):
    """Стопът ОТПРЕДИ да се премести на входа.
    ПРЕДПОЧИТАНО: tr['sl0'], записан при отварянето (един нов ключ).
    РЕЗЕРВА: правилото на _levels — sl = вход − знак × SL_D (live_bot.py:655)."""
    if tr.get("sl0") is not None:
        return float(tr["sl0"])
    зн = 1 if tr["direction"] == "long" else -1
    ед = lb.SL_D if tr.get("sym", "XAUUSD") == "XAUUSD" else lb.S_SL
    return round(float(tr["entry"]) - зн * ед, dec)


