def карта3(tr, spot, now):
    зн = 1 if tr["direction"] == "long" else -1
    _сим = tr.get("sym", "XAUUSD")
    _ст = PIP if _сим == "XAUUSD" else 0.001
    метал = "злато" if _сим == "XAUUSD" else "сребро"
