def подвижен_блок(x, L, B=4000, rng=None):
    """истински блоков бутстрап: съседни блокове по L последователни сделки"""
    rng = rng or np.random.default_rng(7)
    n = len(x); nb = int(np.ceil(n / L))
    старт = rng.integers(0, max(n - L + 1, 1), size=(B, nb))
    из = (старт[:, :, None] + np.arange(L)[None, None, :]).reshape(B, -1)[:, :n]
    return np.percentile(x[np.minimum(из, n - 1)].mean(axis=1), [2.5, 97.5])


def newey_west(x, lag):
    n = len(x); xm = x - x.mean(); g0 = (xm @ xm) / n
    s = g0
    for l in range(1, lag + 1):
        gl = (xm[l:] @ xm[:-l]) / n
        s += 2 * (1 - l / (lag + 1)) * gl
    return np.sqrt(max(s, 0) / n)


