# ── предложени ПОМОЩНИЦИ (нови в live_bot) ───────────────────────────────
def _за10(win):
    """«8 от 10» от процент — думата и числото казват едно и също."""
    return f"{float(win)/10:.0f} от 10" if win is not None else ""

def _интервал(lo, hi, метал="XAUUSD"):
    ст = PIP if метал == "XAUUSD" else 0.001
    def _z(v): return ("+" if v >= 0 else "−") + f"{abs(v)/ст:,.0f}"
    return f"{_z(lo)} и {_z(hi)} пипса ({lo:+.2f}$ .. {hi:+.2f}$)"

def _очаквано(м, метал="XAUUSD"):
    """Трите реда «какво се очаква» ИЗЦЯЛО от `_gate_trace['мерено']`."""
    if not м or м.get("win") is None or (м.get("n") or 0) < lb.MIN_N:
        return ["📊 за такъв случай нямам достатъчно измервания · затова не обещавам нищо"]
    L = [f"📊 какво се очаква · мерено назад до 2006: такъв случай е засичан "
         f"{м['n']:,} пъти".replace(",", " ")]
    L.append(f"✅ {_за10(м['win'])} от тях са свършвали на плюс ({м['win']}%) · "
             f"средно {lb._пари(float(м['net']), метал)} на сделка")
    if м.get("lo") is not None and м.get("hi") is not None:
        L.append(f"📉 честната граница: СРЕДНОТО е между {_интервал(м['lo'], м['hi'], метал)} · "
                 f"една отделна сделка спокойно може да удари стопа и да даде "
                 f"−{lb.SL_PIPS} пипса")
    return L

