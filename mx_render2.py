def _бр(n):
    return f"{int(n):,}".replace(",", " ")


def _ппз(д, метал="XAUUSD"):
    ст = PIP if метал == "XAUUSD" else 0.001
    return f"{'+' if д >= 0 else '−'}{abs(д)/ст:,.0f}"


def _зона_текст(zone):
    т = (zone or (None, ""))[1] or ""
    return re.sub(r"^[^\wА-Яа-я<]+", "", т).strip()


def _фмт(p, dec=2):
    return f"{p:,.{dec}f}"


def _дял_фраза(дял):
    if дял == "пълен размер":
        return "целия си обичаен размер"
    return дял.replace("от пълния", "от обичайния си размер")


