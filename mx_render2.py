def _разпределение(st_json, метал="XAUUSD"):
    """Формата на изхода под ДОСТАВЕНАТА стълба. Източник: stats['tp_hits_доставена']."""
    # 🔴 НАМЕРЕНО ПРИ РЕНДИРАНЕ · `tp_hits_доставена` е мерено ВЪРХУ ЗЛАТО
    # (geom_harness, XAUUSD). Първата ми версия делеше златните долари на
    # СРЕБЪРНАТА стъпка и даваше «+2 540 пипса» — чуждо число, преоблечено.
    # Правилото В1 в самия бот: сребро цитира САМО сребърни числа.
    if метал != "XAUUSD":
        return ["⚠️ «на плюс» може да значи и съвсем малко · за среброто такова "
                "разпределение не е мерено · затова не го цитирам"]
    d = (st_json or {}).get("tp_hits_доставена") or {}
    дял = d.get("дял_взети_цели") or {}
    ср = d.get("средно_по_брой_цели") or {}
    n = d.get("n")
    if not дял or not ср or not n:
        return ["⚠️ «на плюс» може да значи и съвсем малко · но точното "
                "разпределение не се чете от файла"]
    ст = PIP if метал == "XAUUSD" else 0.001

    def П(k):
        v = ср[k] / ст
        return f"{'+' if v >= 0 else '−'}{abs(v):,.0f}"

    def Д(k):
        return f"{дял[k]:.0f}"

    def ДП(k):
        return f"{'+' if ср[k] >= 0 else '−'}{abs(ср[k]):.2f}"

    return [
        (f"⚠️ «НА ПЛЮС» НЕ ЗНАЧИ МНОГО — мерено на всичките {_бр(n)} сделки по същата "
         f"стълба · всякакви дни · не само такива като днешния: {Д('1')} от 100 стигат "
         f"САМО първата цел → {П('1')} пипса ({ДП('1')}$) и толкова"),
        (f"↳ {Д('2')} от 100 стигат две цели → {П('2')} пипса ({ДП('2')}$) · "
         f"{Д('3')} от 100 минават и трите → {П('3')} пипса ({ДП('3')}$)"),
        (f"↳ {Д('0')} от 100 не стигат нито една цел → средно {П('0')} пипса "
         f"({ДП('0')}$) · това е групата · в която може да попадне и тази"),
    ]


def _десет(win):
    """«8 от всеки 10» + «2 от всеки 10» — със защита да не станат 10 и 0."""
    п = win / 10.0
    г = 10.0 - п
    if г < 0.5:
        return f"{п:.0f} от всеки 10", "по-малко от 1 от всеки 10"
    if п < 0.5:
        return "по-малко от 1 от всеки 10", f"{г:.0f} от всеки 10"
    return f"{п:.0f} от всеки 10", f"{г:.0f} от всеки 10"


def _очаквай(м, метал="XAUUSD"):
    if not м or not м.get("n") or м.get("win") is None or м["n"] < lb.MIN_N:
        return ["📊 КОЛКО ЧЕСТО ВЪРВИ — за случай като днешния нямам достатъчно "
                "измервания · затова не обещавам нищо"]
    доб, лош = _десет(м["win"])
    L = [f"📊 КОЛКО ЧЕСТО ВЪРВИ — мерено на дни като днешния "
         f"({КОФА_ОПИС.get(м['кофа'], м['кофа'])}): {_бр(м.get('дни') or 0)} такива дни "
         f"в историята · {_бр(м['n'])} входа · {м['win']:.1f}% са свършили на плюс",
         f"↳ {м['win']:.1f}% значи {доб} · но {лош} губят · и предварително никой не "
         f"знае коя от двете е ТАЗИ"]
    if м.get("lo") is not None and м.get("hi") is not None:
        L.append(f"↳ средно на вход излиза {lb._пари(float(м['net']), метал)} · истинското "
                 f"средно е някъде между {_ппз(м['lo'], метал)} и {_ппз(м['hi'], метал)} "
                 f"пипса — числото е за СРЕДНОТО · не за твоята сделка")
    else:
        L.append(f"↳ средно на вход излиза {lb._пари(float(м['net']), метал)} · без "
                 f"измерен интервал около него")
    return L


