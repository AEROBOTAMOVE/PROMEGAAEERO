def _бр(n):
    """4019 → «4 019». Английската запетая бърка окото на български.
    ПЛУМБИНГ: това парче го НЯМА в live_bot.py (сверено с AST на 21.08)."""
    return f"{int(n):,}".replace(",", " ")


def _мн(n, ед, мн):
    return f"{n} {ед if n == 1 else мн}"


def _ден_от(tr, now_utc):
    """Кой ден от най-много ДНИ_МАКС е сделката. Същият израз като live_bot.py:2410."""
    try:
        return (pd.Timestamp(now_utc) - pd.Timestamp(tr["opened"])).days + 1
    except Exception:
        return None


def _затваря_отваря(now_utc):
    """(затваря, отваря) по СОФИЙСКО, измерено чрез `_market_closed` — не по спомен.

    🔴 ПЪРВАТА МИ ВЕРСИЯ ЛЪЖЕШЕ. Тръгваше от «сега» и връщаше първия момент, в
    който пазарът е отворен — а в петък следобед това е САМО СЕГА. Картата
    написа «отваря в нощта срещу понеделник около 21:05», тоест текущия час.
    Сега първо се търси ЗАТВАРЯНЕТО, чак после отварянето след него."""
    t = pd.Timestamp(now_utc).floor("15min")     # без него «00:05» вместо «00:00»
    зат = None
    for _ in range(4 * 24 * 4):                      # до 4 денонощия напред
        if lb._market_closed(t.isoformat()):
            зат = t
            break
        t += pd.Timedelta(minutes=15)
    if зат is None:
        return None, None
    t = зат
    for _ in range(4 * 24 * 4):
        if not lb._market_closed(t.isoformat()):
            return lb._sofia(зат.isoformat()), lb._sofia(t.isoformat())
        t += pd.Timedelta(minutes=15)
    return lb._sofia(зат.isoformat()), None


def _мерено_ред(м, заглавие, метал="XAUUSD"):
    """ЕДИНСТВЕН вход: клетката, по която гейтът РЕШАВА. Под MIN_N — нищо не обещава.

    ПАРИТЕ ВОДЯТ, процентът идва СЛЕД тях. Обратният ред («68.6% на плюс», после
    «−0.47$») дава ред, който сам си противоречи, ако спреш да четеш на него."""
    if not м or not м.get("n") or м.get("win") is None or м["n"] < lb.MIN_N:
        return ["📊 за такъв случай нямам достатъчно измервания · затова не обещавам нищо"]
    L = [f"📊 {заглавие} — мерено в {_бр(м['дни'])} дни ({_бр(м['n'])} входа): "
         f"средно {lb._пари(float(м['net']), метал)} на вход"]
    if м.get("win") is not None:
        L.append(f"↳ {м['win']:.1f}% от входовете свършват на плюс и въпреки това сборът е "
                 f"под нулата · печалбите са дребни, а всяка загуба е цели "
                 f"{lb.SL_PIPS} пипса")
    return L


