MA_ДУМА={"ma50":"средната цена за последните 50 дни","ma200":"средната за 200 дни",
         "ema200":"плъзгащата средна за 200 дни","ma21":"средната за 21 дни"}
def mx_ниво(direction, ma_name, price, mb):
    ико="🟢" if direction=="long" else "🔴"
    накъде="нагоре" if direction=="long" else "надолу"
    мб = mb if isinstance(mb,dict) else {}
    нето,брой = мб.get("net"), мб.get("n")
    L=[f"📌 НИВО · цената се обърна {накъде} от {MA_ДУМА.get(ma_name, ma_name.upper())} · {lb._sofia()}",
       f"{ико} злато <code>{lb._fmt(price)}</code> · това е знак къде да гледаш, не сделка",
       "👉 ТИ НЕ ПРАВИШ НИЩО — по този знак не отварям сделка и нива за слагане няма"]
    if нето is None or not брой:
        L.append("📊 ЗАЩО НЕ — за такъв отскок нямам нито едно измерване · затова не обещавам нищо")
    else:
        шум = bool(мб.get("шум")) or (мб.get("lo") is not None and мб.get("hi") is not None
                                      and мб["lo"] <= 0 <= мб["hi"])
        L.append(f"📊 КОЛКО СТРУВА ТОЗИ ОТСКОК — мерен на {_бр(брой)} случая: "
                 f"{lb._пари(float(нето))} на случай")
        if мб.get("lo") is not None and мб.get("hi") is not None:
            L.append(f"↳ истинската стойност е някъде между {lb._пари(float(мб['lo']))} и "
                     f"{lb._пари(float(мб['hi']))}" + (" · нулата е вътре, тоест не се различава от нищо"
                     if шум else " · целият отрязък е под нулата, тоест уверено губещ"))
        if мб.get("win") is not None and float(нето) <= 0:
            L.append(f"⚠️ {float(мб['win']):.0f}% от тези отскоци свършват на плюс, а сборът пак не е над "
                     f"нулата — печалбите са дребни, загубите цели")
        L.append("👁 " + ("НЕ ВЛИЗАМ по него — мереното казва, че не си струва"
                 if (шум or float(нето)<=0) else
                 "ЗНАК, НЕ СЕ СЛЕДИ — този отскок изобщо не е вързан за сделки: няма нива, няма следене"))
    L.append("📅 СЛЕДВА — картата с истински вход идва отделно, когато има вход")
    return "\n".join(L)

