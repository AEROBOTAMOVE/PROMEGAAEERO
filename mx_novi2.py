def mx_изход(т, вид, цена, зн, свод=None):
    """🔴 ЧИСЛОТО СЕ СМЯТА КАКТО В ДНЕВНИКА (`_мозък_следене`, ОДИТ-57):
    щом цел1 е взета, наблюдението е ДВЕ ПОЛОВИНИ. Днешната карта показва
    голото (изход−вход) и си противоречи със собствения си дневник."""
    посока = "нагоре" if т["посока"] == "long" else "надолу"
    ч2 = (цена - т["вход"]) * зн
    ч1 = (т["цел1"] - т["вход"]) * зн if т.get("цел1_взета") and вид != "цел1" else None
    общо = (ч1/2.0 + ч2/2.0) if ч1 is not None else ч2
    глави = {"цел1": ("✅","ПЪРВАТА ЦЕЛ падна"), "цел2": ("🏆","ВТОРАТА ЦЕЛ падна"),
             "стоп": ("🛑","СТОПЪТ удари")}
    ико, дума = глави.get(вид, ("📌", вид))
    L=[f"{ико} {дума} · наблюдението от {lb._sofia(т['отворен'])} · злато {посока}",
       "👉 ТИ НЕ ПРАВИШ НИЩО — по това наблюдение не си влизал, значи няма и от какво да излезеш",
       f"💵 КРАЙНА СМЕТКА — {lb._пари(общо)} на унция · толкова щеше да е, ако беше влязъл"]
    if ч1 is not None:
        L.append(f"↳ по половина от всяка: цел 1 хвана {lb._пари(ч1)}, после стопът върна {lb._пари(ч2)}")
    else:
        L.append(f"↳ {lb._fmt(т['вход'],2)} → {lb._fmt(цена,2)} · един изход, без делене")
    if вид=="цел1" and т.get("цел2") is not None:
        L.append(f"🎯 ОСТАВА ВТОРАТА — {lb._fmt(т['цел2'],2)} · още {lb._пипс(abs(т['цел2']-цена))} оттук")
    else:
        L.append("👁 НАБЛЮДЕНИЕТО ПРИКЛЮЧИ — следващото отварям щом мозъкът види ново място")
    if свод:
        n,пл,сб = свод["общо"]
        L.append(f"📊 ТЕФТЕРЪТ — {_бр(n)} развръзки от {свод['от_дата'][8:10]}.{свод['от_дата'][5:7]} насам: "
                 f"{пл} на плюс, сборът е {lb._пари(сб)}")
    L.append("🧪 БЕЗ ПАРИ — тази логика няма зад себе си бектест · показвам я, за да се види работи ли")
    return "\n".join(L)

