БРОЙ_УСЛОВИЯ = 8


def f_степен(точки: int) -> str:
    """Броене на съвпадения → една от 7-те степени.

    0-1 → ИСКРА · 2 → НАБЛЮДЕНИЕ · 3 → ОФОРМЯ СЕ · 4 → ГОТОВ ·
    5 → СИЛЕН · 6 → МНОГО СИЛЕН · 7-8 → РЯДЪК

    8 условия, а не 7 — по същата причина както в b_свипове.py: с точно 7
    условия последната степен иска ВСИЧКИТЕ 7 наведнъж и остава празна.
    """
    т = int(max(0, min(БРОЙ_УСЛОВИЯ, точки)))
    if т <= 1:
        return СТЕПЕНИ[0]
    if т >= 7:
        return СТЕПЕНИ[6]
    return СТЕПЕНИ[т - 1]


