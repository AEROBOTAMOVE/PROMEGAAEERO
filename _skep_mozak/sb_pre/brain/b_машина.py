def f_часов_отпечатък(df: pd.DataFrame, дни_база: int = 20, **_) -> dict:
    """Казва колко широк е ОБИКНОВЕНО текущият час, спрямо последните 20 дни.

    Не гадае посока — измерено е, че посока по час НЯМА (0 от 24 часа с |t|>3).
    Казва РАЗМЕР: с колко да се разтегли или свие стопът точно сега.

    БЕЗ НАДНИЧАНЕ: базата е средният диапазон на МИНАЛИТЕ `дни_база` дни.
    """
    # 100 бара стигат: самата таблица по час е ВГРАДЕНА (мерена е върху 20
    # години) и не иска история. История иска само базата в долари — а тя е
    # добавка. Затова при къс прозорец връщам отговор БЕЗ базата, не «празно».
    # (Първата версия искаше 500 бара и мълчеше на живия прозорец от 400.)
    if df is None or len(df) < 100:
        return {"празно": True, "защо": "под 100 бара", "етикет": ЕТИКЕТ_НОВО}

    ix = pd.DatetimeIndex(df.index)
    диап = (df["high"] - df["low"]).values
    стъпка_мин = _стъпка_минути(ix)
    прозорец = max(96, int(дни_база * 24 * 60 / max(стъпка_мин, 1)))
    мин_периода = int(min(прозорец // 4, max(48, len(df) // 3)))
    база = pd.Series(диап).shift(1).rolling(
        min(прозорец, len(df) - 1), min_periods=мин_периода).mean().values
    сега = len(df) - 1
    b = база[сега]
    достатъчна_база = bool(b is not None and np.isfinite(b)
                           and len(df) >= прозорец // 2)
    ч = int(ix[сега].hour)
    дн = int(ix[сега].dayofweek)

    очакван_отн = ОТПЕЧАТЪК_ЧАС_ДЕН.get((дн, ч), ОТПЕЧАТЪК_ЧАС.get(ч, 1.0))
    има_ден = (дн, ч) in ОТПЕЧАТЪК_ЧАС_ДЕН
    очакван_дол = (b * очакван_отн) if (b and np.isfinite(b)) else None

    подредени = sorted(ОТПЕЧАТЪК_ЧАС.items(), key=lambda x: -x[1])
    ранг = [k for k, _ in подредени].index(ч) + 1

    точки = 0
    точки += 1 if очакван_отн >= 0.9 else 0
    точки += 1 if очакван_отн >= 1.0 else 0
    точки += 1 if очакван_отн >= 1.2 else 0
    точки += 1 if очакван_отн >= 1.4 else 0
    точки += 1 if очакван_отн >= 1.7 else 0
    точки += 1 if има_ден and очакван_отн >= 1.3 else 0
    точки += 1 if ранг <= 3 else 0
    точки += 1 if очакван_отн >= 1.9 else 0

    if очакван_отн >= 1.5:   състояние = "БУРЕН ЧАС"
    elif очакван_отн >= 1.1: състояние = "работен час"
    elif очакван_отн >= 0.85: състояние = "обичаен час"
    elif очакван_отн >= 0.7: състояние = "спокоен час"
    else:                    състояние = "ЗАСПАЛ ЧАС"

    return {
        "час_UTC": ч,
        "ден": ИМЕНА_ДНИ[дн],
        "относителна_широчина": очакван_отн,
        "от_таблица_час_ден": има_ден,
        "очакван_диапазон_долари": round(очакван_дол, 2) if очакван_дол else None,
        "база_20дни_долари": round(float(b), 2) if (b and np.isfinite(b)) else None,
        "базата_е_пълна": достатъчна_база,
        "ранг_на_часа": ранг,
        "състояние": състояние,
        "най_бурен_час_UTC": подредени[0][0],
        "най_тих_час_UTC": подредени[-1][0],
        "съотношение_бурен_тих": round(подредени[0][1] / подредени[-1][1], 2),
        "степен": f_степен(точки),
        "точки": точки,
        "посоката_не_работи": True,
        "мерено": "517 091 бара · ранг-корелация обуч↔провер 0.912 · p=0.00005",
        "етикет": ЕТИКЕТ_НОВО,
        "предупреждение": "Часът казва КОЛКО ще се движи, не НАКЪДЕ. "
                          "Посока по час е мерена: 0 от 24 часа са значими.",
    }


def _стъпка_минути(ix: pd.DatetimeIndex) -> int:
    if len(ix) < 3:
        return 15
    d = np.diff(_наносекунди(ix)[-60:])
    d = d[d > 0]
    return int(np.median(d) / 60_000_000_000) if len(d) else 15


