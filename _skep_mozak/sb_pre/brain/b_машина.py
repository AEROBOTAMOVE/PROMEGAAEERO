# М3 · СКОРОСТТА НА ВРЪЩАНЕ (вътре в свещта)
# ═══════════════════════════════════════════════════════════════════════════
#
# ЗАЩО ГРАФИКАТА НЕ МОЖЕ: на 15-минутна графика една свещ с фитил нагоре
# изглежда еднакво, независимо дали цената е била отвъд нивото 1 минута или
# 12 минути. Това е РАЗЛИЧНО събитие, но окото не го различава.
# Ботът има минутните барове и ги брои.
#
# ═══ КАКВО ИЗМЕРИХ (29 321 свипа на 15-мин рамка, срещу 7 658 440 мин. бара) ═══
# Колко минути (от 15) цената е ЗАТВАРЯЛА отвъд нивото:
#     0 мин → 12 815 свипа (43.7%!)   1 → 6 072   2 → 3 233   3 → 1 999
#     4 → 1 400   5 → 1 067   6 → 793   7 → 583   8 → 461   9 → 326
#     10 → 241   11 → 144   12 → 105   13 → 54   14 → 28
#     средно 1.75 мин · медиана 1 мин
# Тоест: при 43.7% от свиповете НИТО ЕДНА минутна свещ не е затворила отвъд
# нивото. Фитилът е пробол, но нищо не се е задържало. Това число просто
# НЕ СЪЩЕСТВУВА на 15-минутната графика.
#
# 🔴 ПОСОКА — НЕ РАБОТИ. Пак го казвам веднага.
# ТП=СТОП=7.5$, 24ч, платен спред:
#   ШОРТ след обран връх: 1мин -0.605 · 2мин -0.300 · 3-4мин -0.565 ·
#                         5-7мин -0.681 · 8+мин -0.498
#   ЛОНГ след обрано дъно: 1мин -0.363 · 2мин -0.531 · 3-4мин -0.284 ·
#                          5-7мин -0.619 · 8+мин -0.865
# Базова линия -0.30/-0.56. Никаква подредба. Проверих и на мащаба, на който
# собственикът наистина търгува — цел 2/3/5$ и хоризонт 2/4/8 часа, 12 нагласи
# общо. Никъде ръб. «Мълниеносното» връщане НЕ е по-добра сделка от мудното.
#
# ✅ КАКВО ОСТАВА ПОЛЗВАЕМО: описанието. «Цената стоя 9 минути над нивото»
# е различно състояние от «фитилът мина и се дръпна за 1 минута», дори когато
# не мога да докажа, че носи пари. Картата го казва, ботът го записва, и
# когато се натрупат живи случаи, ще се премери.
#
# ═══════════════════════════════════════════════════════════════════════════

def f_скорост_на_свипа(df: pd.DataFrame, df_1мин: pd.DataFrame,
                       колко: int = 5, пивот: int = ПИВОТ, **_) -> dict:
    """Мери колко МИНУТИ цената е стояла отвъд нивото при последните свипове.

    df       — 15-минутни барове
    df_1мин  — едноминутни барове (индекс = време, колони high/low/close)
    колко    — колко последни свипа да опише

    БЕЗ НАДНИЧАНЕ: гледат се само минутите ВЪТРЕ в 15-минутния бар на свипа,
    който вече е затворил.
    """
    if df is None or len(df) < 100 or df_1мин is None or len(df_1мин) < 100:
        return {"празно": True, "защо": "малко барове", "етикет": ЕТИКЕТ_НОВО}

    h, l, c = df["high"].values, df["low"].values, df["close"].values
    съб = _свипове(h, l, c, пивот)
    if not съб:
        return {"свипове": [], "брой": 0, "степен": СТЕПЕНИ[0],
                "етикет": ЕТИКЕТ_НОВО}

    t15 = _наносекунди(df.index)
    tm = _наносекунди(df_1мин.index)
    mh = df_1мин["high"].values; ml = df_1мин["low"].values
    mc = df_1мин["close"].values
    МИН = 60_000_000_000
    стъпка = int(np.median(np.diff(t15[-50:]))) if len(t15) > 51 else 15 * МИН

    изход = []
    for бар, пос, ниво, екс in съб[-колко:]:
        s = int(np.searchsorted(tm, t15[бар], "left"))
        e = int(np.searchsorted(tm, t15[бар] + стъпка, "left"))
        if e - s < 3:
            continue
        hh, ll, cc = mh[s:e], ml[s:e], mc[s:e]
        отвъд = (cc > ниво) if пос > 0 else (cc < ниво)
        проб = np.where(hh > ниво)[0] if пос > 0 else np.where(ll < ниво)[0]
        if len(проб) == 0:
            continue
        f = int(проб[0])
        назад = np.where(~отвъд)[0]; назад = назад[назад > f]
        връщане = int(назад[0] - f) if len(назад) else int(e - s - f)
        минути = int(отвъд.sum())
        изход.append({
            "бар": int(бар),
            "време": str(df.index[бар]),
            "посока": "ОБРАН ВРЪХ" if пос > 0 else "ОБРАНО ДЪНО",
            "ниво": round(float(ниво), 2),
            "екстремум": round(float(екс), 2),
            "минути_отвъд": минути,
            "минути_до_връщане": връщане,
            "минутни_барове_в_свещта": int(e - s),
            "описание": _опиши_скорост(минути),
        })

    посл = изход[-1] if изход else None
    точки = 0
    if посл:
        м = посл["минути_отвъд"]
        точки += 1                                   # има измерен свип
        точки += 1 if м == 0 else 0                  # чист фитил
        точки += 1 if посл["минути_до_връщане"] <= 2 else 0
        точки += 1 if м <= 1 else 0
        точки += 1 if посл["минутни_барове_в_свещта"] >= 12 else 0  # пълни данни
        точки += 1 if м <= 3 else 0
        точки += 1 if посл["минути_до_връщане"] <= 1 else 0
        точки += 1 if (м == 0 and посл["минути_до_връщане"] <= 1) else 0

    return {
        "свипове": изход,
        "последен": посл,
        "брой": len(изход),
        "степен": f_степен(точки),
        "точки": точки,
        "посоката_не_работи": True,
        "мерено": "описателно, 29 321 свипа срещу 7 658 440 мин. бара",
        "етикет": ЕТИКЕТ_НОВО,
        "предупреждение": "Скоростта описва СЪСТОЯНИЕТО. Мерена е за посока "
                          "в 12 нагласи и НЕ дава ръб. Не се залага на нея.",
    }


def _опиши_скорост(минути: int) -> str:
    """Описание на български, без забранената дума «слаб»."""
    if минути == 0:  return "чист фитил · нито една минута не затвори отвъд"
    if минути == 1:  return "мълния · 1 минута отвъд"
    if минути <= 2:  return "бързо връщане · %d минути отвъд" % минути
    if минути <= 4:  return "премерено · %d минути отвъд" % минути
    if минути <= 7:  return "задържа се · %d минути отвъд" % минути
    return "дълго стоене · %d минути отвъд (почти половин свещ)" % минути


def _наносекунди(ix) -> np.ndarray:
    """Индекс от времена → int64 наносекунди, без часова зона."""
    ix = pd.DatetimeIndex(ix)
    if ix.tz is not None:
        ix = ix.tz_localize(None)
    return ix.values.astype("datetime64[ns]").astype(np.int64)


