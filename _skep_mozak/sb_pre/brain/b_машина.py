# М4 · ЧАСОВИЯТ ОТПЕЧАТЪК
# ═══════════════════════════════════════════════════════════════════════════
#
# ЗАЩО ГРАФИКАТА НЕ МОЖЕ: за да каже «14:00 обикновено е 3 пъти по-широк от
# 21:00», човек трябва да преброи 20 години барове по час. Никой не го прави.
# Машината го прави за секунда и го помни.
#
# ═══ КАКВО ИЗМЕРИХ ═══
# Мярката е БЕЗРАЗМЕРНА: диапазонът на бара ÷ средния бар от последните
# 20 дни. Задължително безразмерна, защото златото е 430$ през 2005 и 4139$
# през 2026 — долари не се сравняват през 20 години.
# Нормализацията е ПРИЧИННА (само минали 20 дни) → ползваема на живо.
# Проверих я срещу нормализация «по същия ден» (която надничa): ранг-корелация
# 0.9983 — същата подредба, значи причинната версия не губи нищо.
#
# ОТПЕЧАТЪК ПО ЧАС (UTC), обучение 2005-2015 → проверка 2016-2026:
#   00: 0.890 → 0.853    08: 1.010 → 1.041    16: 1.287 → 1.129
#   01: 0.877 → 1.130    09: 0.972 → 0.918    17: 1.167 → 1.011
#   02: 0.714 → 0.829    10: 0.960 → 0.883    18: 1.025 → 0.992
#   03: 0.677 → 0.683    11: 1.024 → 0.968    19: 0.898 → 0.894
#   04: 0.685 → 0.591    12: 1.479 → 1.476    20: 0.709 → 0.699
#   05: 0.748 → 0.788    13: 1.677 → 1.808    21: 0.581 → 0.598
#   06: 0.895 → 0.963    14: 1.673 → 1.769    22: 0.733 → 0.758
#   07: 1.014 → 1.063    15: 1.500 → 1.476    23: 0.765 → 0.725
#
# ✅ УСТОЙЧИВОСТ: ранг-корелация обучение↔проверка = 0.9122 (причинна) /
#    0.9200 (по деня). Пермутационен тест, 20 000 разбърквания: p = 0.00005.
#    Топ-3 бурни часа: обучение [13,14,15] · проверка [13,14,12] — същите.
#    Топ-3 тихи часа:  обучение [21,3,4]  · проверка [21,4,3]  — същите.
#    Подредбата издържа 10 години напред. 13:00 UTC е 3.02 пъти по-широк от
#    21:00 UTC (1.808 / 0.598).
#
# 🔴 ПОСОКА ПО ЧАС — НЯМА. Проверих средния ход (close−open) за всеки от
#    24-те часа, 2016-2026. Часове с |t| > 3: НУЛА от 24. Най-силният е
#    23:00 UTC с t=+2.92, което при 24 гледания е точно каквото се очаква
#    от шума. Часът казва КОЛКО, не НАКЪДЕ.
#
# ✅ ЧАС × ДЕН — тук машината намери нещо, което не съм търсил:
#    сряда 18:00 = 1.36 срещу 0.81-0.95 за другите дни в същия час, и
#    сряда 19:00 = 1.17 срещу 0.78-0.89. Това е FOMC (20:00 ч. в София).
#    петък 13:00 = 2.00 срещу понеделник 13:00 = 1.58 — данните в началото
#    на месеца. Понеделникът е най-тихият ден (0.959), петъкът най-бурният
