def _atr(h, l, c, n: int = 14) -> np.ndarray:
    """ATR по Уайлдър. Същата сметка като в останалите модули."""
    h = np.asarray(h, float); l = np.asarray(l, float); c = np.asarray(c, float)
    pc = np.concatenate(([c[0]], c[:-1]))
    tr = np.maximum(h - l, np.maximum(np.abs(h - pc), np.abs(l - pc)))
    a = np.full(len(tr), np.nan)
    if len(tr) < n:
        return a
    a[n - 1] = tr[:n].mean()
    k = (n - 1) / n
    for i in range(n, len(tr)):
        a[i] = a[i - 1] * k + tr[i] / n
    return a


def _прерамкирай(d: pd.DataFrame, k: int):
    """15-минутни барове → рамка от k пъти по 15 мин.

    Връща и `край` — индексът на 15-минутния бар, НА КОЙТО рамката затваря.
    Това е моментът, в който събитието става известно. Ползва се, за да не
    се пише събитие върху бар, на който то още не е било видимо.
    """
    o = d["open"].values; h = d["high"].values
    l = d["low"].values;  c = d["close"].values
    v = d["volume"].values if "volume" in d.columns else np.zeros(len(d))
    if k == 1:
        return o, h, l, c, v, np.arange(len(d))
    гр = np.arange(len(d)) // k
    f = pd.DataFrame({"o": o, "h": h, "l": l, "c": c, "v": v,
                      "i": np.arange(len(d)), "g": гр})
    a = f.groupby("g").agg(o=("o", "first"), h=("h", "max"), l=("l", "min"),
                           c=("c", "last"), v=("v", "sum"), i=("i", "last"))
    return (a["o"].values, a["h"].values, a["l"].values, a["c"].values,
            a["v"].values, a["i"].values.astype(np.int64))


def _пивоти(x: np.ndarray, p: int = ПИВОТ, връх: bool = True) -> np.ndarray:
    """Булев масив: x[i] е пивот (центрирано прозорче 2p+1).

    ВНИМАНИЕ: пивотът на бар i е известен чак на бар i+p. Всяка функция,
    която ползва това, ТРЯБВА да чака p бара. Тук масивът се смята наведнъж
    за скорост, но потребителите му спазват закъснението.
    """
    s = pd.Series(x)
    if връх:
        м = s.rolling(2 * p + 1, center=True).max().values
        return (x >= м) & np.isfinite(м)
    м = s.rolling(2 * p + 1, center=True).min().values
    return (x <= м) & np.isfinite(м)


def _свипове(h, l, c, p: int = ПИВОТ, макс_нива: int = 500):
    """Свип = барът минава отвъд старо пивот-ниво и ЗАТВАРЯ обратно.

    Връща списък (бар, посока, ниво, екстремум).
    посока +1 = обран ВРЪХ (сигнал надолу) · -1 = обрано ДЪНО (сигнал нагоре).

    Тук е и първото надграждане спрямо Pine: индикаторът пази 10 нива ОБЩО
    (таван на рисунките). Тук пазя 500 на страна — Python няма такъв таван.
    """
    n = len(h)
    пв = _пивоти(h, p, True); пд = _пивоти(l, p, False)
    съб = []
    гор: list[float] = []   # възходящо по цена
    дол: list[float] = []   # възходящо по цена, вадя от края
    for j in range(p, n):
        i = j - p                      # пивотът е потвърден чак сега
        if пв[i]:
            insort(гор, h[i]); гор[:] = гор[-макс_нива:]
        if пд[i]:
            insort(дол, l[i]); дол[:] = дол[:макс_нива]
        hj = h[j]; lj = l[j]; cj = c[j]
        while гор and гор[0] < hj:
            ниво = гор.pop(0)
            if cj < ниво:
                съб.append((j, +1, ниво, hj))
        while дол and дол[-1] > lj:
            ниво = дол.pop()
            if cj > ниво:
                съб.append((j, -1, ниво, lj))
    return съб


