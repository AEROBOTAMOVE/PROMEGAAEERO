def тест_без_надничане(df: pd.DataFrame, точки: int = 12,
                       напред: int = 400, **params) -> dict:
    """ИСТИНСКАТА проверка: намира ли се СЪЩОТО събитие на бар j, когато
    бъдещето е налично, и когато не е?

    Плиткият вариант (пусни ф(df[:k]) два пъти) не може да гръмне никога —
    функцията и без това вижда само df[:k]. Затова тук сравнявам СЪБИТИЯТА:
    пускам откривателя върху КЪС отрязък (до k) и върху ДЪЛЪГ (до k+напред),
    после гледам само събитията на барове ≤ k−ПИВОТ−1, тоест такива, чието
    потвърждение е приключило и в двата случая.

    Ако дългият отрязък намира там събитие, което късият не намира —
    откривателят чете бъдещето и на живо ще лъже.
    """
    h_всички = df["high"].values
    l_всички = df["low"].values
    c_всички = df["close"].values
    n = len(df)
    старт = max(2000, n - 60000)
    места = np.linspace(старт, n - напред - 2, точки).astype(int)

    несъвпадения = []
    сверени = 0
    for k in места:
        k = int(k)
        къс = _свипове(h_всички[:k], l_всички[:k], c_всички[:k])
        дълъг = _свипове(h_всички[:k + напред], l_всички[:k + напред],
                         c_всички[:k + напред])
        праг = k - ПИВОТ - 1
        a = {(б, п, round(нв, 4)) for б, п, нв, _ in къс if б <= праг}
        b = {(б, п, round(нв, 4)) for б, п, нв, _ in дълъг if б <= праг}
        сверени += len(a | b)
        само_в_дългия = b - a
        само_в_късия = a - b
        if само_в_дългия or само_в_късия:
            несъвпадения.append({
                "бар": k,
                "само_с_бъдеще": len(само_в_дългия),
                "само_без_бъдеще": len(само_в_късия),
                "примери": sorted(само_в_дългия)[:3],
            })

    # втора проверка: ползва ли отпечатъкът бъдещи барове за базата си
    базови = []
    for k in места[:5]:
        k = int(k)
        a = f_часов_отпечатък(df.iloc[:k], **params)
        b = f_часов_отпечатък(df.iloc[:k + напред].iloc[:k], **params)
        базови.append(a.get("база_20дни_долари") == b.get("база_20дни_долари"))

    return {
        "места": [int(x) for x in места],
        "сверени_събития": сверени,
        "несъвпадения": несъвпадения,
        "чисто": len(несъвпадения) == 0,
        "база_стабилна": all(базови),
    }


def _сравни(a: dict, b: dict) -> bool:
    """Плитко сравнение на два отговора, без плаващите дреболии."""
    ключове = set(a) & set(b)
    for к in ключове:
        if к in ("нива", "свипове", "предупреждение", "мерено", "етикет"):
            continue
        va, vb = a[к], b[к]
        if isinstance(va, float) and isinstance(vb, float):
            if not (np.isnan(va) and np.isnan(vb)) and abs(va - vb) > 1e-9:
                return False
        elif va != vb:
            return False
    return True
