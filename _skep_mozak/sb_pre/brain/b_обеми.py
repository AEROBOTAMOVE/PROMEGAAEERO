def f_относителен_обем(df: pd.DataFrame,
                       дни: int | None = None,
                       мин_дни: int | None = None) -> dict:
    """
    ФУНДАМЕНТЪТ НА БЛОКА. Всичко останало стъпва тук.

    Връща за всеки бар:
      отн        — обем / медиана на същия слот от предишните `дни` дни (1.0 = нормално)
      база       — самата медиана (за да се вижда срещу какво се мери)
      отн_диап   — същото, но за ДИАПАЗОНА на свещта (high-low). Диапазонът има
                   същата часова сезонност и без нея сравненията лъжат по същия начин.
      z          — колко стандартни отклонения е log(отн) спрямо последните 10 дни
                   (причинно: средната и разсейката са само от минали барове)

    ВСИЧКО Е „НОВО · още не е мерено".

    Параметри:
      дни     — колко предишни появявания на слота правят базата (по подр. 20)
      мин_дни — под толкова базата е неготова и отн е None (по подр. 5)
    """
    дни = int(дни or ПРАГОВЕ["дни_профил"])
    мин_дни = int(мин_дни or ПРАГОВЕ["мин_дни"])
    D = _подготви(df)
    v, h, l, t = D["v"], D["h"], D["l"], D["t"]
    стъпка = _стъпка_минути(t)
    ключ = _ключове(t, стъпка)

    база_v = _базова_линия(v, ключ, дни, мин_дни)
    отн = _отношение(v, база_v)

    диап = h - l
    база_д = _базова_линия(диап, ключ, дни, мин_дни)
    отн_д = _отношение(диап, база_д)

    # z по log(отн), причинно: пълзяща средна/разсейка само от ПРЕДИШНИ барове
    с = pd.Series(np.log(np.where(отн > 0, отн, np.nan)))
    прз = max(20, дни * 4)
    м = с.rolling(прз, min_periods=прз // 4).mean().shift(1)
    ст = с.rolling(прз, min_periods=прз // 4).std().shift(1)
    z = ((с - м) / ст.replace(0, np.nan)).to_numpy(dtype="float64")

    готови = int(np.isfinite(отн).sum())
    return dict(
        отн=отн, база=база_v, отн_диап=отн_д, база_диап=база_д, z=z,
        обем=v, ключ=ключ, стъпка_минути=стъпка, времена=t,
        мета=dict(
            барове=len(v), готови=готови,
            дял_готови=round(готови / max(1, len(v)), 4),
            дни_профил=дни, слотове=int(len(np.unique(ключ))),
            статус=СТАТУС,
            обяснение="1.00 = точно колкото обикновено в този час; 2.00 = двойно",
        ),
    )


def f_обемен_профил(df: pd.DataFrame, дни: int | None = None) -> dict:
    """
    ДИАГНОСТИКА, не сигнал. Показва самата часова карта на обема и ДОКАЗВА, че
    нормализацията работи: остатъчната сезонност след деленето трябва да падне
    до ~1.0, докато при плоска средна остава ~7.

    Връща и двете, за да може числото да се провери, а не да се вярва.
    """
    R = f_относителен_обем(df, дни=дни)
    t, v, отн = R["времена"], R["обем"], R["отн"]
    час = t.hour.values

    сурово = pd.Series(v).groupby(pd.Series(час)).median()
    ok = np.isfinite(отн)
    след = pd.Series(отн[ok]).groupby(pd.Series(час[ok])).median()

    # наивният метод за сравнение: плоска средна на едно денонощие
    n = ПРАГОВЕ["прозорец_ден"]
    наив = (pd.Series(v) / pd.Series(v).rolling(n, min_periods=n // 5).mean().shift(1)).to_numpy()
    ok2 = np.isfinite(наив)
    след_наив = pd.Series(наив[ok2]).groupby(pd.Series(час[ok2])).median()

    def разсейка(s):
        s = s[s > 0]
        return float(s.max() / s.min()) if len(s) and s.min() > 0 else float("nan")

    return dict(
        профил_по_час={int(k): round(float(x), 3) for k, x in сурово.items()},
        сезонност_сурова=round(разсейка(сурово), 2),
        сезонност_след_часовник=round(разсейка(след), 2),
        сезонност_след_плоска_средна=round(разсейка(след_наив), 2),
        най_тих_час=int(сурово.idxmin()), най_натоварен_час=int(сурово.idxmax()),
        мета=dict(статус=СТАТУС,
                  чете_се="сезонност 1.00 = напълно изчистено; 7.00 = часът се брои за сигнал"),
    )


