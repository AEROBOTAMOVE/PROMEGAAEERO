# 8 · НАДГРАЖДАНЕ · ОБЕМЪТ НА 7 РАМКИ ЕДНОВРЕМЕННО
# ═══════════════════════════════════════════════════════════════════════════

РАМКИ = ("15мин", "30мин", "1час", "2часа", "4часа", "8часа", "1ден")
_ПРАВИЛА = {"15мин": "15min", "30мин": "30min", "1час": "1h", "2часа": "2h",
            "4часа": "4h", "8часа": "8h", "1ден": "1D"}
_МИНУТИ = {"15мин": 15, "30мин": 30, "1час": 60, "2часа": 120,
           "4часа": 240, "8часа": 480, "1ден": 1440}


def _прерамкирай(df: pd.DataFrame, правило: str, махни_непълния: bool = True) -> pd.DataFrame:
    """
    OHLC + СУМА на обема. Празните кофи падат (уикендите на златото).

    ⚠ МАХА ПОСЛЕДНАТА НЕЗАВЪРШЕНА КОФА (`махни_непълния`). Това не е дреболия:
    ако 4-часовият бар върви от 40 минути, в него има 1/6 от обема си, а базата му
    е от ПЪЛНИ 4-часови барове → отношението излиза ~0.17 и ботът би крещял
    „СУХ ОБЕМ" на всеки нов по-висок бар. Измерено преди поправката: дневната рамка
    даваше 0.61× просто защото денят беше стигнал до 15:45.

    Същата дисциплина има и индикаторът — `request.security(..., lookahead_off)` с
    `[1]`, тоест САМО ЗАВЪРШЕНИ свещи (v9.3 р. 222-268).
    Незавършената кофа не се губи — мери се честно от `_частичен_отн()` по-долу.
    """
    к = {c.lower(): c for c in df.columns}
    д = df.resample(правило, label="left", closed="left").agg({
        к["open"]: "first", к["high"]: "max", к["low"]: "min",
        к["close"]: "last", к["volume"]: "sum",
    })
    д.columns = ["open", "high", "low", "close", "volume"]
    д = д.dropna(subset=["open", "high", "low", "close"])
    if махни_непълния and len(д):
        стъпка = pd.Timedelta(minutes=_стъпка_минути(df.index))
        период = pd.Timedelta(minutes=_минути_на_правило(правило))
        # кофата е пълна само ако последният наличен бар стига до края ѝ
        if df.index[-1] < д.index[-1] + период - стъпка:
            д = д.iloc[:-1]
    return д


def _минути_на_правило(правило: str) -> int:
    return int(pd.Timedelta(правило.replace("min", "min")).total_seconds() // 60)


def _частичен_отн(df: pd.DataFrame, правило: str, дни: int, мин: int) -> dict:
    """
    НАДГРАЖДАНЕ, КОЕТО ГРАФИКАТА НЕ МОЖЕ ИЗОБЩО.

    Текущият 4-часов бар е изкарал 40 минути. Колко обем Е НОРМАЛНО да има на
    40-ата минута от 4-часов бар в този час на деня? Индикаторът не може да пита
    това — той вижда само завършени свещи. Ботът може: сравнява натрупаното досега
    със СЪЩИТЕ ПЪРВИ k подбара от предишните дни.

    Тоест: не „днешният ден срещу целите предишни дни" (нечестно), а
    „днес до 15:45 срещу предишните дни до 15:45" (честно).

    ИЗМЕРЕНО В ТАЗИ СЕСИЯ · 200 случайни момента ВЪТРЕ в деня, данни от 2024 нататък.
    Случаен момент от обичаен ден трябва да дава медиана ~1.00:

        метод                                     медиана   обявява „СУХ" (<=0.55)
        частичен ден срещу ЦЕЛИ дни (наивно)       0.456          56.0%
        частичен ден срещу СЪЩИТЕ първи N подбара  1.037           2.5%

    Тоест наивното сравнение би крещяло „СУХ ОБЕМ" на дневната рамка в 56% от
    случаите без никаква причина — просто защото денят още не е свършил.

    БЕЗ НАДНИЧАНЕ: ползват се само подбарове, които вече са затворили, и само
    предишни кофи.
    """
    к = {c.lower(): c for c in df.columns}
    кофа = df.index.floor(правило)
    d = pd.DataFrame({"кофа": кофа, "v": df[к["volume"]].to_numpy(dtype="float64")})
    d["поз"] = d.groupby("кофа").cumcount()
    брой = d.groupby("кофа")["поз"].size()
    k = int(d["поз"].iloc[-1])                     # 0-базирана позиция в текущата кофа

    # само кофи, стигнали поне до същата позиция — иначе сумата им е подценена
    годни = брой[брой >= k + 1].index
    под = d[d["кофа"].isin(годни) & (d["поз"] <= k)]
    сум = под.groupby("кофа")["v"].sum()
    if len(сум) < мин + 1:
        return dict(отн=None, изминали=k + 1, база=None, годни_кофи=len(сум))

    idx = pd.DatetimeIndex(сум.index)
    ключ = _ключове(idx, _минути_на_правило(правило))
    база = _базова_линия(сум.to_numpy(dtype="float64"), ключ, дни, мин)
    b = база[-1]
    if not np.isfinite(b) or b <= 0:
        return dict(отн=None, изминали=k + 1, база=None, годни_кофи=len(сум))
    return dict(отн=float(сум.iloc[-1] / b), изминали=k + 1,
                база=round(float(b), 4), годни_кофи=len(сум))


def f_обем_рамки(df: pd.DataFrame, рамки=РАМКИ, **params) -> dict:
    """
    НАДГРАЖДАНЕ, КОЕТО ГРАФИКАТА НЕ МОЖЕ. Човекът гледа една рамка. Ботът гледа 7
    и БРОИ СЪВПАДЕНИЯТА — колко от 7-те рамки в момента показват обем над обичайния
    за своя час.

    Всяка рамка си има СОБСТВЕН часовник-профил (обичайният обем за 4-часов бар в
    12:00 не е същият като за 4-часов бар в 00:00), затова нормализацията се прави
    ОТДЕЛНО за всяка рамка, а не се преизползва 15-минутната.

    Степента = броят съгласни рамки (0..7), картографиран в 7-те състояния:
    съгласието на 7 рамки е 💎 РЯДЪК по построение.

    ВСИЧКО Е НОВО · още не е мерено.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    редове, съгласни, налични = [], 0, 0
    for име in рамки:
        пр = _ПРАВИЛА.get(име)
        if пр is None:
            continue
        try:
            д = _прерамкирай(df, пр)                    # само ЗАВЪРШЕНИ кофи
            if len(д) < P["мин_дни"] * 3:
                редове.append(dict(рамка=име, отн=None, състояние="малко история",
                                   барове=len(д)))
                continue
            R = f_относителен_обем(д, дни=P["дни_профил"], мин_дни=max(3, P["мин_дни"] // 2))
            r = R["отн"][-1]
            ч = _частичен_отн(df, пр, P["дни_профил"], max(3, P["мин_дни"] // 2))

            # за живо решение тежи ТЕКУЩАТА кофа (честно пропорционално),
            # а ако я няма — последната завършена
            живо = ч["отн"] if ч["отн"] is not None else (float(r) if np.isfinite(r) else None)
            if живо is None:
                редове.append(dict(рамка=име, отн=None, състояние="няма база",
                                   барове=len(д)))
                continue
            налични += 1
            над = bool(живо >= 1.3)
            съгласни += int(над)
            редове.append(dict(
                рамка=име,
                отн=round(float(живо), 2),                       # това, което тежи сега
                отн_завършен=(round(float(r), 2) if np.isfinite(r) else None),
                отн_текущ=(round(float(ч["отн"]), 2) if ч["отн"] is not None else None),
                изминали_подбара=ч["изминали"],
                барове=len(д), време=д.index[-1],
                състояние=("СКОК" if живо >= P["скок"] else
                           ("НАД ОБИЧАЙНОТО" if над else
                            ("СУХ" if живо <= P["сух"] else "ОБИЧАЕН"))),
                над_обичайното=над,
                основа=("текуща кофа, пропорционално" if ч["отн"] is not None
                        else "последна завършена кофа"),
            ))
        except Exception as гр:                                  # noqa: BLE001
            редове.append(dict(рамка=име, отн=None, състояние="грешка: %s" % гр))

    точки = int(round(съгласни / max(1, налични) * БРОЙ_УСЛОВИЯ)) if налични else 0
    return dict(
        рамки=редове, съгласни=съгласни, налични=налични,
        точки=точки, степен=f_степен(точки),
        текст=("%d ОТ %d РАМКИ ПОКАЗВАТ ОБЕМ НАД ОБИЧАЙНИЯ ЗА СВОЯ ЧАС" % (съгласни, налични)
               if налични else "НЯМА ДОСТАТЪЧНО ИСТОРИЯ ЗА РАМКИТЕ"),
        мета=dict(статус=СТАТУС,
                  праг_съгласие=1.3,
                  обяснение="съгласие = отн. обем >= 1.30 на съответната рамка"),
    )


