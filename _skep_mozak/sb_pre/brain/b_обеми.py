# 12 · ПРОВЕРКА ЗА НАДНИЧАНЕ В БЪДЕЩЕТО
# ═══════════════════════════════════════════════════════════════════════════

def тест_без_надничане(df: pd.DataFrame, точки: int = 12, **params) -> dict:
    """
    МАШИННА ПРОВЕРКА, не обещание.

    Пуска блока върху все по-дълги префикси на данните. Ако функция надничаше в
    бъдещето, събитие издадено на бар i щеше да се ПРОМЕНИ, когато дойдат още барове.
    Изисква се: всяко събитие, издадено на префикс A, да се появява БАЙТ В БАЙТ
    същото и на всеки по-дълъг префикс.

    Мери се и относителният обем сам по себе си — не само събитията.
    """
    n = len(df)
    старт = max(int(n * 0.5), 200)
    стъпки = [int(старт + (n - старт) * k / точки) for k in range(1, точки + 1)]
    стъпки = sorted(set(min(s, n) for s in стъпки))

    еталон_съб, еталон_отн = {}, {}
    несъвпадения, проверени = [], 0
    for край in стъпки:
        под = df.iloc[:край]
        R = f_относителен_обем(под, **{k: v for k, v in params.items()
                                       if k in ("дни", "мин_дни")})
        отн = R["отн"]
        # 1 · самата база не бива да се променя със задна дата
        for i in range(0, край):
            if not np.isfinite(отн[i]):
                continue
            кл = i
            нов = round(float(отн[i]), 9)
            проверени += 1
            ако = еталон_отн.get(кл)
            if ако is None:
                еталон_отн[кл] = нов
            elif abs(ако - нов) > 1e-9:
                несъвпадения.append(("отн_обем", i, ако, нов))

        # 2 · събитията също
        for име, бл, ключ in (("скок", f_обемен_скок(под, **params), "скокове"),
                              ("разминаване", f_разминаване(под, **params), "разминавания")):
            for e in бл[ключ]:
                кл = (име, e["бар"])
                отпечатък = (e["вид"], e["точки"], e["отн_обем"], e["степен"])
                ако = еталон_съб.get(кл)
                if ако is None:
                    еталон_съб[кл] = отпечатък
                elif ако != отпечатък:
                    несъвпадения.append((име, e["бар"], ако, отпечатък))

    ок = len(несъвпадения) == 0
    return dict(
        чисто=ок,
        префикси=стъпки,
        проверени_стойности=проверени,
        проверени_събития=len(еталон_съб),
        несъвпадения=несъвпадения[:10],
        присъда=("ЧИСТО · нито една издадена стойност не се промени със задна дата"
                 if ок else "🔴 НАДНИЧАНЕ · %d промени със задна дата" % len(несъвпадения)),
    )


