# 10 · КАРТАТА (на български, за Телеграм)
# ═══════════════════════════════════════════════════════════════════════════

def f_карта_обеми(рез: dict, макс: int = 3) -> str:
    """Готов текст за картата. Никъде не се твърди, че е мерено."""
    с = рез.get("сега", {})
    р = ["📊 ОБЕМИ · НОВО · още не е мерено",
         "──────────────────────────────"]
    ако = с.get("отн_обем")
    if ако is None:
        р.append("Няма достатъчно история за този час — базата се строи от 20 предишни дни.")
        return "\n".join(р)
    р.append("Сега: %s · %.2f× обичайния обем за този час" % (с["състояние"], ако))
    if с.get("отн_диапазон") is not None:
        р.append("Диапазон: %.2f× обичайния за този час" % с["отн_диапазон"])

    рм = рез.get("рамки") or {}
    if рм.get("налични"):
        р.append("Рамки: %s · %s" % (рм["текст"], рм["степен"]))
        р.append("  " + " · ".join(
            "%s %.2f×" % (x["рамка"], x["отн"]) for x in рм["рамки"]
            if x.get("отн") is not None))

    for ключ, вътрешен, заглавие in (("скокове", "скокове", "СКОК НА ОБЕМА"),
                                     ("разминавания", "разминавания", "РАЗМИНАВАНЕ"),
                                     ("сухи", "сухи", "СУХ ОБЕМ")):
        бл = рез.get(ключ) or {}
        сп = бл.get(вътрешен) or []
        if not сп:
            continue
        р.append("")
        р.append("%s · последни %d:" % (заглавие, min(макс, len(сп))))
        for e in сп[-макс:]:
            р.append("  %s %s · %s" % (e["степен"], _къс_час(e.get("време")), e["текст"]))
            р.append("     цена %.2f · обем %.2f× · %d/%d условия"
                     % (e["цена"], e["отн_обем"], e["точки"], БРОЙ_УСЛОВИЯ))

    р.append("")
    р.append("⚠ Този блок е НОВ. Старите правила имат 20 години измерване, тези — нямат.")
    return "\n".join(р)


def _къс_час(t) -> str:
    if t is None:
        return "—"
    try:
        return pd.Timestamp(t).strftime("%d.%m %H:%M")
    except Exception:                                            # noqa: BLE001
        return str(t)


