# 11 · АКО ЛИПСВА ОБЕМ — ЧЕСТНИЯТ ЗАМЕСТИТЕЛ
# ═══════════════════════════════════════════════════════════════════════════

def f_заместител_без_обем(df: pd.DataFrame, **params) -> dict:
    """
    ЗА ДРУГ ИЗТОЧНИК НА ДАННИ, КЪДЕТО ОБЕМ НЯМА (примерно чист спот фийд).

    В ТЕЗИ parquet-и ОБЕМ ИМА — проверено — така че тази функция НЕ се ползва за
    златото тук. Стои, защото бойният фийд на бота може да е друг, и защото
    алтернативата е да се измисли обем, което е по-лошо от липсващ.

    Заместителят е `диапазон × брой посоки` — активността, която ЛИЧИ в цената:
    отн. диапазон за часа × колко пъти свещта е сменила посоката вътре в себе си
    (по-ситни барове, ако има). Тук се дава само отн. диапазон, честно наречен
    ЗАМЕСТИТЕЛ, за да не се бърка със същински обем.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    к = {c.lower(): c for c in df.columns}
    t = df.index
    стъпка = _стъпка_минути(t)
    ключ = _ключове(t, стъпка)
    диап = (df[к["high"]].to_numpy(dtype="float64") - df[к["low"]].to_numpy(dtype="float64"))
    база = _базова_линия(диап, ключ, P["дни_профил"], P["мин_дни"])
    отн = _отношение(диап, база)
    i = len(отн) - 1
    return dict(
        отн_диапазон=отн, база=база,
        сега=(round(float(отн[i]), 2) if np.isfinite(отн[i]) else None),
        мета=dict(вид="ЗАМЕСТИТЕЛ — НЕ Е ОБЕМ",
                  предупреждение="мери активност, видяна в цената; не мери участници",
                  статус=СТАТУС),
    )


