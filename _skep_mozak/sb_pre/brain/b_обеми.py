def зареди_реални(път: str = ПЪТ_15М, последни: int | None = None,
                  от: str | None = None) -> pd.DataFrame:
    """
    Чете parquet-а през fastparquet (pyarrow е блокиран от Application Control на
    машината). Същият четец като в b_свипове.py, за да са сравними числата.

    OHLC = средата между bid и ask. Обем = volume_bid + volume_ask.
    Изхвърля непълния последен бар и застоялите котировки (1191 бара).
    """
    import fastparquet
    к = ["timestamp_utc", "open_bid", "high_bid", "low_bid", "close_bid", "volume_bid",
         "open_ask", "high_ask", "low_ask", "close_ask", "volume_ask",
         "is_incomplete_last_bar_bid", "is_stale_quote_bid", "session"]
    d = fastparquet.ParquetFile(път).to_pandas(columns=к)
    d = d[~d["is_incomplete_last_bar_bid"].astype(bool)]
    d = d[~d["is_stale_quote_bid"].astype(bool)]
    изх = pd.DataFrame({
        "open": (d["open_bid"] + d["open_ask"]) / 2.0,
        "high": (d["high_bid"] + d["high_ask"]) / 2.0,
        "low": (d["low_bid"] + d["low_ask"]) / 2.0,
        "close": (d["close_bid"] + d["close_ask"]) / 2.0,
        "volume": (d["volume_bid"] + d["volume_ask"]).astype("float64"),
        "session": d["session"].values,
    })
    изх.index = pd.DatetimeIndex(d["timestamp_utc"])
    изх = изх.sort_index()
    if от:
        изх = изх[изх.index >= от]
    if последни:
        изх = изх.iloc[-последни:]
    return изх
