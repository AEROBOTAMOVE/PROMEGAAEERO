# 5 · СУХ ОБЕМ / ИЗЧЕРПВАНЕ
# ═══════════════════════════════════════════════════════════════════════════

def f_сух_обем(df: pd.DataFrame, сух: float | None = None, **params) -> dict:
    """
    НАМИРА: участъци, в които обемът е ПРЕСЪХНАЛ спрямо обичайното за часа.

    Защо на бота му трябва: сух обем значи „никой не се интересува тук".
    Две различни четения, затова се връщат РАЗДЕЛЕНИ, а не в една купчина:

      ИЗСЪХВАНЕ_В_ХОД  — цената още се движи, но обемът си отива. Движението
                         остава без гориво. (тренд без участници)
      ЗАТИШИЕ          — и обемът, и диапазонът са свити. Пружина преди ход.

    8 условия за степента:
      1 под_прага · 2 много_сух · 3 три_бара_подред · 4 най-малък_за_20
      5 диапазонът_също_е_свит · 6 цената_още_върви (за изсъхването)
      7 z_под_-1 · 8 след_скок (изсъхване веднага след скок = изчерпване)

    ВСИЧКО Е НОВО · още не е мерено.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    праг = float(сух if сух is not None else P["сух"])
    R = f_относителен_обем(df, дни=P["дни_профил"], мин_дни=P["мин_дни"])
    D = _подготви(df)
    o, h, l, c, v, t = D["o"], D["h"], D["l"], D["c"], D["v"], D["t"]
    отн, отн_д, z = R["отн"], R["отн_диап"], R["z"]

    мин20 = pd.Series(v).rolling(P["прозорец_най_голям"], min_periods=2).min().shift(1).to_numpy()
    n_под = P["сух_поредица"]

    събития, сериен = [], 0
    for i in range(len(v)):
        r = отн[i]
        if not np.isfinite(r) or r > праг:
            continue
        сериен += 1
        подред = 0
        j = i
        while j >= 0 and np.isfinite(отн[j]) and отн[j] <= праг:
            подред += 1; j -= 1
            if подред >= 10:
                break
        # цената още ли върви? посоката на последните 5 бара срещу диапазона им
        от = max(0, i - 4)
        ход = abs(c[i] - c[от])
        обхват = max(float(np.max(h[от:i + 1]) - np.min(l[от:i + 1])), 1e-9)
        още_върви = (ход / обхват) >= 0.6
        след_скок = bool(any(np.isfinite(отн[k]) and отн[k] >= P["скок"]
                             for k in range(max(0, i - 3), i)))

        у = [
            ("под_прага", r <= праг),
            ("много_сух", r <= P["много_сух"]),
            ("%d_бара_подред" % n_под, подред >= n_под),
            ("най-малък_за_%d" % P["прозорец_най_голям"],
             bool(np.isfinite(мин20[i]) and v[i] < мин20[i])),
            ("диапазонът_също_свит",
             bool(np.isfinite(отн_д[i]) and отн_д[i] <= P["диапазон_свит"])),
            ("цената_още_върви", bool(още_върви)),
            ("z_под_-1", bool(np.isfinite(z[i]) and z[i] <= -1.0)),
            ("веднага_след_скок", след_скок),
        ]
        точки = sum(1 for _, б in у if б)
        вид = "ИЗСЪХВАНЕ В ХОД" if още_върви else "ЗАТИШИЕ"
        текст = ("ДВИЖЕНИЕТО ОСТАВА БЕЗ ГОРИВО — %.0f%% ОТ ОБИЧАЙНИЯ ОБЕМ" % (r * 100)
                 if още_върви else
                 "ЗАТИШИЕ — %.0f%% ОТ ОБИЧАЙНИЯ ОБЕМ, СВИТ ДИАПАЗОН" % (r * 100))
        събития.append(dict(
            номер=сериен, бар=int(i), време=t[i],
            цена=round(float(c[i]), 3), вид=вид, текст=текст,
            отн_обем=round(float(r), 2),
            отн_диапазон=(round(float(отн_д[i]), 2) if np.isfinite(отн_д[i]) else None),
            z=(round(float(z[i]), 2) if np.isfinite(z[i]) else None),
            барове_подред=int(подред),
            обем=round(float(v[i]), 4), обичаен_обем=round(float(R["база"][i]), 4),
            точки=точки, съвпадения=[име for име, б in у if б],
            степен=f_степен(точки), статус=СТАТУС,
        ))

    раз = {}
    for e in събития:
        раз[e["вид"]] = раз.get(e["вид"], 0) + 1
    return dict(
        сухи=събития, последен=(събития[-1] if събития else None),
        мета=dict(брой=len(събития), праг=праг, по_вид=раз,
                  дял_от_баровете=round(len(събития) / max(1, len(v)), 4), статус=СТАТУС),
    )


