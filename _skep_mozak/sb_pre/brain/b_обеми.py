def _подготви(df: pd.DataFrame) -> dict:
    """
    Вади масивите. Изисква open/high/low/close; обемът е ЗАДЪЛЖИТЕЛЕН за този блок —
    ако липсва, се гърми ясно, вместо да се измисля заместител наум.
    """
    к = {c.lower(): c for c in df.columns}
    липсва = [x for x in ("open", "high", "low", "close") if x not in к]
    if липсва:
        raise ValueError("липсват колони: %s (има: %s)" % (липсва, list(df.columns)))
    if "volume" not in к:
        raise ValueError(
            "БЛОК 7 иска колона `volume`. Няма я. Виж f_заместител_без_обем() — "
            "не измисляй обем."
        )
    t = df.index
    if not isinstance(t, pd.DatetimeIndex):
        raise ValueError("индексът трябва да е DatetimeIndex — часовникът е основата на блока")
    return dict(
        o=df[к["open"]].to_numpy(dtype="float64"),
        h=df[к["high"]].to_numpy(dtype="float64"),
        l=df[к["low"]].to_numpy(dtype="float64"),
        c=df[к["close"]].to_numpy(dtype="float64"),
        v=df[к["volume"]].to_numpy(dtype="float64"),
        t=t,
    )


def _стъпка_минути(t: pd.DatetimeIndex) -> int:
    """Дължината на бара в минути — по медианата на разликите (устойчиво на уикендите)."""
    if len(t) < 3:
        return 15
    d = np.diff(t.values).astype("timedelta64[m]").astype("float64")
    m = float(np.median(d[d > 0])) if np.any(d > 0) else 15.0
    return max(1, int(round(m)))


def _ключове(t: pd.DatetimeIndex, стъпка: int) -> np.ndarray:
    """
    Ключът, по който се сравнява „същият час в предишните дни".

    ключ = тип_ден × 10000 + слот_в_деня

    · слот = (час*60 + минута) // стъпка  → при 15 мин има 96 слота в денонощието
    · тип_ден = 1 за неделя, 0 за делник — измерено: неделните барове са 1.33×
      спрямо делниците (частична сесия), затова се сравняват само с предишни недели.
    · Ако барът е дневен или по-голям (стъпка >= 1440), слотът е 0 и ключът остава
      само типът ден → базата се изражда в проста медиана на предишните N дни.
    """
    ако_дневен = стъпка >= 1440
    слот = np.zeros(len(t), dtype="int64") if ако_дневен else \
        ((t.hour.values * 60 + t.minute.values) // стъпка).astype("int64")
    тип = (t.dayofweek.values == 6).astype("int64")  # 6 = неделя
    return тип * 10000 + слот


def _базова_линия(x: np.ndarray, ключ: np.ndarray, дни: int, мин: int) -> np.ndarray:
    """
    Базова линия на бар i = МЕДИАНАТА на същия ключ (същия слот, същия тип ден)
    от предишните `дни` появявания.

    БЕЗ НАДНИЧАНЕ: `.shift(1)` е вътре в групата → стойността за бар i се смята от
    появявания СТРОГО ПРЕДИ i. Собственият обем на бара никога не влиза в базата му.

    Медиана, не средна — измерено е, че обемът има изхвърчащи стойности (макс 45.2
    при медиана 1.4 през 2017); една новина би вдигнала средната за 20 дни напред.
    """
    s = pd.Series(x, dtype="float64")
    г = s.groupby(pd.Series(ключ))
    б = г.transform(lambda z: z.rolling(дни, min_periods=мин).median().shift(1))
    # copy=True — pandas връща изглед само за четене и присвояването гърми
    out = np.array(б.to_numpy(dtype="float64"), dtype="float64", copy=True)
    out[~np.isfinite(out)] = np.nan
    out[out <= 0] = np.nan
    return out


def _отношение(x: np.ndarray, база: np.ndarray) -> np.ndarray:
    """x / база, с NaN там, където базата още не е готова (първите дни)."""
    с = np.full(len(x), np.nan)
    ok = np.isfinite(база) & (база > 0)
    с[ok] = x[ok] / база[ok]
    return с


