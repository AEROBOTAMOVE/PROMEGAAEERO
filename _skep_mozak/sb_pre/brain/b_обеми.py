# 9 · СЪБИРАНЕ · СЪСТОЯНИЕТО НА ОБЕМА В МОМЕНТА
# ═══════════════════════════════════════════════════════════════════════════

def f_обеми(df: pd.DataFrame, свипове=None, зони=None, **params) -> dict:
    """
    ЕДНА ВРАТА КЪМ ЦЕЛИЯ БЛОК. Пуска всичко и връща състоянието на ПОСЛЕДНИЯ
    ЗАТВОРЕН бар + събитията. Това е функцията, която главният агент да закачи в бота.

    ВСИЧКО Е НОВО · още не е мерено — не се смесва с меренето на старите правила.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    R = f_относителен_обем(df, дни=P["дни_профил"], мин_дни=P["мин_дни"])
    скокове = f_обемен_скок(df, **params)
    сухи = f_сух_обем(df, **params)
    разм = f_разминаване(df, **params)
    рамки = f_обем_рамки(df, **params)

    i = len(R["отн"]) - 1
    r = R["отн"][i]
    има = np.isfinite(r)
    състояние = "НЯМА БАЗА"
    if има:
        if r >= P["голям_скок"]:
            състояние = "ГОЛЯМ СКОК"
        elif r >= P["скок"]:
            състояние = "СКОК"
        elif r >= 1.3:
            състояние = "НАД ОБИЧАЙНОТО"
        elif r <= P["много_сух"]:
            състояние = "ПРЕСЪХНАЛ"
        elif r <= P["сух"]:
            състояние = "СУХ"
        else:
            състояние = "ОБИЧАЕН"

    изход = dict(
        сега=dict(
            бар=int(i), време=R["времена"][i],
            отн_обем=(round(float(r), 2) if има else None),
            отн_диапазон=(round(float(R["отн_диап"][i]), 2)
                          if np.isfinite(R["отн_диап"][i]) else None),
            z=(round(float(R["z"][i]), 2) if np.isfinite(R["z"][i]) else None),
            обичаен_обем=(round(float(R["база"][i]), 4)
                          if np.isfinite(R["база"][i]) else None),
            състояние=състояние, статус=СТАТУС,
        ),
        основа=R, скокове=скокове, сухи=сухи, разминавания=разм, рамки=рамки,
        мета=dict(барове=len(R["отн"]), статус=СТАТУС),
    )
    if свипове is not None:
        изход["свипове_с_обем"] = f_обем_при_свип(df, свипове, **params)
    if зони is not None:
        изход["зони_с_обем"] = f_обем_при_зона(df, зони, **params)
    return изход


