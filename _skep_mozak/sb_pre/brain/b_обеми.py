# 7 · ОБЕМ ВЪРХУ ЧУЖДО СЪБИТИЕ (свип от b_свипове, зона от b_зони)
# ═══════════════════════════════════════════════════════════════════════════

_КЛЮЧОВЕ_БАР = ("бар", "бар_пробождане", "родена", "бар_създаване", "index", "i")


def _извади_бар(e: dict) -> int | None:
    for k in _КЛЮЧОВЕ_БАР:
        if k in e and e[k] is not None:
            try:
                return int(e[k])
            except (TypeError, ValueError):
                continue
    return None


def f_обем_при_събитие(df: pd.DataFrame, събития: list,
                       прозорец: int = 3, име: str = "СЪБИТИЕ", **params) -> dict:
    """
    ОБЩАТА ФУНКЦИЯ: взима готови събития от друг блок (свипове, зони, гапове) и
    им ЗАКАЧА измерен обемен подпис. Нарочно е развързана — намира бара под всяко
    от имената `бар` / `бар_пробождане` / `родена` / `бар_създаване`, за да работи
    и с b_свипове.py, и с b_зони.py, без да ги пипа.

    НЕ променя подадените събития — връща КОПИЯ (оригиналът на другия блок остава цял;
    „нищо съществуващо не се маха").

    Закача:
      обем_отн        — колко пъти над обичайното за часа е бил обемът НА бара
      обем_отн_макс   — най-високото в прозореца (събитието може да е узряло 1-2 бара)
      обем_подпис     — СКОК / НОРМАЛЕН / СУХ
      обем_точки      — 0..3 добавка към степента на чуждото събитие
      обем_текст      — готов ред за картата

    ВСИЧКО Е НОВО · още не е мерено.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    R = f_относителен_обем(df, дни=P["дни_профил"], мин_дни=P["мин_дни"])
    отн, отн_д, z = R["отн"], R["отн_диап"], R["z"]
    n = len(отн)

    изход, без_база = [], 0
    for e in списък_или_празно(събития):
        i = _извади_бар(e)
        к = dict(e)  # КОПИЕ
        if i is None or not (0 <= i < n) or not np.isfinite(отн[i]):
            без_база += 1
            к.update(обем_отн=None, обем_отн_макс=None, обем_подпис="НЯМА ДАННИ",
                     обем_точки=0,
                     обем_текст="обем: няма база за този бар (началото на историята)",
                     обем_статус=СТАТУС)
            изход.append(к); continue
        от = max(0, i - int(прозорец) + 1)
        прз = отн[от:i + 1]
        прз = прз[np.isfinite(прз)]
        макс = float(np.max(прз)) if len(прз) else float(отн[i])
        r = float(отн[i])

        if макс >= P["голям_скок"]:
            подпис, точки = "СКОК", 3
        elif макс >= P["скок"]:
            подпис, точки = "СКОК", 2
        elif r <= P["сух"]:
            подпис, точки = "СУХ", 0
        else:
            подпис, точки = "НОРМАЛЕН", 1

        if подпис == "СКОК":
            текст = "обем: %.1f× обичайния за часа — ИМА КОЙ ДА ГО ПРАВИ" % макс
        elif подпис == "СУХ":
            текст = "обем: %.0f%% от обичайния — НЯМА УЧАСТНИЦИ, движението е само" % (r * 100)
        else:
            текст = "обем: %.1f× обичайния — обичайно участие" % r
        к.update(
            обем_отн=round(r, 2), обем_отн_макс=round(макс, 2),
            обем_отн_диапазон=(round(float(отн_д[i]), 2) if np.isfinite(отн_д[i]) else None),
            обем_z=(round(float(z[i]), 2) if np.isfinite(z[i]) else None),
            обем_подпис=подпис, обем_точки=точки, обем_текст=текст, обем_статус=СТАТУС,
        )
        изход.append(к)

    раз = {}
    for e in изход:
        раз[e["обем_подпис"]] = раз.get(e["обем_подпис"], 0) + 1
    return dict(
        събития=изход,
        мета=dict(име=име, брой=len(изход), без_база=без_база,
                  по_подпис=раз, прозорец=int(прозорец), статус=СТАТУС),
    )


def списък_или_празно(x) -> list:
    if x is None:
        return []
    if isinstance(x, dict):
        for k in ("свипове", "зони", "събития", "скокове", "гапове"):
            if k in x and isinstance(x[k], list):
                return x[k]
        return []
    return list(x)


def f_обем_при_свип(df: pd.DataFrame, свипове, **params) -> dict:
    """
    СВИПЪТ + ОБЕМЪТ. Приема направо изхода на `b_свипове.f_свипове(...)` (целия dict
    или списъка) и връща същите свипове с измерен обемен подпис.

    ЗАЩО Е ВАЖНО ИМЕННО ТУК: обраният стоп с ГОЛЯМ обем и обраният стоп със СУХ обем
    изглеждат еднакво на графиката — една и съща свещ с фитил. Единствената разлика,
    която ги дели, е обемът, а него индикаторът не мери (проверено: 0 срещания на
    `volume` в двата .pine файла). Това е чиста добавка, не замяна.

    ВНИМАНИЕ · b_свипове.py вече има поле `обем_кратно`, но то е спрямо ПЛОСКА
    96-барова средна. Измерено: този метод оставя 7.02× часова сезонност, дава 33%
    фалшиви тревоги в 12-16h UTC и пропуска 74.7% от истинските скокове в тихите
    часове. Тук `обем_отн` е спрямо СЪЩИЯ ЧАС. Старото поле не се маха — стои до
    новото, за да се вижда разликата.

    ВСИЧКО Е НОВО · още не е мерено.
    """
    return f_обем_при_събитие(df, списък_или_празно(свипове), име="СВИП", **params)


def f_обем_при_зона(df: pd.DataFrame, зони, **params) -> dict:
    """
    ЗОНАТА + ОБЕМЪТ. Приема изхода на `b_зони.f_зони(...)`.

    Зоната е родена от импулсен бар. Импулс с голям обем е следа от истински
    участник; импулс със сух обем е бягство в тънък пазар. Оценката на зоната в
    Pine (р. 783-792) брои 8 неща и НИТО ЕДНО не е обем — просто няма достъп.

    ВСИЧКО Е НОВО · още не е мерено.
    """
    return f_обем_при_събитие(df, списък_или_празно(зони), име="ЗОНА", **params)


