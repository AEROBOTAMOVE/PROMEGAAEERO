# 6 · РАЗМИНАВАНЕ ОБЕМ ↔ ДИАПАЗОН (тук е собствената информация на обема)
# ═══════════════════════════════════════════════════════════════════════════

def f_разминаване(df: pd.DataFrame, **params) -> dict:
    """
    ДВЕТЕ НАХОДКИ, КОИТО ДИАПАЗОНЪТ НЕ МОЖЕ ДА ВИДИ.

    ДВЕ РАЗЛИЧНИ ЧИСЛА, ЗА ДА НЕ СЕ БЪРКАТ:
      · по петили (диагностиката, с която проверих дали обемът изобщо носи нещо):
        1.07% поглъщане + 1.50% тънък ход = 2.57% от баровете
      · с праговете НА ТАЗИ ФУНКЦИЯ (по-строги): измерено 1.14% от 248 358 бара
        — 750 поглъщания + 2 090 тънки хода.
    Второто е това, което функцията наистина връща.

      ПОГЛЪЩАНЕ  — голям обем, малка свещ. Някой пълни поръчка, а цената не помръдва.
                   Значи отсрещната страна поема всичко. Обикновено на ръба на зона.
      ТЪНЪК ХОД  — голяма свещ, малък обем. Цената е минала през празно.
                   Такова движение няма кой да го защити.

    Точно това е причината обемът да не е излишен: измерено r = 0.689 между
    log(обем) и log(диапазон) → R² = 0.475, значи 52.5% от обема е СОБСТВЕНА
    информация. Разминаването е тази информация в чист вид.

    ВСИЧКО Е НОВО · още не е мерено.
    """
    P = dict(ПРАГОВЕ); P.update(params)
    R = f_относителен_обем(df, дни=P["дни_профил"], мин_дни=P["мин_дни"])
    D = _подготви(df)
    o, h, l, c, v, t = D["o"], D["h"], D["l"], D["c"], D["v"], D["t"]
    отн, отн_д, z = R["отн"], R["отн_диап"], R["z"]
    макс20 = _рол_макс(v, P["прозорец_най_голям"])

    събития, сериен = [], 0
    for i in range(len(v)):
        r, rd = отн[i], отн_д[i]
        if not (np.isfinite(r) and np.isfinite(rd)):
            continue
        поглъщане = (r >= P["поглъщане_обем"]) and (rd <= P["диапазон_свит"])
        тънък = (rd >= P["тънък_диапазон"]) and (r <= P["тънък_обем"])
        if not (поглъщане or тънък):
            continue
        сериен += 1
        поз = _посока_на_затварянето(o, h, l, c, i)
        тяло = abs(c[i] - o[i]); диап = max(h[i] - l[i], 1e-9)

        if поглъщане:
            # кой поема: затваряне във ВЪРХА след голям обем = купувачите поемат
            страна = "КУПУВАЧИТЕ ПОЕМАТ" if поз >= 0.6 else \
                     ("ПРОДАВАЧИТЕ ПОЕМАТ" if поз <= 0.4 else "БОРБА БЕЗ ПОБЕДИТЕЛ")
            у = [
                ("обем_над_2x", r >= 2.0),
                ("обем_над_3x", r >= 3.0),
                ("диапазон_свит", rd <= P["диапазон_свит"]),
                ("диапазон_много_свит", rd <= 0.6),
                ("малко_тяло", (тяло / диап) <= 0.35),
                ("има_победител", поз >= 0.6 or поз <= 0.4),
                ("най-голям_за_20", bool(np.isfinite(макс20[i]) and v[i] > макс20[i])),
                ("z_над_2", bool(np.isfinite(z[i]) and z[i] >= 2.0)),
            ]
            вид, текст = "ПОГЛЪЩАНЕ", "ГОЛЯМ ОБЕМ, ЦЕНАТА НЕ МЪРДА — %s" % страна
        else:
            страна = "НАГОРЕ" if c[i] > o[i] else "НАДОЛУ"
            у = [
                ("диапазон_над_1.6", rd >= P["тънък_диапазон"]),
                ("диапазон_над_2.2", rd >= 2.2),
                ("обем_под_0.75", r <= P["тънък_обем"]),
                ("обем_под_0.5", r <= 0.5),
                ("голямо_тяло", (тяло / диап) >= 0.5),
                ("решително_затваряне", поз >= 0.7 or поз <= 0.3),
                ("z_под_0", bool(np.isfinite(z[i]) and z[i] <= 0.0)),
                ("не_е_най-голям_за_20", bool(np.isfinite(макс20[i]) and v[i] < макс20[i])),
            ]
            вид, текст = "ТЪНЪК ХОД", "ГОЛЯМА СВЕЩ БЕЗ УЧАСТНИЦИ (%s) — МИНАЛА Е ПРЕЗ ПРАЗНО" % страна
        точки = sum(1 for _, б in у if б)
        събития.append(dict(
            номер=сериен, бар=int(i), време=t[i], вид=вид, текст=текст,
            цена=round(float(c[i]), 3),
            връх=round(float(h[i]), 3), дъно=round(float(l[i]), 3),
            страна=страна,
            отн_обем=round(float(r), 2), отн_диапазон=round(float(rd), 2),
            затваряне_в_свещта=round(поз, 2),
            дял_тяло=round(float(тяло / диап), 2),
            точки=точки, съвпадения=[име for име, б in у if б],
            степен=f_степен(точки), статус=СТАТУС,
        ))

    раз = {}
    for e in събития:
        раз[e["вид"]] = раз.get(e["вид"], 0) + 1
    return dict(
        разминавания=събития, последен=(събития[-1] if събития else None),
        поглъщания=[e for e in събития if e["вид"] == "ПОГЛЪЩАНЕ"],
        тънки=[e for e in събития if e["вид"] == "ТЪНЪК ХОД"],
        мета=dict(брой=len(събития), по_вид=раз,
                  дял_от_баровете=round(len(събития) / max(1, len(v)), 4), статус=СТАТУС),
    )


