# ПРЕНОС 1:1 · веригата на съседните пивоти (v9.3 р. 472–479)
# ─────────────────────────────────────────────────────────────────────────────
def _нива_pine(high, върхове, low, дъна, толеранс, max_each_side, pivot):
    """
    Точно както на графиката, ДЕФЕКТИТЕ ВКЛЮЧИТЕЛНО:
      · сравнява се само със СЪСЕДНИЯ пивот (Д3)
      · `previous` се презаписва винаги → троен връх дава 2 припокриващи се нива (Д2)
      · сила винаги 2 (Д1)
      · таван max_each_side, FIFO изхвърляне (Д4)

    `бар_потвърден` = центърът на ПО-КЪСНИЯ пивот + pivot.
    Точно това е барът, на който Pine изпълнява f_add_liquidity — нито един по-рано.
    """
    out = []
    for центрове, src, вид in ((върхове, high, "връх"), (дъна, low, "дъно")):
        редица = []
        предишен_цена, предишен_бар = None, None
        for c in центрове:
            p = float(src[c])
            if предишен_цена is not None and abs(p - предишен_цена) <= толеранс:
                редица.append({
                    "цена": (p + предишен_цена) / 2.0,   # р. 474/478: средата
                    "вид": вид,
                    "допири": 2,                          # Д1: твърдо 2
                    "ширина": abs(p - предишен_цена),
                    "бар_първи": int(предишен_бар),
                    "бар_последен": int(c),
                    "бар_потвърден": int(c) + int(pivot),
                })
            предишен_цена, предишен_бар = p, c            # Д2: винаги се презаписва
        # Д4: таван — FIFO, най-старите отпадат
        if len(редица) > max_each_side:
            редица = редица[-max_each_side:]
        out.extend(редица)
    return out


