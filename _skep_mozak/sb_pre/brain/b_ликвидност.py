# ─────────────────────────────────────────────────────────────────────────────
# СКАЛА ОТ 7 СТЕПЕНИ · по СЪСТОЯНИЕ, не по качество
# Степента идва от броя изпълнени условия (0–8), не от усещане.
# ─────────────────────────────────────────────────────────────────────────────
СКАЛА = [
    (0, "✨ ИСКРА"),
    (2, "👀 НАБЛЮДЕНИЕ"),
    (3, "🔨 ОФОРМЯ СЕ"),
    (4, "✅ ГОТОВ"),
    (5, "🔥 СИЛЕН"),
    (6, "⚡ МНОГО СИЛЕН"),
    (7, "💎 РЯДЪК"),
]


def степен(точки: int) -> str:
    """точки 0–8 → една от 7-те степени. Чисто броене, без преценка."""
    име = СКАЛА[0][1]
    for праг, етикет in СКАЛА:
        if точки >= праг:
            име = етикет
    return име


# ─────────────────────────────────────────────────────────────────────────────
# ПОМОЩНИ · ATR и пивоти
# ─────────────────────────────────────────────────────────────────────────────
def _atr_rma(df: pd.DataFrame, period: int = 14) -> np.ndarray:
    """ta.atr(14) на Pine = RMA (Wilder) на True Range. Пренос 1:1."""
    h = df["high"].to_numpy(float)
    l = df["low"].to_numpy(float)
    c = df["close"].to_numpy(float)
    pc = np.concatenate(([c[0]], c[:-1]))
    tr = np.maximum(h - l, np.maximum(np.abs(h - pc), np.abs(l - pc)))
    # RMA: alpha = 1/period, seed = SMA на първите period
    atr = np.full(len(tr), np.nan)
    if len(tr) < period:
        return atr
    atr[period - 1] = tr[:period].mean()
    a = 1.0 / period
    for i in range(period, len(tr)):
        atr[i] = atr[i - 1] * (1 - a) + tr[i] * a
    return atr


def _пресметни_рамка(d: pd.DataFrame, правило: str) -> pd.DataFrame | None:
    """
    Сглобява по-висока рамка от вече ОТРЯЗАНИЯ `d`.
    Последната кофа се маха, защото свещта ѝ още не е затворена — същото, което
    прави `lookahead_off` в Pine (v9.3 р. 222–268: подават се само `[1]` стойности).
    """
    ix = d.index
    if not isinstance(ix, pd.DatetimeIndex):
        for к in ("timestamp_utc", "timestamp", "time", "datetime"):
            if к in d.columns:
                ix = pd.DatetimeIndex(pd.to_datetime(d[к]))
                break
        else:
            return None
    агр = {"open": "first", "high": "max", "low": "min", "close": "last"}
    if "volume" in d.columns:
        агр["volume"] = "sum"
    t = d[list(агр)].copy()
    t.index = ix
    r = t.resample(правило, label="left", closed="left").agg(агр).dropna(subset=["close"])
    return r.iloc[:-1] if len(r) > 1 else None


def _pivot_centers(series: np.ndarray, left: int, right: int, посока: str) -> np.ndarray:
    """
    Индексите на баровете-ЦЕНТРОВЕ на пивотите.

    ПРЕНОС на ta.pivothigh(src, left, right):
      центърът е строго по-висок от `left` бара наляво И от `right` бара надясно.

    ⚠ ЧЕСТНО: точното държане на TradingView при ТОЧНО РАВНИ съседни барове
    (кой печели при равенство) НЕ Е ПРОВЕРЕНО в тази сесия — нямам достъп до
    вътрешния код на ta.pivothigh. Ползвам строго `>` от двете страни, което е
    най-разпространената реализация. Разликата засяга само ТОЧНИТЕ равенства
    в рамките на ±5 бара, а те са МЕРЕНИ: 4 958 от 530 659 бара = 0.187%
    (t_ликвидност.py, тест 4). Тоест дори да греша за равенствата, ефектът е
    под една пета от процента.
    """
    s = pd.Series(series)
    if посока == "high":
        лява = s.rolling(left).max().shift(1)          # max(i-left .. i-1)
        дясна = s.rolling(right).max().shift(-right)   # max(i+1 .. i+right)
        флаг = (s > лява) & (s > дясна)
    else:
        лява = s.rolling(left).min().shift(1)
        дясна = s.rolling(right).min().shift(-right)
        флаг = (s < лява) & (s < дясна)
    return np.flatnonzero(флаг.fillna(False).to_numpy())


# ─────────────────────────────────────────────────────────────────────────────
# ГЛАВНАТА ФУНКЦИЯ
# ─────────────────────────────────────────────────────────────────────────────
def f_ликвидност(
    df: pd.DataFrame,
    *,
    # ── настройки от графиката (пренос) ──────────────────────────────────────
    pivot: int = 5,                    # liquidityPivot        (v9.3 р. 53)
    tolerance_pct: float = 0.06,       # liquidityTolerancePct (v9.3 р. 54)
    max_each_side: int = 5,            # maxLiquidityEachSide  (v9.3 р. 55)
    fresh_bars: int = 12,              # sweepFreshBars        (v9.3 р. 56)
    # ── управление ───────────────────────────────────────────────────────────
    mode: str = "plus",                # "pine" = 1:1 с графиката · "plus" = надградено
    as_of: int | None = None,          # индекс на последния ЗАТВОРЕН бар
    lookback: int = 1500,              # колко бара назад се търсят нива (plus)
    # ── надграждания ─────────────────────────────────────────────────────────
    mtf: tuple | None = ("1h", "4h"),  # Н5 · правила за пресмятане на по-високи рамки
    max_dist_atr: float = 25.0,        # по-далечните нива не влизат в изхода
) -> dict:
    """
    Намира нивата на струпана ликвидност (равни върхове EQH / равни дъна EQL)
    и ги подрежда по сила.

    Вход : df с колони open/high/low/close (+ volume, ако има), подредени по време.
    Изход: dict — виж `ключове` накрая на функцията.

    Всяко ниво в изхода е речник с:
      цена            float · нивото (средата на клъстера)
      вид             "връх" | "дъно"     (EQH / EQL)
      допири          int   · колко пивота го образуват  (ПРЕНОСЪТ винаги дава 2)
      ширина          float · $ разлика между най-високия и най-ниския пивот
      бар_първи       int   · индекс на първия пивот-център
      бар_последен    int   · индекс на последния пивот-център
      бар_потвърден   int   · КОГА нивото е станало видимо = бар_последен + pivot
                              ⇒ доказателството срещу надничане
      възраст_барове  int   · as_of − бар_потвърден
      обран           bool  · вече ли са обрани стоповете там
      обран_на_бар    int|None
      обран_свеж      bool  · свипът е в последните `fresh_bars` бара
      разстояние      float · цена − текущата цена  (със знак)
      разстояние_абс  float
      разстояние_пц   float · в проценти
      разстояние_atr  float · в ATR-и — това е меродавното за злато
      обем_х          float · обем, стоял на тази цена / обем на ТИПИЧНАТА цена
                              в прозореца. x1.0 = обикновено, x2.0 = двойно (Н3)
      рамки           list  · на кои по-високи рамки нивото също съществува (Н5)
      точки           int   · 0–8, изпълнените условия
      условия         dict  · КОИ точно условия са изпълнени (за проверка)
      степен          str   · една от 7-те
      мерено          bool  · ВИНАГИ False — няма бектест зад това ниво
    """
    if mode not in ("pine", "plus"):
        raise ValueError("mode трябва да е 'pine' или 'plus'")

    n_общо = len(df)
    if as_of is None:
        as_of = n_общо - 1
    if as_of < pivot * 2 + 2:
        return _празен(as_of, mode, "твърде малко барове")

    # ═══ ЗАЩИТА ОТ НАДНИЧАНЕ · стъпка 1 ═══
    # Отрязваме всичко след `as_of`. Оттук нататък бъдещето физически го няма.
    #
    # РАБОТЕН ПРОЗОРЕЦ: не смятаме върху 530 000 бара, а само върху нужното.
    # Това НЕ е компромис — Pine сам гледа най-много `max_bars_back = 1200`
    # бара назад (v9.3 р. 8), тоест графиката също не вижда по-старото.
    назад = (1200 if mode == "pine" else lookback) + pivot * 2 + 60
    отместване = max(0, as_of - назад)
    d = df.iloc[отместване : as_of + 1]
    край = as_of - отместване            # индексът на `as_of` ВЪТРЕ в прозореца

    high = d["high"].to_numpy(float)
    low = d["low"].to_numpy(float)
    close = d["close"].to_numpy(float)
    има_обем = "volume" in d.columns
    vol = d["volume"].to_numpy(float) if има_обем else None

    цена_сега = float(close[-1])
    atr_ред = _atr_rma(d, 14)
    atr = float(atr_ред[-1]) if not np.isnan(atr_ред[-1]) else float(np.nanmean(high - low))
    if not np.isfinite(atr) or atr <= 0:
        atr = max(1e-9, float(np.nanmean(high - low)))

    # ПРЕНОС р. 445: толерансът е процент от цената.
    толеранс = цена_сега * tolerance_pct / 100.0

    # ═══ ЗАЩИТА ОТ НАДНИЧАНЕ · стъпка 2 ═══
    # Пивот с център `c` се знае едва на бар `c + pivot`. Приемаме само тези,
    # чийто потвърждаващ бар вече е минал.
    # всички индекси оттук нататък са ВЪТРЕ в прозореца; накрая се връща `отместване`
    върхове = _pivot_centers(high, pivot, pivot, "high")
    дъна = _pivot_centers(low, pivot, pivot, "low")
    върхове = върхове[върхове + pivot <= край]
    дъна = дъна[дъна + pivot <= край]

    # ── ОБЕМ ПРИ ЦЕНА (Н3) · подготовка ─────────────────────────────────────
    # Мери се «колко обем е стоял на тази цена» спрямо ТИПИЧНОТО за прозореца,
    # а не спрямо обема на един бар. Иначе всяко ниво излиза «огромен обем»
    # (първата версия даваше x40–x100 на всичко → безполезна точка).
    обем_профил = None
    if има_обем:
        стъпка = max(толеранс, 0.01)
        мрежа = np.arange(float(np.nanmin(low)), float(np.nanmax(high)) + стъпка, стъпка)
        if 2 <= len(мрежа) <= 20000:
            # обем на всеки ценови коридор: бар дава обема си на всеки коридор,
            # който диапазонът му покрива
            i0 = np.clip(np.searchsorted(мрежа, low, "right") - 1, 0, len(мрежа) - 1)
            i1 = np.clip(np.searchsorted(мрежа, high, "right") - 1, 0, len(мрежа) - 1)
            профил = np.zeros(len(мрежа))
            v_ok = np.nan_to_num(vol)
            for k in range(len(low)):
                профил[i0[k] : i1[k] + 1] += v_ok[k]
            непразни = профил[профил > 0]
            if len(непразни):
                обем_профил = (мрежа, профил, float(np.median(непразни)))

    # ── СЪБИРАНЕ НА НИВАТА ──────────────────────────────────────────────────
    if mode == "pine":
        сурови = _нива_pine(high, върхове, low, дъна, толеранс, max_each_side, pivot)
    else:
        сурови = _нива_клъстер(high, върхове, low, дъна, толеранс, pivot)

    # ── МНОГО РАМКИ (Н5) ────────────────────────────────────────────────────
    # ⚠ СРЕЩУ НАДНИЧАНЕ: по-високите рамки НЕ идват отвън, а се сглобяват от
    # СЪЩИЯ вече отрязан `d`. Така е физически невъзможно да влезе бар след
    # `as_of`. Освен това последната (недовършена) кофа се ИЗХВЪРЛЯ — точно
    # както `request.security(..., lookahead_off)` дава само ЗАТВОРЕНИ свещи
    # (v9.3 р. 222–268).
    mtf_нива: dict[str, list[float]] = {}
    if mode == "plus" and mtf:
        for правило in mtf:
            try:
                едф = _пресметни_рамка(d, правило)
                if едф is None or len(едф) < pivot * 2 + 4:
                    mtf_нива[правило] = []
                    continue
                r = f_ликвидност(
                    едф, pivot=pivot, tolerance_pct=tolerance_pct,
                    max_each_side=max_each_side, fresh_bars=fresh_bars,
                    mode="plus", as_of=None, lookback=lookback,
                    mtf=None, max_dist_atr=1e9,
                )
                mtf_нива[правило] = [x["цена"] for x in r["нива"]]
            except Exception:
                mtf_нива[правило] = []

    # ── ОБРАБОТКА НА ВСЯКО НИВО ─────────────────────────────────────────────
    готови = []
    for ниво in сурови:
        цена = ниво["цена"]
        е_връх = ниво["вид"] == "връх"
        b_потв = ниво["бар_потвърден"]

        # ═══ СВИП · ПРЕНОС р. 489–490 ═══
        # връх: high > level  И  close < level   (пробожда и се връща под нивото)
        # дъно: low  < level  И  close > level
        # Гледаме САМО баровете СЛЕД потвърждението — оттам нататък нивото
        # съществува на графиката. Това е и второто място, където бъдещето е спряно.
        от = b_потв + 1
        обран, обран_на = False, None
        if от <= край:
            h_s, l_s, c_s = high[от : край + 1], low[от : край + 1], close[от : край + 1]
            ако = (h_s > цена) & (c_s < цена) if е_връх else (l_s < цена) & (c_s > цена)
            idx = np.flatnonzero(ако)
            if len(idx):
                обран = True
                # v9.3 р. 492: нивото се маркира `used` при ПЪРВИЯ свип и повече
                # не гърми → взимаме idx[0]. v8.1 (Д5) няма това и пали на всеки
                # бар — затова v8.1 брои свипове по няколко пъти за едно ниво.
                обран_на = int(от + idx[0])

        обран_свеж = bool(обран and (край - обран_на) <= fresh_bars)

        # ── разстояние (Н4) ─────────────────────────────────────────────────
        разст = цена - цена_сега
        разст_atr = abs(разст) / atr
        if разст_atr > max_dist_atr:
            continue

        # ── обем при нивото (Н3) ────────────────────────────────────────────
        # x1.0 = толкова обем, колкото стои на ТИПИЧНАТА цена в прозореца.
        # x2.0 = двойно повече стопове/сделки са минали точно там.
        обем_х = None
        if обем_профил is not None:
            мрежа, профил, медиана = обем_профил
            k = int(np.clip(np.searchsorted(мрежа, цена, "right") - 1, 0, len(мрежа) - 1))
            обем_х = float(профил[k] / медиана) if медиана > 0 else None

        # ── на кои по-високи рамки съществува (Н5) ──────────────────────────
        рамки = [име for име, ц in mtf_нива.items()
                 if any(abs(x - цена) <= толеранс for x in ц)]

        # ═══════════════════════════════════════════════════════════════════
        # 8-ТЕ УСЛОВИЯ · всяко е ИЗМЕРИМО, нито едно не е усещане
        # ═══════════════════════════════════════════════════════════════════
        у = {
            "два_допира":     ниво["допири"] >= 2,
            "трети_допир":    ниво["допири"] >= 3,
            "четвърти_допир": ниво["допири"] >= 4,
            "стегнато":       ниво["ширина"] <= толеранс * 0.40,
            "обем_над":       bool(обем_х is not None and обем_х >= 1.5),
            "непокътнато":    not обран,
            "прясно":         (край - b_потв) <= lookback // 4,
            "друга_рамка":    len(рамки) > 0,
        }
        точки = int(sum(у.values()))

        готови.append({
            "цена": round(float(цена), 3),
            "вид": ниво["вид"],
            "допири": int(ниво["допири"]),
            "ширина": round(float(ниво["ширина"]), 3),
            # индексите се връщат в координатите на ПОДАДЕНИЯ df, не на прозореца
            "бар_първи": int(ниво["бар_първи"] + отместване),
            "бар_последен": int(ниво["бар_последен"] + отместване),
            "бар_потвърден": int(b_потв + отместване),
            "възраст_барове": int(край - b_потв),
            "обран": bool(обран),
            "обран_на_бар": None if обран_на is None else int(обран_на + отместване),
            "обран_свеж": обран_свеж,
            "разстояние": round(float(разст), 3),
            "разстояние_абс": round(float(abs(разст)), 3),
            "разстояние_пц": round(float(abs(разст) / цена_сега * 100.0), 4),
            "разстояние_atr": round(float(разст_atr), 3),
            "обем_х": None if обем_х is None else round(обем_х, 2),
            "рамки": рамки,
            "точки": точки,
            "условия": у,
            "степен": степен(точки),
            "мерено": False,   # НОВО · още не е мерено
        })

    # ── ПОДРЕЖДАНЕ ПО СИЛА (Н2) ─────────────────────────────────────────────
    # първо точките, после близостта — далечното ниво не е за днес
    готови.sort(key=lambda x: (-x["точки"], x["разстояние_atr"]))

    над = [x for x in готови if x["цена"] > цена_сега]
    под = [x for x in готови if x["цена"] <= цена_сега]
    най_над = min(над, key=lambda x: x["разстояние_atr"]) if над else None
    най_под = min(под, key=lambda x: x["разстояние_atr"]) if под else None

    свежи_горе = [x for x in готови if x["вид"] == "връх" and x["обран_свеж"]]
    свежи_долу = [x for x in готови if x["вид"] == "дъно" and x["обран_свеж"]]

    return {
        "блок": "ликвидност",
        "режим": mode,
        "as_of": int(as_of),
        "цена": round(цена_сега, 3),
        "atr": round(atr, 3),
        "толеранс": round(толеранс, 3),
        "нива": готови,
        "брой": len(готови),
        "брой_върхове": sum(1 for x in готови if x["вид"] == "връх"),
        "брой_дъна": sum(1 for x in готови if x["вид"] == "дъно"),
        "непокътнати": sum(1 for x in готови if not x["обран"]),
        "най_близко_над": най_над,
        "най_близко_под": най_под,
        # ПРЕНОС р. 515–516 · recentSweepAbove / recentSweepBelow
        "свеж_свип_горе": bool(свежи_горе),
        "свеж_свип_долу": bool(свежи_долу),
        "най_силно": готови[0] if готови else None,
        "мерено": False,
        "бележка": "НОВО · още не е мерено — няма бектест зад тези нива",
    }


