# КАРТА ЗА TELEGRAM · на български, по състояние
# ─────────────────────────────────────────────────────────────────────────────
def карта_ликвидност(r: dict, колко: int = 6) -> str:
    if not r["нива"]:
        return "💧 ЛИКВИДНОСТ · няма струпани стопове наблизо"
    ред = ["💧 СТРУПАНИ СТОПОВЕ  ·  НОВО · още не е мерено",
           f"цена {r['цена']}  ·  ATR {r['atr']}  ·  толеранс {r['толеранс']}$"]
    for x in r["нива"][:колко]:
        # ⬆/⬇ = къде е нивото спрямо цената СЕГА
        # видът казва къде спрямо самото ниво стоят стоповете
        посока = "⬆" if x["разстояние"] > 0 else "⬇"
        вид = ("равни върхове · стопове НАД" if x["вид"] == "връх"
               else "равни дъна · стопове ПОД")
        състояние = "ОБРАНИ ✓" if x["обран"] else "стоят"
        ред.append(
            f"{посока} {x['цена']}  {вид}  ·  {x['допири']} допира  ·  "
            f"{x['разстояние_atr']} ATR ({x['разстояние_абс']}$)  ·  "
            f"{състояние}  ·  {x['степен']} [{x['точки']}/8]"
            + (f"  ·  обем x{x['обем_х']}" if x["обем_х"] else "")
            + (f"  ·  и на {'/'.join(x['рамки'])}" if x["рамки"] else "")
        )
    if r["свеж_свип_горе"]:
        ред.append("⚡ ПРЯСНО ОБРАНИ СТОПОВЕ ГОРЕ")
    if r["свеж_свип_долу"]:
        ред.append("⚡ ПРЯСНО ОБРАНИ СТОПОВЕ ДОЛУ")
    return "\n".join(ред)
