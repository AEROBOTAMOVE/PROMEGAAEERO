# НАДГРАЖДАНЕ Н1 · КЛЪСТЕР — всички пивоти в толеранса стават ЕДНО ниво
# ─────────────────────────────────────────────────────────────────────────────
def _нива_клъстер(high, върхове, low, дъна, толеранс, pivot):
    """
    Поправя Д1 + Д2 + Д3 наведнъж.

    Алгоритъм (без верижно разтягане):
      1. пивотите се сортират по ЦЕНА
      2. клъстер започва от най-ниския; приема следващия, ДОКАТО
         `цена − най_ниската_в_клъстера <= толеранс`
         → ширината на клъстера НИКОГА не надхвърля толеранса
      3. клъстер с >= 2 пивота става ниво; цената е СРЕДНОТО на пивотите
         (Pine взима средата на двойката — при 2 пивота съвпада точно)

    Троен връх A≈B≈C вече дава ЕДНО ниво с `допири = 3`, вместо две по 2.
    """
    out = []
    for центрове, src, вид in ((върхове, high, "връх"), (дъна, low, "дъно")):
        if len(центрове) < 2:
            continue
        двойки = sorted(((float(src[c]), int(c)) for c in центрове), key=lambda t: t[0])
        i = 0
        while i < len(двойки):
            j = i
            while j + 1 < len(двойки) and (двойки[j + 1][0] - двойки[i][0]) <= толеранс:
                j += 1
            група = двойки[i : j + 1]
            if len(група) >= 2:
                цени = [g[0] for g in група]
                барове = sorted(g[1] for g in група)
                out.append({
                    "цена": float(np.mean(цени)),
                    "вид": вид,
                    "допири": len(група),
                    "ширина": float(max(цени) - min(цени)),
                    "бар_първи": барове[0],
                    "бар_последен": барове[-1],
                    # СРЕЩУ НАДНИЧАНЕ: нивото съществува едва когато ПОСЛЕДНИЯТ
                    # пивот е потвърден, т.е. `pivot` бара след центъра му.
                    "бар_потвърден": барове[-1] + int(pivot),
                })
                i = j + 1
            else:
                i += 1
    return out


