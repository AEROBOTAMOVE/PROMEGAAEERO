# ─────────────────────────────────────────────────────────────────────────────
# ПОМОЩНИ
# ─────────────────────────────────────────────────────────────────────────────
def _atr_rma(high, low, close, period: int = 14) -> float:
    """ta.atr(14) на Pine = RMA (Wilder) на True Range. Връща само последната стойност."""
    h = np.asarray(high, float)
    l = np.asarray(low, float)
    c = np.asarray(close, float)
    if len(c) < period + 1:
        return float("nan")
    pc = np.concatenate(([c[0]], c[:-1]))
    tr = np.maximum(h - l, np.maximum(np.abs(h - pc), np.abs(l - pc)))
    a = 1.0 / period
    val = tr[:period].mean()
    for i in range(period, len(tr)):
        val = val * (1 - a) + tr[i] * a
    return float(val)


def _индекс_време(df: pd.DataFrame) -> pd.DatetimeIndex:
    """Вади времевия индекс. Приема DatetimeIndex или колона с времето."""
    ix = df.index
    if isinstance(ix, pd.DatetimeIndex):
        return ix
    for к in ("timestamp_utc", "timestamp", "time", "datetime"):
        if к in df.columns:
            return pd.DatetimeIndex(pd.to_datetime(df[к]))
    raise ValueError("няма времеви индекс — този блок мери ВЪВ ВРЕМЕ и без часовник не работи")


def _мащаб_на_времето(ix: pd.DatetimeIndex) -> int:
    """
    Колко НАНОСЕКУНДИ е една единица в `ix.asi8`.

    🔴 УЛОВЕН НА ЖИВО В ТАЗИ СЕСИЯ (не предположен): pandas 2 пази времето и в
    микросекунди. `xauusd_15min_bid_ask.parquet` идва като `datetime64[us, UTC]`,
    тоест `asi8` връща МИКРОсекунди. Ако извадиш от него наносекунди, „2 часа"
    мълчаливо става „83 дни" — точно това се случи при първото пускане:
    2-часовият прозорец върна диапазон 3942–4890$ при цена 4139$, а месечният
    върна цялата 22-годишна история. Нищо не гръмва, числата просто са други.
    Затова единицата се ЧЕТЕ от dtype-а, а не се приема за дадена.
    """
    ед = getattr(ix.dtype, "unit", None)
    if ед is None:
        ед = np.datetime_data(ix.dtype)[0]
    таблица = {"ns": 1, "us": 1_000, "ms": 1_000_000, "s": 1_000_000_000}
    if ед not in таблица:
        raise ValueError(f"непозната единица за време: {ед}")
    return таблица[ед]


def _минути_на_деня(ix: pd.DatetimeIndex, зона: str) -> np.ndarray:
    """
    Минути от полунощ в дадената часова зона. Лятното/зимното време се държи от
    pandas/zoneinfo — не се смята ръчно отместване (това е капанът, в който вече
    сме падали: `TZ=` връща UTC мълчаливо).
    ⚠ Приема, че времевата отметка на бара е неговото ОТВАРЯНЕ (така е и в Pine).
    """
    if ix.tz is None:
        ix = ix.tz_localize("UTC")
    л = ix.tz_convert(зона)
    return (л.hour * 60 + л.minute).to_numpy()


def _в_сесия(минути: np.ndarray, име: str) -> np.ndarray:
    н, к = СЕСИИ[име]
    return (минути >= н) & (минути < к)


def _обемен_профил(low, high, vol, кошчета: int, дял: float) -> dict | None:
    """
    Н5 · Разпределя обема на всеки бар пропорционално по ценовите кошчета, които
    неговият диапазон [low, high] покрива. Връща POC и стойностната зона.
    Това е стандартният начин; индикаторът НЕ прави нищо подобно.
    """
    low = np.asarray(low, float)
    high = np.asarray(high, float)
    if vol is None:
        return None
    vol = np.asarray(vol, float)
    lo, hi = float(low.min()), float(high.max())
    if not np.isfinite(lo) or not np.isfinite(hi) or hi <= lo or vol.sum() <= 0:
        return None
    ръбове = np.linspace(lo, hi, кошчета + 1)
    центрове = (ръбове[:-1] + ръбове[1:]) / 2.0
    тегла = np.zeros(кошчета)
    дн = ръбове[:-1]
    гр = ръбове[1:]
    for l, h, v in zip(low, high, vol):
        if not np.isfinite(v) or v <= 0:
            continue
        if h <= l:
            i = min(int((l - lo) / (hi - lo) * кошчета), кошчета - 1)
            тегла[i] += v
            continue
        застъп = np.clip(np.minimum(гр, h) - np.maximum(дн, l), 0.0, None)
        s = застъп.sum()
        if s > 0:
            тегла += v * застъп / s
    общо = тегла.sum()
    if общо <= 0:
        return None
    p = int(тегла.argmax())
    # стойностна зона: разширяване от POC към по-дебелото съседно кошче
    долу = горе = p
    натрупано = тегла[p]
    цел = общо * дял
    while натрупано < цел and (долу > 0 or горе < кошчета - 1):
        д = тегла[долу - 1] if долу > 0 else -1.0
        г = тегла[горе + 1] if горе < кошчета - 1 else -1.0
        if г >= д:
            горе += 1
            натрупано += тегла[горе]
        else:
            долу -= 1
            натрупано += тегла[долу]
    return {
        "poc": round(float(центрове[p]), 3),
        "va_дъно": round(float(ръбове[долу]), 3),
        "va_връх": round(float(ръбове[горе + 1]), 3),
        "va_дял": round(float(натрупано / общо), 3),
        "кошчета": кошчета,
    }


def _позиция(цена: float, дъно: float, връх: float) -> float:
    """0 = на самото дъно, 100 = на самия таван. При нулева ширина → 50."""
    ш = връх - дъно
    if not np.isfinite(ш) or ш <= 0:
        return 50.0
    return float(np.clip((цена - дъно) / ш * 100.0, -50.0, 150.0))


def _състояние(поз: float) -> str:
    """Присъдата на Pine е строга: под средата = дискаунт, над = премиум."""
    if поз < 50.0:
        return "ДИСКАУНТ"
    if поз > 50.0:
        return "ПРЕМИУМ"
    return "РАВНОВЕСИЕ"


def _празен(as_of, mode, причина) -> dict:
    return {
        "режим": mode, "as_of": int(as_of), "празен": True, "причина": причина,
        "точки": 0, "условия": {}, "степен": степен(0), "мерено": False,
    }


# ─────────────────────────────────────────────────────────────────────────────
# ГЛАВНАТА ФУНКЦИЯ
# ─────────────────────────────────────────────────────────────────────────────
def f_диапазон(
    df: pd.DataFrame,
    *,
    # ── настройки от графиката (пренос) ──────────────────────────────────────
    range_bars: int = 30,              # rangeBars, v9.3 р. 92  (v8.1 pzP = 20)
    # ── поправката на дефекта Д1 ─────────────────────────────────────────────
    часове: float = 7.5,               # прозорецът ВЪВ ВРЕМЕ (режим "plus")
    # ── управление ───────────────────────────────────────────────────────────
    mode: str = "plus",                # "pine" = 1:1 с графиката · "plus" = надградено
    as_of: int | None = None,          # индекс на последния ЗАТВОРЕН бар
    зона: str = "Europe/Sofia",
    # ── надграждания ─────────────────────────────────────────────────────────
    хоризонти: tuple = ХОРИЗОНТИ,      # Н2
    обем_кошчета: int = 48,            # Н5
    va_дял: float = 0.70,              # Н5 · стойностна зона 70%
    свитост_проба: int = 1200,         # Н4 · колко бара назад за ТИПИЧНАТА ширина
    таблица: dict | None = ТАБЛИЦА_ВЕРОЯТНОСТИ,   # Н7
) -> dict:
    """
    Къде е цената спрямо диапазона си — и в коя сесия.

    Вход : df с колони open/high/low/close (+ volume, ако има) и времеви индекс,
           подредени по време.
    Изход: dict. Всички цени са закръглени до 3 знака.

    Основните полета:
      диапазон      dict · главният прозорец (в барове при "pine", във време при "plus")
                           връх · дъно · среда · ширина · ширина_atr · позиция_пц ·
                           състояние · барове · часове
      азия          dict · азиатският диапазон 03:00–11:00 София + пробиви (Н6)
      сесия         dict · коя сесия тече, минути от началото/до края, US щит (Н8)
      хоризонти     list · 7-те прозореца във време, всеки със своята позиция (Н2)
      съгласие      dict · колко от 7-те сочат дискаунт и колко премиум (Н2)
      свитост       dict · сегашна ширина / типична ширина (Н4)
      обем          dict · POC и стойностна зона вътре в главния прозорец (Н5)
      вероятност    dict · честота от историята за тази десетина (Н7)
      посока        str  · "ДИСКАУНТ" | "ПРЕМИУМ" | "РАВНОВЕСИЕ" — присъдата
      точки         int  · 0–8, колко условия са изпълнени
      условия       dict · КОИ точно (за проверка отвън)
      степен        str  · една от 7-те
      блокира_вход  bool · US щитът е активен (Pine спира вход в този прозорец)
      мерено        bool · ВИНАГИ False — няма бектест зад този блок

    ОСЕМТЕ УСЛОВИЯ и колко често пали всяко (4000 момента, измерено в сесията):
        1 главният и дневният съгласни  71.0%
        2 крайна четвърт                43.9%
        3 крайна десета                 15.0%
        4 съгласие 5 от 7               70.9%
        5 единодушно 7 от 7             23.9%
        6 край на азиатския диапазон    56.1%
        7 диапазонът е широк            53.0%
        8 извън стойностната зона       37.2%
    """
    if mode not in ("pine", "plus"):
        raise ValueError("mode трябва да е 'pine' или 'plus'")

    n = len(df)
    if as_of is None:
        as_of = n - 1
    as_of = int(as_of)
    if as_of < 20 or as_of >= n:
        return _празен(as_of, mode, "твърде малко барове")

    ix = _индекс_време(df)
    # ═══ ЗАЩИТА ОТ НАДНИЧАНЕ · ключалка 1 ═══
    # Оттук нататък НИЩО не пипа барове след as_of: ВСЕКИ срез свършва на
    # `as_of + 1`, а `np.searchsorted` работи върху `времена[:as_of + 1]`, тоест
    # не може да върне индекс отвъд as_of. Няма нито едно `shift(-k)`.
    hi_всички = df["high"].to_numpy(float)
    lo_всички = df["low"].to_numpy(float)
    cl_всички = df["close"].to_numpy(float)
    vol_всички = df["volume"].to_numpy(float) if "volume" in df.columns else None
    времена = ix.asi8                                  # изглед, не копие
    мащаб = _мащаб_на_времето(ix)                      # 1 единица = колко ns
    ЧАС = 3_600_000_000_000 // мащаб                   # един час в единиците на `времена`
    сега_ns = int(времена[as_of])
    цена = float(cl_всички[as_of])

    # ATR за мащаба (само назад)
    a0 = max(0, as_of - 200)
    atr = _atr_rma(hi_всички[a0:as_of + 1], lo_всички[a0:as_of + 1], cl_всички[a0:as_of + 1], 14)

    # ── помощник: прозорец по време ──────────────────────────────────────────
    def прозорец_време(ч: float) -> tuple[int, int]:
        нач = сега_ns - int(ч * ЧАС)
        i0 = int(np.searchsorted(времена[:as_of + 1], нач, side="left"))
        return min(i0, as_of), as_of

    def прозорец_барове(k: int) -> tuple[int, int]:
        return max(0, as_of - k + 1), as_of

    def диапазон_на(i0: int, i1: int) -> dict:
        h = float(np.nanmax(hi_всички[i0:i1 + 1]))
        l = float(np.nanmin(lo_всички[i0:i1 + 1]))
        m = (h + l) / 2.0
        поз = _позиция(цена, l, h)
        return {
            "връх": round(h, 3), "дъно": round(l, 3), "среда": round(m, 3),
            "ширина": round(h - l, 3),
            "ширина_пц": round((h - l) / цена * 100.0, 4) if цена else None,
            "ширина_atr": round((h - l) / atr, 2) if np.isfinite(atr) and atr > 0 else None,
            "позиция_пц": round(поз, 1),
            "състояние": _състояние(поз),
            "барове": int(i1 - i0 + 1),
            "от": str(ix[i0]), "до": str(ix[i1]),
        }

    # ═════════════════════════════════════════════════════════════════════════
    # ПРЕНОС · главният диапазон
    #   "pine" : ta.highest(high, rangeBars) / ta.lowest(low, rangeBars)  — В БАРОВЕ
    #   "plus" : същото, но прозорецът е ВЪВ ВРЕМЕ  (Н1, поправя Д1)
    # ═════════════════════════════════════════════════════════════════════════
    if mode == "pine":
        i0, i1 = прозорец_барове(range_bars)
        главен = диапазон_на(i0, i1)
        главен["часове"] = None
        главен["прозорец"] = f"{range_bars} свещи (както на графиката)"
    else:
        i0, i1 = прозорец_време(часове)
        главен = диапазон_на(i0, i1)
        главен["часове"] = часове
        главен["прозорец"] = f"{часове}ч (във ВРЕМЕ, не в свещи)"

    # ═════════════════════════════════════════════════════════════════════════
    # ПРЕНОС · АЗИАТСКИ ДИАПАЗОН (v9.3 р. 277–285)
    # Pine: зануляване при старт на сесията, после running max/min.
    # Тук: същото, но се броят и баровете (Д8) и се търсят пробивите (Н6).
    # ═════════════════════════════════════════════════════════════════════════
    a_i0 = int(np.searchsorted(времена[:as_of + 1], сега_ns - 120 * ЧАС, side="left"))
    a_i0 = min(a_i0, as_of)
    мин_сл = _минути_на_деня(ix[a_i0:as_of + 1], зона)
    в_азия = _в_сесия(мин_сл, "азия")
    азия: dict | None = None
    if в_азия.any():
        предишен = np.concatenate(([False], в_азия[:-1]))
        стартове = np.flatnonzero(в_азия & ~предишен)
        s = int(стартове[-1]) if len(стартове) else 0
        след = np.flatnonzero(~в_азия[s:])
        e = s + int(след[0]) - 1 if len(след) else len(в_азия) - 1
        gs, ge = a_i0 + s, a_i0 + e
        ah = float(np.nanmax(hi_всички[gs:ge + 1]))
        al = float(np.nanmin(lo_всички[gs:ge + 1]))
        още_тече = bool(в_азия[-1]) and ge == as_of
        азия = {
            "връх": round(ah, 3), "дъно": round(al, 3),
            "среда": round((ah + al) / 2.0, 3),
            "ширина": round(ah - al, 3),
            "ширина_atr": round((ah - al) / atr, 2) if np.isfinite(atr) and atr > 0 else None,
            "позиция_пц": round(_позиция(цена, al, ah), 1),
            "барове": int(ge - gs + 1),          # Д8 · колко бара реално са я образували
            "начало": str(ix[gs]), "край": str(ix[ge]),
            "в_сесия": още_тече,
        }
        # Н6 · пробиви СЛЕД затварянето на сесията (само ако вече е затворила)
        if not още_тече and ge < as_of:
            сл_h = hi_всички[ge + 1:as_of + 1]
            сл_l = lo_всички[ge + 1:as_of + 1]
            пв = bool(np.nanmax(сл_h) > ah) if len(сл_h) else False
            пд = bool(np.nanmin(сл_l) < al) if len(сл_l) else False
            вътре = bool(al <= цена <= ah)
            азия.update({
                "пробит_връх": пв,
                "пробит_дъно": пд,
                "вътре_сега": вътре,
                # фалшив пробив = мина отвъд и се върна В диапазона (капанът)
                "фалшив_пробив_горе": bool(пв and вътре),
                "фалшив_пробив_долу": bool(пд and вътре),
                "барове_след_сесията": int(as_of - ge),
            })
        else:
            азия.update({"пробит_връх": False, "пробит_дъно": False,
                         "вътре_сега": True, "фалшив_пробив_горе": False,
                         "фалшив_пробив_долу": False, "барове_след_сесията": 0})

    # ═════════════════════════════════════════════════════════════════════════
    # ПРЕНОС · СЕСИИ (v9.3 р. 1009–1017) + Н8 (минутите като числа)
    # Д7 · няма `intraday` условие — ботът няма графика.
    # ═════════════════════════════════════════════════════════════════════════
    м = int(_минути_на_деня(ix[as_of:as_of + 1], зона)[0])
    флагове = {име: bool(н <= м < к) for име, (н, к) in СЕСИИ.items()}
    активни = [и for и in ("азия", "лондон", "ню_йорк") if флагове[и]]
    if len(активни) == 0:
        име_сесия = "извън сесия"
    elif len(активни) == 1:
        име_сесия = активни[0]
    else:
        име_сесия = "+".join(активни)      # припокриването Лондон+НЮ е най-силният час
    сесия = {
        "име": име_сесия,
        "местно_време": str(ix[as_of].tz_localize("UTC").tz_convert(зона)
                            if ix.tz is None else ix[as_of].tz_convert(зона)),
        "минути_на_деня": м,
        "азия": флагове["азия"], "лондон": флагове["лондон"],
        "ню_йорк": флагове["ню_йорк"], "us_щит": флагове["us_щит"],
        "припокриване": len(активни) >= 2,
        "минути_до_края": min([СЕСИИ[и][1] - м for и in активни]) if активни else None,
        "минути_от_началото": max([м - СЕСИИ[и][0] for и in активни]) if активни else None,
        "щит_остават_минути": (СЕСИИ["us_щит"][1] - м) if флагове["us_щит"] else 0,
        "блокира_вход": bool(флагове["us_щит"]),
    }

    # ── режим "pine" свършва тук: това е ВСИЧКО, което графиката знае ────────
    if mode == "pine":
        у = {
            "отвъд_средата": главен["състояние"] in ("ДИСКАУНТ", "ПРЕМИУМ"),
            "азия_има": азия is not None,
            "в_сесия": len(активни) > 0,
        }
        т = int(sum(1 for v in у.values() if v))
        return {
            "режим": "pine", "as_of": as_of, "време": str(ix[as_of]), "цена": round(цена, 3),
            "atr": round(atr, 3) if np.isfinite(atr) else None,
            "диапазон": главен, "азия": азия, "сесия": сесия,
            "посока": главен["състояние"],
            "текст_v81": ("ПРЕМИУМ — скъпо, търси ШОРТ" if главен["състояние"] == "ПРЕМИУМ"
                          else "ДИСКАУНТ — евтино, търси ЛОНГ" if главен["състояние"] == "ДИСКАУНТ"
                          else "РАВНОВЕСИЕ"),
            "хоризонти": None, "съгласие": None, "свитост": None, "обем": None, "вероятност": None,
            "блокира_вход": сесия["блокира_вход"],
            "точки": т, "условия": у, "степен": степен(т),
            "таван_на_степента": "в режим pine условията са само 3 (толкова знае графиката) "
                                 "→ по-високо от 🔨 ОФОРМЯ СЕ не може да се стигне. "
                                 "НЕ сравнявай степен от pine със степен от plus.",
            "мерено": False,
        }

    # ═════════════════════════════════════════════════════════════════════════
    # НАДГРАЖДАНЕ · Н2 · 7 ХОРИЗОНТА ЕДНОВРЕМЕННО
    # ═════════════════════════════════════════════════════════════════════════
    хор = []
    for име, ч in хоризонти:
        j0, j1 = прозорец_време(ч)
        d = диапазон_на(j0, j1)
        d["име"] = име
        d["часове"] = ч
        # ЧЕСТНОСТ: покрива ли историята целия поискан прозорец, или е отрязан
        # отпред (началото на данните). Отрязаният хоризонт лъже за „екстремума".
        d["покрити_часове"] = round((сега_ns - int(времена[j0])) / ЧАС, 2)
        d["пълен"] = bool(d["покрити_часове"] >= ч * 0.9)
        хор.append(d)

    n_диск = sum(1 for d in хор if d["състояние"] == "ДИСКАУНТ")
    n_прем = sum(1 for d in хор if d["състояние"] == "ПРЕМИУМ")
    водеща = "ДИСКАУНТ" if n_диск > n_прем else "ПРЕМИУМ" if n_прем > n_диск else "РАВНОВЕСИЕ"
    съгласие = {
        "дискаунт": n_диск, "премиум": n_прем, "общо": len(хор),
        "водеща": водеща,
        "мнозинство": max(n_диск, n_прем),
        "единодушно": bool(max(n_диск, n_прем) == len(хор)),
        "средна_позиция_пц": round(float(np.mean([d["позиция_пц"] for d in хор])), 1),
        "най_дълбок": min(хор, key=lambda d: d["позиция_пц"])["име"],
        "най_висок": max(хор, key=lambda d: d["позиция_пц"])["име"],
    }

    # ═════════════════════════════════════════════════════════════════════════
    # НАДГРАЖДАНЕ · Н4 · СВИТОСТ — сегашната ширина спрямо ТИПИЧНАТА
    # ═════════════════════════════════════════════════════════════════════════
    свитост = None
    s0 = max(0, as_of - свитост_проба + 1)
    if as_of - s0 > 50:
        ср = pd.DataFrame(
            {"high": hi_всички[s0:as_of + 1], "low": lo_всички[s0:as_of + 1]},
            index=ix[s0:as_of + 1],
        )
        пр = f"{int(часове * 60)}min"
        ш = (ср["high"].rolling(пр).max() - ср["low"].rolling(пр).min()).to_numpy()
        ш = ш[np.isfinite(ш)]
        if len(ш) > 30:
            типична = float(np.median(ш))
            х = float(главен["ширина"] / типична) if типична > 0 else float("nan")
            свитост = {
                "типична_ширина": round(типична, 3),
                "сега_х": round(х, 2),
                "състояние": ("свит" if х < 0.75 else "разширен" if х > 1.40 else "обикновен"),
                "проба_барове": int(len(ш)),
                "бележка": "v8.1 р. 630 казва «⏸ ЧАКАЙ, диапазонът е свит», но без число. Ето числото.",
            }

    # ═════════════════════════════════════════════════════════════════════════
    # НАДГРАЖДАНЕ · Н5 · ОБЕМЕН ПРОФИЛ вътре в главния прозорец
    # ═════════════════════════════════════════════════════════════════════════
    обем = None
    if vol_всички is not None:
        обем = _обемен_профил(lo_всички[i0:i1 + 1], hi_всички[i0:i1 + 1],
                              vol_всички[i0:i1 + 1], обем_кошчета, va_дял)
        if обем:
            обем["позиция_на_poc_пц"] = round(_позиция(обем["poc"], главен["дъно"], главен["връх"]), 1)
            обем["цена_над_poc"] = bool(цена > обем["poc"])
            обем["в_стойностната_зона"] = bool(обем["va_дъно"] <= цена <= обем["va_връх"])
            обем["изместена_надолу"] = bool(цена < обем["va_дъно"])
            обем["изместена_нагоре"] = bool(цена > обем["va_връх"])
            обем["разстояние_до_poc"] = round(float(цена - обем["poc"]), 3)

    # ═════════════════════════════════════════════════════════════════════════
    # НАДГРАЖДАНЕ · Н7 · ВЕРОЯТНОСТ ОТ ИСТОРИЯТА (не цвят — число)
    # ═════════════════════════════════════════════════════════════════════════
    вероятност = None
    десетина = int(np.clip(главен["позиция_пц"] // 10, 0, 9))
    if таблица and "десетини" in таблица:
        зап = таблица["десетини"].get(десетина)
        if зап:
            вероятност = {
                "десетина": десетина,
                "нагоре_след_8_бара_пц": зап["нагоре_8"],
                "средно_движение_$": зап["средно_8"],
                "проба_барове": зап["н"],
                "източник": таблица["източник"],
                "внимание": "честота на ДВИЖЕНИЕТО без спред и комисиона — НЕ е доходност",
            }

    # ═════════════════════════════════════════════════════════════════════════
    # СТЕПЕНТА · 8 УСЛОВИЯ, ИЗМЕРИМО БРОЕНЕ
    # Броят се условията, които подкрепят ВОДЕЩАТА посока.
    # ═════════════════════════════════════════════════════════════════════════
    поз = главен["позиция_пц"]
    диск = водеща == "ДИСКАУНТ"
    прем = водеща == "ПРЕМИУМ"
    поз_24 = next((d["позиция_пц"] for d in хор if d["име"] == "24ч"), поз)

    # У1 · главният прозорец И дневният сочат ЕДНО И СЪЩО.
    #      (Първата версия искаше само главния → палеше 81.8% — почти безплатна.)
    у1 = bool((диск and поз < 50 and поз_24 < 50) or (прем and поз > 50 and поз_24 > 50))
    у2 = bool((диск and поз < 25) or (прем and поз > 75))
    у3 = bool((диск and поз < 10) or (прем and поз > 90))
    # У4 · 🔴 ТУК БЕШЕ ТАВТОЛОГИЯ. Първата версия питаше `мнозинство >= 4`, но
    #      `водеща` Е ПО ОПРЕДЕЛЕНИЕ мнозинството от 7 → условието палеше в
    #      100.0% от 4000 измерени момента. Това не е условие, а подарена точка.
    #      Сега прагът е 5 от 7 — истинско изискване.
    у4 = bool(съгласие["мнозинство"] >= 5)
    у5 = bool(съгласие["единодушно"])          # 7 от 7 (беше 6 → 46.4%)
    у6 = False
    if азия is not None:
        ап = азия["позиция_пц"]
        у6 = bool((диск and (ап < 20 or азия["фалшив_пробив_долу"])) or
                  (прем and (ап > 80 or азия["фалшив_пробив_горе"])))
    # У7 · сравнение с МЕДИАНАТА → пали по построение около 50% от времето.
    #      (Първата версия искаше само «не е задушен» → 74.6%.)
    у7 = bool(свитост is not None and свитост["сега_х"] >= 1.0)
    у8 = False
    if обем:
        у8 = bool((диск and обем["изместена_надолу"]) or (прем and обем["изместена_нагоре"]))

    условия = {
        "1_главният_и_дневният_съгласни": у1,
        "2_крайна_четвърт": у2,
        "3_крайна_десета": у3,
        "4_съгласие_5_от_7": у4,
        "5_единодушно_7_от_7": у5,
        "6_край_на_азиатския_диапазон": у6,
        "7_диапазонът_е_широк": у7,
        "8_извън_стойностната_зона": у8,
    }
    точки = int(sum(условия.values()))

    return {
        "режим": "plus", "as_of": as_of, "време": str(ix[as_of]), "цена": round(цена, 3),
        "atr": round(atr, 3) if np.isfinite(atr) else None,
        "диапазон": главен,
        "азия": азия,
        "сесия": сесия,
        "хоризонти": хор,
        "съгласие": съгласие,
        "свитост": свитост,
        "обем": обем,
        "вероятност": вероятност,
        "посока": водеща,
        "точки": точки,
        "условия": условия,
        "степен": степен(точки),
        "блокира_вход": сесия["блокира_вход"],
        "мерено": False,
        "етикет": "НОВО · още не е мерено",
    }


# ─────────────────────────────────────────────────────────────────────────────
# Н7 · ИЗМЕРВАНЕ НА ТАБЛИЦАТА · това строи ТАБЛИЦА_ВЕРОЯТНОСТИ
# ─────────────────────────────────────────────────────────────────────────────
def f_диапазон_история(
    df: pd.DataFrame,
    *,
    часове: float = 7.5,
    напред: int = 8,
    от: int | None = None,
    до: int | None = None,
) -> dict:
    """
    Мери ЧЕСТОТА НА ДВИЖЕНИЕТО по десетини на позицията в диапазона.

    За всеки бар: смята се позицията в `часове`-часовия прозорец (само назад),
    после се гледа `close[+напред] − close[0]`.

    ⚠ ТОВА НЕ Е БЕКТЕСТ. Няма спред, няма комисиона, няма стоп, няма изпълнение.
    Казва «колко често цената е била по-високо след N бара», не «колко се печели».

    БЕЗ НАДНИЧАНЕ: позицията на бар i ползва само барове ≤ i. Бъдещето влиза
    САМО в измервания резултат (`close[i+напред]`), което е точно смисълът на
    измерването — но никога не влиза в самата позиция.
    """
    ix = _индекс_време(df)
    h = df["high"].to_numpy(float)
    l = df["low"].to_numpy(float)
    c = df["close"].to_numpy(float)
    n = len(df)
    от = 0 if от is None else int(от)
    до = n if до is None else int(до)

    прозорец = f"{int(часове * 60)}min"
    s = pd.DataFrame({"high": h, "low": l}, index=ix)
    rh = s["high"].rolling(прозорец).max().to_numpy()
    rl = s["low"].rolling(прозорец).min().to_numpy()
    ш = rh - rl
    поз = np.where(ш > 0, (c - rl) / np.where(ш > 0, ш, 1) * 100.0, 50.0)

    напред_c = np.concatenate((c[напред:], np.full(напред, np.nan)))
    движение = напред_c - c

    дес = np.clip((поз // 10).astype(float), 0, 9)
    добри = np.isfinite(движение) & np.isfinite(поз) & (ш > 0)
    добри[:max(от, 20)] = False
    добри[до:] = False

    изход = {}
    for d in range(10):
        m = добри & (дес == d)
        нн = int(m.sum())
        if нн == 0:
            изход[d] = {"н": 0, "нагоре_8": None, "средно_8": None}
            continue
        дв = движение[m]
        изход[d] = {
            "н": нн,
            "нагоре_8": round(float((дв > 0).mean() * 100.0), 2),
            "средно_8": round(float(дв.mean()), 4),
            "медиана_8": round(float(np.median(дв)), 4),
        }
    return {
        "източник": f"{len(df)} бара · {ix[0]} → {ix[-1]}",
        "часове": часове, "хоризонт_барове": напред,
        "прозорец_редове": [int(от), int(до)],
        "десетини": изход,
        "внимание": "честота на ДВИЖЕНИЕТО без разходи — НЕ е доходност",
    }


