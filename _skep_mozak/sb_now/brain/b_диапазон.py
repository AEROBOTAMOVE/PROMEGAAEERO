# КАРТАТА ЗА ТЕЛЕГРАМ · на български, по състояние
# ─────────────────────────────────────────────────────────────────────────────
def карта_диапазон(r: dict) -> str:
    """Текст за човек. Не смята нищо ново — само подрежда вече измереното."""
    if r.get("празен"):
        return f"📏 ДИАПАЗОН · няма какво да се покаже ({r.get('причина')})"

    д = r["диапазон"]
    редове = []
    редове.append(f"📏 ДИАПАЗОН И СЕСИЯ · {r['степен']}")
    редове.append(f"цена {r['цена']:.2f} · {r['време']}")
    редове.append("")
    редове.append(f"{д['прозорец']}:  {д['дъно']:.2f} ─── {д['среда']:.2f} ─── {д['връх']:.2f}")
    стрелка = "▼" if д["състояние"] == "ДИСКАУНТ" else "▲" if д["състояние"] == "ПРЕМИУМ" else "="
    редове.append(f"позиция {д['позиция_пц']:.0f}% {стрелка} {д['състояние']}"
                  f" · ширина {д['ширина']:.2f}$"
                  + (f" ({д['ширина_atr']:.1f} ATR)" if д.get("ширина_atr") else ""))

    if r["режим"] == "pine":
        редове.append(f"({r['текст_v81']})")
    else:
        с = r["съгласие"]
        редове.append("")
        редове.append(f"🔭 7 ХОРИЗОНТА: {с['дискаунт']} казват ДИСКАУНТ · "
                      f"{с['премиум']} казват ПРЕМИУМ → {с['водеща']}"
                      + (" (единодушно)" if с["единодушно"] else ""))
        for х in r["хоризонти"]:
            b = "▼" if х["състояние"] == "ДИСКАУНТ" else "▲" if х["състояние"] == "ПРЕМИУМ" else "="
            редове.append(f"   {х['име']:>10}  {х['позиция_пц']:5.0f}% {b}  "
                          f"{х['дъно']:.2f}–{х['връх']:.2f}")
        if r["свитост"]:
            св = r["свитост"]
            редове.append("")
            редове.append(f"📐 ширина x{св['сега_х']:.2f} спрямо типичната "
                          f"({св['типична_ширина']:.2f}$) → {св['състояние']}")
        if r["обем"]:
            о = r["обем"]
            къде = ("в стойностната зона" if о["в_стойностната_зона"]
                    else "ИЗМЕСТЕНА НАДОЛУ" if о["изместена_надолу"] else "ИЗМЕСТЕНА НАГОРЕ")
            редове.append(f"🔊 най-много обем на {о['poc']:.2f} · зона "
                          f"{о['va_дъно']:.2f}–{о['va_връх']:.2f} · цената е {къде}")

    if r["азия"]:
        а = r["азия"]
        оп = "тече" if а["в_сесия"] else "затворена"
        редове.append("")
        редове.append(f"🌏 АЗИЯ ({оп}) {а['дъно']:.2f}–{а['връх']:.2f} · "
                      f"ширина {а['ширина']:.2f}$ · цената на {а['позиция_пц']:.0f}%")
        if а.get("фалшив_пробив_горе"):
            редове.append("   ⚠ мина НАД азиатския връх и се върна вътре (фалшив пробив)")
        if а.get("фалшив_пробив_долу"):
            редове.append("   ⚠ мина ПОД азиатското дъно и се върна вътре (фалшив пробив)")

    с = r["сесия"]
    редове.append("")
    редове.append(f"🕒 сесия: {с['име']} · {с['местно_време'][11:16]} София"
                  + (f" · остават {с['минути_до_края']} мин" if с["минути_до_края"] is not None else ""))
    if с["us_щит"]:
        редове.append(f"   🛡 US ВОЛАТИЛЕН ПРОЗОРЕЦ · вход блокиран още "
                      f"{с['щит_остават_минути']} мин")

    if r.get("вероятност"):
        в = r["вероятност"]
        редове.append("")
        редове.append(f"📊 в тази десетина историята е ходила нагоре в "
                      f"{в['нагоре_след_8_бара_пц']:.1f}% от {в['проба_барове']:,} случая "
                      f"(средно {в['средно_движение_$']:+.3f}$ за 2ч)")
        редове.append(f"   ⚠ {в['внимание']}")

    if r["режим"] == "plus":
        изп = [к for к, v in r["условия"].items() if v]
        редове.append("")
        редове.append(f"⚖ {r['точки']}/8 условия → {r['степен']}")
        редове.append("   " + (", ".join(и[2:].replace("_", " ") for и in изп) if изп else "нито едно"))
        редове.append("🆕 НОВО · още не е мерено срещу пари")
    return "\n".join(редове)
