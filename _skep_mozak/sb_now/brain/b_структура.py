def f_структура(df: pd.DataFrame, само_както_графиката: bool = False, **пар) -> dict:
    """
    Пазарна структура: BOS (пробив по посоката), CHoCH (първи знак за обръщане),
    ретест задържа / ретест пропадна, плюс — в режим надграждане — фалшив пробив,
    пул от непробити нива, сила на пробива и последователност HH/HL.

    ВХОД : df с колони open/high/low/close (+ volume, ако има). Индексът може да е
           DatetimeIndex — тогава събитията носят и време. Всеки ред трябва да е
           ЗАТВОРЕН бар (както Pine с confirmOnClose=true, р. 20).
    ИЗХОД: dict — виж ключовете най-долу в тялото.

    само_както_графиката=True → изключва ВСИЧКО ново: една памет за суинг, зачеркване
    след пробив, един чакащ ретест, без пул, без фалшиви пробиви, без обем.
    Точно поведението на v9.3, р. 337-429.
    """
    п = dict(ПАРАМ_ГРАФИКА)
    п.update(ПАРАМ_НАДГРАЖДАНЕ)
    п.update(пар)
    # ⚠ ЕДИНСТВЕНО ЗА ТЕСТОВЕ. Отмества момента, в който пивотът влиза в игра.
    # 0 = както в Pine (пивотът чака десните си барове). Стойност > 0 нарочно
    # ВКАРВА надничане в бъдещето, за да се докаже, че проверките изобщо могат да
    # гръмнат. Пазач, който не може да гръмне, е празно зелено — вж. поуката
    # „тествай в ДВЕТЕ посоки".
    надничане = int(п.pop("_надничане_за_тест", 0))
    # ⚠ ВТОРИ ТЕСТОВ ХУК. Съди пробива по ЗАТВАРЯНЕТО НА СЛЕДВАЩИЯ бар — най-грубото
    # възможно надничане. Служи да се докаже, че проверките Д2/Д3 наистина гърмят.
    надн_цена = bool(п.pop("_надничане_цена", False))
    чист = bool(само_както_графиката)
    if чист:
        п["пул"] = False

    o, h, l, c, v, t = _подготви(df)
    n = len(c)
    П = int(п["пивот"])
    atr = _atr_wilder(h, l, c, int(п["atr_период"]))
    обем_ср = None if чист else _среден_обем(v, int(п["обем_период"]))

    вр_маска = _пивоти(h, П, П, True)
    дъ_маска = _пивоти(l, П, П, False)

    # ── състояние ─────────────────────────────────────────────────────────
    посока = 0                      # structureDirection (р. 345)
    посл_бик_бар = None             # lastBullBreakBar   (р. 346)
    посл_меч_бар = None             # lastBearBreakBar   (р. 347)
    посл_текст = "Няма потвърден пробив"   # lastStructureText (р. 351)

    # ПРЕНОС · единична памет (р. 339-342)
    сг_връх = None                  # dict(цена, бар, докосвания) или None
    сг_дъно = None
    # ПРЕНОС · един чакащ ретест (р. 349-350)
    чакащ_бик = None                # dict(ниво, бар_пробив, номер_bos) или None
    чакащ_меч = None

    # НАДГРАЖДАНЕ · пул от непробити нива, ДВА сортирани по цена списъка
    цени_горе: list[float] = []     # възходящо; всички са НАД текущата цена
    мета_горе: list[dict] = []
    цени_долу: list[float] = []     # възходящо; всички са ПОД текущата цена
    мета_долу: list[dict] = []
    чакащи: list[dict] = []         # много едновременни ретести
    # НАДГРАЖДАНЕ · О2 · пробитите нива НЕ се зачеркват (Pine ги трие, р. 387).
    # Те слизат в отделен списък „обърнати" и вече служат за подкрепа/цел, НО не
    # раждат нови BOS събития — иначе цена, която трепти около едно ниво, би пълнила
    # картата с десетки фалшиви пробива на едно и също място.
    флип: list[dict] = []

    # НАДГРАЖДАНЕ · последователност HH/HL — четимата „скелетна" структура
    посл_връх_цена = None
    посл_дъно_цена = None
    вид_връх = None                 # "HH" / "LH"
    вид_дъно = None                 # "HL" / "LL"
    серия_нагоре = 0                # колко поредни BOS нагоре
    серия_надолу = 0

    събития: list[dict] = []
    сериен = 0

    def _цена_позиция(i):
        рнг = h[i] - l[i]
        if рнг <= 0:
            return 0.5
        return (c[i] - l[i]) / рнг

    def _обем_кратно(i):
        if обем_ср is None or v is None:
            return None
        ср = обем_ср[i]
        if ср is None or not np.isfinite(ср) or ср <= 0:
            return None
        return float(v[i]) / float(ср)

    def _оцени(i, ниво, посока_с, choch, пометени, докосвания, възраст, a):
        """
        ОСЕМТЕ УСЛОВИЯ (НОВО · още не е мерено).
        Всяко е булево и се БРОИ — няма тегла, няма усещане.
        """
        у = {}
        у["обръщане (CHoCH)"] = bool(choch)
        у["мете >=2 нива"] = bool(пометени >= 2)
        поз = _цена_позиция(i)
        у["затваря в крайните 25%"] = bool(поз >= п["затваряне_дял"] if посока_с > 0
                                           else поз <= 1.0 - п["затваряне_дял"])
        тяло = abs(c[i] - o[i])
        у["импулсно тяло >=1 ATR"] = bool(a and a > 0 and тяло >= п["импулс_atr"] * a)
        навл = (c[i] - ниво) if посока_с > 0 else (ниво - c[i])
        у["навлиза >=0.25 ATR"] = bool(a and a > 0 and навл >= п["навлизане_atr"] * a)
        ок = _обем_кратно(i)
        у["обем >=1.3x"] = bool(ок is not None and ок >= п["обем_кратно"])
        у["нивото е свежо"] = bool(възраст is not None and възраст <= п["свежо_ниво_барове"])
        у["нивото е атакувано >=2 пъти"] = bool(докосвания >= 2)
        точки = sum(1 for х in у.values() if х)
        return точки, у, _окр(навл / a, 2) if (a and a > 0) else None, ок, поз

    def _ново(i, вид, посока_с, ниво, **допълнително):
        nonlocal сериен
        сериен += 1
        e = dict(
            номер=сериен,
            бар=int(i),
            време=(t[i] if t is not None else None),
            вид=вид,
            посока=int(посока_с),
            ниво=_окр(ниво),
            затваряне=_окр(c[i]),
            atr=_окр(atr[i]) if np.isfinite(atr[i]) else None,
            статус="ПРЕНОС · както на графиката" if чист else "НОВО · още не е мерено",
        )
        e.update(допълнително)
        събития.append(e)
        return e

    # ── ГЛАВЕН ЦИКЪЛ · строго по барове, само данни <= i ──────────────────
    for i in range(n):
        a = atr[i] if np.isfinite(atr[i]) else None
        # `c_съд` е цената, по която се СЪДИ пробивът. Без тестовия хук тя е close[i],
        # тоест затварянето на бара, който току-що е приключил — точно каквото Pine
        # вижда при barstate.isconfirmed (р. 181) и каквото ботът ще има на живо.
        c_съд = c[min(i + 1, n - 1)] if надн_цена else c[i]

        # ─ А · потвърждаване на пивот, чиито ДЕСНИ барове вече са налице ─
        #      Pine: ta.pivothigh(high,6,6) връща стойност на бар p+6 (р. 337-338)
        p = i - П + надничане
        if 0 <= p < n:
            if вр_маска[p]:
                цена = float(h[p])
                if посл_връх_цена is not None:
                    вид_връх = "HH" if цена > посл_връх_цена else "LH"
                посл_връх_цена = цена
                if чист or not п["пул"]:
                    # О1: презаписва се дори непробитият стар връх (р. 354-356)
                    сг_връх = dict(цена=цена, бар=p, докосвания=0)
                else:
                    зп = dict(цена=цена, бар=p, докосвания=0, вид=вид_връх)
                    поз = bisect.bisect_left(цени_горе, цена)
                    цени_горе.insert(поз, цена)
                    мета_горе.insert(поз, зп)
            if дъ_маска[p]:
                цена = float(l[p])
                if посл_дъно_цена is not None:
                    вид_дъно = "HL" if цена > посл_дъно_цена else "LL"
                посл_дъно_цена = цена
                if чист or not п["пул"]:
                    сг_дъно = dict(цена=цена, бар=p, докосвания=0)
                else:
                    зп = dict(цена=цена, бар=p, докосвания=0, вид=вид_дъно)
                    поз = bisect.bisect_left(цени_долу, цена)
                    цени_долу.insert(поз, цена)
                    мета_долу.insert(поз, зп)

        # ─ Б · броене на ДОКОСВАНИЯТА (НОВО) ────────────────────────────
        #      Колко пъти цената е стигала до нивото, без да затвори отвъд него.
        #      Това е мярка колко стопове са се струпали зад него.
        if not чист and a:
            праг = п["докосване_atr"] * a
            j = 0
            while j < len(цени_горе) and цени_горе[j] <= h[i] + праг:
                if цени_горе[j] > c[i] and мета_горе[j]["бар"] < i:
                    мета_горе[j]["докосвания"] += 1
                j += 1
                if j > 12:
                    break
            j = len(цени_долу) - 1
            брой = 0
            while j >= 0 and цени_долу[j] >= l[i] - праг:
                if цени_долу[j] < c[i] and мета_долу[j]["бар"] < i:
                    мета_долу[j]["докосвания"] += 1
                j -= 1
                брой += 1
                if брой > 12:
                    break
        elif чист:
            if сг_връх is not None and a and сг_връх["бар"] < i:
                if h[i] >= сг_връх["цена"] - п["докосване_atr"] * a and c[i] <= сг_връх["цена"]:
                    сг_връх["докосвания"] += 1
            if сг_дъно is not None and a and сг_дъно["бар"] < i:
                if l[i] <= сг_дъно["цена"] + п["докосване_atr"] * a and c[i] >= сг_дъно["цена"]:
                    сг_дъно["докосвания"] += 1

        # ─ В · ПРОБИВ НАГОРЕ ─────────────────────────────────────────────
        #      Pine р. 364: structureUp = close > lastSwingHigh (при затворена свещ)
        пробив_нагоре = False
        ниво_г = None
        пометени_г = 0
        докосв_г = 0
        възраст_г = None
        if чист:
            if сг_връх is not None and c_съд > сг_връх["цена"]:
                пробив_нагоре = True
                ниво_г = сг_връх["цена"]
                пометени_г = 1
                докосв_г = сг_връх["докосвания"]
                възраст_г = i - сг_връх["бар"]
                сг_връх = None                      # р. 387 · зачеркване
        else:
            к = bisect.bisect_left(цени_горе, c_съд)  # всички под close са пробити
            if к > 0:
                пробив_нагоре = True
                пометени_г = к
                ниво_г = цени_горе[к - 1]            # НАЙ-ВИСОКОТО помето ниво
                докосв_г = max(м["докосвания"] for м in мета_горе[:к])
                възраст_г = i - мета_горе[к - 1]["бар"]
                # О2: нивата НЕ изчезват — минават в „обърнати" (бивша съпротива → подкрепа)
                for идx in range(к):
                    зп = мета_горе[идx]
                    зп["пробито_на"] = i
                    зп["беше"] = "таван"
                    флип.append(зп)
                del цени_горе[:к]
                del мета_горе[:к]
                if len(флип) > п["макс_нива"]:
                    del флип[:len(флип) - п["макс_нива"]]

        # ─ Г · ПРОБИВ НАДОЛУ ─────────────────────────────────────────────
        пробив_надолу = False
        ниво_д = None
        пометени_д = 0
        докосв_д = 0
        възраст_д = None
        if чист:
            if сг_дъно is not None and c_съд < сг_дъно["цена"]:
                пробив_надолу = True
                ниво_д = сг_дъно["цена"]
                пометени_д = 1
                докосв_д = сг_дъно["докосвания"]
                възраст_д = i - сг_дъно["бар"]
                сг_дъно = None
        else:
            к = bisect.bisect_right(цени_долу, c_съд)
            брой = len(цени_долу) - к
            if брой > 0:
                пробив_надолу = True
                пометени_д = брой
                ниво_д = цени_долу[к]                # НАЙ-НИСКОТО помето ниво
                докосв_д = max(м["докосвания"] for м in мета_долу[к:])
                възраст_д = i - мета_долу[к]["бар"]
                for идx in range(к, len(цени_долу)):
                    зп = мета_долу[идx]
                    зп["пробито_на"] = i
                    зп["беше"] = "под"
                    флип.append(зп)
                del цени_долу[к:]
                del мета_долу[к:]
                if len(флип) > п["макс_нива"]:
                    del флип[:len(флип) - п["макс_нива"]]

        # ─ Д · издаване на събитието нагоре ──────────────────────────────
        if пробив_нагоре:
            choch = (посока == -1)                  # р. 366
            точки, у, навл_atr, ок, поз_c = _оцени(i, ниво_г, +1, choch, пометени_г,
                                                    докосв_г, възраст_г, a)
            серия_нагоре = серия_нагоре + 1 if посока == 1 else 1
            серия_надолу = 0
            txt = ("ПЪРВИ ЗНАК ЗА ОБРЪЩАНЕ НАГОРЕ (CHoCH)" if choch
                   else "ПРОБИВ НА СТРУКТУРАТА НАГОРЕ (BOS)")     # р. 378
            e = _ново(i, "CHoCH" if choch else "BOS", +1, ниво_г,
                      пивот_бар=(i - възраст_г) if възраст_г is not None else None,
                      възраст_барове=възраст_г,
                      пометени_нива=пометени_г,
                      докосвания=докосв_г,
                      навлизане_atr=навл_atr,
                      тяло_atr=_окр(abs(c[i] - o[i]) / a, 2) if a else None,
                      затваряне_дял=_окр(поз_c, 3),
                      обем_кратно=_окр(ок, 2),
                      условия=у, точки=точки, степен=f_степен(точки),
                      серия=серия_нагоре, скелет=f"{вид_връх or '?'}/{вид_дъно or '?'}",
                      текст=txt)
            посока = 1                               # р. 383
            посл_бик_бар = i                         # р. 385
            посл_текст = txt
            зп = dict(ниво=ниво_г, бар_пробив=i, номер_bos=e["номер"], посока=+1,
                      точки_bos=точки, степен_bos=e["степен"])
            if чист:
                чакащ_бик = зп                       # р. 380
                чакащ_меч = None                     # р. 381
            else:
                чакащи.append(зп)
                if len(чакащи) > п["макс_чакащи"]:
                    чакащи.pop(0)

        if пробив_надолу:
            choch = (посока == 1)
            точки, у, навл_atr, ок, поз_c = _оцени(i, ниво_д, -1, choch, пометени_д,
                                                    докосв_д, възраст_д, a)
            серия_надолу = серия_надолу + 1 if посока == -1 else 1
            серия_нагоре = 0
            txt = ("ПЪРВИ ЗНАК ЗА ОБРЪЩАНЕ НАДОЛУ (CHoCH)" if choch
                   else "ПРОБИВ НА СТРУКТУРАТА НАДОЛУ (BOS)")
            e = _ново(i, "CHoCH" if choch else "BOS", -1, ниво_д,
                      пивот_бар=(i - възраст_д) if възраст_д is not None else None,
                      възраст_барове=възраст_д,
                      пометени_нива=пометени_д,
                      докосвания=докосв_д,
                      навлизане_atr=навл_atr,
                      тяло_atr=_окр(abs(c[i] - o[i]) / a, 2) if a else None,
                      затваряне_дял=_окр(поз_c, 3),
                      обем_кратно=_окр(ок, 2),
                      условия=у, точки=точки, степен=f_степен(точки),
                      серия=серия_надолу, скелет=f"{вид_връх or '?'}/{вид_дъно or '?'}",
                      текст=txt)
            посока = -1
            посл_меч_бар = i
            посл_текст = txt
            зп = dict(ниво=ниво_д, бар_пробив=i, номер_bos=e["номер"], посока=-1,
                      точки_bos=точки, степен_bos=e["степен"])
            if чист:
                чакащ_меч = зп
                чакащ_бик = None
            else:
                чакащи.append(зп)
                if len(чакащи) > п["макс_чакащи"]:
                    чакащи.pop(0)

        # ─ Е · РЕТЕСТИ (р. 406-429) ──────────────────────────────────────
        #      В Pine чакащият е точно ЕДИН и всяко от четирите събития го гаси.
        #
        # 🔴 ДЕФЕКТ О5, открит при преноса (проверен по реда на редовете в Pine):
        #    блокът на пробива е на р. 377-402, а bullRetestHeld се пресмята на р. 406 —
        #    НА СЪЩИЯ БАР. На бара на пробива `waitingBullRetest` вече е true, а
        #    условието `low <= brokenHighLevel and close > brokenHighLevel` е изпълнено
        #    почти винаги (свещта, която е пробила нивото, е тръгнала изпод него).
        #    → „РЕТЕСТЪТ ЗАДЪРЖА" пали ВЕДНАГА, гаси чакането (р. 415) и истинският
        #    ретест няколко свещи по-късно вече няма кой да го отбележи.
        #    Тук дефектът е ЗАПАЗЕН в режим ПРЕНОС (за да съвпада с графиката) и е
        #    измерен — вж. изхода на t_структура.py. В надграждането барът на пробива
        #    се пропуска и ретестът се чака истински.
        if чист:
            for чак, знак in ((чакащ_бик, +1), (чакащ_меч, -1)):
                if чак is None:
                    continue
                L = чак["ниво"]
                if знак > 0:
                    задържа = (l[i] <= L and c[i] > L)                       # р. 406
                    пропадна = (a is not None and c[i] < L - п["ретест_atr"] * a)  # р. 408
                else:
                    задържа = (h[i] >= L and c[i] < L)
                    пропадна = (a is not None and c[i] > L + п["ретест_atr"] * a)
                if задържа or пропадна:
                    _ново(i, "РЕТЕСТ_ЗАДЪРЖА" if задържа else "РЕТЕСТ_ПРОПАДНА",
                          знак, L, номер_bos=чак["номер_bos"],
                          барове_след_пробив=i - чак["бар_пробив"],
                          дълбочина_atr=_окр(((L - l[i]) if знак > 0 else (h[i] - L)) / a, 2)
                          if a else None,
                          текст=("РЕТЕСТЪТ ЗАДЪРЖА НАГОРЕ" if (задържа and знак > 0) else
                                 "РЕТЕСТЪТ ЗАДЪРЖА НАДОЛУ" if задържа else
                                 "НЕУСПЕШЕН ВЪЗХОДЯЩ РЕТЕСТ" if знак > 0 else
                                 "НЕУСПЕШЕН НИЗХОДЯЩ РЕТЕСТ"))
                    if знак > 0:
                        чакащ_бик = None
                    else:
                        чакащ_меч = None
        else:
            остават = []
            for чак in чакащи:
                if чак["бар_пробив"] == i:
                    остават.append(чак)
                    continue
                L = чак["ниво"]
                зн = чак["посока"]
                стар = i - чак["бар_пробив"]
                if зн > 0:
                    задържа = (l[i] <= L and c[i] > L)
                    пропадна = (a is not None and c[i] < L - п["ретест_atr"] * a)
                    дълб = (L - l[i]) / a if a else None
                else:
                    задържа = (h[i] >= L and c[i] < L)
                    пропадна = (a is not None and c[i] > L + п["ретест_atr"] * a)
                    дълб = (h[i] - L) / a if a else None
                if not (задържа or пропадна):
                    if стар <= п["живот_барове"]:
                        остават.append(чак)
                    continue
                # НОВО · ФАЛШИВ ПРОБИВ: пропадна в първите `фалшив_барове` свещи.
                # Това не е просто „неуспешен ретест" — това е обран стоп на пробива.
                фалшив = пропадна and стар <= п["фалшив_барове"]
                ок = _обем_кратно(i)
                if задържа:
                    # осемте условия за КАЧЕСТВО НА РЕТЕСТА
                    у = {}
                    у["плитък ретест (<=0.5 ATR)"] = bool(дълб is not None and дълб <= 0.5)
                    у["бърз (<=10 свещи)"] = bool(стар <= 10)
                    у["сухо връщане (обем <1x)"] = bool(ок is not None and ок < 1.0)
                    поз = _цена_позиция(i)
                    у["затваря силно"] = bool(поз >= 0.6 if зн > 0 else поз <= 0.4)
                    у["по посоката на структурата"] = bool(посока == зн)
                    у["пробивът беше >=4 точки"] = bool(чак["точки_bos"] >= 4)
                    у["не е първият опит"] = bool(стар > 1)
                    у["ATR е известен"] = bool(a is not None)
                    точки = sum(1 for х in у.values() if х)
                else:
                    у, точки = {}, 0
                _ново(i, "ФАЛШИВ_ПРОБИВ" if фалшив else
                      ("РЕТЕСТ_ЗАДЪРЖА" if задържа else "РЕТЕСТ_ПРОПАДНА"),
                      зн, L, номер_bos=чак["номер_bos"],
                      барове_след_пробив=стар,
                      дълбочина_atr=_окр(дълб, 2),
                      обем_кратно=_окр(ок, 2),
                      условия=у, точки=точки,
                      степен=f_степен(точки) if задържа else None,
                      текст=("РЕТЕСТЪТ ЗАДЪРЖА НАГОРЕ" if (задържа and зн > 0) else
                             "РЕТЕСТЪТ ЗАДЪРЖА НАДОЛУ" if задържа else
                             "ФАЛШИВ ПРОБИВ НАГОРЕ — цената се върна веднага" if (фалшив and зн > 0) else
                             "ФАЛШИВ ПРОБИВ НАДОЛУ — цената се върна веднага" if фалшив else
                             "НЕУСПЕШЕН ВЪЗХОДЯЩ РЕТЕСТ" if зн > 0 else
                             "НЕУСПЕШЕН НИЗХОДЯЩ РЕТЕСТ"))
            чакащи = остават

        # ─ Ж · чистене на пула (само за скорост; не променя вече издаденото) ─
        if not чист and (i % 200 == 0) and a:
            _прочисти(цени_горе, мета_горе, цени_долу, мета_долу, c[i], a, i, п)

    # ── изход ─────────────────────────────────────────────────────────────
    посл = c[-1] if n else None
    свеж_бик = (посл_бик_бар is not None and (n - 1) - посл_бик_бар <= п["свеж_барове"])
    свеж_меч = (посл_меч_бар is not None and (n - 1) - посл_меч_бар <= п["свеж_барове"])

    if чист:
        горе = [] if сг_връх is None else [dict(цена=_окр(сг_връх["цена"]),
                                                бар=сг_връх["бар"],
                                                докосвания=сг_връх["докосвания"])]
        долу = [] if сг_дъно is None else [dict(цена=_окр(сг_дъно["цена"]),
                                                бар=сг_дъно["бар"],
                                                докосвания=сг_дъно["докосвания"])]
        чак_изх = [x for x in (чакащ_бик, чакащ_меч) if x is not None]
        обърнати = []
    else:
        обърнати = [dict(цена=_окр(м["цена"]), пробито_на=м["пробито_на"],
                         беше=м["беше"], докосвания=м["докосвания"])
                    for м in флип[-10:]]
        горе = [dict(цена=_окр(м["цена"]), бар=м["бар"], докосвания=м["докосвания"],
                     вид=м.get("вид"), пробито_преди=("пробито_на" in м))
                for м in мета_горе[:10]]
        долу = [dict(цена=_окр(м["цена"]), бар=м["бар"], докосвания=м["докосвания"],
                     вид=м.get("вид"), пробито_преди=("пробито_на" in м))
                for м in reversed(мета_долу[-10:])]
        чак_изх = чакащи[-п["брой_чакащи_карта"]:]

    return dict(
        събития=събития,
        структура=dict(
            посока=посока,
            текст=посл_текст,
            последен_бик_пробив_бар=посл_бик_бар,
            последен_мечи_пробив_бар=посл_меч_бар,
            пресен_бик_пробив=bool(свеж_бик),      # recentBullBreak (р. 1086)
            пресен_мечи_пробив=bool(свеж_меч),     # recentBearBreak (р. 1087)
            скелет=f"{вид_връх or '?'}/{вид_дъно or '?'}",
            серия_нагоре=серия_нагоре,
            серия_надолу=серия_надолу,
        ),
        нива_горе=горе,
        нива_долу=долу,
        обърнати_нива=обърнати,      # НОВО · О2: бивша съпротива → подкрепа и обратно
        чакащи_ретести=чак_изх,
        цена=_окр(посл),
        atr=_окр(atr[-1]) if n and np.isfinite(atr[-1]) else None,
        мета=dict(
            режим="ПРЕНОС · както на графиката" if чист else "ПРЕНОС + НАДГРАЖДАНЕ",
            статус_мерене=("ПРЕНОС · логиката е гледана от собственика с години; "
                           "числата в оценката са НОВИ"
                           if чист else "НОВО · още не е мерено"),
            барове=n, пивот=П,
            брой_bos=sum(1 for e in събития if e["вид"] in ("BOS", "CHoCH")),
            брой_choch=sum(1 for e in събития if e["вид"] == "CHoCH"),
            брой_ретест_задържа=sum(1 for e in събития if e["вид"] == "РЕТЕСТ_ЗАДЪРЖА"),
            брой_ретест_пропадна=sum(1 for e in събития if e["вид"] == "РЕТЕСТ_ПРОПАДНА"),
            брой_фалшиви=sum(1 for e in събития if e["вид"] == "ФАЛШИВ_ПРОБИВ"),
            активни_нива_горе=len(цени_горе), активни_нива_долу=len(цени_долу),
            има_обем=bool(v is not None),
        ),
    )


def _прочисти(цг, мг, цд, мд, цена, a, i, п):
    """Изхвърля нива, които са твърде стари или твърде далеч. Само за скорост."""
    гр = п["забрава_atr"] * a
    ж = п["живот_барове"]
    for цени, мета, горе in ((цг, мг, True), (цд, мд, False)):
        к = 0
        while к < len(цени):
            м = мета[к]
            далеч = abs(цени[к] - цена) > гр
            старо = (i - м["бар"]) > ж
            if далеч or старо:
                del цени[к]
                del мета[к]
            else:
                к += 1
        while len(цени) > п["макс_нива"]:
            # маха се най-далечното от цената
            if abs(цени[0] - цена) > abs(цени[-1] - цена):
                del цени[0]
                del мета[0]
            else:
                del цени[-1]
                del мета[-1]


