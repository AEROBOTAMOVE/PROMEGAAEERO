РАМКИ_МИН = {"1мин": 1, "5мин": 5, "15мин": 15, "30мин": 30,
             "1час": 60, "4часа": 240, "1ден": 1440}


def _прередактирай(df: pd.DataFrame, минути: int) -> pd.DataFrame:
    """Сглобява по-голяма рамка от по-малката. Само затворени барове."""
    к = {c.lower(): c for c in df.columns}
    r = df.resample(f"{минути}min", label="left", closed="left")
    нов = pd.DataFrame({
        "open": r[к["open"]].first(),
        "high": r[к["high"]].max(),
        "low": r[к["low"]].min(),
        "close": r[к["close"]].last(),
    })
    if "volume" in к:
        нов["volume"] = r[к["volume"]].sum()
    return нов.dropna(subset=["close"])


def _стъпка_минути(df: pd.DataFrame) -> int:
    if len(df) < 3:
        return 0
    d = pd.Series(df.index[1:8]).diff().dropna()
    return int(d.median().total_seconds() // 60) if len(d) else 0


def f_структура_многорамково(df: pd.DataFrame,
                              рамки=("15мин", "30мин", "1час", "4часа", "1ден"),
                              съвпад_минути: int = 480, **пар) -> dict:
    """
    НОВО · още не е мерено.

    Човекът не може да чете структурата на 7 рамки едновременно; ботът може.
    Пуска се същият детектор на всяка рамка и се БРОЯТ съвпаденията: колко рамки са
    дали пробив в една и съща посока в прозорец `съвпад_минути`.

    🔴 ВАЖНО СРЕЩУ НАДНИЧАНЕТО В БЪДЕЩЕТО:
    барът на 4-часовата рамка с етикет 12:00 се ЗАТВАРЯ в 16:00. Ако сравняваме по
    етикета, ще излезе, че 4-часовата „е потвърдила в 12:00" — а на живо това се
    научава чак в 16:00. Затова всяко събитие носи `узнато_в = етикет + дължина_рамка`
    и прозорецът за съвпадение се мери по `узнато_в`, НЕ по етикета.
    (Този капан го няма в Pine, защото там request.security с lookahead_off го върши
     автоматично; в pandas трябва да се направи на ръка.)

    Изисква DatetimeIndex.
    """
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("нужен е DatetimeIndex")
    стъпка = _стъпка_минути(df)
    по_рамка, съб = {}, []
    for име in рамки:
        м = РАМКИ_МИН[име]
        if м < стъпка:
            continue                          # wrongTf (Pine р. 216): не смятаме под графиката
        d = df if м == стъпка else _прередактирай(df, м)
        if len(d) < 30:
            continue
        r = f_структура(d, **пар)
        по_рамка[име] = r
        for e in r["събития"]:
            if e["вид"] in ("BOS", "CHoCH") and e["време"] is not None:
                съб.append(dict(узнато_в=pd.Timestamp(e["време"]) + pd.Timedelta(minutes=м),
                                етикет=pd.Timestamp(e["време"]), рамка=име, е=e))
    съб.sort(key=lambda x: x["узнато_в"])

    # плъзгащ прозорец назад (два указателя) — без квадратично търсене
    съвпадения = []
    времена = [s["узнато_в"] for s in съб]
    ляво = 0
    for k, s in enumerate(съб):
        t0 = s["узнато_в"]
        while (t0 - времена[ляво]).total_seconds() > съвпад_минути * 60:
            ляво += 1
        прозорец = [съб[j] for j in range(ляво, k + 1)
                    if съб[j]["е"]["посока"] == s["е"]["посока"]]
        рамки_вътре = sorted({s2["рамка"] for s2 in прозорец},
                             key=lambda x: РАМКИ_МИН[x])
        if len(рамки_вътре) >= 2:
            бонус = len(рамки_вътре) - 1
            съвпадения.append(dict(
                узнато_в=t0, водеща_рамка=s["рамка"], посока=s["е"]["посока"],
                рамки=рамки_вътре, брой_рамки=len(рамки_вътре),
                точки_водещ=s["е"]["точки"],
                степен=f_степен(min(БРОЙ_УСЛОВИЯ, s["е"]["точки"] + бонус)),
                нива=[_окр(s2["е"]["ниво"]) for s2 in прозорец],
                статус="НОВО · още не е мерено"))
    # съгласие СЕГА: посоката на структурата на всяка рамка към последния бар
    съгласие = {име: r["структура"]["посока"] for име, r in по_рамка.items()}
    н = sum(1 for x in съгласие.values() if x == 1)
    м_ = sum(1 for x in съгласие.values() if x == -1)
    return dict(по_рамка=по_рамка, съвпадения=съвпадения,
                съгласие_сега=съгласие,
                съгласие_текст=f"{н} рамки нагоре · {м_} рамки надолу · "
                               f"{len(съгласие) - н - м_} без посока",
                мета=dict(рамки=list(по_рамка.keys()), съвпад_минути=съвпад_минути,
                          статус_мерене="НОВО · още не е мерено"))


