def _atr_wilder(h: np.ndarray, l: np.ndarray, c: np.ndarray, n: int = 14) -> np.ndarray:
    """ATR на Уайлдър (ta.atr в Pine). Причинен: atr[i] ползва барове <= i."""
    к = len(h)
    if к == 0:
        return np.empty(0)
    tr = np.empty(к)
    tr[0] = h[0] - l[0]
    if к > 1:
        д1 = h[1:] - l[1:]
        д2 = np.abs(h[1:] - c[:-1])
        д3 = np.abs(l[1:] - c[:-1])
        tr[1:] = np.maximum(д1, np.maximum(д2, д3))
    atr = np.full(к, np.nan)
    if к >= n:
        atr[n - 1] = tr[:n].mean()
        for i in range(n, к):
            atr[i] = (atr[i - 1] * (n - 1) + tr[i]) / n
    return atr


def _пивоти(x: np.ndarray, ляво: int, дясно: int, връх: bool) -> np.ndarray:
    """
    Булев масив: True на индекс p, ако p е пивот (връх или дъно).
    Строго сравнение и от двете страни — равни стойности НЕ дават пивот.
    ⚠ ПРЕДПОЛОЖЕНО: точното поведение на ta.pivothigh при РАВНИ барове не е сверено
      в самия TradingView в тази сесия. Строгото сравнение е по-консервативното.
    ВАЖНО: масивът се смята наведнъж, но се КОНСУМИРА само на бар p+дясно (виж цикъла),
      затова няма надничане. Това се проверява машинно от тестовете в края.
    """
    к = len(x)
    рез = np.zeros(к, dtype=bool)
    ш = ляво + дясно + 1
    if к < ш:
        return рез
    прозорци = np.lib.stride_tricks.sliding_window_view(x, ш)
    център = прозорци[:, ляво][:, None]
    др = np.delete(прозорци, ляво, axis=1)
    ок = np.all((център > др) if връх else (център < др), axis=1)
    рез[ляво: ляво + len(ок)] = ок
    return рез


def _среден_обем(v, n: int):
    """Среден обем на ПРЕДХОДНИТЕ n бара (изместен с 1 — текущият НЕ влиза)."""
    if v is None:
        return None
    s = pd.Series(v, dtype="float64")
    return s.rolling(n, min_periods=max(3, n // 5)).mean().shift(1).to_numpy()


def _подготви(df: pd.DataFrame):
    к = {c.lower(): c for c in df.columns}
    липсва = [x for x in ("open", "high", "low", "close") if x not in к]
    if липсва:
        raise ValueError("липсват колони: %s (има: %s)" % (липсва, list(df.columns)))
    o = df[к["open"]].to_numpy(dtype="float64")
    h = df[к["high"]].to_numpy(dtype="float64")
    l = df[к["low"]].to_numpy(dtype="float64")
    c = df[к["close"]].to_numpy(dtype="float64")
    v = df[к["volume"]].to_numpy(dtype="float64") if "volume" in к else None
    if isinstance(df.index, pd.DatetimeIndex):
        t = df.index
    elif "timestamp" in к:
        t = pd.DatetimeIndex(df[к["timestamp"]])
    else:
        t = None
    return o, h, l, c, v, t


def _окр(x, з=2):
    if x is None:
        return None
    if isinstance(x, float) and (np.isnan(x) or np.isinf(x)):
        return None
    return round(float(x), з)


