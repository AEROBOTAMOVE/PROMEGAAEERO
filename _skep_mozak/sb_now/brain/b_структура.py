def f_структура_история(df: pd.DataFrame, рез: dict | None = None,
                        хоризонт: int = 48, тп1: float = 7.5, стоп: float = 20.0,
                        в_atr: tuple | None = None, **пар) -> dict:
    """
    ⚠ ТОВА ГЛЕДА В БЪДЕЩЕТО — УМИШЛЕНО. Не се вика на живо. Служи само да ИЗМЕРИ дали
    осемте условия изобщо разделят: дали 💎 РЯДЪК се държи различно от ✨ ИСКРА.

    За всяко BOS/CHoCH събитие на бар b:
      · вход = close[b] (както Pine заключва плана на р. 1198)
      · гледа се напред `хоризонт` бара
      · достига ли първо +тп1$ (по посоката) или −стоп$
      · ако и двете са в ЕДИН И СЪЩ бар → брои се като СТОП (консервативно) и се
        отчита отделно като „двусмислен"
      · МАКС ход по посоката (MFE) в долари
    БЕЗ спред, БЕЗ комисиона, in-sample. Затова НЕ е бектест и не бива да се
    представя като такъв.

    `в_atr=(цел, стоп)` → целта и стопът се мерят в ATR на бара на пробива, а не в
    долари. Нужно е, защото 7.5$ на злато за 850$ (2009) и за 4170$ (2026) са съвсем
    различни разстояния; фиксираните долари смесват две различни игри в една таблица.
    """
    if рез is None:
        рез = f_структура(df, **пар)
    o, h, l, c, v, t = _подготви(df)
    n = len(c)
    _a = _atr_wilder(h, l, c, int(пар.get("atr_период", ПАРАМ_ГРАФИКА["atr_период"])))
    по_степен = {}
    for e in рез["събития"]:
        if e["вид"] not in ("BOS", "CHoCH"):
            continue
        b, зн = e["бар"], e["посока"]
        if b + хоризонт >= n:
            continue                       # хоризонтът не е изцяло в миналото → пропуска се
        вход = c[b]
        if в_atr is not None:
            a_b = _a[b]
            if not np.isfinite(a_b) or a_b <= 0:
                continue
            д_цел, д_стоп = в_atr[0] * a_b, в_atr[1] * a_b
        else:
            д_цел, д_стоп = тп1, стоп
        цел = вход + зн * д_цел
        сл = вход - зн * д_стоп
        изход, двусмислен = None, False
        mfe = 0.0
        for j in range(b + 1, b + 1 + хоризонт):
            ход = (h[j] - вход) if зн > 0 else (вход - l[j])
            mfe = max(mfe, ход)
            хит_тп = (h[j] >= цел) if зн > 0 else (l[j] <= цел)
            хит_сл = (l[j] <= сл) if зн > 0 else (h[j] >= сл)
            if хит_тп and хит_сл:
                изход, двусмислен = "СТОП", True
                break
            if хит_тп:
                изход = "ЦЕЛ"
                break
            if хит_сл:
                изход = "СТОП"
                break
        ст = e["степен"]
        д = по_степен.setdefault(ст, dict(n=0, цел=0, стоп=0, без=0, двусмислени=0,
                                          mfe_сбор=0.0, mfe_atr=0.0, точки=e["точки"]))
        д["n"] += 1
        д["mfe_сбор"] += mfe
        if np.isfinite(_a[b]) and _a[b] > 0:
            д["mfe_atr"] += mfe / _a[b]
        if двусмислен:
            д["двусмислени"] += 1
        if изход == "ЦЕЛ":
            д["цел"] += 1
        elif изход == "СТОП":
            д["стоп"] += 1
        else:
            д["без"] += 1
    таблица = []
    for ст in СТЕПЕНИ:
        д = по_степен.get(ст)
        if not д:
            continue
        решени = д["цел"] + д["стоп"]
        таблица.append(dict(степен=ст, брой=д["n"],
                            дял_цел=round(д["цел"] / решени, 3) if решени else None,
                            цел=д["цел"], стоп=д["стоп"], без_изход=д["без"],
                            двусмислени=д["двусмислени"],
                            среден_mfe=round(д["mfe_сбор"] / д["n"], 2),
                            среден_mfe_atr=round(д["mfe_atr"] / д["n"], 2)))
    return dict(таблица=таблица, хоризонт=хоризонт,
                тп1=(f"{в_atr[0]} ATR" if в_atr else тп1),
                стоп=(f"{в_atr[1]} ATR" if в_atr else стоп),
                статус="ИЗМЕРЕНО В ТАЗИ СЕСИЯ · описателно, in-sample, без спред и "
                       "разход — НЕ Е БЕКТЕСТ")


