def _еднакви(a, b) -> bool:
    if a == b:
        return True
    if isinstance(a, float) and isinstance(b, float):
        return abs(a - b) < 1e-9
    return False


def тест_без_надничане(df: pd.DataFrame, точки: int = 150, **пар) -> dict:
    """
    Пуска f_структура върху НАРАСТВАЩИ префикси. Ако функцията надничаше напред,
    събитие, издадено на бар i, щеше да се промени (или изчезне), щом добавим
    следващите барове. Изисква: всяко събитие в префикса да съвпада с пълния пробег.

    🔴 ИЗМЕРЕНО ОГРАНИЧЕНИЕ (в тази сесия, върху 11 744 реални 15-минутни бара):
    тази проверка вижда само местата, където режем. С нарочно вкарано надничане по
    цената (`_надничане_цена=True`) тя МЪЛЧИ при 6 и при 40 точки на рязане и
    проговаря чак при 150 (24 провала). Затова подразбираното е 150, а не 12 —
    и затова обвързващото доказателство е `тест_строг_причинен`, не това.
    """
    n = len(df)
    пълно = {e["номер"]: {k: e.get(k) for k in _КЛЮЧОВЕ}
             for e in f_структура(df, **пар)["събития"]}
    провали, проверени = [], 0
    for стъпка in range(1, точки + 1):
        край = int(n * стъпка / (точки + 1))
        if край < 60:
            continue
        for e in f_структура(df.iloc[:край], **пар)["събития"]:
            проверени += 1
            ет = пълно.get(e["номер"])
            if ет is None:
                провали.append((край, e["бар"], "събитие само в префикса"))
                continue
            for k in _КЛЮЧОВЕ:
                if not _еднакви(ет[k], e.get(k)):
                    провали.append((край, e["бар"], f"{k}: префикс={e.get(k)} пълно={ет[k]}"))
    return dict(проверени_събития=проверени, провали=провали, чисто=(len(провали) == 0))


def тест_строг_причинен(df: pd.DataFrame, от: int, до: int, **пар) -> dict:
    """
    Най-строгата проверка: симулира ЖИВ бот. За всеки бар i от `от` до `до` пуска
    функцията върху df.iloc[:i+1] (сякаш барът току-що е затворил) и записва кои
    събития са издадени НА ТОЗИ БАР. После сверява с пълния пробег.

    Ако някъде има разлика → функцията вижда бъдещето и е безполезна на живо.
    """
    пълно = f_структура(df, **пар)["събития"]
    по_бар = {}
    for e in пълно:
        по_бар.setdefault(e["бар"], []).append({k: e.get(k) for k in _КЛЮЧОВЕ})
    разлики, барове = [], 0
    for i in range(от, до):
        барове += 1
        живо = [{k: e.get(k) for k in _КЛЮЧОВЕ}
                for e in f_структура(df.iloc[:i + 1], **пар)["събития"] if e["бар"] == i]
        офлайн = по_бар.get(i, [])
        if len(живо) != len(офлайн):
            разлики.append((i, f"живо={len(живо)} офлайн={len(офлайн)}"))
            continue
        for ж, оф in zip(живо, офлайн):
            for k in _КЛЮЧОВЕ:
                if not _еднакви(оф[k], ж[k]):
                    разлики.append((i, f"{k}: живо={ж[k]} офлайн={оф[k]}"))
    return dict(проверени_барове=барове, разлики=разлики, чисто=(len(разлики) == 0))


def тест_пивот_закъснение(df: pd.DataFrame, пивот: int = 6, **пар) -> dict:
    """
    Пряка проверка на закъснението: всяко BOS/CHoCH събитие трябва да стои поне
    `пивот` бара след бара на своя пивот. По-малко = функцията е видяла върха,
    преди десните му барове да са затворили = надничане.
    """
    r = f_структура(df, пивот=пивот, **пар)
    нарушения = []
    for e in r["събития"]:
        if e["вид"] in ("BOS", "CHoCH") and e.get("пивот_бар") is not None:
            if e["бар"] - e["пивот_бар"] < пивот:
                нарушения.append((e["бар"], e["пивот_бар"], e["бар"] - e["пивот_бар"]))
    return dict(проверени=sum(1 for e in r["събития"] if e["вид"] in ("BOS", "CHoCH")),
                нарушения=нарушения, чисто=(len(нарушения) == 0),
                мин_закъснение=min([e["бар"] - e["пивот_бар"] for e in r["събития"]
                                    if e.get("пивот_бар") is not None] or [None]))


