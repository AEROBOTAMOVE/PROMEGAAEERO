ПЪТ_15М = r"C:/Users/User/Downloads/ЛОЦО/f6_data/parquet/xauusd_15min_bid_ask.parquet"
ПЪТ_1М = r"C:/Users/User/Downloads/ЛОЦО/f6_data/parquet/xauusd_1min_bid_ask.parquet"


def зареди_реални(път: str = ПЪТ_15М, последни: int | None = None,
                  групи: int | None = None) -> pd.DataFrame:
    """
    Чете parquet-а през fastparquet (pyarrow е блокиран от Application Control на машината).
    OHLC = средата между bid и ask; обем = bid+ask тик-обем.
    Изхвърля непълния последен бар и застоялите котировки.
    `групи` = чети само последните N row-group-а (за 466MB 1-минутния файл).
    """
    import fastparquet
    к = ["timestamp_utc", "open_bid", "high_bid", "low_bid", "close_bid", "volume_bid",
         "open_ask", "high_ask", "low_ask", "close_ask", "volume_ask",
         "is_incomplete_last_bar_bid", "is_stale_quote_bid", "session"]
    pf = fastparquet.ParquetFile(път)
    if групи:
        pf = pf[len(pf.row_groups) - групи:]
    d = pf.to_pandas(columns=к)
    d = d[~d["is_incomplete_last_bar_bid"].astype(bool)]
    d = d[~d["is_stale_quote_bid"].astype(bool)]
    изх = pd.DataFrame({
        "open": (d["open_bid"] + d["open_ask"]) / 2.0,
        "high": (d["high_bid"] + d["high_ask"]) / 2.0,
        "low": (d["low_bid"] + d["low_ask"]) / 2.0,
        "close": (d["close_bid"] + d["close_ask"]) / 2.0,
        "volume": d["volume_bid"] + d["volume_ask"],
        "session": d["session"].values,
    })
    изх.index = pd.DatetimeIndex(d["timestamp_utc"])
    изх = изх.sort_index()
    return изх.iloc[-последни:] if последни else изх
