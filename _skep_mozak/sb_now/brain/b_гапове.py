def изследване_запълване(df: pd.DataFrame, *, рамка: str = "1h", име: str = "1час",
                         хоризонти=(20, 60, 200, 1000)) -> dict:
    """
    Н11 · ВЕРОЯТНОСТ ОТ ИСТОРИЯТА вместо цвят.
    Мери на реалните барове: колко често гап от даден клас се запълва до N базови
    бара напред. Разбива по размер (в ATR) и по посока.

    ⚠⚠ ТАЗИ ФУНКЦИЯ ГЛЕДА В БЪДЕЩЕТО ПО ПРОЕКТ. Тя е измервателен уред, не сигнал.
    НЕ Я ВИКАЙ от живия бот. `f_гапове` не я ползва и не я вика.

    ⚠ И числата ѝ са ЧЕСТОТА НА ЗАПЪЛВАНЕ, не доходност. «Запълва се в 80%»
    не значи «печели». Не ги представяй като измерена печалба.
    """
    ix = _индекс(df)
    if ix is None:
        return {"грешка": "няма времеви индекс"}
    разлики = np.diff(ix.to_numpy()).astype("timedelta64[s]").astype(float)
    стъпка = pd.Timedelta(seconds=float(np.median(разлики)))
    рм = _рамка(df, ix, рамка, стъпка)
    if рм is None:
        return {"грешка": "рамката не се сглоби"}

    high = df["high"].to_numpy(float)
    low = df["low"].to_numpy(float)
    atr = _atr_rma(df, 14)
    n = len(df)

    кандидати = _открий(рм, име, 1.0, "plus", n - 1)
    редове = []
    for г in кандидати:
        от = г["бар_потвърден"]
        if от >= n - 1:
            continue
        a = atr[от] if от < len(atr) and not np.isnan(atr[от]) else np.nan
        if not np.isfinite(a) or a <= 0:
            continue
        размер = г["горе"] - г["долу"]
        ред = {"вид": г["вид"], "размер_atr": размер / a}
        for H in хоризонти:
            до = min(n - 1, от + H)
            if г["вид"] == "бичи":
                ред[H] = bool((low[от:до + 1] <= г["долу"]).any())
            else:
                ред[H] = bool((high[от:до + 1] >= г["горе"]).any())
        редове.append(ред)

    if not редове:
        return {"грешка": "няма гапове"}
    t = pd.DataFrame(редове)
    кофи = pd.cut(t["размер_atr"], [0, 0.25, 0.5, 1.0, 2.0, 1e9],
                  labels=["<0.25 ATR", "0.25–0.5", "0.5–1.0", "1.0–2.0", ">2 ATR"])
    таблица = {}
    for к, гр in t.groupby(кофи, observed=True):
        таблица[str(к)] = {"брой": int(len(гр)),
                           **{f"до {H} бара": round(float(гр[H].mean()) * 100, 1)
                              for H in хоризонти}}
    общо = {f"до {H} бара": round(float(t[H].mean()) * 100, 1) for H in хоризонти}
    return {"рамка": име, "брой_гапове": int(len(t)), "по_размер": таблица,
            "общо_пц": общо,
            "предупреждение": "ГЛЕДА НАПРЕД · само за изследване · честота, НЕ доходност"}


