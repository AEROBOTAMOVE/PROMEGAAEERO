def _atr_rma(df: pd.DataFrame, period: int = 14) -> np.ndarray:
    """ta.atr(14) на Pine = RMA (Wilder) на True Range. Пренос 1:1."""
    h = df["high"].to_numpy(float)
    l = df["low"].to_numpy(float)
    c = df["close"].to_numpy(float)
    pc = np.concatenate(([c[0]], c[:-1]))
    tr = np.maximum(h - l, np.maximum(np.abs(h - pc), np.abs(l - pc)))
    atr = np.full(len(tr), np.nan)
    if len(tr) < period:
        return atr
    atr[period - 1] = tr[:period].mean()
    a = 1.0 / period
    for i in range(period, len(tr)):
        atr[i] = atr[i - 1] * (1 - a) + tr[i] * a
    return atr


def _индекс(d: pd.DataFrame) -> pd.DatetimeIndex | None:
    """Времевият индекс — от index или от колона."""
    ix = d.index
    if isinstance(ix, pd.DatetimeIndex):
        return ix
    for к in ("timestamp_utc", "timestamp", "time", "datetime"):
        if к in d.columns:
            return pd.DatetimeIndex(pd.to_datetime(d[к]))
    return None


def _кофи(ix: pd.DatetimeIndex, правило: str, стъпка: pd.Timedelta,
          край_време: pd.Timestamp) -> tuple | None:
    """
    Реже отрязания прозорец на кофи от по-висока рамка — БЕЗ `resample`, за да
    имам за всяка кофа точните базови индекси (първи и последен бар в нея).

    ═══ КЛЮЧАЛКА 3 СРЕЩУ НАДНИЧАНЕ ═══
    Кофа влиза САМО ако е завършила ПО ВРЕМЕ:
        край_на_кофата <= време(as_of) + стъпка_на_базата
    Тоест последният ѝ възможен бар вече е затворил. Недовършената последна кофа
    отпада — същото, което прави `request.security(..., lookahead_off)` с `[1]`
    в Pine (v9.3 р. 222–225): подава САМО завършени свещи.

    Връща (старт_идx, край_идx, край_време_на_кофата) — масиви по кофи.
    """
    try:
        ключ = ix.floor(правило)
    except Exception:
        return None
    n = len(ключ)
    if n < 4:
        return None
    к = ключ.to_numpy()
    смени = np.flatnonzero(к[1:] != к[:-1]) + 1
    старт = np.concatenate(([0], смени))
    крайове = np.concatenate((смени - 1, [n - 1]))
    delta = pd.Timedelta(правило)
    край_кофа = ключ[старт] + delta
    завършени = край_кофа <= (край_време + стъпка)
    if not завършени.any():
        return None
    return старт[завършени], крайове[завършени], край_кофа[завършени]


def _рамка(d: pd.DataFrame, ix: pd.DatetimeIndex, правило: str,
           стъпка: pd.Timedelta) -> dict | None:
    """
    Сглобява една по-висока рамка от вече ОТРЯЗАНИЯ `d` (ключалка 2).
    Връща OHLCV на кофите + за всяка кофа:
        посл_база  · индекс на ПОСЛЕДНИЯ базов бар в кофата
        след_база  · индекс на ПЪРВИЯ базов бар СЛЕД кофата (или n, ако няма)
    Тези два индекса са двете възможни времена на потвърждение (виж Н10).
    """
    к = _кофи(ix, правило, стъпка, ix[-1])
    if к is None:
        return None
    старт, крайове, край_кофа = к
    if len(старт) < 3:
        return None
    h = d["high"].to_numpy(float)
    l = d["low"].to_numpy(float)
    o = d["open"].to_numpy(float)
    c = d["close"].to_numpy(float)
    v = d["volume"].to_numpy(float) if "volume" in d.columns else None

    # ⚠ НЕ `np.maximum.reduceat` — то стига до следващия СТАРТ, а последната
    # завършена кофа може да е следвана от недовършена, чиито барове НЕ СА неин.
    # Затова изрично [старт .. край] на всяка кофа.
    fh = np.array([h[a:b + 1].max() for a, b in zip(старт, крайове)])
    fl = np.array([l[a:b + 1].min() for a, b in zip(старт, крайове)])
    fo = o[старт]
    fc = c[крайове]
    fv = (np.array([v[a:b + 1].sum() for a, b in zip(старт, крайове)])
          if v is not None else None)

    # първият базов бар СЛЕД кофата
    t = ix.to_numpy()
    след = np.searchsorted(t, край_кофа.to_numpy(), side="left")

    return {"o": fo, "h": fh, "l": fl, "c": fc, "v": fv,
            "посл_база": крайове, "след_база": след,
            "край_кофа": край_кофа, "n": len(старт)}


