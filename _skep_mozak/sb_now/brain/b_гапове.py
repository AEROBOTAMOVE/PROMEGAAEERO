# ОТКРИВАНЕ · ПРЕНОС 1:1 (v9.3 р. 560–571)
# ─────────────────────────────────────────────────────────────────────────────
def _открий(рм: dict, име: str, тежест: float, timing: str, as_of_вътре: int) -> list:
    """
    ПРЕНОС на f_detect_fvg:
        бичи ако low[0]  > high[2]  →  кутия (low[0],  high[2])   top=low[0]
        мечи ако high[0] < low[2]   →  кутия (low[2],  high[0])   top=low[2]
    `[0]` е най-новата ЗАТВОРЕНА свещ на рамката, `[2]` е две назад.
    Условието `top > bottom` е от f_add_fvg (р. 538).

    timing:
      "pine" · гапът е известен на ПЪРВИЯ базов бар от следващата кофа
               (`ta.change(k1) != 0`, р. 257–268) — както на графиката
      "plus" · гапът е известен при ЗАТВАРЯНЕТО на последния бар от кофата (Н10)
    """
    n = рм["n"]
    if n < 3:
        return []
    fh, fl, fv = рм["h"], рм["l"], рм["v"]
    посл, след = рм["посл_база"], рм["след_база"]
    мед_обем = float(np.median(fv[fv > 0])) if fv is not None and (fv > 0).any() else None

    out = []
    for i in range(2, n):
        # ── бичи ────────────────────────────────────────────────────────────
        for бичи in (True, False):
            if бичи:
                if not (fl[i] > fh[i - 2]):
                    continue
                горе, долу = float(fl[i]), float(fh[i - 2])
            else:
                if not (fh[i] < fl[i - 2]):
                    continue
                горе, долу = float(fl[i - 2]), float(fh[i])
            if not (горе > долу):          # f_add_fvg р. 538
                continue
            потв = int(посл[i]) if timing == "plus" else int(след[i])
            if потв > as_of_вътре + 1:     # още не е известен → не съществува
                continue
            # Н7 · обемът на СРЕДНАТА свещ — тази, която е скочила и е оставила гапа
            обем_х = None
            if fv is not None and мед_обем and мед_обем > 0:
                обем_х = float(fv[i - 1]) / мед_обем
            out.append({
                "вид": "бичи" if бичи else "мечи",
                "рамка": име,
                "тежест": тежест,
                "горе": горе,
                "долу": долу,
                "бар_потвърден": потв,
                "бар_кофа": int(посл[i]),
                "обем_х": обем_х,
            })
    return out


# ─────────────────────────────────────────────────────────────────────────────
# ЖИВОТ НА ГАПА · запълване, проникване, допири
# ─────────────────────────────────────────────────────────────────────────────
def _живот(г: dict, high: np.ndarray, low: np.ndarray, край: int) -> dict:
    """
    Мери какво се е случило с гапа от `бар_потвърден` до `as_of` — и НИТО БАР ПРЕДИ.
    ═══ КЛЮЧАЛКА 4 СРЕЩУ НАДНИЧАНЕ ═══

    ПРЕНОС (v9.3 р. 586): бичи запълнен ако `low <= долу` · мечи ако `high >= горе`.
    НАДГРАЖДАНЕ Н3/Н4/Н5: процент проникване, брой отделни допира, свежест.
    """
    от = г["бар_потвърден"]
    размер = г["горе"] - г["долу"]
    празно = {"запълнен": False, "бар_запълнен": None, "запълнен_пц": 0.0,
              "допири": 0, "свеж": True, "средата_взета": False}
    if от > край or размер <= 0:
        return празно

    h = high[от:край + 1]
    l = low[от:край + 1]
    if len(h) == 0:
        return празно

    if г["вид"] == "бичи":
        # цената слиза отгоре надолу в гапа
        дълбочина = (г["горе"] - float(l.min())) / размер
        пълни = np.flatnonzero(l <= г["долу"])
    else:
        дълбочина = (float(h.max()) - г["долу"]) / размер
        пълни = np.flatnonzero(h >= г["горе"])

    запълнен = len(пълни) > 0
    бар_зап = int(от + пълни[0]) if запълнен else None
    пц = float(np.clip(дълбочина, 0.0, 1.0) * 100.0)

    # Н4 · допири = брой ОТДЕЛНИ влизания (същото броене като при зоните, р. 749:
    # `nowInside and not wasInside`). Барът пипа гапа, ако диапазонът му го сече.
    вътре = (h >= г["долу"]) & (l <= г["горе"])
    ако = вътре.astype(np.int8)
    допири = int(ако[0] + int((ако[1:] > ако[:-1]).sum())) if len(ако) else 0

    return {"запълнен": запълнен, "бар_запълнен": бар_зап,
            "запълнен_пц": round(пц, 1), "допири": допири,
            "свеж": допири == 0, "средата_взета": пц >= 50.0}


# ─────────────────────────────────────────────────────────────────────────────
# ПРЕНОС · ТАВАНЪТ (v9.3 р. 546–558) — истинска симулация по барове
# ─────────────────────────────────────────────────────────────────────────────
def _симулация_pine(кандидати: list, high: np.ndarray, low: np.ndarray,
                    край: int, cap: int, ред_рамки: list) -> list:
    """
    Pine държи ЕДИН общ масив за всички рамки с таван `maxFvgPerTf * 4` = 16 (р. 546)
    и изхвърля НАЙ-СТАРИЯ (`array.shift`, р. 548) при препълване. Запълнените се
    трият напълно (р. 589–600). Кой оцелява ЗАВИСИ ОТ РЕДА ВЪВ ВРЕМЕТО —
    затова тук има истинска симулация бар по бар, а не филтър.

    Ред в рамките на един бар — точно както в Pine (р. 573–577):
      1) добавяне за tf1, после tf2, после tf3, после дневен
      2) чак след това проверка за запълване с high/low на ТЕКУЩИЯ бар
    """
    по_бар: dict[int, list] = {}
    for г in кандидати:
        по_бар.setdefault(г["бар_потвърден"], []).append(г)
    ранг = {име: i for i, име in enumerate(ред_рамки)}
    for b in по_бар:
        по_бар[b].sort(key=lambda x: (ранг.get(x["рамка"], 99), x["бар_кофа"]))

    живи: list = []
    старт = min(по_бар) if по_бар else край + 1
    for j in range(старт, край + 1):
        for г in по_бар.get(j, []):
            живи.append(dict(г))
            while cap is not None and len(живи) > cap:
                живи.pop(0)                     # array.shift → най-старият пада
        hb, lb = high[j], low[j]
        оцелели = []
        for г in живи:
            зап = (lb <= г["долу"]) if г["вид"] == "бичи" else (hb >= г["горе"])
            if not зап:
                оцелели.append(г)
        живи = оцелели
    # гаповете, потвърдени на as_of+1 (Pine ги вижда на формиращия се бар)
    for г in по_бар.get(край + 1, []):
        живи.append(dict(г))
        while cap is not None and len(живи) > cap:
            живи.pop(0)
    return живи


# ═════════════════════════════════════════════════════════════════════════════
# ГЛАВНАТА ФУНКЦИЯ
# ═════════════════════════════════════════════════════════════════════════════
def f_гапове(
    df: pd.DataFrame,
    *,
    # ── настройки от графиката (пренос) ──────────────────────────────────────
    max_fvg_per_tf: int = 4,            # maxFvgPerTf (v9.3 р. 64) → таван 4*4 = 16
    # ── управление ───────────────────────────────────────────────────────────
    mode: str = "plus",                 # "pine" = 1:1 с графиката · "plus" = надградено
    as_of: int | None = None,           # индекс на последния ЗАТВОРЕН бар
    lookback: int = 2000,               # колко базови бара назад (plus)
    рамки: tuple | None = None,         # None → РАМКИ_PINE / РАМКИ_PLUS според mode
    # ── надграждания ─────────────────────────────────────────────────────────
    max_dist_atr: float = 30.0,         # по-далечните гапове не влизат в изхода
    пази_запълнени: bool = False,       # plus: да върне ли и запълнените (за изследване)
    праг_обем: float = 1.5,             # Н7 · x колко над медианата брои за точка
) -> dict:
    """
    Намира НЕЗАПЪЛНЕНИТЕ ценови гапове на няколко рамки и ги подрежда по сила.

    Вход : df с колони open/high/low/close (+volume, ако има), подредени по време,
           с времеви индекс (DatetimeIndex) или колона timestamp_utc.
           БАЗОВАТА рамка е тази на df (за живия бот: 15-минутна).
    Изход: dict. Всеки гап е речник с:

      вид             "бичи" | "мечи"      (бичи = опора отдолу · мечи = таван отгоре)
      рамка           str   · на коя рамка е роден
      тежест          float · 1..4 (pine) или 1..7 (plus) — по-голяма рамка тежи повече
      горе / долу     float · двата ръба на кутията           ← ботът пази САМО единия
      среда           float · 50% — «дозапълването», което мнозина ползват за вход
      размер          float · горе − долу, в долари
      размер_atr      float · размерът в ATR-и
      бар_потвърден   int   · КОГА гапът е станал видим  ⇒ доказателството срещу надничане
      бар_кофа        int   · последният базов бар от кофата, която го е родила
      възраст_барове  int   · as_of − бар_потвърден
      възраст_часове  float
      запълнен        bool  · ПРЕНОС: бичи low<=долу · мечи high>=горе
      бар_запълнен    int|None
      запълнен_пц     float · 0–100, най-дълбокото проникване                    (Н3)
      допири          int   · колко ОТДЕЛНИ пъти цената е влизала в гапа         (Н4)
      свеж            bool  · допири == 0, никога не е пипан                     (Н5)
      средата_взета   bool  · запълнен_пц >= 50
      обем_х          float · обем на импулсната свещ / медианния на рамката     (Н7)
      стек            int   · колко ДРУГИ гапа в същата посока го застъпват      (Н8)
      стек_рамки      list  · от кои рамки са те
      разстояние      float · среда − цена (със знак) · и _абс/_пц/_atr          (Н9)
      точки           int   · 0–8, изпълнените условия
      условия         dict  · КОИ точно условия са изпълнени (за проверка)
      степен          str   · една от 7-те
      мерено          bool  · ВИНАГИ False — няма бектест зад този гап
    """
    if mode not in ("pine", "plus"):
        raise ValueError("mode трябва да е 'pine' или 'plus'")

    n_общо = len(df)
    if as_of is None:
        as_of = n_общо - 1
    if as_of < 20:
        return _празен(as_of, mode, "твърде малко барове")

    if рамки is None:
        рамки = РАМКИ_PINE if mode == "pine" else РАМКИ_PLUS

    # ═══ КЛЮЧАЛКА 1 СРЕЩУ НАДНИЧАНЕ ═══
    # Отрязваме всичко след `as_of`. Оттук нататък бъдещето физически го няма.
    # Работен прозорец: Pine сам гледа най-много max_bars_back = 1200 бара
    # назад (v9.3 р. 8) — тоест графиката също не вижда по-старото.
    назад = (1200 if mode == "pine" else lookback) + 60
    отместване = max(0, as_of - назад)
    d = df.iloc[отместване:as_of + 1]
    край = as_of - отместване                     # индексът на as_of ВЪТРЕ в прозореца

    ix = _индекс(d)
    if ix is None:
        return _празен(as_of, mode, "няма времеви индекс — рамките не могат да се сглобят")

    high = d["high"].to_numpy(float)
    low = d["low"].to_numpy(float)
    close = d["close"].to_numpy(float)
    цена_сега = float(close[-1])

    atr_ред = _atr_rma(d, 14)
    atr = float(atr_ред[-1]) if not np.isnan(atr_ред[-1]) else float(np.nanmean(high - low))
    if not np.isfinite(atr) or atr <= 0:
        atr = max(1e-9, float(np.nanmean(high - low)))

    разлики = np.diff(ix.to_numpy()).astype("timedelta64[s]").astype(float)
    стъпка_сек = float(np.median(разлики)) if len(разлики) else 900.0
    стъпка = pd.Timedelta(seconds=стъпка_сек)

    # ═══ КЛЮЧАЛКА 2 · рамките се строят от отрязания `d`, не отвън ═══
    timing = "pine" if mode == "pine" else "plus"
    кандидати: list = []
    ред_рамки: list = []
    по_рамки: dict[str, int] = {}
    for име, правило, тежест in рамки:
        if _СЕК.get(име, 0) < стъпка_сек - 1:      # рамка ПОД базовата е невъзможна
            continue
        ред_рамки.append(име)
        рм = _рамка(d, ix, правило, стъпка)
        if рм is None:
            continue
        кандидати += _открий(рм, име, float(тежест), timing, край)

    if not кандидати:
        return _празен(as_of, mode, "няма открити гапове в прозореца")

    # ── ПРЕНОС · таванът е ОБЩ и зависи от реда във времето ─────────────────
    if mode == "pine":
        cap = max_fvg_per_tf * 4                  # р. 546
        живи = _симулация_pine(кандидати, high, low, край, cap, ред_рамки)
        for г in живи:
            г.update(_живот(г, high, low, край))
        оставащи = живи                           # симулацията вече е махнала запълнените
    else:
        # Н2 · БЕЗ ТАВАН — пазим всичко
        for г in кандидати:
            г.update(_живот(г, high, low, край))
        оставащи = [г for г in кандидати if пази_запълнени or not г["запълнен"]]

    # ── Н8 · СТЕК: застъпване между гапове в СЪЩАТА посока ──────────────────
    # (същото сечение като f_fvg_overlap, v9.3 р. 627:
    #  min(top_a, top_b) >= max(bottom_a, bottom_b))
    незап = [г for г in оставащи if not г["запълнен"]]
    for г in оставащи:
        сек = [о for о in незап
               if о is not г and о["вид"] == г["вид"]
               and min(г["горе"], о["горе"]) >= max(г["долу"], о["долу"])]
        г["стек"] = len(сек)
        г["стек_рамки"] = sorted({о["рамка"] for о in сек})

    # ── ОФОРМЯНЕ НА ИЗХОДА ──────────────────────────────────────────────────
    готови = []
    for г in оставащи:
        размер = г["горе"] - г["долу"]
        среда = (г["горе"] + г["долу"]) / 2.0
        разст = среда - цена_сега
        разст_atr = abs(разст) / atr
        if разст_atr > max_dist_atr:
            continue
        възраст = int(край - г["бар_потвърден"])

        # ═══════════════════════════════════════════════════════════════════
        # 8-ТЕ УСЛОВИЯ · всяко е ИЗМЕРИМО, нито едно не е усещане
        # ═══════════════════════════════════════════════════════════════════
        у = {
            "голям":        размер / atr >= 0.50,
            "много_голям":  размер / atr >= 1.00,
            "висока_рамка": _СЕК.get(г["рамка"], 0) >= 3600,      # >= 1 час
            "дневна_рамка": _СЕК.get(г["рамка"], 0) >= 86400,     # >= 1 ден
            "свеж":         bool(г["свеж"]),                      # 0 допира
            "средата_чиста": not г["средата_взета"],              # < 50% проникване
            "обем_над":     bool(г["обем_х"] is not None and г["обем_х"] >= праг_обем),
            "стек":         г["стек"] >= 1,
        }
        точки = int(sum(у.values()))

        готови.append({
            "вид": г["вид"],
            "рамка": г["рамка"],
            "тежест": float(г["тежест"]),
            "горе": round(float(г["горе"]), 3),
            "долу": round(float(г["долу"]), 3),
            "среда": round(float(среда), 3),
            "размер": round(float(размер), 3),
            "размер_atr": round(float(размер / atr), 3),
            # индексите се връщат в координатите на ПОДАДЕНИЯ df, не на прозореца
            "бар_потвърден": int(г["бар_потвърден"] + отместване),
            "бар_кофа": int(г["бар_кофа"] + отместване),
            "възраст_барове": възраст,
            "възраст_часове": round(възраст * стъпка_сек / 3600.0, 2),
            "запълнен": bool(г["запълнен"]),
            "бар_запълнен": (None if г["бар_запълнен"] is None
                             else int(г["бар_запълнен"] + отместване)),
            "запълнен_пц": float(г["запълнен_пц"]),
            "допири": int(г["допири"]),
            "свеж": bool(г["свеж"]),
            "средата_взета": bool(г["средата_взета"]),
            "обем_х": None if г["обем_х"] is None else round(float(г["обем_х"]), 2),
            "стек": int(г["стек"]),
            "стек_рамки": г["стек_рамки"],
            "разстояние": round(float(разст), 3),
            "разстояние_абс": round(float(abs(разст)), 3),
            "разстояние_пц": round(float(abs(разст) / цена_сега * 100.0), 4),
            "разстояние_atr": round(float(разст_atr), 3),
            "точки": точки,
            "условия": у,
            "степен": степен(точки),
            "мерено": False,        # НОВО · още не е мерено
        })
        по_рамки[г["рамка"]] = по_рамки.get(г["рамка"], 0) + 1

    # първо точките, после близостта — далечният гап не е за днес
    готови.sort(key=lambda x: (-x["точки"], x["разстояние_atr"]))

    жив = [x for x in готови if not x["запълнен"]]
    под = [x for x in жив if x["горе"] <= цена_сега]      # цял гап ПОД цената
    над = [x for x in жив if x["долу"] >= цена_сега]      # цял гап НАД цената
    вътре = [x for x in жив if x["долу"] < цена_сега < x["горе"]]

    опори = [x for x in под if x["вид"] == "бичи"]
    тавани = [x for x in над if x["вид"] == "мечи"]
    подпора = min(опори, key=lambda x: x["разстояние_atr"], default=None)
    таван = min(тавани, key=lambda x: x["разстояние_atr"], default=None)
    # ⚠ НАЙ-БЛИЗКИЯТ може да е гап от 0.24$ на 30м — истински, но безполезен за стоп.
    # Затова и НАЙ-СИЛНИЯТ: първо точките, при равни точки — по-близкият.
    подпора_силна = min(опори, key=lambda x: (-x["точки"], x["разстояние_atr"]),
                        default=None)
    таван_силен = min(тавани, key=lambda x: (-x["точки"], x["разстояние_atr"]),
                      default=None)

    return {
        "блок": "гапове",
        "режим": mode,
        "as_of": int(as_of),
        "време": str(ix[-1]),
        "цена": round(цена_сега, 3),
        "atr": round(atr, 3),
        "базова_рамка_сек": int(стъпка_сек),
        "рамки_ползвани": ред_рамки,
        "гапове": готови,
        "брой": len(готови),
        "брой_бичи": sum(1 for x in готови if x["вид"] == "бичи"),
        "брой_мечи": sum(1 for x in готови if x["вид"] == "мечи"),
        "брой_свежи": sum(1 for x in готови if x["свеж"]),
        "по_рамки": по_рамки,
        "най_близък_под": min(под, key=lambda x: x["разстояние_atr"], default=None),
        "най_близък_над": min(над, key=lambda x: x["разстояние_atr"], default=None),
        "вътре_в_гап": вътре,
        "подпора": подпора,              # най-БЛИЗКИЯТ бичи гап под цената
        "таван": таван,                  # най-БЛИЗКИЯТ мечи гап над цената
        "подпора_силна": подпора_силна,  # най-СИЛНИЯТ бичи гап под цената (за стоп)
        "таван_силен": таван_силен,      # най-СИЛНИЯТ мечи гап над цената (за цел)
        "най_силен": готови[0] if готови else None,
        "мерено": False,
        "бележка": "НОВО · още не е мерено — няма бектест зад тези гапове",
    }


# псевдоним за бота (ASCII име, ако някъде кирилицата пречи)
f_gaps = f_гапове


def _празен(as_of, mode, защо) -> dict:
    return {
        "блок": "гапове", "режим": mode, "as_of": int(as_of), "време": None,
        "цена": None, "atr": None, "базова_рамка_сек": None, "рамки_ползвани": [],
        "гапове": [], "брой": 0, "брой_бичи": 0, "брой_мечи": 0, "брой_свежи": 0,
        "по_рамки": {}, "най_близък_под": None, "най_близък_над": None,
        "вътре_в_гап": [], "подпора": None, "таван": None,
        "подпора_силна": None, "таван_силен": None, "най_силен": None,
        "мерено": False, "бележка": "НОВО · още не е мерено", "празно_защото": защо,
    }


# ─────────────────────────────────────────────────────────────────────────────
# ПРЕНОС · f_fvg_overlap (v9.3 р. 622–630)
# Ползва се от оценката на ЗОНАТА (р. 778: `hasFvg` дава +1 точка).
# БЛОК 4 (зони) ще вика точно това.
# ─────────────────────────────────────────────────────────────────────────────
def f_застъпване(r: dict, горе: float, долу: float, бичи: bool) -> bool:
    """Има ли НЕЗАПЪЛНЕН гап в СЪЩАТА посока, който се застъпва с [долу, горе]?"""
    вид = "бичи" if бичи else "мечи"
    for x in r.get("гапове", ()):
        if x["запълнен"] or x["вид"] != вид:
            continue
        if min(горе, x["горе"]) >= max(долу, x["долу"]):     # р. 627
            return True
    return False


