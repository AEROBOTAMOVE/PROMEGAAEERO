def f_както_в_бота_v64(h1, direction: str):
    """
    ДОСЛОВНО КОПИЕ на `_zones` от live_bot.py v6.4 (р. 719–768), сложено ТУК
    само за да може интеграторът да мери старото срещу новото, БЕЗ да пипа
    живия файл. Логиката отдолу Е МЕРЕНАТА (ОДИТ-14): A +1.998$ · B +1.457$ ·
    C +0.502$. Не я променяй — за нея има 20 години числа, за новото няма.
    """
    try:
        if h1 is None or len(h1) < 30:
            return "B", ""
        hi = h1["High"].values[-400:] if "High" in h1 else h1["high"].values[-400:]
        lo = h1["Low"].values[-400:] if "Low" in h1 else h1["low"].values[-400:]
        bull = bear = None
        for i in range(2, len(hi)):
            if lo[i] > hi[i - 2]:
                bull = float(hi[i - 2])
            if bull is not None and lo[i] < bull:
                bull = None
            if hi[i] < lo[i - 2]:
                bear = float(lo[i - 2])
            if bear is not None and hi[i] > bear:
                bear = None
        if direction == "short":
            bull, bear = bear, bull
        have, clean = bull is not None, bear is None
        if have and clean:
            return "A", "зона отдолу, чисто отгоре"
        if have:
            return "B", "зона отдолу, но има насрещна отгоре"
        if clean:
            return "B", "чисто отгоре, но без зона-опора отдолу"
        return "C", "без зона отдолу и с насрещна отгоре"
    except Exception:
        return "B", ""


def съвместимост_ABC(r: dict, посока: str = "long") -> tuple:
    """
    Същият A/B/C речник, но пресметнат от МНОГОРАМКОВИЯ двигател.

    ⚠ ЧЕСТНО: измереното число на ОДИТ-14 важи за СТАРАТА функция
    (`f_както_в_бота_v64`) — 1 рамка, 1 ръб, 400 бара. ТУК класът идва от друг
    вход, значи МЕРЕНОТО ЧИСЛО НЕ СЕ ПРЕНАСЯ АВТОМАТИЧНО. Съвпадението между
    двете е измерено в `t_гапове.py` (тест 6); докато няма собствен бектест,
    в живия бот трябва да остане СТАРАТА.
    """
    жив = [x for x in r.get("гапове", ()) if not x["запълнен"]]
    опора = "бичи" if посока == "long" else "мечи"
    насрещна = "мечи" if посока == "long" else "бичи"
    има = any(x["вид"] == опора for x in жив)
    чисто = not any(x["вид"] == насрещна for x in жив)
    if има and чисто:
        return "A", "гап-опора в посоката, нищо насреща"
    if има:
        return "B", "гап-опора има, но има и насрещен"
    if чисто:
        return "B", "чисто насреща, но без гап-опора"
    return "C", "без гап-опора и с насрещен"


