def карта_гапове(r: dict, колко: int = 6) -> str:
    if not r.get("гапове"):
        return "🕳 ГАПОВЕ · няма незапълнени празнини наблизо"
    ред = ["🕳 НЕЗАПЪЛНЕНИ ПРАЗНИНИ  ·  НОВО · още не е мерено",
           f"цена {r['цена']}  ·  ATR {r['atr']}  ·  "
           f"{r['брой']} гапа ({r['брой_бичи']}↑ / {r['брой_мечи']}↓) · "
           f"{r['брой_свежи']} непипани"]
    for x in r["гапове"][:колко]:
        посока = "⬆" if x["разстояние"] > 0 else "⬇"
        стрелка = "▲ опора" if x["вид"] == "бичи" else "▼ таван"
        състояние = ("непипан" if x["свеж"]
                     else f"{x['допири']} допира · {x['запълнен_пц']:.0f}% взет")
        ред.append(
            f"{посока} {x['долу']}–{x['горе']} ({x['среда']})  {стрелка}  ·  "
            f"{x['рамка']}  ·  {x['размер']}$ ({x['размер_atr']} ATR)  ·  "
            f"{x['разстояние_atr']} ATR оттук  ·  {състояние}  ·  "
            f"{x['степен']} [{x['точки']}/8]"
            + (f"  ·  обем x{x['обем_х']}" if x["обем_х"] else "")
            + (f"  ·  стек {x['стек']} ({'/'.join(x['стек_рамки'])})" if x["стек"] else "")
        )
    for ключ, етикет in (("подпора", "🟩 ОПОРА ОТДОЛУ (най-близка)"),
                         ("подпора_силна", "🟩 ОПОРА ОТДОЛУ (най-силна)"),
                         ("таван", "🟥 ТАВАН ОТГОРЕ (най-близък)"),
                         ("таван_силен", "🟥 ТАВАН ОТГОРЕ (най-силен)")):
        x = r.get(ключ)
        if not x:
            continue
        # ако най-близкото и най-силното са едно и също — не го пиши два пъти
        if ключ.endswith("силна") and r.get("подпора") is x:
            continue
        if ключ.endswith("силен") and r.get("таван") is x:
            continue
        ред.append(f"{етикет}: {x['долу']}–{x['горе']} · {x['рамка']} · "
                   f"{x['размер']}$ · {x['разстояние_atr']} ATR · {x['степен']}")
    if r.get("вътре_в_гап"):
        ред.append(f"⚠ ЦЕНАТА Е ВЪТРЕ В {len(r['вътре_в_гап'])} гап(а) — "
                   f"дозапълва ги в момента")
    return "\n".join(ред)
