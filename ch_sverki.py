# -*- coding: utf-8 -*-
"""Сверки: колко често идва такава карта · клонът «връх-шорт» · размерът на загубата."""
import sys, json
sys.stdout.reconfigure(encoding='utf-8')
sys.argv = ["x"]
import live_bot as lb
from pathlib import Path
import numpy as np

S = json.loads(Path("backtest_stats.json").read_text(encoding="utf-8"))
lb._сребро_разход(S, None)
P = lb.PIP

print("=== A · КОЛКО ЧЕСТО ИДВА ТАКАВА КАРТА (от ['дни']) ===")
години = 2026.52 - 2006.0        # периодът в _meta: злато 2006-2026
print("  период за клетките (по _meta злато): ~%.1f години" % години)
общо = 0
for c in ("day1", "fresh", "stale"):
    d = S["fresh"]["long"][c]["дни"]
    общо += d
    print("  long/%-6s дни=%4d -> %.1f дни/година" % (c, d, d / години))
print("  СБОР на трите пускащи клетки: %d дни -> %.1f дни/година" % (общо, общо / години))
print("  _meta казва за същото правило: 'ДОЛАР+ЛИХВИ +44462$ при 72' карти-дни/год")
print("  -> СВЕРКА: %.1f срещу 72 %s" % (общо / години,
      "СЪВПАДА" if abs(общо / години - 72) < 3 else "РАЗМИНАВА СЕ"))
print("  НО: числото 72 (и 53) НЕ са ключове в json — само текст в _meta.")

print()
print("=== Б · КЛОНЪТ 'ЗЛАТО НА ВЪРХА' (short, стрийк 2-3, dd20 < %.3f) ===" % lb.NEAR_HIGH_DD20)
nh = S["fresh"]["short"]["near_high"]
print("  near_high:", json.dumps(nh, ensure_ascii=False))
print("  net %.2f$ = %.1f пипса · 95%%: %.1f .. %.1f пипса · _noise=%s"
      % (nh["net"], nh["net"] / P, nh["lo"] / P, nh["hi"] / P, lb._noise(nh)))
for dd in (0.005, 0.02):
    tr = {}
    txt, ok = lb._advice_entry("short", 2, S, None, False, 0, sym="XAUUSD", dd20=dd, trace=tr)
    print("  dd20=%.3f -> вход=%-3s | %s | trace=%s"
          % (dd, "ДА" if ok else "не", txt, json.dumps(tr, ensure_ascii=False)))

print()
print("=== В · КОЛКО ГУБИ, КОГАТО ГУБИ (може ли да се каже честно?) ===")
T = S["tp_hits_доставена"]
загуба = T["средно_по_брой_цели"]["0"]
print("  измерено: 0 взети цели -> %.2f$ = %.1f пипса (n=%s, ЦЯЛАТА извадка)"
      % (загуба, загуба / P, T["n"]))
print("  ВНИМАНИЕ: тази извадка е ГУБЕЩА и НЕ Е филтрирана от гейта.")
print("     _f28.txt ред '0 доставената 20$ ... нето -0.114$' на същите 6846 входа.")
print("  Може ли да се извади средната ПЕЧАЛБА по клетка? САМО с допускане:")
for c in ("day1", "fresh", "stale"):
    seg = S["fresh"]["long"][c]
    w = seg["win"] / 100.0
    ср_печ = (seg["net"] - (1 - w) * загуба) / w
    print("     long/%-6s ако загубата е %.2f$ -> средна печалба %.2f$ = %.0f пипса  <-- ДОПУСКАНЕ"
          % (c, загуба, ср_печ, ср_печ / P))
print("  -> НЕ Е ИЗМЕРЕНО. Не бива да влиза в карта.")

print()
print("=== Г · ЧТО ЗНАЧИ 'ПЕЧЕЛИВША' (дефиницията от инструмента) ===")
print("  geom_harness.py ред 453: win_rate_pct = (net > 0).mean() * 100")
print("  -> сделка, взела САМО ТП1 и после стоп на входа, брои се за ПЕЧЕЛИВША (+2.5$).")
print("  -> тоест 79.9%% печеливши НЕ значи 79.9%% пъти голяма печалба.")
print("  Измерено в същата геометрия: 25.1%% от сделките са точно такива (+2.54$ = 25 пипса).")

print()
print("=== Д · СВЕРКА НА ТРИТЕ ЖИВИ КЛЕТКИ В ПИПСОВЕ (за текста на картата) ===")
for c, име in (("day1", "първи ден"), ("fresh", "ден 2-3"), ("stale", "ден 4+")):
    s = S["fresh"]["long"][c]
    print("  %-6s (%s): %s%% печеливши · средно %+.0f пипса · "
          "в 95%% от случаите между %+.0f и %+.0f пипса · %s сделки / %s дни"
          % (c, име, s["win"], s["net"] / P, s["lo"] / P, s["hi"] / P, s["n"], s["дни"]))
