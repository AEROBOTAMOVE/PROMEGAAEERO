def _пипс_знак(долари, метал="XAUUSD"):
    ст = lb.PIP if метал == "XAUUSD" else 0.001
    return f"{'+' if долари >= 0 else '−'}{abs(долари) / ст:,.0f}"


ЦЕЛ_ЗН = {"tp1": "1️⃣", "tp2": "2️⃣", "tp3": "3️⃣"}


def _части(kind, hit, lv, e, зн, дол, hit_px=None):
    """Разбива сметката по стълбата на ИМЕНУВАНИ парчета.
    Връща (прибрани_преди[(знак, долари)], сега_долари, брой_трети_сега, хартия_долари)."""
    преди = []
    n_hit = 0
    for k2 in ("tp1", "tp2"):
        if hit.get(k2) and k2 != kind:
            _ц = (hit_px or {}).get(k2)
            преди.append((ЦЕЛ_ЗН[k2],
                          round(((float(_ц) if _ц is not None else lv[k2]) - e) * зн / 3.0, 2)))
            n_hit += 1
    трета = дол / 3.0
    ост = 3 - n_hit                       # трети, които още не са прибрани
    if kind in ("tp1", "tp2"):            # прибира се ЕДНА, останалите стоят
        return преди, round(трета, 2), 1, round(трета * (ост - 1), 2)
    return преди, round(трета * ост, 2), ост, 0.0   # tp3/sl/time/flip затварят всичко


def _дни(tr, when):
    try:
        d = (pd.Timestamp(when).tz_localize(None) - pd.Timestamp(tr["opened"]).tz_localize(None)).days + 1
        return d if 1 <= d <= 400 else None
    except Exception:
        try:
            d = (pd.Timestamp(when) - pd.Timestamp(tr["opened"])).days + 1
            return d if 1 <= d <= 400 else None
        except Exception:
            return None


