print("  съвпаднали:", {k:v for k,v in съвп.items() if k.startswith('Z')})

# 2) същата мярка, но само 5 от 7
диап2={"посока":"ДИСКАУНТ","съгласие":{"водеща":"ДИСКАУНТ","мнозинство":5,"единодушно":False},"обем":{}}
т2,съвп2,_,_=m._брои(True,пов,d,R(диап2),1.0)
