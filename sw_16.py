d=pd.DataFrame({"high":[10.0]*30,"low":[9.0]*30,"close":[9.5]*30,"open":[9.5]*30,"volume":[1.0]*30})
пов=[dict(вид="структура",лонг=True,обект={},текст="")]
def R(диап):
    return {"ликвидност":{},"гапове":{},"зони":{},"структура":{},"обем":{},"диапазон":диап,"свип":{}}

# 1) ЕДНА мярка: «дискаунт», единодушна по всичките 7 хоризонта
диап={"посока":"ДИСКАУНТ","съгласие":{"водеща":"ДИСКАУНТ","мнозинство":7,"единодушно":True},"обем":{}}
т,съвп,у,_=m._брои(True,пов,d,R(диап),1.0)
