# 3) може ли Z2/Z2b да са ВЕРНИ без Z1? (изчерпателна проверка)
лош=0
for пос in ("ДИСКАУНТ","ПРЕМИУМ","РАВНОВЕСИЕ"):
  for вод in ("ДИСКАУНТ","ПРЕМИУМ","РАВНОВЕСИЕ"):
    for мн in range(0,8):
      for ед in (False,True):
        rr=R({"посока":пос,"съгласие":{"водеща":вод,"мнозинство":мн,"единодушно":ед},"обем":{}})
        _,_,у3,_=m._брои(True,пов,d,rr,1.0)
        if (у3["Z2_хоризонти"] or у3["Z2b_единодушно"]) and not у3["Z1_дискаунт_премиум"]: лош+=1
print("случаи, в които Z2/Z2b горят БЕЗ Z1 (от 3*3*8*2=144):", лош)
