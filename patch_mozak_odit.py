def _защо(карта, таблица) -> str:
    """ОДИТ-29 · ЗАЩО, събрано в един ред.

    Дотук тук се печатаха до 25 реда: заглавие на всяка група с точките ѝ,
    после всяко условие поотделно с «· », накрая ред «✗ липсва: …».
    Коста чете това на телефон между сделки. Групите, които са СЪВПАДНАЛИ,
    се изброяват с човешките си имена и толкова; какво липсва не му върши
    работа — вече му е казано колко силна е картата със степента отгоре."""
    по_група = {}
    for ключ, (тегло, гр, _текст) in таблица.items():
        if карта["всички_условия"].get(ключ):
            по_група[гр] = по_група.get(гр, 0) + тегло
    # най-тежките групи първи, без «повод» (той е в заглавния ред)
    редени = sorted((г for г in по_група if г != "А"),
                    key=lambda г: -по_група[г])
    return " + ".join(ЧОВЕШКИ.get(г, г) for г in редени[:4])


