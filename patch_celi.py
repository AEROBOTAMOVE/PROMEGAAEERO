# -*- coding: utf-8 -*-
"""
РЕД 4.1 · ЦЕЛИТЕ БЕЗ РАЗСТОЯНИЕ

Планът твърдеше «`_standing_msg` показва нива без разстояние». Проверено —
твърдението е ПОЛОВИН вярно: стопът ВЕЧЕ носи разстояние (`_разст(price_user,
lv['sl'])` → «200 пипса (20.00$)»), но трите цели са голи цени:

    1️⃣ 4,400.00 · 2️⃣ 4,405.00 · 3️⃣ 4,415.00

Собственикът брои в пипсове. За да разбере колко му е целта, трябва да извади
наум от входа — а входът е на друг ред. Точно превъртането, от което се оплака.

След:
    1️⃣ 4,400.00 (75п) · 2️⃣ 4,405.00 (120п) · 3️⃣ 4,415.00 (200п)

Кратката форма «п» е нарочна: трите цели на един ред, а редът има таван. Пълната
форма «200 пипса (20.00$)» остава на стопа, където има място и където числото
е най-важно.
"""
import io, sys, ast, hashlib

p = "live_bot.py"
s = io.open(p, encoding="utf-8", newline="").read()

СТАРО = '''         " · ".join(f"{n} <code>{_fmt(lv[k], 2)}</code>"
                    for n, k in (("1️⃣", "tp1"), ("2️⃣", "tp2"), ("3️⃣", "tp3")))]'''

НОВО = '''         # 🔴 РЕД 4.1 · ДОТУК ТУК ЦЕЛИТЕ БЯХА ГОЛИ ЦЕНИ. Стопът отдолу вече
         # носи «200 пипса (20.00$)», а целите — само число. Собственикът брои
         # в пипсове и трябваше да вади наум от входа, който е на ДРУГ ред.
         # Кратката форма «(75п)» е заради тавана на реда: три цели наведнъж.
         " · ".join(f"{n} <code>{_fmt(lv[k], 2)}</code> "
                    f"({abs(lv[k] - price_user) / PIP:,.0f}п)"
                    for n, k in (("1️⃣", "tp1"), ("2️⃣", "tp2"), ("3️⃣", "tp3")))]'''

if s.count(СТАРО) != 1:
    print(f"  x СПИРАМ: {s.count(СТАРО)} съвпадения")
    sys.exit(1)
s = s.replace(СТАРО, НОВО)
io.open(p, "wb").write(s.encode("utf-8"))
ast.parse(io.open(p, encoding="utf-8").read())
b = io.open(p, encoding="utf-8").read()
print(f"целите носят разстояние · {len(b.splitlines())} реда · "
      f"sha {hashlib.sha256(b.encode()).hexdigest()[:12]}")
