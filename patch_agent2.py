# -*- coding: utf-8 -*-
"""Останалите четири потвърдени находки на армията (v12.5)."""
import io, sys, ast, hashlib

ops = []


def rep(old, new, why, n=1):
    global s
    c = s.count(old)
    if c != n:
        print(f"  x СПИРАМ <<{why}>>: {c} съвпадения, чакам {n}")
        sys.exit(1)
    s = s.replace(old, new)
    ops.append(why)


p = "live_bot.py"
s = io.open(p, encoding="utf-8", newline="").read()

# ── 3 · «ВИЖДАМ, но не давам» изхвърляше мереното обяснение ─────────────
