RNG = np.random.default_rng(22)


def разлика(A, Б):
    """бутстрап на РАЗЛИКАТА по ден (сдвоено)"""
    a = A.groupby("day")["net"].agg(["sum", "count"])
    b = Б.groupby("day")["net"].agg(["sum", "count"])
    j = a.join(b, lsuffix="_a", rsuffix="_b", how="inner")
    if len(j) < 30: return None
    S = (j["sum_a"] - j["sum_b"]).to_numpy(); C = j["count_a"].to_numpy()
    k = len(S); из = RNG.integers(0, k, size=(4000, k))
    d = S[из].sum(axis=1) / np.maximum(C[из].sum(axis=1), 1)
    a_ = (100 - 99.17) / 2
    return float(S.sum() / C.sum()), np.percentile(d, a_), np.percentile(d, 100 - a_), len(j)


