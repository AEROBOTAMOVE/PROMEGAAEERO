ВЪЗРАСТ_ВХОД = ((6, 0.231), (12, 0.052), (24, -1.590), (48, -0.681), (10**9, -1.219))
def _възраст_нето(h):
    for п, н in ВЪЗРАСТ_ВХОД:
        if h < п: return н
    return ВЪЗРАСТ_ВХОД[-1][1]
def _бр(n): return f"{n:,}".replace(",", " ")
def _мерено(t, sym="XAUUSD"):
    L=[]
    if not t or not t.get("n"): return L
    L.append(f"📊 такава нагласа се е случвала {_бр(t['n'])} пъти · {t['win']:.1f}% от тях са свършили на плюс")
    L.append(f"📈 средно {lb._пари(t['net'], sym)} на сделка")
    if t.get("lo") is not None:
        L.append(f"📐 честната граница на това средно: {t['lo']/PIP:+,.0f} до {t['hi']/PIP:+,.0f} пипса")
    L.append("⚠️ това е средното от много сделки · ТАЗИ може да удари стопа")
    return L

def карта_сигнал(direction, entry, lv, защо, дял, зона_защо, t, sym="XAUUSD", dec=2):
    ико = "🟢" if direction=="long" else "🔴"
    глагол = "КУПИ" if direction=="long" else "ПРОДАЙ"
    метал = "ЗЛАТО" if sym=="XAUUSD" else "СРЕБРО"
    ст = PIP if sym=="XAUUSD" else 0.001
    трета = (lb.TPS[0][2] if sym=="XAUUSD" else lb.S_TPS[0]) / 3.0
    def п(k): return abs(lv[k]-entry)/ст
    L = [f"{ико} {глагол} {метал} · {lb._sofia()}",
         f"📌 защо сега: {защо}",
         f"🎯 влизаш на {lb._fmt(entry,dec)}",
         f"📏 размер: {дял} от твоя пълен за една сделка"]
    if зона_защо: L.append(f"🟨 защо не пълен: {зона_защо}")
    L += [f"1️⃣ {lb._fmt(lv['tp1'],dec)} · +{п('tp1'):,.0f} пипса · тук прибираш първата трета",
          f"2️⃣ {lb._fmt(lv['tp2'],dec)} · +{п('tp2'):,.0f} пипса · тук прибираш втората трета",
          f"3️⃣ {lb._fmt(lv['tp3'],dec)} · +{п('tp3'):,.0f} пипса · тук затваряш и последната",
          f"🔒 щом мине 1️⃣ · стопът отива на входа {lb._fmt(entry,dec)} и оттам нататък не губиш",
          f"🛑 ако тръгне срещу теб · излизаш на {lb._fmt(lv['sl'],dec)} · {lb._разст(entry,lv['sl'],sym,dec)} на унция",
          f"⏳ държа я най-много {ДНИ_МАКС} календарни дни · после излизам по цената, каквато е"]
    L += _мерено(t, sym)
    L.append(f"⚖️ «на плюс» брои и сделки само с първа цел: {lb._пари(трета,sym)} · печалба, но малка")
    return "\n".join(L)

def карта_без_вход(direction, entry, lv, причина, t, тишина, сянка=None, sym="XAUUSD", dec=2):
    ст = PIP if sym=="XAUUSD" else 0.001
    накъде = "нагоре" if direction=="long" else "надолу"
    L = [f"⏸ НЕ ВЛИЗАМ · злато · {lb._sofia()}",
         f"📌 бордът сочи {накъде}, но {причина}",
         f"👉 ти не правиш нищо · в тази карта няма нареждане"]
    if t and t.get("n"):
        L.append(f"📊 мерено: в такъв пазар {_бр(t['n'])} сделки са дали средно {lb._пари(t['net'],sym)}")
        L.append("📉 тоест влизането там не е риск, който се изплаща")
    if тишина:
        L.append(f"⏳ такива паузи траят още ~{тишина['оставащи_медиана_дни']} дни в половината случаи · "
                 f"{тишина['оставащи_до_седмица_pct']}% свършват до седмица")
    L.append("👁 гледам нататък · щом стане вход, пращам карта КУПИ или ПРОДАЙ")
    L.append(f"🔎 ако въпреки това решиш сам — твое решение, не мое:")
    L.append(f"🎯 {lb._fmt(entry,dec)} · 🛑 {lb._fmt(lv['sl'],dec)} · {lb._разст(entry,lv['sl'],sym,dec)}")
    L.append(" · ".join(f"{n} {lb._fmt(lv[k],dec)} ({abs(lv[k]-entry)/ст:,.0f}п)"
                        for n,k in (("1️⃣","tp1"),("2️⃣","tp2"),("3️⃣","tp3"))))
    if сянка:
        L.append(f"👁 записах този отказ (от {сянка['ден']}, цена {lb._fmt(сянка['entry'],dec)}) · "
                 f"после ще ти кажа щеше ли да е на плюс")
    return "\n".join(L)

