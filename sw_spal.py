# -*- coding: utf-8 -*-
import sys; sys.argv=["x"]
import live_bot as lb

def проба(име, откога, докога):
    мин = lb._търговски_минути(откога, докога)
    реално = (lb.pd.Timestamp(докога)-lb.pd.Timestamp(откога)).total_seconds()/60.0
    weekend = lb._market_closed(докога)
    print("="*72)
    print(f"{име}\n  вход: {откога} -> {докога}")
    print(f"  стенно време = {реално:.0f} мин ({реално/60:.1f}ч)")
    print(f"  _търговски_минути = {мин:.0f} мин ({мин/60:.2f}ч)")
    print(f"  weekend(now)={weekend}  СПАЛ_МИН={lb.СПАЛ_МИН}  пали ли се={мин>=lb.СПАЛ_МИН and not weekend}")
    print("  --- КАРТАТА ---")
    print(lb._спал_msg(мин, откога, докога))

проба("A) твърдение 1: ср 12.08 08:00 UTC -> чт 13.08 11:20 UTC",
      "2026-08-12T08:00:00", "2026-08-13T11:20:00")
проба("B) твърдение 2: пет 14.08 18:00 UTC -> пон 17.08 10:00 UTC",
      "2026-08-14T18:00:00", "2026-08-17T10:00:00")
