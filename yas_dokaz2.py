"""Д9-Д11 · сблъсъци между дума и множител + пазачът мери грешната цел."""
import sys, json
sys.argv = ["x"]
import live_bot as lb

stats = json.load(open("backtest_stats.json", encoding="utf-8"))
lv = {"sl": 4400.0, "tp1": 4430.0, "tp2": 4448.0, "tp3": 4475.0}
entry, spot = 4420.0, {"mid": 4420.5, "src": "gold"}
ПЪЛНО = "ДА — доларът и лихвите падат от днес, това вдига златото"
МАЛКО = "ДА (малък размер) — подреждането е отпреди 4 дни"

print("=" * 78)
print("Д9 · ПРИ БАЛАНС, ПРИ КОЙТО ДУМИТЕ ИЗОБЩО СЕ ПОЯВЯВАТ (10 000$) —")
print("     6-те множителя дават само 3 различни изречения")
print("=" * 78)
групи = {}
for zc in ("A", "B", "C"):
    for име, adv in (("ПЪЛЕН", ПЪЛНО), ("малък", МАЛКО)):
        м = lb.ZONE_W[zc] * (0.5 if "малък размер" in adv else 1.0)
        t = lb._sig_msg("long", 7.0, 6, "с", spot, 4420.3, "x", lv, entry, adv, {}, 1,
                        "тренд", stats, 10000.0, 2.0, adv_ok=True, zone=(zc, "т"))
        ред = [l for l in t.split("\n") if l.startswith("📏")][0]
        дума = ред.split("· ")[-1] if "⚠️" in ред else "(нищо не се казва)"
        групи.setdefault(дума, []).append((f"{zc}/{име}", round(м, 4)))
for дума, кой in sorted(групи.items(), key=lambda x: -max(m for _, m in x[1])):
    мн = [m for _, m in кой]
    print(f"\n«{дума}»")
    for к, m in кой:
        print(f"     {к:10} множител {m:.4f}")
    if len(мн) > 1:
        print(f"     ↳ СБЛЪСЪК: {max(мн)/min(мн):.2f}× разлика в парите, ЕДНА И СЪЩА дума")

print("\n" + "=" * 78)
print("Д10 · РАЗМЕНЕНИ ПО СИЛА: 'зоната е по-слаба' (0.33) е ПО-МАЛКО от")
print("      'сигналът не е пресен' (0.50), но първото звучи по-меко")
print("=" * 78)
print("A/малък  множител 0.500  дума: «сигналът не е пресен»")
print("C/ПЪЛЕН  множител 0.330  дума: «зоната е по-слаба»")
print("→ по-малкият размер носи по-меката дума. Няма как да се подредят на телефон.")

print("\n" + "=" * 78)
print("Д11 · ПАЗАЧЪТ ЗА МИН. ЛОТ МЕРИ СРЕЩУ risk_pct, НЕ СРЕЩУ НАМАЛЕНАТА ЦЕЛ")
print("=" * 78)
BAL, RISK = 1000.0, 2.0
мин_риск = lb.SL_D * 1.0            # 0.01 лот злато = 1 унция × 20$ стоп
for zc in ("A", "B", "C"):
    for име, adv in (("ПЪЛЕН", ПЪЛНО), ("малък", МАЛКО)):
        м = lb.ZONE_W[zc] * (0.5 if "малък размер" in adv else 1.0)
        цел = BAL * RISK / 100 * м
        t = lb._sig_msg("long", 7.0, 6, "с", spot, 4420.3, "x", lv, entry, adv, {}, 1,
                        "тренд", stats, BAL, RISK, adv_ok=True, zone=(zc, "т"))
        каза = "ДА" if "рискуваш" in t else "не"
        print(f"зона {zc}/{име:6} цел на риска {цел:6.2f}$ · най-малката позиция рискува "
              f"{мин_риск:.2f}$ = {мин_риск/цел:4.2f}× над целта · картата предупреждава: {каза}")
print("\nпазачът: `if _мин_п > risk_pct + 0.05` → 2.0% > 2.05% е ЛЪЖА → мълчи винаги,")
print("защото сравнява с ПЪЛНИЯ процент (2%), а не с намаления (1% / 0.67% / 0.33%).")

