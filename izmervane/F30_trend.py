ШИРИНИ = [10.0, 15.0, 20.0, 30.0, 40.0, 50.0, 70.0, 100.0]
R = {}
for sl in ШИРИНИ:
    g = {"name": f"g{sl:.0f}", "sl": sl, "be_after_tp1": True,
         "tps": [(1/3, sl * p) for p in ПРОП]}
    v = GH.simulate_paired(E, g, B)
    R[sl] = v / sl
