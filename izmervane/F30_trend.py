RNG = np.random.default_rng(30)
д = pd.Series(ДЕН)


def тенденция(маска=None, ит=4000):
    """блоков бутстрап ПО ДЕН → интервал на ранговата корелация ширина↔R"""
    дни = д.unique()
    инд = {x: np.where((д == x).to_numpy() & (маска if маска is not None
                                              else np.ones(len(д), bool)))[0] for x in дни}
    дни = [x for x in дни if len(инд[x]) > 0]
    k = len(дни)
    рангове = np.arange(1, len(ШИРИНИ) + 1)
    корел = []
    for _ in range(ит):
        изб = RNG.integers(0, k, size=k)
        ред = np.concatenate([инд[дни[i]] for i in изб])
        ср = []
        for sl in ШИРИНИ:
            v = R[sl][ред]
            ср.append(np.nanmean(v) if np.isfinite(v).any() else np.nan)
        ср = np.array(ср)
        if np.isnan(ср).any():
            continue
        рс = pd.Series(ср).rank().to_numpy()
        корел.append(np.corrcoef(рангове, рс)[0, 1])
    корел = np.array(корел)
    ср_реал = np.array([np.nanmean(R[sl][маска] if маска is not None else R[sl])
                        for sl in ШИРИНИ])
    рс = pd.Series(ср_реал).rank().to_numpy()
    return (np.corrcoef(рангове, рс)[0, 1], np.percentile(корел, 2.5),
            np.percentile(корел, 97.5), ср_реал)


