"""
F30 · МОНОТОННАТА ПОСОКА: РЪБ ИЛИ ДРИФТ

## Какво намери F28б
В единици риск R = нето/стоп, при живия хоризонт 21 ден:
    10$ −0.0219 · 15$ −0.0071 · 20$ −0.0057 · 30$ −0.0007 · 40$ +0.0107 · 50$ +0.0164
ИДЕАЛНО МОНОТОННО през шест ширини. Нито едно поотделно сравнение не мина
99.17% Bonferroni — но монотонност през 6 нива е много по-малко вероятна от
случайност, отколкото едно сравнение. Пропускането ѝ би било грешка.

## Двете обяснения, които трябва да се разделят
A · РЪБ: широкият стоп не спира сделката преждевременно и тя стига целта си.
B · ДРИФТ (бета): широкият стоп значи по-рядко спиране → по-дълго на пазара →
    повече изложеност на 22-годишния ръст на златото. Това НЕ е ръб. Ако е B,
    ефектът ще е САМО в ЛОНГ, а ШОРТ ще се ВЛОШАВА с ширината.

## Три заковани проверки
1. ТЕСТ ЗА ТЕНДЕНЦИЯ: рангова корелация между ширината и R, с блоков бутстрап
   по ден. Ако интервалът на корелацията не минава през нулата — тенденцията е
   истинска, независимо че отделните двойки не се доказват.
2. РАЗДЕЛЕНО ПО ПОСОКА: същата тенденция за ЛОНГ и за ШОРТ поотделно.
   · и двете нагоре → РЪБ (геометрията работи в двете посоки)
   · само ЛОНГ нагоре → ДРИФТ (изложеност на бичи пазар, не ръб)
3. ПРОДЪЛЖАВА ЛИ: добавям 70$ и 100$. Ако R расте безкрайно с ширината, това е
   доказателство за B — при стоп, който никога не се удря, остава само дрифтът.
   Истински геометричен ръб трябва да има ВРЪХ и после да спада.

## Кога казвам РЪБ
Само ако: тенденцията е значима И в двете посоки И има връх (не расте безкрайно).
Иначе — ДРИФТ, и геометрията остава, а находката се записва като обяснена.
"""
