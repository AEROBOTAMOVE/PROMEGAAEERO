# -*- coding: utf-8 -*-
"""sp1_vsichki.py — ВСЯКА СПИРАЧКА, ЕДНА ПО ЕДНА, срещу ЖИВАТА база.

БАЗА = живият бот както е сега (прочетен от live_bot в тази сесия):
       пауза 5/5 · ре-офер 2ч/1ч, таван 48ч/96ч, клас medium, 0-23 ·
       таван 12 едновременни · пазач 1 стоп/4ч · ЖИВИЯТ гейт ·
       дневен таван ИЗКЛЮЧЕН · праг по точки ИЗКЛЮЧЕН.

Всеки ред мени ЕДНО нещо. Δ = ВАРИАНТ минус БАЗА, сдвоено ПО ТЪРГОВСКИ ДЕН,
блоков бутстрап по ден, 5000 реплики, seed 20260905.
  Δ>0 доказано → спирачката ВРЕДИ (маха се / отпуска се)
  Δ<0 доказано → спирачката ПАЗИ (остава)
  нулата вътре → НЕДОКАЗАНА
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ТУК = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУК))
import sp_yadro as S                                              # noqa: E402
sys.path.insert(0, str(S.MJ))
import mer                                                        # noqa: E402
import jiv                                                        # noqa: E402


def main():
    B, G, D, брой_дни, години = S.зареди()
    jiv.лог("лента %.2f години · %d търговски дни" % (години, брой_дни))
    БАЗА_CFG, Ж, lb = S.жива_база(G)
    print("\nЖИВИТЕ СТОЙНОСТИ, ПРОЧЕТЕНИ ОТ live_bot В ТАЗИ СЕСИЯ:")
    for k in ("cool_min", "cool_flip", "reoffer_h", "reoffer_h_fresh",
              "max_age", "max_age_fresh", "reoffer_tier", "reoffer_lo",
              "reoffer_hi", "cap", "guard", "guard_stops", "guard_h"):
        print("   %-16s %s" % (k, Ж[k]))
    print("   %-16s %s" % ("ТАВАН_ВХОД_ДЕН", lb.ТАВАН_ВХОД_ДЕН))
    print("   %-16s %s" % ("ГЕЙТ_МИН_ТОЧКИ", lb.ГЕЙТ_МИН_ТОЧКИ))
    print("   %-16s %s" % ("МИН_ДНИ", lb.МИН_ДНИ))
    print("   %-16s %s" % ("MIN_N", lb.MIN_N))
    print("   %-16s %s" % ("СПИРАЧКИ_ДОЛУ", lb.СПИРАЧКИ_ДОЛУ))

    t0 = time.time()
    БАЗА = S.пробег(D, B, БАЗА_CFG, mer.геом_жива)
    jiv.лог("БАЗА · %d сделки · %d карти · %.1fs"
            % (len(БАЗА["сделки"]), БАЗА["карти"], time.time() - t0))
    m, lo, hi, дни = S.сам(БАЗА, брой_дни)
    сум = sum(x[4] for x in БАЗА["сделки"])
    print("  БАЗА: n=%d дни=%d  $/сделка %+.3f [%+.3f..%+.3f] %s  общо %+.1f$  /год %+.2f$"
          % (len(БАЗА["сделки"]), дни, m, lo, hi, jiv.присъда(lo, hi, дни),
             сум, сум / години))
    print("  спрени от: пазач %d · гейт %d · таван %d · fill %d"
          % (БАЗА["сп_пазач"], БАЗА["сп_гейт"], БАЗА["сп_таван"], БАЗА["сп_fill"]))

    def г(**kw):
        return dict(БАЗА_CFG, **kw)

    ВАРИАНТИ = [
        # ── СТОП-ПАЗАЧЪТ
        ("ПАЗАЧ_ВКЛ", "ПАЗАЧ=не (изключен изцяло)", г(guard=False)),
        ("ПАЗАЧ_СТОПОВЕ", "2 стопа (отпуснат)", г(guard_stops=2)),
        ("ПАЗАЧ_СТОПОВЕ", "3 стопа (по-отпуснат)", г(guard_stops=3)),
        ("ПАЗАЧ_ПРОЗОРЕЦ_Ч", "2ч (по-къс = по-отпуснат)", г(guard_h=2.0)),
        ("ПАЗАЧ_ПРОЗОРЕЦ_Ч", "1ч (най-къс)", г(guard_h=1.0)),
        ("ПАЗАЧ_ПРОЗОРЕЦ_Ч", "8ч (по-дълъг = по-строг)", г(guard_h=8.0)),
        ("ПАЗАЧ_ПРОЗОРЕЦ_Ч", "24ч (по-строг)", г(guard_h=24.0)),
        ("ПАЗАЧ_ПРОЗОРЕЦ_Ч", "0 = до края на деня (старото)", г(guard_h=0.0)),
        # ── ТАВАНИТЕ
        ("ТАВАН_СДЕЛКИ", "без таван (∞)", г(cap=None)),
        ("ТАВАН_СДЕЛКИ", "24 (двойно отпуснат)", г(cap=24)),
        ("ТАВАН_СДЕЛКИ", "5 (по-строг)", г(cap=5)),
        ("ТАВАН_СДЕЛКИ", "1 (както мереше старият уред)", г(cap=1)),
        ("ТАВАН_ВХОД_ДЕН", "3 входа/ден (включване)", г(ден_таван=3)),
        ("ТАВАН_ВХОД_ДЕН", "2 входа/ден (включване)", г(ден_таван=2)),
        # ── ПАУЗАТА
        ("COOL_MIN", "0 мин (без пауза)", г(cool_min=0, cool_flip=0)),
        ("COOL_MIN", "15 мин", г(cool_min=15, cool_flip=15)),
        ("COOL_MIN", "45/15 (старото на уреда)", г(cool_min=45, cool_flip=15)),
        # ── ПОВТОРНОТО ПРЕДЛАГАНЕ
        ("РЕ-ОФЕР", "изключен изцяло", г(reoffer=False)),
        ("REOFFER_H", "1ч / пресен 0.5ч (отпуснат)",
         г(reoffer_h=1.0, reoffer_h_fresh=0.5)),
        ("REOFFER_H", "0.25ч / 0.25ч (почти без праг)",
         г(reoffer_h=0.25, reoffer_h_fresh=0.25)),
        ("REOFFER_H", "6ч / 3ч (СПИРАЧКИ=МЕРЕНИ)",
         г(reoffer_h=6.0, reoffer_h_fresh=3.0)),
        ("MAX_AGE", "без таван на възрастта",
         г(max_age=0, max_age_fresh=0)),
        ("MAX_AGE", "240ч / 480ч (СПИРАЧКИ=МЕРЕНИ)",
         г(max_age=240.0, max_age_fresh=480.0)),
        ("MAX_AGE", "12ч / 12ч (по-строг)",
         г(max_age=12.0, max_age_fresh=12.0)),
        ("РЕОФЕР_КЛАС", "strong (по-строг)", г(reoffer_tier=2)),
        ("REOFFER_LO/HI", "8-22 София (по-строг прозорец)",
         г(reoffer_lo=8, reoffer_hi=22)),
        # ── ГЕЙТЪТ
        ("ГЕЙТ", "изключен изцяло", г(_гейт=None)),
        ("ГЕЙТ_МИН_ТОЧКИ", "5 (включване = по-строг)", г(мин_точки=5)),
        ("ГЕЙТ_МИН_ТОЧКИ", "6 (включване = по-строг)", г(мин_точки=6)),
    ]

    редове = []
    for име, как, cfg in ВАРИАНТИ:
        t = time.time()
        r = S.пробег(D, B, cfg, mer.геом_жива)
        m2, lo2, hi2, д2 = S.сам(r, брой_дни)
        dm, dlo, dhi, dд = S.сдвоено(БАЗА, r, брой_дни)
        s2 = sum(x[4] for x in r["сделки"])
        ред = dict(ключ=име, вариант=как, n=len(r["сделки"]), карти=r["карти"],
                   dn=len(r["сделки"]) - len(БАЗА["сделки"]),
                   dкарти=r["карти"] - БАЗА["карти"],
                   общо=s2, dобщо=s2 - сум, на_година=(s2 - сум) / години,
                   д_ден=dm, д_lo=dlo, д_hi=dhi, дни=dд,
                   присъда=jiv.присъда(dlo, dhi, dд))
        редове.append(ред)
        print("  %-16s %-34s n=%6d (%+6d) карти=%7d (%+7d)  Δ$/ден %+8.3f "
              "[%+8.3f..%+8.3f] %-16s Δ$/год %+9.2f   %.0fs"
              % (име, как, ред["n"], ред["dn"], ред["карти"], ред["dкарти"],
                 dm, dlo, dhi, ред["присъда"], ред["на_година"], time.time() - t))

    (ТУК / "rez_sp1.json").write_text(
        json.dumps({"база": dict(n=len(БАЗА["сделки"]), карти=БАЗА["карти"],
                                 общо=сум, на_сделка=m, lo=lo, hi=hi, дни=дни,
                                 години=години),
                    "редове": редове, "reps": S.REPS, "seed": S.SEED},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    jiv.лог("записано rez_sp1.json")


if __name__ == "__main__":
    main()
