def nfp_маска(G):
    """True за чекпойнтите в прозореца −20…+40 мин около NFP (първи петък,
    13:30 UTC). Изчислено от календара, не от таблица."""
    ts = G["ts"]                       # микросекунди от епохата, UTC
    сек = (ts // 1_000_000).astype(np.int64)
    tm = [time.gmtime(int(x)) for x in сек]
    год = np.array([t.tm_year for t in tm])
    мес = np.array([t.tm_mon for t in tm])
    ден = np.array([t.tm_mday for t in tm])
    wd = np.array([t.tm_wday for t in tm])          # 0=понеделник … 4=петък
    мин = np.array([t.tm_hour * 60 + t.tm_min for t in tm])
    # първи петък: петък И ден <= 7
    пръв_петък = (wd == 4) & (ден <= 7)
    # NFP 13:30 UTC → прозорец 13:10 … 14:10
    return пръв_петък & (мин >= 13 * 60 + 10) & (мин <= 14 * 60 + 10), год


def просадка(v):
    """Макс. просадка по кумулативната дневна крива."""
    c = np.cumsum(v)
    return float(np.max(np.maximum.accumulate(c) - c))


def опашка(r, брой_дни, име):
    v = S.по_дни(r["сделки"], брой_дни)
    най = float(v.min())
    ден_най = int(np.argmin(v))
    print("  %-40s общо %+9.1f$ · най-лош ден %+8.2f$ · просадка %8.2f$ · n=%d"
          % (име, v.sum(), най, просадка(v), len(r["сделки"])), flush=True)
    return dict(име=име, общо=float(v.sum()), най_лош_ден=най,
                ден=ден_най, просадка=просадка(v), n=len(r["сделки"]))


def main():
    B, G, D, брой_дни, години = S.зареди()
    БАЗА_CFG, Ж, lb = S.жива_база(G)
    маска, год = nfp_маска(G)
    jiv.лог("NFP прозорци: %d чекпойнта от %d (%.3f%%)"
            % (int(маска.sum()), len(маска), 100.0 * маска.mean()))

    БАЗА = S.пробег(D, B, БАЗА_CFG, mer.геом_жива)
    jiv.лог("БАЗА %d сделки" % len(БАЗА["сделки"]))

    # ── А · макро-щит (NFP част) ────────────────────────────────────────
    гейт0 = БАЗА_CFG["_гейт"]

    def гейт_щит(dr, streak, i):
        if маска[i]:
            return False
        return гейт0(dr, streak, i)

    print("\n" + "=" * 120)
    print("А · МАКРО-ЩИТ (само NFP частта, −20…+40 мин, първи петък 13:30 UTC)")
    print("   Δ = С ЩИТ минус БЕЗ ЩИТ.  Δ>0 → щитът НОСИ пари")
    print("=" * 120)
    СЩИТ = S.пробег(D, B, dict(БАЗА_CFG, _гейт=гейт_щит), mer.геом_жива)
    dm, dlo, dhi, dд = S.сдвоено(БАЗА, СЩИТ, брой_дни)
    s0 = sum(x[4] for x in БАЗА["сделки"]); s1 = sum(x[4] for x in СЩИТ["сделки"])
    print("  сделки без щит %d · с щит %d (−%d, тоест щитът реже %.2f%% от входовете)"
          % (len(БАЗА["сделки"]), len(СЩИТ["сделки"]),
             len(БАЗА["сделки"]) - len(СЩИТ["сделки"]),
             100.0 * (len(БАЗА["сделки"]) - len(СЩИТ["сделки"]))
             / max(len(БАЗА["сделки"]), 1)))
    print("  Δ$/ден %+0.4f [%+0.4f..%+0.4f] %s · дни=%d · Δ$/год %+0.2f"
          % (dm, dlo, dhi, jiv.присъда(dlo, dhi, dд), dд, (s1 - s0) / години),
          flush=True)
    # и само върху отрязаните сделки — колко печелеха те
    рязани = set()
    for x in БАЗА["сделки"]:
        if маска[x[0]]:
            рязани.add(x[0])
    net_р = np.array([x[4] for x in БАЗА["сделки"] if маска[x[0]]])
    dor_р = np.array([x[6] for x in БАЗА["сделки"] if маска[x[0]]])
    if len(net_р):
        m2, l2, h2, д2 = jiv.бутстрап_по_ден(net_р, dor_р, S.REPS, S.SEED)
        print("  САМИТЕ отрязани сделки: n=%d дни=%d  $/сделка %+0.3f [%+0.3f..%+0.3f] %s"
              % (len(net_р), д2, m2, l2, h2, jiv.присъда(l2, h2, д2)), flush=True)

    # ── Б · опашката ────────────────────────────────────────────────────
    print("\n" + "=" * 120)
    print("Б · ОПАШКАТА · най-лош ДЕН и просадка по дневната крива")
    print("=" * 120)
    редове = [опашка(БАЗА, брой_дни, "ЖИВАТА база (както е сега)")]
    for име, cfg in (("ПАЗАЧ изключен", dict(БАЗА_CFG, guard=False)),
                     ("ТАВАН_ВХОД_ДЕН=3", dict(БАЗА_CFG, ден_таван=3)),
                     ("ТАВАН_ВХОД_ДЕН=2", dict(БАЗА_CFG, ден_таван=2)),
                     ("ТАВАН_СДЕЛКИ без таван", dict(БАЗА_CFG, cap=None)),
                     ("ГЕЙТ изключен", dict(БАЗА_CFG, _гейт=None)),
                     ("МАКРО-ЩИТ (NFP) включен",
                      dict(БАЗА_CFG, _гейт=гейт_щит))):
        r = S.пробег(D, B, cfg, mer.геом_жива)
        редове.append(опашка(r, брой_дни, име))

    (ТУК / "rez_sp3.json").write_text(
        json.dumps({"щит": dict(д_ден=dm, lo=dlo, hi=dhi, дни=dд,
                                на_година=(s1 - s0) / години,
                                dn=len(СЩИТ["сделки"]) - len(БАЗА["сделки"])),
                    "опашка": редове, "години": години},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    jiv.лог("записано rez_sp3.json")


if __name__ == "__main__":
    main()
