"""sp2_geyt_i_epohi.py — ДВЕ неща, които sp1 не може:

  А) СПИРАЧКИТЕ ВЪТРЕ В ГЕЙТА (US-щит, МИН_ДНИ, MIN_N, ГЕЙТ_*_НЕДОКАЗАНО).
     Те не са отделен слой — те са условия ВЪТРЕ в `live_bot._advice_entry`.
     Мерят се като се сменя РЪЧКАТА в паметта на процеса и се строи НОВ гейт.
  Б) СТОП-ПАЗАЧЪТ ПО ЕПОХИ, В СВЕТА С ГЕЙТА. Записаното «+66.34$/ден и в
     четирите епохи» е мерено БЕЗ гейта. Тук се проверява със ЖИВИЯ гейт —
     ако падне там, находката трябва да падне.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np

ТУК = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУК))
import sp_yadro as S                                              # noqa: E402
sys.path.insert(0, str(S.MJ))
import mer                                                        # noqa: E402
import jiv                                                        # noqa: E402
import potok                                                      # noqa: E402

ЕПОХИ = ((2004, 2010), (2011, 2015), (2016, 2020), (2021, 2026))


def година_на_ден(B, брой_дни):
    """dord → година, по първия бар на всеки търговски ден."""
    dord = B["dord"]; tsmin = B["tsmin"]
    из = np.searchsorted(dord, np.arange(брой_дни), side="left")
    из = np.clip(из, 0, len(tsmin) - 1)
    # tsmin е минути от епохата (UTC)
    сек = tsmin[из].astype(np.int64) * 60
    год = np.array([time.gmtime(int(x)).tm_year for x in сек])
    return год


def main():
    B, G, D, брой_дни, години = S.зареди()
    год = година_на_ден(B, брой_дни)
    jiv.лог("лента %.2f години · %d дни · %d..%d"
            % (години, брой_дни, год.min(), год.max()))

    БАЗА_CFG, Ж, lb = S.жива_база(G)
    БАЗА = S.пробег(D, B, БАЗА_CFG, mer.геом_жива)
    jiv.лог("БАЗА %d сделки · спрени: пазач %d гейт %d таван %d"
            % (len(БАЗА["сделки"]), БАЗА["сп_пазач"], БАЗА["сп_гейт"],
               БАЗА["сп_таван"]))

    # ── А · ръчките ВЪТРЕ в гейта ────────────────────────────────────────
    print("\n" + "=" * 130)
    print("А · СПИРАЧКИТЕ ВЪТРЕ В ГЕЙТА · Δ спрямо ЖИВАТА база, сдвоено по ден")
    print("=" * 130)
    ГЕЙТ_ВАР = [
        ("US-щит", "изключен (шортът минава 8:25-9:15 NY)", dict(us_щит=False)),
        ("МИН_ДНИ", "0 (клетка под 100 дни пак съди)", dict(мин_дни=0)),
        ("MIN_N", "0 (кофа под 100 сделки пак реже)", dict(min_n=0)),
        ("MIN_N", "1000 (по-строг праг за «има числа»)", dict(min_n=1000)),
        ("ГЕЙТ_ЛОНГ_НЕДОКАЗАНО", "не (лонгът пак се реже)",
         dict(лонг_недоказано=False)),
        ("ГЕЙТ_ШОРТ_НЕДОКАЗАНО", "не (шортът пак се реже)",
         dict(шорт_недоказано=False)),
    ]
    редове = []
    for име, как, кв in ГЕЙТ_ВАР:
        # всеки път ЧИСТ гейт: първо връщаме живите стойности
        гейт, _lb = S.направи_гейт(G, us_щит=True, мин_дни=100, min_n=100,
                                   лонг_недоказано=True, шорт_недоказано=True)
        гейт, _lb = S.направи_гейт(G, **кв)
        r = S.пробег(D, B, dict(БАЗА_CFG, _гейт=гейт), mer.геом_жива)
        dm, dlo, dhi, dд = S.сдвоено(БАЗА, r, брой_дни)
        s2 = sum(x[4] for x in r["сделки"])
        s1 = sum(x[4] for x in БАЗА["сделки"])
        ред = dict(ключ=име, вариант=как, n=len(r["сделки"]),
                   dn=len(r["сделки"]) - len(БАЗА["сделки"]),
                   д_ден=dm, д_lo=dlo, д_hi=dhi, дни=dд,
                   на_година=(s2 - s1) / години,
                   присъда=jiv.присъда(dlo, dhi, dд))
        редове.append(ред)
        print("  %-22s %-40s n=%6d (%+6d)  Δ$/ден %+8.3f [%+8.3f..%+8.3f] %-16s "
              "Δ$/год %+9.2f"
              % (име, как, ред["n"], ред["dn"], dm, dlo, dhi, ред["присъда"],
                 ред["на_година"]), flush=True)
    # връщаме живите стойности
    S.направи_гейт(G, us_щит=True, мин_дни=100, min_n=100,
                   лонг_недоказано=True, шорт_недоказано=True)

    # ── Б · пазачът по епохи, СЪС ЖИВИЯ ГЕЙТ ─────────────────────────────
    print("\n" + "=" * 130)
    print("Б · СТОП-ПАЗАЧЪТ ПО ЕПОХИ · Δ = БЕЗ ПАЗАЧ минус С ПАЗАЧ (в света с ре-офер И с ЖИВИЯ ГЕЙТ)")
    print("   отрицателно = пазачът ПЕЧЕЛИ пари")
    print("=" * 130)
    БЕЗ = S.пробег(D, B, dict(БАЗА_CFG, guard=False), mer.геом_жива)
    va = S.по_дни(БАЗА["сделки"], брой_дни)
    vb = S.по_дни(БЕЗ["сделки"], брой_дни)
    d = vb - va
    епохи = []
    for a, b in ЕПОХИ + (("ВСИЧКИ", None),):
        if b is None:
            m = np.ones(брой_дни, bool)
            име = "2004-2026 (цялата лента)"
        else:
            m = (год >= a) & (год <= b)
            име = "%d-%d" % (a, b)
        жив = np.nonzero(m & (np.abs(va) + np.abs(vb) > 0))[0]
        dm, dlo, dhi, dд = jiv.бутстрап_по_ден(d[жив], жив, S.REPS, S.SEED)
        епохи.append(dict(епоха=име, дни=dд, д_ден=dm, lo=dlo, hi=dhi,
                          присъда=jiv.присъда(dlo, dhi, dд)))
        print("  %-26s дни=%5d  Δ$/ден БЕЗ−С %+9.3f [%+9.3f..%+9.3f]  %s"
              % (име, dд, dm, dlo, dhi, jiv.присъда(dlo, dhi, dд)), flush=True)
    print("\n  n сделки: С ПАЗАЧ %d · БЕЗ ПАЗАЧ %d (+%d)"
          % (len(БАЗА["сделки"]), len(БЕЗ["сделки"]),
             len(БЕЗ["сделки"]) - len(БАЗА["сделки"])))
    print("  общо $: С ПАЗАЧ %+0.1f · БЕЗ ПАЗАЧ %+0.1f"
          % (va.sum(), vb.sum()))

    (ТУК / "rez_sp2.json").write_text(
        json.dumps({"гейт": редове, "епохи": епохи, "години": години},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    jiv.лог("записано rez_sp2.json")


if __name__ == "__main__":
    main()
