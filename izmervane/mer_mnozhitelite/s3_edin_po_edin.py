# -*- coding: utf-8 -*-
"""s3 · КОЙ ОТ ЧЕТИРИТЕ НОСИ ПОЛЗА И КОЙ САМО РЕЖЕ.

Два различни въпроса, и двата сдвоени върху едни и същи входове:
  ИЗВАДЕН · махаме САМО този множител (другите три остават) —
            Δ = средно((W/w_f)·нето) − средно(W·нето)
            положително ⇒ БЕЗ него е по-добре ⇒ множителят ВРЕДИ
  САМ      · само този множител, останалите на 1 —
            Δ = средно(w_f·нето) − средно(нето)

И двете, повторени върху СЛЕПИТЕ входове (същия ден, случаен момент) — това е
базата: тегло, което «работи» и върху случаен момент, съди ДЕНЯ, не сигнала.

Пробвани са 4 множителя × 2 въпроса × 2 популации × 3 варианта на ZONE_W.
Броят е казан, за да може да се поправи за него: най-малкото p, което би
оцеляло на 24 сравнения по Бонферони, е 0.05/24 = 0.0021 — тоест 95%-ните
интервали тук НЕ са коригирани и се четат като описателни, освен където е
казано друго.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

TUK = Path(__file__).resolve().parent
sys.path.insert(0, str(TUK))
import tegla                                                         # noqa: E402
from s2_parite import Б2, дв                                         # noqa: E402

ИМЕНА = {"zw": "зона  _zw", "мw": "малък _мw", "рw": "режим _рw", "пw": "превес _пw"}


def main():
    E = tegla.данни()
    net = np.load(TUK / "net_6846.npy")
    BL = np.load(TUK / "slepi_15.npy")
    net_b = np.nanmean(BL, axis=0)
    гейт, _ = tegla.гейт_маска(E)
    dayid = tegla.ден_ид(E)

    print("=" * 78)
    print("s3 · ИЗВАЖДАМЕ ГИ ЕДИН ПО ЕДИН")
    print("=" * 78)

    for име_поп, m in (("ВСИЧКИ 6846", np.ones(len(E), bool)),
                       ("ГЕЙТ-ПУСНАТИТЕ", гейт)):
        b = Б2(dayid[m])
        nt = net[m]; nb = net_b[m]
        for име_z, zmap in tegla.ZONE_ВАРИАНТИ.items():
            Wd = tegla.множители(E, zone_w=zmap)
            W = Wd["W"].values[m]
            print("\n" + "=" * 78)
            print("%s  ·  ZONE_W %s   n=%d дни=%d" % (име_поп, име_z, int(m.sum()), b.k))
            print("=" * 78)
            print("  %-11s %6s  %-34s %-34s" % ("множител", "пали", "ИЗВАДЕН (Δ без него)", "САМ (Δ срещу плоско)"))
            for k in ("zw", "мw", "рw", "пw"):
                w = Wd[k].values[m]
                пали = 100.0 * (w < 0.999).mean()
                if пали == 0.0:
                    print("  %-11s %5.1f%%  %-34s %-34s"
                          % (ИМЕНА[k], пали, "— не се пали (плоско)", "— не се пали (плоско)"))
                    continue
                Wbez = W / w
                d_izv = (Wbez - W) * nt
                d_sam = (w - 1.0) * nt
                a = дв(*b.средно(d_izv))
                c = дв(*b.средно(d_sam))
                print("  %-11s %5.1f%%  %-34s %-34s" % (ИМЕНА[k], пали, a, c))
                # базата
                d_izv_b = (Wbez - W) * nb
                d_sam_b = (w - 1.0) * nb
                a2 = дв(*b.средно(d_izv - d_izv_b))
                c2 = дв(*b.средно(d_sam - d_sam_b))
                print("  %-11s %5s  %-34s %-34s" % ("  ↑ над базата", "", a2, c2))


if __name__ == "__main__":
    main()
