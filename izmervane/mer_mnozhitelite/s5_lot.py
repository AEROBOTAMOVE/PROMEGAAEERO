# -*- coding: utf-8 -*-
"""s5 · СТАВА ЛИ РАЗМЕРЪТ ТОЛКОВА МАЛЪК, ЧЕ СДЕЛКАТА ДА НЯМА СМИСЪЛ?

Сметката е ДОСЛОВНО тази на бота (live_bot.py:2840-2848 и 2888-2895), пусната
с истинските константи (импортирани, не преписани):

    риск = balance · risk_pct/100 · W
    лот  = риск / SL_D / 100                      (злато: 0.01 лот = 1 унция)
    лот_окр = round(лот, 2)
    ако лот < 0.01 → картата минава по клона «и с най-малката позиция…»

Минималният лот при златото е 0.01 = 1 унция = 20$ риск при стоп 20$/oz.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

TUK = Path(__file__).resolve().parent
REPO = TUK.parent.parent
sys.path.insert(0, str(TUK))
sys.path.insert(0, str(REPO))
import live_bot as lb                                                # noqa: E402
import tegla                                                         # noqa: E402


def main():
    E = tegla.данни()
    гейт, _ = tegla.гейт_маска(E)
    print("=" * 78)
    print("s5 · МИНИМАЛНИЯТ ЛОТ")
    print("=" * 78)
    print("SL_D=%.2f$/oz · дел=100 (0.01 лот = 1 унция) · минимален риск = %.2f$"
          % (lb.SL_D, lb.SL_D * 1.0))
    print("по подразбиране: BALANCE=1000$ · RISK_PCT=2  (live_bot.py:4990-4991)")

    for име_z, zmap in (("плоска (жива днес)", tegla.ZONE_ВАРИАНТИ["плоска (жива днес)"]),
                        ("мерена (до 01.09)", tegla.ZONE_ВАРИАНТИ["мерена (до 01.09)"])):
        W = tegla.множители(E, zone_w=zmap)["W"].values
        print("\n" + "-" * 78)
        print("ZONE_W %s" % име_z)
        print("  %8s %8s %10s %10s %10s %9s   %s"
              % ("дял W", "лот", "риск $", "лот_окр", "мин.лот %", "цел %", "какво прави картата"))
        for w in sorted(set(np.round(W, 6)), reverse=True):
            риск = 1000.0 * 2.0 / 100.0 * w
            лот = риск / lb.SL_D / 100.0
            лот_окр = round(лот, 2)
            мин_р = lb.SL_D * 1.0
            мин_п = мин_р / 1000.0 * 100.0
            цел = 2.0 * w
            if лот < 0.01:
                предупр = ("⚠️ казва «над целта»" if мин_п > 2.0 + 0.05
                           else "🔴 МЪЛЧИ (условието гледа 2%%, не целта %.2f%%)" % цел)
            else:
                предупр = "дава лот %.2f" % лот_окр
            print("  %7.1f%% %8.4f %10.2f %10.2f %9.2f%% %8.2f%%   %s"
                  % (100 * w, лот, риск, лот_окр, мин_п, цел, предупр))

        под = W < 0.999
        print("\n  при 1000$/2%%: лот < 0.01 в %.1f%% от всичките 6846 входа "
              "и в %.1f%% от гейт-пуснатите"
              % (100.0 * (W < 0.999).mean(), 100.0 * (W[гейт] < 0.999).mean()))
        # каква сметка трябва, за да е изпълним размерът
        print("\n  НУЖЕН БАЛАНС при риск 2%%, за да излезе поне 0.01 лот:")
        for w in sorted(set(np.round(W, 6)), reverse=True):
            need = lb.SL_D * 100.0 * 0.01 / (2.0 / 100.0) / w
            дял = 100.0 * (np.abs(W - w) < 1e-9).mean()
            дялг = 100.0 * (np.abs(W[гейт] - w) < 1e-9).mean()
            print("    дял %6.1f%% → баланс ≥ %8.0f$   (%.1f%% от всички · %.1f%% от гейт-пуснатите)"
                  % (100 * w, need, дял, дялг))

    print("\n" + "-" * 78)
    print("КОЛКО ГРУБО Е ЗАКРЪГЛЯНЕТО (при какъв баланс размерът е изпълним)")
    print("  При баланс 10 000$ и риск 2%%: 0.01 лот = 20$ = 0.20%% — стъпката е")
    print("  10%% от целевия риск, тоест дялът W се закръгля до най-близките 10%%.")
    for bal in (1000, 2000, 5000, 10000, 25000, 50000):
        W = tegla.множители(E)["W"].values
        риск = bal * 2.0 / 100.0 * W
        лот = риск / lb.SL_D / 100.0
        окр = np.round(лот, 2)
        под = лот < 0.01
        with np.errstate(invalid="ignore", divide="ignore"):
            греш = np.where(окр >= 0.01, np.abs(окр - лот) / np.maximum(лот, 1e-12), np.nan)
        print("  баланс %6d$: под мин. лот %5.1f%% · медианна грешка от закръглянето %5.1f%%"
              % (bal, 100.0 * под.mean(), 100.0 * np.nanmedian(греш)))


if __name__ == "__main__":
    main()
