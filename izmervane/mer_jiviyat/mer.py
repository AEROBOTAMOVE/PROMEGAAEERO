"""mer.py — СТАРИЯТ УРЕД СРЕЩУ ЖИВИЯ, СТЪПАЛО ПО СТЪПАЛО.

Всяко стъпало добавя ЕДНО живо звено. Така разликата не е една каша, а се
вижда КОЕ звено колко мени. Разликите се мерят СДВОЕНО ПО ТЪРГОВСКИ ДЕН
(парите, отворени в този ден, при А минус при Б), блоков бутстрап по ДЕН,
5000 реплики, seed 20260905.

Условие преди което и да е число (проверено в тази сесия):
  sverka.py  · jiv.едно  == geom_harness._one_trade   → 0 разминавания
  sverka2.py · jiv.бързо == jiv.едно (4 режима)       → 0 разминавания
  potok.сверка_с1 · СТАРАТА настройка ⇒ доставените 6846 входа → 0
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ТУК = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУК))
import jiv                                                        # noqa: E402
import potok                                                      # noqa: E402

REPS = 5000
SEED = 20260905
ГОДИНИ = None            # смята се от лентата


def геом_доставена(_dir):
    return jiv.ДОСТАВЕНА_5Д


def геом_доставена_21(_dir):
    return dict(jiv.ДОСТАВЕНА_5Д, дни=21)


def геом_жива(d):
    return jiv.жива_геом(d, 21)


def геом_жива_5(d):
    return jiv.жива_геом(d, 5)


def по_дни(сделки, брой_дни):
    """Вектор с дължина брой_дни: сумата на нетата, ОТВОРЕНИ в този ден."""
    v = np.zeros(брой_дни)
    for x in сделки:
        net, dord = x[4], x[6]
        v[dord] += net
    return v


def отчет(име, r, брой_дни, години):
    с = r["сделки"]
    if not с:
        return dict(име=име, n=0)
    net = np.array([x[4] for x in с])
    dord = np.array([x[6] for x in с])
    dr = np.array([x[2] for x in с])
    m, lo, hi, дни = jiv.бутстрап_по_ден(net, dord, REPS, SEED)
    return dict(име=име, n=len(с), карти=r["карти"],
                reoffer_карти=r["карти_reoffer"],
                общо=float(net.sum()), на_година=float(net.sum()) / години,
                на_сделка=m, lo=lo, hi=hi, дни=дни,
                n_long=int((dr == "long").sum()), n_short=int((dr == "short").sum()),
                сп_таван=r["сп_таван"], сп_пазач=r["сп_пазач"],
                стоп_pct=100.0 * np.mean([x[5] == "stop" for x in с]),
                време_pct=100.0 * np.mean([str(x[5]).startswith("time") for x in с]))


def покажи(o):
    if o.get("n", 0) == 0:
        print("  %-42s  n=0" % o["име"])
        return
    print("  %-42s n=%6d  карти=%7d  $/сделка %+7.3f [%+7.3f..%+7.3f] %s  "
          "общо %+9.1f$  /год %+7.2f$  дни=%d  лонг/шорт %d/%d"
          % (o["име"], o["n"], o["карти"], o["на_сделка"], o["lo"], o["hi"],
             jiv.присъда(o["lo"], o["hi"], o["дни"]),
             o["общо"], o["на_година"], o["дни"], o["n_long"], o["n_short"]))


def сдвои(име, a, b, брой_дни, години):
    """Б МИНУС А, ден по ден. Положително = новото звено НОСИ пари."""
    va = по_дни(a["сделки"], брой_дни)
    vb = по_дни(b["сделки"], брой_дни)
    d = vb - va
    жив = np.nonzero(np.abs(va) + np.abs(vb) > 0)[0]      # дни с поне една сделка
    dd = d[жив]
    dayid = жив
    m, lo, hi, дни = jiv.бутстрап_по_ден(dd, dayid, REPS, SEED)
    print("  %-42s Δ$/ден %+7.4f [%+7.4f..%+7.4f] %-16s  Δ$/год %+8.2f  "
          "Δсделки %+6d"
          % (име, m, lo, hi, jiv.присъда(lo, hi, дни),
             float(d.sum()) / години,
             len(b["сделки"]) - len(a["сделки"])))
    return dict(име=име, дневно=m, lo=lo, hi=hi, дни=дни,
                на_година=float(d.sum()) / години,
                delta_n=len(b["сделки"]) - len(a["сделки"]))


def main():
    B = jiv.лента()
    G = jiv.решетка()
    D = potok.подготви(G)
    assert potok.сверка_с1(D, G), "С1 падна — нищо оттук не важи"

    брой_дни = int(B["dord"][-1]) + 1
    минути = int(B["tsmin"][-1] - B["tsmin"][0])
    години = минути / (60 * 24 * 365.25)
    jiv.лог("лентата покрива %.2f години · %d търговски дни" % (години, брой_дни))

    ЖИВ = potok.жива_настройка()

    # ── стъпалата ────────────────────────────────────────────────────────
    С0 = dict(potok.СТАР)
    С1 = dict(С0)                                    # + жив хоризонт
    С2 = dict(С0)                                    # + жива геометрия
    С3 = dict(С0, cap=ЖИВ["cap"])                    # + ТАВАН 12
    С4 = dict(С3, guard=True, guard_h=ЖИВ["guard_h"],
              guard_stops=ЖИВ["guard_stops"])        # + СТОП-ПАЗАЧ
    С5 = dict(С4, cool_min=ЖИВ["cool_min"],
              cool_flip=ЖИВ["cool_flip"])            # + жива пауза 5/5
    С6 = dict(С5, reoffer=True, reoffer_h=ЖИВ["reoffer_h"],
              reoffer_h_fresh=ЖИВ["reoffer_h_fresh"],
              max_age=ЖИВ["max_age"], max_age_fresh=ЖИВ["max_age_fresh"],
              reoffer_lo=ЖИВ["reoffer_lo"], reoffer_hi=ЖИВ["reoffer_hi"],
              reoffer_tier=ЖИВ["reoffer_tier"])      # + РЕ-ОФЕР = ЖИВИЯТ УРЕД

    СТЪПАЛА = [
        ("0 · СТАРИЯТ УРЕД (доставена, 5д, ∞, без пазач)", С0, геом_доставена),
        ("1 · + жив хоризонт 21 търг. дни", С1, геом_доставена_21),
        ("2 · + жива геометрия (SL 130п · шорт ½¼¼)", С2, геом_жива),
        ("3 · + ТАВАН 12 едновременни", С3, геом_жива),
        ("4 · + СТОП-ПАЗАЧ (1 стоп · 4ч)", С4, геом_жива),
        ("5 · + жива пауза 5/5 мин", С5, геом_жива),
        ("6 · + РЕ-ОФЕР = ЖИВИЯТ УРЕД", С6, геом_жива),
    ]

    резултати = []
    отчети = []
    print("")
    print("=" * 132)
    print("Т1 · СТЪПАЛАТА · всяко добавя ЕДНО живо звено")
    print("=" * 132)
    for име, cfg, gf in СТЪПАЛА:
        r = потичай(D, B, cfg, gf)
        резултати.append((име, cfg, gf, r))
        o = отчет(име, r, брой_дни, години)
        отчети.append(o)
        покажи(o)

    print("")
    print("=" * 132)
    print("Т2 · КОЛКО МЕНИ ВСЯКО ЗВЕНО · сдвоено ПО ТЪРГОВСКИ ДЕН, бутстрап по ден, %d реплики"
          % REPS)
    print("=" * 132)
    двойки = []
    for i in range(1, len(резултати)):
        двойки.append(сдвои(резултати[i][0], резултати[i - 1][3],
                            резултати[i][3], брой_дни, години))

    print("")
    print("=" * 132)
    print("Т3 · ОТГОВОРЪТ · СТАРИЯТ УРЕД срещу ЖИВИЯ, на ЕДНА И СЪЩА лента")
    print("=" * 132)
    общо = сдвои("СТАР → ЖИВ (всичките звена наведнъж)",
                 резултати[0][3], резултати[-1][3], брой_дни, години)
    a, b = отчети[0], отчети[-1]
    print("")
    print("  СТАР : %d сделки · %+0.3f$/сделка · %+0.1f$ общо · %+0.2f$/год"
          % (a["n"], a["на_сделка"], a["общо"], a["на_година"]))
    print("  ЖИВ  : %d сделки · %+0.3f$/сделка · %+0.1f$ общо · %+0.2f$/год"
          % (b["n"], b["на_сделка"], b["общо"], b["на_година"]))
    if a["на_година"] != 0:
        дял = 100.0 * (b["на_година"] - a["на_година"]) / abs(a["на_година"])
        print("  РАЗЛИКА В ПАРИТЕ НА ГОДИНА: %+0.2f$ = %+0.1f%% от старото число"
              % (b["на_година"] - a["на_година"], дял))
    print("  РАЗЛИКА В БРОЯ СДЕЛКИ: %+d (%.1f× на стария)"
          % (b["n"] - a["n"], b["n"] / max(a["n"], 1)))

    (ТУК / "rezultat.json").write_text(
        json.dumps({"отчети": отчети, "двойки": двойки, "общо": общо,
                    "години": години, "reps": REPS, "seed": SEED},
                   ensure_ascii=False, indent=1), encoding="utf-8")
    jiv.лог("записано %s" % (ТУК / "rezultat.json"))


def потичай(D, B, cfg, gf):
    r = potok.пробег(D, B, cfg, gf)
    jiv.лог("  ... сделки %d · карти %d · спрени: таван %d · пазач %d"
            % (len(r["сделки"]), r["карти"], r["сп_таван"], r["сп_пазач"]))
    return r


if __name__ == "__main__":
    main()
