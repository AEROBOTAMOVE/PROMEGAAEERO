"""ВЕРСИЯТА СРЕЩУ ПОСЛЕДНИЯ КОМИТ · пуска се СЛЕД commit, ПРЕДИ push.

🔴🔴🔴 05.09 · ЗАЩО СЪЩЕСТВУВА ТОЗИ ФАЙЛ.
Днес ботът беше ДОЛУ 23 МИНУТИ (пет паднали ръна, нула карти, включително
изходни карти за пари НА РИСК). Причината не беше код, а ЕДИН НИЗ: комитнах
`v18.62b`, без да вдигна `VERSION` — той остана `v18.62`.
П47 сравнява (18,62,'') >= (18,62,'b') → НЕВЯРНО → selftest gate пада →
стъпката «run bot» се прескача.

ПАЗАЧЪТ Е РАБОТИЛ ВЯРНО. Грешката е моя, и е от НАЙ-КОВАРНИЯ вид:

  П47 зависи от ТЕКСТА НА КОМИТА. Значи може да се провери САМО СЛЕД като
  комитът вече съществува — а аз пуснах selftest ПРЕДИ да комитна.
  Тоест целият selftest беше зелен и въпреки това качих счупено.

И второ, по-лошо: пуснах качената двойка в ЧИСТО дърво (`git archive | tar -x`)
за да я проверя «както я вижда GitHub» — 2921 ЗЕЛЕНИ. Излъга ме, защото БЕЗ
`.git` П47 се ПРОПУСКА нарочно («без git тестът не бива да мълчи тихо»).
Тоест единствената падаща проверка беше и единствената пропусната в моята
проверка. Истината дойде чак от Actions API.

ЗАТОВА: този файл прави САМО тази проверка и я прави за ПОД СЕКУНДА, за да
може да се пуска между `git commit` и `git push` без да боли.

    python dev_versiya.py        → изход 0 (наред) или 1 (НЕ КАЧВАЙ)

Логиката е ДОСЛОВНО тази на П47 (ако П47 се смени, тук се чупи и се вижда —
пази се от П153).
"""
import io
import re
import subprocess
import sys


def _номер(v):
    """«v18.62b» → (18, 62, 'b') — за сравнение, не за красота."""
    m = re.match(r"v(\d+)\.(\d+)([a-z]*)", str(v or ""))
    return (int(m.group(1)), int(m.group(2)), m.group(3)) if m else (0, 0, "")


def провери(път="live_bot.py"):
    _и = io.open(път, encoding="utf-8").read()
    _м = re.search(r'^VERSION\s*=\s*"([^"]+)"', _и, re.M)
    if not _м:
        print("🔴 НЕ НАМИРАМ VERSION в %s" % път)
        return 1
    версия = _м.group(1)
    try:
        _р = subprocess.run(["git", "log", "-1", "--format=%s"],
                            capture_output=True, text=True,
                            encoding="utf-8", timeout=60)
        тема = (_р.stdout or "").strip()
    except Exception as _e:
        print("⚪ БЕЗ GIT (%s) — не мога да проверя. Това НЕ е «наред»."
              % type(_e).__name__)
        return 1
    if not тема:
        print("⚪ git не върна тема на комита — не мога да проверя.")
        return 1
    _вк = re.search(r"v\d+\.\d+[a-z]*", тема)
    ком = _номер(_вк.group(0) if _вк else "")
    тек = _номер(версия)
    print("  VERSION в кода : %s  %s" % (версия, тек))
    print("  последен комит : %s  %s" % ((_вк.group(0) if _вк else "—"), ком))
    if тек >= ком:
        print("  ✅ НАРЕД — версията не изостава. Може да се качва.")
        return 0
    print("  🔴 НЕ КАЧВАЙ. Версията ИЗОСТАВА от комита.")
    print("     П47 ще падне на GitHub, гейтът ще спре бота, и той ще стои")
    print("     мълчалив, докато не го видиш. Днес така стояхме 23 минути.")
    print("     ЛЕК: вдигни VERSION на поне %s и комитни наново (--amend)."
          % (тема[:40]))
    return 1


if __name__ == "__main__":
    sys.exit(провери(sys.argv[1] if len(sys.argv) > 1 else "live_bot.py"))
