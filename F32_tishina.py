# -*- coding: utf-8 -*-
"""
F32 · КОЙ Е ВЕРНИЯТ ВЪПРОС ЗА ТИШИНАТА

Във v13.0 качих: «такива паузи траят обикновено 2 дни (най-дългата мерена: 30)».
2 дни е МЕДИАНАТА НА ДЪЛЖИНАТА НА ЕПИЗОД.

Армията твърди друго число — медиана 4 дни — и е права по СМИСЪЛ, ако е права
по сметка. Разликата не е грешка в аритметиката, а РАЗЛИЧЕН ВЪПРОС:

  · «колко трае типичен епизод» → мери епизодите, всеки с тежест 1
  · «колко ОЩЕ ще трае ТОЗИ, в който съм» → мери от ПРОИЗВОЛЕН ТИХ ДЕН

Второто е въпросът на собственика — той чете картата ВЪТРЕ в паузата, не преди
нея. И е систематично по-голямо число: дългите епизоди съдържат повече дни,
значи по-вероятно е да си попаднал в дълъг. (Парадоксът на инспекцията.)

Ако е така, числото, което качих, ОТГОВАРЯ НА ГРЕШНИЯ ВЪПРОС и трябва да се
смени. Меря и двете и сравнявам.
"""
import warnings
warnings.filterwarnings("ignore")
import numpy as np, pandas as pd

D = "C:/Users/User/Downloads/ЛОЦО/f6_data"


def dc(p):
    d = pd.read_csv(p)
    k = [x for x in d.columns if x.lower() in ("date", "datetime", "observation_date")][0]
    d[k] = pd.to_datetime(d[k], errors="coerce")
    return d.dropna(subset=[k]).set_index(k).sort_index()


dx = dc(f"{D}/dxy_yahoo_full.csv")["Close"]
rr = pd.to_numeric(dc(f"{D}/DFII10.csv")["DFII10"], errors="coerce").reindex(dx.index).ffill()
d20, r20 = dx.pct_change(20), rr - rr.shift(20)
дол, лих = (-d20) > 0, (-r20) > 0
ок = d20.notna() & r20.notna()
съгл = ((дол == лих) & ок)[ок]                 # True = подредено
тихо = ~съгл                                    # True = карат се

# епизодите
гр = (тихо != тихо.shift()).cumsum()
дълж = тихо.groupby(гр).agg(["first", "size"])
Е = дълж[дълж["first"]]["size"].to_numpy()      # дължини на ТИХИТЕ епизоди

print("=" * 76)
print("F32 · ДВА РАЗЛИЧНИ ВЪПРОСА ЗА ЕДНА И СЪЩА ТИШИНА")
print("=" * 76)
print(f"  дни общо {int(ок.sum()):,} · тихи {int(тихо.sum()):,} = {тихо.mean()*100:.1f}%")
print(f"  епизоди: {len(Е)}")
print()
print("  ВЪПРОС 1 · «колко трае ТИПИЧЕН епизод» (всеки епизод с тежест 1):")
print(f"    медиана {np.median(Е):.0f} дни · средно {Е.mean():.1f} · най-дълъг {Е.max()}")
print()
# ВЪПРОС 2: от произволен ТИХ ДЕН — колко ОЩЕ, броейки днешния
оставащи = np.concatenate([np.arange(n, 0, -1) for n in Е])
print("  ВЪПРОС 2 · «колко ОЩЕ, ако съм ВЪТРЕ в пауза» (от произволен тих ДЕН):")
print(f"    медиана {np.median(оставащи):.0f} дни · средно {оставащи.mean():.1f}")
print(f"    до 3 дни: {(оставащи <= 3).mean()*100:.0f}% · до 7: {(оставащи <= 7).mean()*100:.0f}%"
      f" · до 14: {(оставащи <= 14).mean()*100:.0f}%")
print()
print("  🔴 РАЗЛИКАТА:", f"{np.median(оставащи):.0f} срещу {np.median(Е):.0f} дни —",
      "дългите епизоди съдържат повече дни, значи по-вероятно е да си в дълъг.")
print("     Собственикът чете картата ВЪТРЕ в паузата → верният е ВЪПРОС 2.")
print()
# и условно: ако вече е траяла N дни, колко още
print("  И най-полезното — УСЛОВНО, ако паузата вече трае N дни:")
for н in (1, 5, 10, 15, 20):
    ост = [n - i for n in Е for i in range(n) if i + 1 == н]
    if len(ост) >= 10:
        print(f"    вече {н:2d} дни → медиана още {np.median(ост):.0f} дни "
              f"(случаи: {len(ост)})")
    else:
        print(f"    вече {н:2d} дни → само {len(ост)} случая, не се цитира")
