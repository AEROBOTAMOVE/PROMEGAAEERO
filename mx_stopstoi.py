ВЪЗРАСТ_ВХОД = ((6, 0.231), (12, 0.052), (24, -1.590), (48, -0.681), (10**9, -1.219))
ВЪЗРАСТ_ДУМА = {6: "в първите шест часа", 12: "между шестия и дванадесетия час",
                24: "между дванадесетия и двадесет и четвъртия час",
                48: "на втория ден", 10**9: "след втория ден"}
РЕД_ДУМА = {1: "първият", 2: "вторият", 3: "третият", 4: "четвъртият", 5: "петият"}


def _възраст_нето(age_h):
    for праг, нето in ВЪЗРАСТ_ВХОД:
        if age_h < праг:
            return нето, ВЪЗРАСТ_ДУМА[праг]
    return ВЪЗРАСТ_ВХОД[-1][1], ВЪЗРАСТ_ДУМА[10**9]


def _часове_живот(tr, now_utc):
    try:
        import pandas as pd
        return (pd.Timestamp(now_utc) - pd.Timestamp(tr["opened"])).total_seconds() / 3600
    except Exception:
        return None


def _срок(ч):
    if ч is None:
        return ""
    if ч < 24:
        return f"{ч:.0f} часа"
    if ч < 48:
        return "1 ден"
    return f"{ч/24:.0f} дни"


# ───────────────────────── КАРТА 5 · СТОП ─────────────────────────
def нов_стоп(kind, tr, price_hit, when, via, gap, guard_n=0, next_line="", now_utc=None, dec=2):
    _сим = tr.get("sym", "XAUUSD")
    ст = PIP if _сим == "XAUUSD" else 0.001
    метал = "злато" if _сим == "XAUUSD" else "сребро"
    посока = "покупка" if tr["direction"] == "long" else "продажба"
    e = tr["entry"]; lv = tr["levels"]; hit = tr.get("hit", {})
    знак = 1 if tr["direction"] == "long" else -1
    дол = (price_hit - e) * знак
    if abs(дол) < 0.005:
        дол = 0.0
    стълба, взети = lb._ladder_pnl(kind, hit, lv, e, знак, дол, tr.get("hit_px"))
    час = lb._sofia(when) if via in ("бар", "спот") else lb._sofia()
    _повече = abs(дол) / ст - SL_PIPS
    без_риск = (взети > 0)
    L = []
    if без_риск:
        нула = стълба >= 0
        L.append((f"✅ ЗАТВОРЕНА НА НУЛА · {метал} {посока} · {час}" if нула
                  else f"🛑 ЗАТВОРЕНА · {метал} {посока} · {час}"))
        L.append("👉 ТИ НЕ ПРАВИШ НИЩО — остатъкът излезе сам, сделката е затворена")
        L.append(f"💵 СДЕЛКАТА ДОНЕСЕ {lb._пари(стълба, _сим)} на унция общо · "
                 f"прибраното по ЦЕЛ 1 си остава твое")
        L.append("↳ пипс = най-малкото мръдване на цената · при златото 1 пипс = 0.10$ на унция")
        L.append(f"🎯 КАК СТАНА — влязохме на <code>{lb._fmt(e, dec)}</code> · "
                 f"на ЦЕЛ 1 преместих стопа точно там, на входа")
        L.append("↳ оттам нататък най-лошото възможно беше НУЛА, а не загуба · "
                 "затова днес не губиш нищо")
        L.append(f"📌 цената се върна на <code>{lb._fmt(price_hit, dec)}</code> и остатъкът "
                 f"излезе там · по него сметката е нула")
    else:
        L.append(f"🛑 СТОПЪТ СЕ ИЗПЪЛНИ · {метал} {посока} · {час}")
        L.append("👉 ТИ НЕ ПРАВИШ НИЩО — брокерът вече те извади, сделката е затворена")
        L.append(f"💵 ЗАГУБАТА — {lb._пари(стълба, _сим)} на унция · това ѝ е всичко")
        L.append("↳ пипс = най-малкото мръдване на цената · при златото 1 пипс = 0.10$ на унция")
        L.append(f"🎯 КАК СТАНА — влязохме на <code>{lb._fmt(e, dec)}</code> · стопът стоеше на "
                 f"<code>{lb._fmt(lv['sl'], dec)}</code> · излязохме на "
                 f"<code>{lb._fmt(price_hit, dec)}</code>")
        if _повече > 0.5:
            L.append("⚠️ ЦЕНАТА ПРЕСКОЧИ СТОПА, вместо да мине през него — "
                     "на това ниво просто не е имало търговия")
            L.append(f"↳ брокерът вади по първата истинска цена · затова загубата е "
                     f"{_повече:,.0f} пипса над планираните {SL_PIPS:,.0f}")
        else:
            L.append(f"↳ толкова беше и планът от самото начало — {SL_PIPS:,.0f} пипса, "
                     f"точно колкото писах в картата за вход")
    ч = _часове_живот(tr, now_utc)
    if ч is not None:
        L.append(f"📅 сделката стоя отворена {_срок(ч)} · по правило я държа "
                 f"най-много {ДНИ_МАКС} дни")
    if not без_риск and guard_n >= 2:
        L.append(f"🛑 СПИРАМ {'ПОКУПКИТЕ' if tr['direction'] == 'long' else 'ПРОДАЖБИТЕ'} ДО УТРЕ"
                 f" — това е {РЕД_ДУМА.get(guard_n, str(guard_n) + '-ят')} стоп днес натам")
    elif not без_риск and guard_n == 1:
        L.append("📌 това е първият стоп днес в тази посока · при втори спирам картите до утре")
    if next_line:
        L.append(f"♻️ ОБРАТНО ВЪТРЕ — {next_line}")
    L.append("👁 СЛЕДВА — чакам следващия чист сигнал · щом дойде, пращам вход, стоп и цели")
    return "\n".join(L)


# ───────────────────────── КАРТА 6 · СТОИ ─────────────────────────
def нов_стои(direction, age_h, price_user, macro, health, now_utc):
    посока = "покупка" if direction == "long" else "продажба"
    lv = lb._levels(round(price_user, 2), direction)
    мъртви = list((health or {}).get("мъртви", []))
    реш = [k for k in ("долар", "лихви") if k in (macro or {}) and k not in мъртви]
    за = sum(1 for k in реш if (macro[k] if direction == "long" else not macro[k]))
    L = [f"⏸ САМО ЗА СВЕДЕНИЕ · нагласата за {посока} още стои · {lb._sofia(now_utc)}",
         "👉 ТИ НЕ ПРАВИШ НИЩО — това не е карта за вход и аз не съм отворил нищо",
         "↳ нагласа = посоката, накъдето пазарът е наклонен · става сделка само с моя карта"]
    if реш:
        имена = " и ".join({"долар": "доларът", "лихви": "лихвите"}[k] for k in реш)
        гл = "сочи" if len(реш) == 1 else "сочат"
        if за == len(реш):
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} още {гл} натам · нищо не се е развалило")
        elif за == 0:
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} вече {гл} в другата посока · нагласата отслабва")
        else:
            L.append(f"📌 КАКВО ВИЖДАМ — {имена} се дърпат в различни посоки · няма съгласие")
    if мъртви:
        L.append(f"⚠️ ЛИПСВА ЕДНО — за {', '.join(мъртви)} нямам число в момента · "
                 f"източникът мълчи и затова не го броя изобщо")
    ясна = age_h is not None and age_h < СТОЯЩ_МАКС_Ч
    if ясна:
        нето, дума = _възраст_нето(age_h)
        L.append(f"📅 ВЪЗРАСТ — нагласата е отпреди {age_h:.0f} часа · "
                 f"пресният вход по нея вече мина")
        L.append(f"📊 ЗАЩО НЕ ДАВАМ ВХОД — ръбът живее в първите {РЪБ_Ч:.0f} часа на нагласата")
        L.append(f"↳ вход, взет {дума}, е мерен на {lb._пари(нето)} на сделка · тоест губи пари")
    else:
        L.append("📅 ВЪЗРАСТ — нагласата стои отдавна · точната ѝ възраст не мога да "
                 "гарантирам, затова не давам число")
        L.append(f"📊 ЗАЩО НЕ ДАВАМ ВХОД — ръбът на такава нагласа живее в първите "
                 f"{РЪБ_Ч:.0f} часа, а тази отдавна ги мина")
    L.append(f"🎯 САМО ЗА ОРИЕНТИР — целите щяха да са 1️⃣ <code>{lb._fmt(lv['tp1'], 2)}</code> · "
             f"2️⃣ <code>{lb._fmt(lv['tp2'], 2)}</code> · 3️⃣ <code>{lb._fmt(lv['tp3'], 2)}</code>")
    L.append(f"🛑 а стопът — <code>{lb._fmt(lv['sl'], 2)}</code> · "
             f"{lb._разст(price_user, lv['sl'])} под сегашната цена "
             f"<code>{lb._fmt(price_user, 2)}</code>")
    L.append(f"👁 СЛЕДВА — пиша ти веднага при нов и пресен сигнал · иначе пак най-рано "
             f"след {СТОЯЩ_Ч:.0f} часа")
    return "\n".join(L)


