ДНИ_МАКС = 30
ВЪЗРАСТ_ВХОД = ((6, 0.231), (12, 0.052), (24, -1.590), (48, -0.681), (10**9, -1.219))

def _възраст_нето(h):
    for п, н in ВЪЗРАСТ_ВХОД:
        if h < п: return н
    return ВЪЗРАСТ_ВХОД[-1][1]

def _бр(n): return f"{n:,}".replace(",", " ")

def _мерено_редове(t, sym="XAUUSD"):
    L = []
    if not t or not t.get("n"): return L
    L.append(f"📊 такава нагласа се е случвала {_бр(t['n'])} пъти · {t['win']:.1f}% от тях са свършили на плюс")
    L.append(f"📈 средно {lb._пари(t['net'], sym)} на сделка")
    if t.get("lo") is not None and t.get("hi") is not None:
        L.append(f"📐 честната граница на това средно: {t['lo']/PIP:+,.0f} до {t['hi']/PIP:+,.0f} пипса")
    L.append("⚠️ това е средното от много сделки · ТАЗИ може да удари стопа")
    return L

# ============ 1 · СИГНАЛ ДА ============
def карта_сигнал(direction, entry, lv, защо, зона_текст, дял, дума, нам, t, sym="XAUUSD", dec=2):
    ико = "🟢" if direction == "long" else "🔴"
    глагол = "КУПИ" if direction == "long" else "ПРОДАЙ"
    метал = "ЗЛАТО" if sym == "XAUUSD" else "СРЕБРО"
    ст = PIP if sym == "XAUUSD" else 0.001
    def п(k): return abs(lv[k] - entry) / ст
    L = [f"{ико} {глагол} {метал} · {lb._sofia()}",
         f"📌 защо сега: {защо}",
         f"🎯 влизаш на {lb._fmt(entry, dec)}",
         f"📏 с {дял} размер, който си определил за една сделка" + (f" · {нам}" if нам else ""),
         f"1️⃣ {lb._fmt(lv['tp1'], dec)} · +{п('tp1'):,.0f} пипса · тук прибираш първата трета",
         f"2️⃣ {lb._fmt(lv['tp2'], dec)} · +{п('tp2'):,.0f} пипса · тук прибираш втората трета",
         f"3️⃣ {lb._fmt(lv['tp3'], dec)} · +{п('tp3'):,.0f} пипса · тук затваряш и последната",
         f"🔒 щом мине 1️⃣ · местиш стопа на входа {lb._fmt(entry, dec)} и сделката вече не може да те извади на минус",
         f"🛑 ако тръгне срещу теб · излизаш на {lb._fmt(lv['sl'], dec)} · {lb._разст(entry, lv['sl'], sym, dec)} на унция",
         f"⏳ държа я най-много {ДНИ_МАКС} календарни дни · на {ДНИ_МАКС}-ия излизам по цената, каквато е"]
    L += _мерено_редове(t, sym)
    L.append("⚖️ «на плюс» брои и сделките, стигнали само първата цел (+25 пипса) — печалба, но малка")
    return "\n".join(L)

